"""Config-space driver for the generated matrix-free (sigma-vector) apply
blocks (src/CodeGeneration/sigma_codegen.py ->
generatedADC/*_apply*.py). Wraps an apply function

    y_full[bra] = sum_{ket} block[bra, ket] * x_full[ket]

with the config-space gather/scatter that turns it into a supermatrix matvec
y_cfg = block_cfg @ v_cfg -- so a matrix-free class-class block can drive a
Davidson/Lanczos solve without ever forming the (n_bra, n_ket) dense block.

Separate from adc_autogenerated.py (the dense/restricted runtime): this
module imports class_configs and the dense solvers read-only.

Scatter/gather convention -- NO sign bookkeeping. A config-space vector is
placed at the CANONICAL ordered positions of the full redundant ket tensor
(holes ascending, particles ascending -- class_configs' order) and left zero
everywhere else. Because the generated block is internally antisymmetric in
its ket (hole and particle) indices, the apply's ket sum then collapses
exactly to the sum over canonical ket configs:

    y_full[bra] = sum_{canonical ket c} block[bra, orbitals(c)] * v_cfg[c]

and gathering y_full at the canonical BRA configs yields block_cfg @ v_cfg
directly. Permutation multiplicity and antisymmetric-fill SIGNS would enter
only if the config mass were spread over all ket orderings; keeping it on the
single canonical representative sidesteps that sign trap entirely. Validated
by the round-trip == dense_config_block @ v in tests/test_sigma_driver.py.
"""
