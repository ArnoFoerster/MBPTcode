def c12_dot_k2(rsolver, sector, v_k2, c12r_module, s12r_module, u2r_module,
              extra_leaves=None):
    """MATRIX-FREE EFFECTIVE ADC(5) (1,2) coupling, forward:

        c12_o2_generated(sector) @ v_k2  ==
            sign * ( raw2 @ v_k2 - U1 @ (S1k2^T @ v_k2) - K1 * (S12 @ v_k2) )

    (adc_autogenerated.c12_o2_generated's dense assembly),
    with NO (n_k1, n_k2) coupling ever formed: raw2/S12 go through
    restricted_class_matvec (the class-class-coupling matvec already used
    for the order-1 k1<->k2 block in production), and the S1k2^T @ v_k2 term
    reuses orb_dot_s2_l2 at l2^(1) (rsolver._u3_amps()['L2_1'] -- already
    computed, no new amplitude derivation)."""
    tag1 = '2h1p' if sector == 'IP' else '2p1h'
    tag2 = '3h2p' if sector == 'IP' else '3p2h'
    no, nv = rsolver.nocc, rsolver.nvir
    cfg1 = rsolver._sector_configs(sector)
    cfg2 = rsolver._kconfigs(sector, 2)
    pool = {**rsolver._rargs, **rsolver._amplitude_pool(), **(extra_leaves or {})}
    v_k2 = np.asarray(v_k2, float).reshape(-1)
    raw2 = restricted_class_matvec(c12r_module, f'apply_c2_{tag1}_{tag2}_',
                                   v_k2, cfg1, pool, no, nv, cfg_ket=cfg2)
    U1 = rsolver._u_block(sector)
    l2_1 = rsolver._u3_amps()['L2_1']
    s1k2_t_v = orb_dot_s2_l2(rsolver, sector, v_k2, u2r_module, l2_1,
                             extra_leaves)
    term2 = U1 @ s1k2_t_v
    s12v = restricted_class_matvec(s12r_module, f'apply_s12_{tag1}_{tag2}_',
                                   v_k2, cfg1, pool, no, nv, cfg_ket=cfg2)
    K1 = np.asarray(cfg1['K'], float)
    term3 = K1 * s12v
    return K2_CLASS_SIGN[sector] * (raw2 - term2 - term3)


def k1_dot_c12(rsolver, sector, v_k1, c12r_module, s12r_module, u2r_module,
              extra_leaves=None):
    """ADJOINT of c12_dot_k2: c12_o2_generated(sector).T @ v_k1, (n_k2,)-shaped,
    for the ADC(5) supermatrix's (2,1) [k2 row] block."""
    tag1 = '2h1p' if sector == 'IP' else '2p1h'
    tag2 = '3h2p' if sector == 'IP' else '3p2h'
    no, nv = rsolver.nocc, rsolver.nvir
    cfg1 = rsolver._sector_configs(sector)
    cfg2 = rsolver._kconfigs(sector, 2)
    pool = {**rsolver._rargs, **rsolver._amplitude_pool(), **(extra_leaves or {})}
    v_k1 = np.asarray(v_k1, float).reshape(-1)
    raw2t = restricted_class_matvec(c12r_module, f'apply_c2_{tag2}_{tag1}_',
                                    v_k1, cfg2, pool, no, nv, cfg_ket=cfg1)
    U1 = rsolver._u_block(sector)
    l2_1 = rsolver._u3_amps()['L2_1']
    u1t_v = U1.T @ v_k1
    term2 = s2_l2_dot_orb(rsolver, sector, u1t_v, u2r_module, l2_1,
                          extra_leaves)
    K1 = np.asarray(cfg1['K'], float)
    k1v = K1 * v_k1
    term3 = restricted_class_matvec(s12r_module, f'apply_s12_{tag2}_{tag1}_',
                                    k1v, cfg2, pool, no, nv, cfg_ket=cfg1)
    return K2_CLASS_SIGN[sector] * (raw2t - term2 - term3)


def _u_block_modules():
    """(module_order, module) for the generated restricted U/S block modules,
    lowest order first. A tag structure lives in the module emitted at the
    order it FIRST appeared; the driver reuses it at higher AMPLITUDE orders
    (that reuse is exactly what adc_order_rule.u_order_terms enumerates).

    Only order 2 (generatedADC/adc3) is required -- it's what plain ADC(3)
    needs. Orders 3-4 (generatedADC/adc4, adc5) are ADC(4)+-only and optional:
    a machine that has only run GenerateRuntime(orders=(2, 3)) still gets a
    working ADC(3) driver, just with no U^(3)+ tag structures to resolve (never silently
    under-computes -- see _struct_unavailable, which treats a structure whose
    home order is above the highest generated module here as pruned-vs-
    missing, not as available)."""
    mods = [(2, generated('adc3_u_blocks_restricted'))]
    for order, name in ((3, 'adc4_u3_blocks_restricted'), (4, 'adc5_u4_blocks_restricted')):
        if is_generated(name):
            mods.append((order, generated(name)))
    return mods


def _resolve_struct(name, tag, kind):
    """(module, module_order) holding tag structure `name`, or None when not
    found. NOTE: `None` alone is ambiguous -- it means EITHER pdaggerq pruned
    the structure (legitimately null) OR the module that would hold it has not
    been generated yet (would silently UNDER-COMPUTE). Use
    _struct_unavailable() to tell those apart."""
    for order, mod in _u_block_modules():
        for row in ('occ', 'vir'):
            if any(a.startswith(f'{kind}{order}_{tag}_{row}_{name}_') for a in dir(mod)):
                return mod, order
    return None


def _struct_unavailable(name, kind):
    """True when the structure is missing because its module has not been
    GENERATED yet (would silently under-compute), as opposed to pdaggerq having
    PRUNED it (legitimately null): adc_order_rule.struct_ungenerated against
    the highest generated U/S block module."""
    orders = {o for o, _ in _u_block_modules()}
    return struct_ungenerated(name, kind, max(orders) if orders else 0)


# =====================================================================
# Auto-Laplace block-routing DRIVER. Every rank>=3 (>4-index)
# amplitude-consuming tag structure of the (0,1) orbital<->k1 coupling has a
# Laplace-FUSED twin that consumes ONLY order<=2 rank<=2 leaves (t2_1/l2_1/
# t2_2/t1_2 + the outer ket t2), so l3/l4/t3/t4 are NEVER materialized inside
# the block (validated per block). This map +
# _lap_rank3_stitch route each such structure of the U^(3)/U^(4) rank>=3
# family to its twin. Structures NOT here are rank<=2 (fed amplitudes the
# normal way). The single-assignment u4/s4 twins (l2vt3..l4ft4, l4t3) are NOT
# combo-suffixed; l3ft2/l3t2 carry two order assignments so they ARE (combo =
# f'{l_order}{t_order}', matching generate_adc5_l3_higherorder_laplace).
# =====================================================================
_LAP_RANK3_ROUTE = {
    # name: ('u4'|'s4' module family, combo-suffixed?)
    'l2vt3': ('u4', False), 'l3vt2': ('u4', False), 'l4vt2': ('u4', False),
    'l3ft3': ('u4', False), 'l4ft3': ('u4', False), 'l4ft4': ('u4', False),
    'l4t3':  ('s4', False),
    'l3ft2': ('l3ho', True), 'l3t2': ('l3ho', True),
}


def _lap_rank3_module(fam):
    """Lazy on purpose: only reached when routing an ADC(4)+ rank>=3
    structure (see _lap_rank3_stitch, called only for the U^(4)/S^(4)/l3ho
    families), so a machine that has only generated through order 3
    (ADC(3)-only) never needs these modules to exist. An ImportError here
    means the required order hasn't been generated on this machine yet
    (orders=[...,5] for u4/s4/l3ho, orders=[...,4] for l3o3) -- raise loudly
    rather than silently resolve it away, same principle as
    _struct_unavailable."""
    if fam == 'l3o3':
        adc4_u3_l3_laplace_restricted = generated('adc4_u3_l3_laplace_restricted')
        return adc4_u3_l3_laplace_restricted
    adc5_u4_laplace_restricted = generated('adc5_u4_laplace_restricted')
    adc5_s4_laplace_restricted = generated('adc5_s4_laplace_restricted')
    adc5_l3_higherorder_laplace_restricted = generated('adc5_l3_higherorder_laplace_restricted')
    return {'u4': adc5_u4_laplace_restricted, 's4': adc5_s4_laplace_restricted,
            'l3ho': adc5_l3_higherorder_laplace_restricted}[fam]


def _lap_rank3_stitch(rsolver, name, kind, tag, sector, l_ord, t_ord, A, eps,
                      laplace_ntau, extra_leaves):
    """Fused (ncfg, norb) stitch for a rank>=3 (>4-index) structure -- the
    runtime auto-Laplace DRIVER's per-structure action. Routes `name` to its
    Laplace-fused twin via rsolver._stitch_k1r, consuming ONLY order<=2 rank<=2
    leaves so l3/l4/t3/t4 are never formed inside the block. Returns None if
    `name` is not a routed rank>=3 structure (caller falls back to the
    materialized stitch). Raises if the mapped fused block is missing.

    l3ft2/l3t2 appear at TWO orders and route to DIFFERENT modules (order =
    l_ord + t_ord, these being f-ham): at ORDER 3 (l3^2,t2^1) to the U^(3)
    l3-fusion module adc4_u3_l3_laplace (prefix u3_/s3_, single fusion, t2_1
    leaves only, NO combo suffix -- u_raw_series builds raw^(3) too, not just
    raw^(4)); at ORDER 4 ((l3^2,t2^2)/(l3^3,t2^1)) to the combo-suffixed
    adc5_l3_higherorder. The single-assignment u4/s4 families are order-4 only."""
    route = _LAP_RANK3_ROUTE.get(name)
    if route is None:
        return None
    fam, _ = route
    okind = 'u4' if kind == 'u' else 's4'          # U-side vs S-side prefix
    pool = dict(rsolver._rargs)
    pool.update(extra_leaves or {})
    pool.update({'eps_a': eps, 'ntau': laplace_ntau,
                 't2_1_aaaa': A['T2_1']['t2_aaaa'], 't2_1_abab': A['T2_1']['t2_abab'],
                 'l2_1_aaaa': A['L2_1']['l2_aaaa'], 'l2_1_abab': A['L2_1']['l2_abab']})
    if fam == 'l3ho' and l_ord + t_ord == 3:
        # order-3 (l3^2,t2^1): U^(3) l3-fusion module, u3_/s3_ prefix, no combo.
        mod = _lap_rank3_module('l3o3')
        pre = 'u3' if kind == 'u' else 's3'
        occ_base, vir_base = f'{pre}_{tag}_occ_{name}', f'{pre}_{tag}_vir_{name}'
    elif fam == 'l3ho':
        # order-4 combo: l3's numerator leaves (order-tagged) + outer ket t2.
        mod = _lap_rank3_module('l3ho')
        t2out = A[f'T2_{t_ord}']
        pool.update({'t2_2_aaaa': A['T2_2']['t2_aaaa'], 't2_2_abab': A['T2_2']['t2_abab'],
                     't1_2_aa': A['T1_2']['t1_aa'],
                     't2out_aaaa': t2out['t2_aaaa'], 't2out_abab': t2out['t2_abab']})
        occ_base = f'{okind}_{tag}_occ_{name}_{l_ord}{t_ord}'
        vir_base = f'{okind}_{tag}_vir_{name}_{l_ord}{t_ord}'
    else:
        mod = _lap_rank3_module(fam)
        occ_base, vir_base = f'{okind}_{tag}_occ_{name}', f'{okind}_{tag}_vir_{name}'
    if not any(a.startswith(occ_base + '_') or a.startswith(vir_base + '_')
               for a in dir(mod)):
        raise RuntimeError(
            f"_lap_rank3_stitch: no fused block {occ_base!r}/{vir_base!r} in "
            f"{mod.__name__} for rank>=3 structure {name!r} (l^{l_ord},t^{t_ord}) "
            f"-- generate it before routing this structure through Laplace.")
    return rsolver._stitch_k1r(mod, occ_base, vir_base, sector, pool)


def _assemble_raw_S(rsolver, sector, n, strict=True, laplace_ntau=None,
                    extra_leaves=None):
    """(raw^(n), S^(n)) in the PRECURSOR basis -- the order-general tag-structure
    assembly with NO ISR/class-GS corrections applied. Shared by the dense oracle
    tests/u_isr_oracle.u_dot_orb_isr
    (dense ISR layer) and _un_pieces (matrix-free ISR layer).

    extra_leaves carrying B_aa selects each block module's DF twin where the
    twin holds the structure; a structure without one falls back to the dense
    module, which is exact whenever the solver still carries g.

    laplace_ntau (int): route every rank>=3 (>4-index) structure through its
    Laplace-fused twin (_lap_rank3_stitch), so l3/l4/t3/t4 are never
    materialized inside those blocks. The rank<=2 structures are unchanged.
    Validated == the exact (materialized) assembly at ntau=6
    (tests/test_sigma_u4_laplace.py).

    In laplace mode the low-rank structures' order-3/4 rank<=2 amplitudes come
    from _amps_order_lowrank_laplace (T1^(3)/L1^(3)/L2^(3)/L1^(4) all Laplace-
    fused), so NO rank>=3 RSPT intermediate (t3_2/t4_2/t3_3) is materialized on
    the AMPLITUDE side either -- together with the rank>=3 block routing above,
    the raw/S coupling is fully non-materializing. (The provider covers order<=4;
    at n>=5 a missing order-5 amp RAISES via the strict check rather than under-
    computing. The dense (n_k1)^2 Delta S build in the ISR layer is wall #2.)"""
    tag = '2h1p' if sector == 'IP' else '2p1h'
    A = (rsolver._amps_order_lowrank_laplace(laplace_ntau)
         if laplace_ntau is not None else rsolver._amps_order(max_order=n))
    df = 'B_aa' in (extra_leaves or {})

    def m_(*dicts):
        p = dict(rsolver._rargs)
        p.update(extra_leaves or {})
        for d in dicts:
            p.update(d)
        return p

    def block_module(mod, kind, order, name):
        if not df:
            return mod
        twin = _df_twin_module(mod)
        if twin is not None and any(
                a.startswith((f'{kind}{order}_{tag}_occ_{name}_',
                              f'{kind}{order}_{tag}_vir_{name}_')) for a in dir(twin)):
            return twin
        return mod

    def amps(j, a, k, b):
        ds = []
        for kind, rank, order in (('L', j, a), ('T', k, b)):
            if rank:
                key = f'{kind}{rank}_{order}'
                if key not in A:
                    return None
                ds.append(A[key])
        return ds

    missing_amp, ungenerated = [], []

    def accumulate(terms, kind):
        acc = None
        for t in terms:
            name = t[0]
            j, a, k, b = (t[1], t[4], t[3], t[5]) if kind == 'u' else (t[1], t[3], t[2], t[4])
            if laplace_ntau is not None and name in _LAP_RANK3_ROUTE:
                # rank>=3 (>4-index) structure -> Laplace-fused twin (DRIVER);
                # l3/l4/t3/t4 never materialized in the block.
                blk = _lap_rank3_stitch(rsolver, name, kind, tag, sector, a, b,
                                        A, rsolver.eps, laplace_ntau, extra_leaves)
                acc = blk if acc is None else acc + blk
                continue
            res = _resolve_struct(name, tag, kind)
            if res is None:
                if _struct_unavailable(name, kind):
                    ungenerated.append(name)
                continue
            ds = amps(j, a, k, b)
            if ds is None:
                missing_amp.append(f"{kind}:{name}(l{j}^{a},t{k}^{b})")
                continue
            mod = block_module(res[0], kind, res[1], name)
            blk = rsolver._stitch_k1r(mod, f'{kind}{res[1]}_{tag}_occ_{name}',
                                      f'{kind}{res[1]}_{tag}_vir_{name}', sector, m_(*ds))
            acc = blk if acc is None else acc + blk
        return acc

    raw = accumulate(u_order_terms(n), 'u')
    S = accumulate(s_order_terms(n), 's')
    if strict and (missing_amp or ungenerated):
        bits = []
        if ungenerated:
            bits.append(f"ungenerated block module for {sorted(set(ungenerated))}")
        if missing_amp:
            bits.append(f"no amplitude for {sorted(set(missing_amp))}")
        raise RuntimeError(f"_assemble_raw_S(n={n}, {sector}) incomplete -- " + "; ".join(bits))
    return raw, S


def u_raw_series(rsolver, sector, n, strict=True, laplace_ntau=None,
                 extra_leaves=None):
    """{order: raw^(order)} and {order: S^(order)} -- the PRECURSOR-basis
    (pre-ISR) orbital<->class coupling and overlap at each order 1..n, from the
    order-general rule. raw^(1) is the bare U^(1) (_u_block); higher orders come
    from the tag-structure assembly. These are the series the ISR/Loewdin layer
    (isr_engine) convolves. laplace_ntau routes each order's rank>=3 structures
    through their Laplace-fused twins, extra_leaves with B_aa their DF twins
    (_assemble_raw_S). n <= 4: U^(5) is ADC(6) content (no rank-5 layer, no
    order-5 amplitudes here), refused rather than under-computed."""
    if n > 4:
        raise ValueError(f"u_raw_series(n={n}): orders above 4 are ADC(6) content")
    raws, Ss = {}, {}
    for m in range(1, n + 1):
        if m == 1:
            raws[1] = rsolver._u_block(sector)
            continue
        r, s = _assemble_raw_S(rsolver, sector, m, strict=strict,
                               laplace_ntau=laplace_ntau, extra_leaves=extra_leaves)
        raws[m] = r
        Ss[m] = s
    return raws, Ss


def u_dot_orb_order(rsolver, sector, p_orb, n, s2cr_module, extra_leaves=None,
                    strict=True, laplace_ntau=None, h00=None):
    """U^(n) @ p_orb at any order n, matrix-free: the adc_order_rule tag-structure
    assembly (u_raw_series) under the order-general ISR layer (_un_apply_fwd).

    extra_leaves carrying B_aa selects the DF twin of every block that has one
    (pass the DF s2c apply module as s2cr_module); laplace_ntau routes the
    rank>=3 structures through their Laplace-fused twins; h00 is the orbital
    block's static part, needed from n = 5 (see _un_pieces). strict=False
    accepts a partial sum where a block or an amplitude is missing."""
    pieces = _un_pieces(rsolver, sector, n, extra_leaves, laplace_ntau, strict, h00)
    return _un_apply_fwd(rsolver, sector, pieces, s2cr_module, p_orb, extra_leaves)


def u3_dot_orb(rsolver, sector, p_orb, s2cr_module, extra_leaves=None,
               laplace_ntau=None, max_rank=None):
    """U^(3) @ p_orb, matrix-free. Thin wrapper over _u3_pieces + _u3_apply_fwd
    (kept as the public entry the parity gate and the downfold already call)."""
    M, U1, n2, cfg, pool, tag = _u3_pieces(rsolver, sector, s2cr_module,
                                           extra_leaves, laplace_ntau,
                                           max_rank=max_rank)
    return _u3_apply_fwd(M, U1, n2, cfg, pool, s2cr_module, tag,
                         rsolver.nocc, rsolver.nvir, p_orb)


def u3_dot_k1(rsolver, sector, y_k1, s2cr_module, extra_leaves=None,
              laplace_ntau=None, max_rank=None):
    """U^(3)^T @ y_k1, matrix-free -- the transpose direction the FULL operator
    needs for its (orbital, k1) block. Same stitches as u3_dot_orb."""
    M, U1, n2, cfg, pool, tag = _u3_pieces(rsolver, sector, s2cr_module,
                                           extra_leaves, laplace_ntau,
                                           max_rank=max_rank)
    return _u3_apply_bwd(M, U1, n2, cfg, pool, s2cr_module, tag,
                         rsolver.nocc, rsolver.nvir, y_k1)


def _u3_pieces(rsolver, sector, s2cr_module, extra_leaves=None,
               laplace_ntau=None, df=None, max_rank=None):
    """Build U^(3)'s cheap (n_k1, norb) stitches -- the U^(3) coupling
    contracted with an orbital trial, WITHOUT building the dense (n_k1, n_k1)
    class-GS S^(2) matrix that u3_generated forms only to compute
    -1/2 (S^(2) @ U^(1)). Replicates u3_generated's assembly

        U^(3) = raw^(3) - N^(2) U^(1) - eps_p S^(3)_pJ - 1/2 (S^(2)_class U^(1))

    but with the ONLY expensive piece -- s2c @ U1 -- reduced to a single S^(2)
    MATVEC: (s2c @ U1) @ p_orb = s2c @ (U1 @ p_orb), applied matrix-free via the
    generated s2c apply functions. raw/S^(3)/U^(1) are the cheap (n_k1, norb)
    stitches u3_generated already builds; only the (n_k1)^2 S^(2) matrix (the
    ~17.5 GB / 284 s aug-cc-pVTZ blocker) is avoided. Returns (n_k1,).

    laplace_ntau: if None (default), the EXACT path -- materializes l3
    (adc4_u3_blocks_restricted l3ft2/l3t2 stitches) and is bit-exact vs
    u3_generated(sector) @ p_orb (test_sigma_dyson_parity). If an int, the
    l3-consuming stitches are supplied by the Laplace-fused
    adc4_u3_l3_laplace_restricted blocks and the t3/l3 amplitudes are NEVER
    materialized (via _u3_amps_laplace) -- the O(no^3 nv^3) memory wall is
    removed; the result matches the exact path to the minimax-quadrature
    accuracy (converges with ntau). The non-l3 stitches are identical in
    both paths. The stitch list mirrors u3_generated so a front-track change
    there is caught by the parity gate.

    max_rank=2: the rank-truncated 'all-t2, no-t3' U^(3) -- DROP the two
    l3-consuming stitches (u3_l3ft2/s3_l3t2, U^(3)'s ONLY genuinely rank-3
    content) and keep every t1/t2 stitch. Amplitudes come from the rank<=2
    Laplace provider (_u3_amps_laplace: T1^(3) quadrature-fused, no rank-3
    array ever formed), so this mode needs no L3 even transiently and no
    Laplace stitch modules. This is the U^(3) piece of the t2-only k<=1
    dressed level (ADC(3) configuration space + all rank<=2 higher-order
    terms) that stays EN-ADC dressable. NOTE: T1^(3) itself is RSPT-exact
    and its recursion passes through T3^(2) inside the fused quadrature; the
    truncation criterion is the rank of what the ADC blocks contract with
    (storage/EN-dressing rank), not the RSPT history of the amplitudes."""
    if max_rank not in (None, 2):
        raise ValueError(f"max_rank={max_rank!r}; expected None (full U^(3)) "
                         "or 2 (drop the l3 stitches)")
    # DF/RI: selected automatically when the caller supplies B leaves (the same
    # convention the adc4_base apply modules use), or forced with df=True/False.
    # ALL of U^(3)'s stitch sources have DF twins now -- adc4_u3_blocks_restricted,
    # adc3_u_blocks_restricted and the Laplace-fused adc4_u3_l3_laplace_restricted
    # -- so the whole U^(3) coupling is density-fitted, not just part of it.
    if df is None:
        df = bool(extra_leaves) and 'B_aa' in (extra_leaves or {})
    if df:
        genu3r = generated('adc4_u3_blocks_restricted_df')
        genr3 = generated('adc3_u_blocks_restricted_df')
    else:
        genu3r = generated('adc4_u3_blocks_restricted')
        genr3 = generated('adc3_u_blocks_restricted')
    tag = '2h1p' if sector == 'IP' else '2p1h'
    eps = rsolver.eps
    rank2 = (max_rank == 2)
    lap = laplace_ntau is not None
    # rank2 always uses the rank<=2 Laplace provider (its only quadrature
    # content is the fused T1^(3); ntau=12 is the converged default).
    A = (rsolver._u3_amps_laplace(laplace_ntau if lap else 12)
         if (lap or rank2) else rsolver._u3_amps())

    def m(*dicts):
        # extra_leaves must be seeded here, not just in the s2c pool: on the DF
        # path the stitch functions take B_aa/B_bb in place of g_*, and
        # _stitch_k1r resolves every arg from this dict (KeyError otherwise).
        p = dict(rsolver._rargs)
        p.update(extra_leaves or {})
        for d in dicts:
            p.update(d)
        return p

    def st(mod, split, amps):
        return rsolver._stitch_k1r(mod, f'{split.split("_",1)[0]}_{tag}_occ_{split.split("_",1)[1]}',
                                   f'{split.split("_",1)[0]}_{tag}_vir_{split.split("_",1)[1]}', sector, amps)

    if rank2:
        # the 'all-t2' truncation: U^(3)'s only rank-3 content is these two
        # stitches -- dropped, everything else below is pure t1/t2.
        u3_l3ft2 = 0.0
        s3_l3t2 = 0.0
    elif lap:
        if df:
            genlap = generated('adc4_u3_l3_laplace_restricted_df')
        else:
            genlap = generated('adc4_u3_l3_laplace_restricted')
        # l3-consuming stitches: Laplace-fused, l3/t3 never formed. Pool carries
        # eps_a (quadrature grid), the T2^(1) leaves as t2_1_* (l3's numerator
        # inputs), and ntau; _stitch_k1r resolves the fused blocks' signature.
        m_lap = m({'eps_a': eps, 'ntau': laplace_ntau,
                   't2_1_aaaa': A['T2_1']['t2_aaaa'], 't2_1_abab': A['T2_1']['t2_abab']})
        u3_l3ft2 = st(genlap, 'u3_l3ft2', m_lap)
        s3_l3t2 = st(genlap, 's3_l3t2', m_lap)
    else:
        u3_l3ft2 = st(genu3r, 'u3_l3ft2', m(A['L3_2'], A['T2_1']))
        s3_l3t2 = st(genu3r, 's3_l3t2', m(A['L3_2'], A['T2_1']))

    raw = (st(genu3r, 'u3_l2vt2', m(A['L2_1'], A['T2_1']))
           + st(genu3r, 'u3_vt1', m(A['T1_2']))
           + st(genu3r, 'u3_l1v', m(A['L1_2']))
           + st(genr3, 'u2_l2v', m(A['L2_2']))
           + st(genr3, 'u2_l2ft2', m(A['L2_1'], A['T2_2']))
           + st(genr3, 'u2_l2ft2', m(A['L2_2'], A['T2_1']))
           + st(genu3r, 'u3_l2ft1', m(A['L2_1'], A['T1_2']))
           + u3_l3ft2
           + st(genr3, 'u2_l1f', m(A['L1_3'])))
    S3 = (st(genu3r, 's3_l2t1', m(A['L2_1'], A['T1_2']))
          + s3_l3t2
          + st(genr3, 's2_l1', m(A['L1_3'])))
    U1 = rsolver._u_block(sector)
    n2 = rsolver.n2_norm()
    cfg = rsolver._sector_configs(sector)
    pool = {**rsolver._rargs, **rsolver._amplitude_pool(), **(extra_leaves or {})}
    M = raw - n2 * U1 - eps[None, :] * S3                       # (n_k1, norb)
    return M, U1, n2, cfg, pool, tag


def _s2c_minus_n2(vec, n2, cfg, pool, s2cr_module, tag, no, nv):
    """(S2C - n2 I) @ vec, matrix-free. S2C is the class-GS overlap S^(2);
    its DENSE form is (n_k1, n_k1) -- the ~17.5 GB / 284 s aug-cc-pVTZ blocker
    that u3_generated materializes and that everything here exists to avoid."""
    return (restricted_class_matvec(s2cr_module, f'apply_s2c_{tag}_', vec, cfg,
                                    pool, no, nv) - n2 * vec)


def _u3_apply_fwd(M, U1, n2, cfg, pool, s2cr_module, tag, no, nv, x_orb):
    """U^(3) @ x_orb  ==  M @ x_orb - 1/2 (S2C - n2) @ (U1 @ x_orb)."""
    u1p = U1 @ x_orb
    return M @ x_orb - 0.5 * _s2c_minus_n2(u1p, n2, cfg, pool, s2cr_module,
                                           tag, no, nv)


def _u3_apply_bwd(M, U1, n2, cfg, pool, s2cr_module, tag, no, nv, y_k1):
    """U^(3)^T @ y_k1 -- the TRANSPOSE direction, needed for the (orbital, k1)
    block of the supermatrix.

    U^(3) = M - 1/2 (S2C - n2) U1, and S2C is an OVERLAP matrix, hence
    symmetric, so (S2C - n2)^T = (S2C - n2) and

        U^(3)^T y = M^T y - 1/2 U1^T [(S2C - n2) y].

    That symmetry is what makes the transpose available from exactly the same
    cheap (n_k1, norb) stitches -- no second derivation, no dense S^(2)."""
    return M.T @ y_k1 - 0.5 * (U1.T @ _s2c_minus_n2(y_k1, n2, cfg, pool,
                                                    s2cr_module, tag, no, nv))


def _delta_s_apply(rsolver, sector, m, v, s2cr_module, A, extra_leaves=None):
    """Delta S^(m) @ v, matrix-free -- the order-m class-class OVERLAP applied to
    a config-space vector WITHOUT forming the (n_k1, n_k1) matrix. The apply twin
    of BuildSuperMatrixADCnRestricted.class_overlap_series[m]: it sums
    restricted_class_matvec over the SAME (overlap structure x amplitude-order)
    terms class_overlap_series/_class_raw_S enumerate (s_order_terms +
    _resolve_class_struct), then applies the normalization recursion
    Delta S^(m) = S^(m) - sum_{j>=2} N^(j) Delta S^(m-j) as matvecs
    (Delta S^(0)=I, Delta S^(1)=0). Every surviving overlap structure is rank<=2
    and resolves to the order-2 s2c apply -- s3c splits were pruned, so a single
    apply module (s2cr_module) covers it; a structure needing an order>2 apply
    raises rather than silently drop a denominator factor. `A` is the shared
    amplitude map (_amps_order[_lowrank_laplace]); reused across the recursion.

    Bit-exact vs the dense class_overlap_series column-by-column (H4/sto-3g,
    IP+EA, exact and laplace paths, err<=7e-24) and the U^(4) apply built on it
    reproduces the dense oracle (tests/u_isr_oracle.u_dot_orb_isr) to ~1e-19 (both directions)."""
    tag = '2h1p' if sector == 'IP' else '2p1h'
    no, nv = rsolver.nocc, rsolver.nvir
    cfg = rsolver._sector_configs(sector)

    def amps(j, a, k, b):
        ds = {}
        for lead, rank, order in (('L', j, a), ('T', k, b)):
            if not rank:
                continue
            key = f'{lead}{rank}_{order}'
            if key not in A:
                return None
            ds.update(A[key])
        return ds

    out = np.zeros(len(cfg['K']))
    for t in s_order_terms(m):
        name = t[0]
        j, a, k, b = t[1], t[3], t[2], t[4]
        res = rsolver._resolve_class_struct(name, tag, 's')
        if res is None:
            continue
        _, order = res
        ds = amps(j, a, k, b)
        if ds is None:
            # amp unavailable (laplace omits rank>=3): the structure's Fock factor
            # is f[o,v]=0 on the class blocks (Brillouin), so it contributes zero.
            continue
        if order != 2:
            raise RuntimeError(
                f"_delta_s_apply({sector}, m={m}): structure {name!r} resolves to "
                f"an order-{order} class module, but only the order-2 s2c apply is "
                f"wired (s3c splits were pruned); a matrix-free order>2 overlap "
                f"apply is needed here.")
        pool = {**rsolver._rargs, **(extra_leaves or {}), **ds}
        out = out + restricted_class_matvec(
            s2cr_module, f'apply_s{order}c_{tag}_{name}_', v, cfg, pool, no, nv)
    for j in range(2, m + 1):
        mj = m - j
        if mj == 0:
            out = out - rsolver.n_norm_order(j) * v            # Delta S^(0) = I
        elif mj == 1:
            continue                                           # Delta S^(1) = 0
        else:
            out = out - rsolver.n_norm_order(j) * _delta_s_apply(
                rsolver, sector, mj, v, s2cr_module, A, extra_leaves)
    return out


def _lowdin_apply(ds_apply, a, v):
    """Y^(a) v of Y = (1 + Delta S)^(-1/2) = sum_k binom(-1/2, k) Delta S^k, with
    Delta S = sum_{m>=2} Delta S^(m) applied as ds_apply(m, w): the order-a part
    sums every ordered composition of a into parts >= 2 (Delta S^(1) = 0)."""
    out = np.zeros_like(v) if a else v
    layer, c = {0: v}, 1.0
    for k in range(1, a // 2 + 1):
        c *= -(2 * k - 1) / (2 * k)                 # binom(-1/2, k) from binom(-1/2, k-1)
        nxt = {}
        for p, w in layer.items():
            for m in range(2, a - p + 1):
                if a - p - m == 1:                  # an order-1 remainder has no part left
                    continue
                t = ds_apply(m, w)
                nxt[p + m] = nxt[p + m] + t if p + m in nxt else t
        if a in nxt:
            out = out + c * nxt.pop(a)
        layer = nxt
    return out


def _gs_metric(ds_class, S):
    """ds(m, w) = Delta S^(m) w for the k1 metric after class-GS against the
    orbital states, W = S_11 - S_10 S_01 (both norm-divided): the class-class
    overlap ds_class minus the orbital projection, which starts at order 4
    because the orbital-class overlap S_10 starts at order 2."""
    def ds(m, w):
        out = ds_class(m, w)
        for i in range(2, m - 1):
            si, sj = S.get(i), S.get(m - i)
            if si is not None and sj is not None:
                out = out - si @ (sj.T @ w)
        return out
    return ds


def _isr_coupling_fwd(n, raws, S, eps, h00, ds_class, p_orb, ncfg):
    """U^(n) @ p_orb from norm-divided series (all (n_k1, norb)):

        U^(n) = sum_{a+b=n} Y^(a) [raw^(b) - (S H_00)^(b)],   H_00 = diag(eps) + V_00

    the (0,1) block of isr_assembly.isr_effective_blocks transposed: class-GS of
    the k1 precursors against the orbital states, then Loewdin within the class.
    ds_class(m, w) applies the class-class Delta S^(m); h00 = {m: V_00^(m)}."""
    ds = _gs_metric(ds_class, S)
    hp = {0: eps * p_orb}
    hp.update({c: v @ p_orb for c, v in h00.items()})
    out = np.zeros(ncfg)
    for a in range(n):
        if a == 1:
            continue                                # Y^(1) = 0
        b = n - a
        g = raws[b] @ p_orb if b in raws else None
        for c, hc in hp.items():
            if b - c in S:
                t = S[b - c] @ hc
                g = -t if g is None else g - t
        if g is not None:
            out = out + _lowdin_apply(ds, a, g)
    return out


def _isr_coupling_bwd(n, raws, S, eps, h00, ds_class, w_k1, norb):
    """U^(n)^T @ w_k1: Y is a function of the symmetric metric and so symmetric,
    U^(n)^T w = sum_{a+b=n} [raw^(b) - (S H_00)^(b)]^T (Y^(a) w), on the same
    Delta S matvecs as _isr_coupling_fwd."""
    ds = _gs_metric(ds_class, S)
    orders_h = [0] + sorted(h00)
    out = np.zeros(norb)
    for a in range(n):
        if a == 1:
            continue
        b = n - a
        if b not in raws and not any(b - c in S for c in orders_h):
            continue
        y = _lowdin_apply(ds, a, w_k1)
        if b in raws:
            out = out + raws[b].T @ y
        for c in orders_h:
            if b - c in S:
                sy = S[b - c].T @ y
                out = out - (eps * sy if c == 0 else h00[c].T @ sy)
    return out


def _un_pieces(rsolver, sector, n, extra_leaves=None, laplace_ntau=None,
               strict=True, h00=None):
    """The (n_k1, norb) series the matrix-free U^(n) reads: the precursor coupling
    raw^(1..n) and orbital-class overlap S^(2..n), each divided by the ground-state
    norm <Psi|Psi> = 1 + sum N^(m) as a series (isr_assembly.norm_divide), plus the
    amplitude map of the Delta S matvecs. Nothing (n_k1)^2 is formed.

    h00: {m: V_00^(m)}, the norm-divided orbital block beyond diag(eps) (its
    order-2 part vanishes by anticommutator cancellation). The class-GS channel
    -S^(2) V_00^(3) reaches the coupling at order 5, so n >= 5 refuses to run
    without it rather than return an inexact U^(n)."""
    if n >= 5 and h00 is None:
        raise NotImplementedError(
            f"U^({n}) needs the orbital block's static part V_00^(m>=3): its class-GS "
            f"channel -S^(n-m) V_00^(m) enters the coupling from order 5. Pass "
            f"h00={{m: V_00^(m)}}.")
    raws, Ss = u_raw_series(rsolver, sector, n, strict=strict,
                            laplace_ntau=laplace_ntau, extra_leaves=extra_leaves)
    norm = {j: rsolver.n_norm_order(j) for j in range(2, n)}
    A = (rsolver._amps_order_lowrank_laplace(laplace_ntau) if laplace_ntau is not None
         else rsolver._amps_order(max_order=n))
    return dict(n=n, raws=norm_divide(raws, norm, n), S=norm_divide(Ss, norm, n),
                A=A, h00=dict(h00 or {}))


def _un_class_overlap(rsolver, sector, pieces, s2cr_module, extra_leaves=None):
    """ds_class(m, w): the solver's norm-divided class-class Delta S^(m) matvec."""
    def ds_class(m, w):
        return _delta_s_apply(rsolver, sector, m, w, s2cr_module, pieces['A'],
                              extra_leaves)
    return ds_class


def _un_apply_fwd(rsolver, sector, pieces, s2cr_module, p_orb, extra_leaves=None):
    """U^(n) @ p_orb, matrix-free, at the order the pieces were built for
    (_isr_coupling_fwd on the solver's series); ADC(5)'s U^(4)."""
    return _isr_coupling_fwd(
        pieces['n'], pieces['raws'], pieces['S'], rsolver.eps, pieces['h00'],
        _un_class_overlap(rsolver, sector, pieces, s2cr_module, extra_leaves),
        p_orb, len(rsolver._sector_configs(sector)['K']))


def _un_apply_bwd(rsolver, sector, pieces, s2cr_module, w_k1, extra_leaves=None):
    """U^(n)^T @ w_k1, matrix-free (_isr_coupling_bwd on the solver's series)."""
    return _isr_coupling_bwd(
        pieces['n'], pieces['raws'], pieces['S'], rsolver.eps, pieces['h00'],
        _un_class_overlap(rsolver, sector, pieces, s2cr_module, extra_leaves),
        w_k1, rsolver.norb)


def solve_dyson_adc4_downfold(rsolver, homo_index, extra_leaves=None, f_orb=None,
                              include_u3=True, include_schur=True, tol=1e-8,
                              laplace_ntau=12,
                              c1r_module=None, c2r_module=None, s2cr_module=None,
                              k2r_module=None, u2r_module=None, v0=None, max_cycle=200):
    """Dyson-ADC(4) by DOWNFOLDING (the user's scheme): solve the exact
    two-sector Dyson-ADC(3) IP/EA, then dynamically correct that root with the
    3h2p/3p2h manifold folded out on the fixed Dyson-ADC(3) eigenvector |p>:

        omega_p = e_p^ADC3 + <p| M^ADC4(omega_p) - M^ADC3 |p>
                = e_p^ADC3 + <p|C^(2)|p> + <p|U^(3)|p>
                            + sum_{J in 3h2p} w_J^2/(omega_p - K_J)
                            + sum_{J in 3p2h} w'_J^2/(omega_p - K_J)

    where w = V^T|p> is the SD->3h2p (3p2h) coupling of |p> (orbital rows via
    U^(2)_3h2p, 2h1p rows via C^(1)), computed MATRIX-FREE. The 3h2p/3p2h
    blocks are diagonal (K), so their Schur complement is the exact rational
    sum above -- no (n3h2p)^2 or (n2h1p x n3h2p) object is ever formed.
    Everything is Dyson (two-sector) and matrix-free.

    homo_index: orbital-block index to follow (e.g. the HOMO for the IP) --
    used as the Davidson seed UNLESS v0 is given, and always used for the
    reported 'homo_wt' diagnostic regardless of v0.
    v0: optional (n1,) seed vector for the inner Dyson-ADC(3) Davidson,
    overriding the default Koopmans unit vector at homo_index -- e.g. an
    ADC(3) eigenvector for a satellite root, which the homo_index-only seed
    cannot reach (its |overlap|-based root-following is structurally biased
    toward whichever root shares homo_index's orbital character). Normalized
    internally; homo_index is still required (for the diagnostic above) even
    when v0 is supplied.
    include_schur=False skips the 3h2p/3p2h manifold ENTIRELY (no k=2 config
    enumeration, no u2_k2 sweep, no omega fixed point): omega_p = e3 + static.
    With include_u3=False too this is the ADC(3)+C^(2) downfold -- only the
    <p|C^(2)|p> satellite dressing on top of exact Dyson-ADC(3).
    include_u3='rank2' keeps only U^(3)'s rank<=2 ('all-t2, no-t3') stitches
    (u3_dot_orb max_rank=2: the two l3 stitches dropped, no Laplace modules
    touched); with include_schur=False this is the full t2-only k<=1 dressed
    level e3 + <p|C^(2)|p> + <p|U^(3)_t2|p> -- ADC(3) configuration space,
    ADC(3) scaling, EN-dressable amplitude content throughout.
    omega_p is a quasiparticle equation with known poles (K_J) and weights
    (w_J^2): MBPTcode's one QP root finder solves it
    (Solvers.qp_equation.solve_qp_equation_poles), the root of largest weight Z
    = 1/(1 + sum w_J^2/(omega_p - K_J)^2); 'Z' and 'branch' report it.
    Returns dict with e_adc3 (exact Dyson-ADC(3)), e_downfold (omega_p), and the
    static/dynamic correction breakdown (all in Hartree)."""
    if c1r_module is None:
        c1r_module = generated('adc4_c1_self_apply_restricted_blocks')
        c2r_module = generated('adc4_c2_apply_restricted_blocks')
        s2cr_module = generated('adc4_c2_s2c_apply_restricted_blocks')
        k2r_module = generated('adc4_k2_apply_restricted_blocks')
    if u2r_module is None and include_schur:
        u2r_module = generated('adc4_u2_k2_apply_restricted_blocks')
    norb, no, nv = rsolver.norb, rsolver.nocc, rsolver.nvir
    n2 = rsolver.n2_norm()
    pool = {**rsolver._rargs, **rsolver._amplitude_pool(), **(extra_leaves or {})}

    # ---- exact Dyson-ADC(3): two-sector, follow the wanted root ----
    op3, diag3 = restricted_dyson_operator(
        rsolver, 'adc3', extra_leaves=extra_leaves, f_orb=f_orb,
        c1r_module=c1r_module, c2r_module=c2r_module, s2cr_module=s2cr_module,
        k2r_module=k2r_module)
    v0_seed = koopmans_seed(op3.shape[0], homo_index, v0, 'the Dyson-ADC(3) space')
    w3, X3, conv3 = follow_roots(op3, diag3, v0_seed, tol=tol, max_cycle=max_cycle)
    e3 = float(w3[0])
    cfgI, cfgE = rsolver._sector_configs('IP'), rsolver._sector_configs('EA')
    nI = len(cfgI['K'])
    p = X3[:, 0]
    p_orb, p_IP, p_EA = p[:norb], p[norb:norb + nI], p[norb + nI:]

    # ---- static corrections (omega-independent): <p|C^(2)|p>, <p|U^(3)|p> ----
    c2 = (p_IP @ assembled_c2_matvec_restricted(p_IP, cfgI, pool, n2, no, nv,
                                                c2r_module, s2cr_module, '2h1p')
          + p_EA @ assembled_c2_matvec_restricted(p_EA, cfgE, pool, n2, no, nv,
                                                  c2r_module, s2cr_module, '2p1h'))
    u3 = u3_EA = u3_IP = 0.0
    if include_u3:
        # 2 p_orb.(u3mat^T p_EA) = 2 p_EA.(u3mat p_orb), the latter MATRIX-FREE
        # (u3_dot_orb avoids u3_generated's dense (n_k1)^2 S^(2) matrix -- the
        # ~17.5 GB / 284 s aug-cc-pVTZ blocker).
        # <p|U^(3)|p> over BOTH sectors. This previously summed the 2p1h(EA)
        # term ONLY, which for an IP omitted the dominant 2h1p contribution and
        # made the downfold a PARTIAL ADC(4). 2 x because U^(3) enters the
        # supermatrix in both the (orb, k1) and (k1, orb) blocks:
        #   2 p_orb.(u3^T p_k1) = 2 p_k1.(u3 p_orb).
        mr = 2 if include_u3 == 'rank2' else None
        u3_EA = 2.0 * float(p_EA @ u3_dot_orb(rsolver, 'EA', p_orb, s2cr_module,
                                              extra_leaves, laplace_ntau=laplace_ntau,
                                              max_rank=mr))
        u3_IP = 2.0 * float(p_IP @ u3_dot_orb(rsolver, 'IP', p_orb, s2cr_module,
                                              extra_leaves, laplace_ntau=laplace_ntau,
                                              max_rank=mr))
        u3 = u3_EA + u3_IP
        # With laplace_ntau set (default), l3/t3 are never materialized -- the
        # O(no^3 nv^3) memory wall is gone. (Exact path only, laplace_ntau=None:
        # l3 is consumed only by the U^(3) stitches above, so drop it before the
        # 3h2p/3p2h sweep to avoid stacking the u2_k2 build on resident l3.)
        if getattr(rsolver, '_u3a', None) is not None:
            rsolver._u3a.pop('L3_2', None)
            gc.collect()

    static = c2 + u3
    if not include_schur:
        return dict(e_adc3=e3, e_downfold=e3 + static, c2=c2, u3=u3,
                    u3_EA=u3_EA, u3_IP=u3_IP,
                    schur=0.0, Z=1.0, homo_wt=float(X3[homo_index, 0] ** 2),
                    conv=bool(conv3.all()))

    # ---- 3h2p / 3p2h Schur weights w = V^T|p| (matrix-free) ----
    cfg2I, cfg2E = rsolver._kconfigs('IP', 2), rsolver._kconfigs('EA', 2)
    wI = (u2_k2_dot_orb(rsolver, 'IP', p_orb, u2r_module, extra_leaves, laplace_ntau=laplace_ntau)
          + K2_CLASS_SIGN['IP'] * restricted_class_matvec(
              k2r_module, 'apply_c1_3h2p_2h1p_', p_IP, cfg2I, pool, no, nv, cfg_ket=cfgI))
    wE = (u2_k2_dot_orb(rsolver, 'EA', p_orb, u2r_module, extra_leaves, laplace_ntau=laplace_ntau)
          + K2_CLASS_SIGN['EA'] * restricted_class_matvec(
              k2r_module, 'apply_c1_3p2h_2p1h_', p_EA, cfg2E, pool, no, nv, cfg_ket=cfgE))
    K2I, K2E = cfg2I['K'], cfg2E['K']

    num = np.concatenate([wI ** 2, wE ** 2])
    pol = np.concatenate([K2I, K2E])
    branch = {}
    om, z = solve_qp_equation_poles(num, pol, e3 + static,
                                    label='ADC(4) diagonal downfold', out=branch)
    return dict(e_adc3=e3, e_downfold=om, c2=c2, u3=u3,
                u3_EA=u3_EA, u3_IP=u3_IP,
                schur=float(np.sum(num / (om - pol))), Z=z, branch=branch,
                homo_wt=float(X3[homo_index, 0] ** 2), conv=bool(conv3.all()))


# =====================================================================
# Eigensolves of the sigma operators go through solve.follow_roots (solve_symmetric, the
# Jacobi-Davidson preconditioner on the zeroth-order K diagonal). diag
# construction (the "K diagonal"), by operator:
#   full_adc4_operator:  concat([eps, diag_K(eps,no,nb,'IP'), diag_K(...,'EA'),
#                                diag_K(...,'IP',k=2), diag_K(...,'EA',k=2)])
#   restricted_sector_operator:  concat([eps, cfg['K']])   (cfg=_sector_configs)
#   restricted_full_operator:    concat([eps, cfg1['K'], cfg2['K']])
# =====================================================================


def solve_dyson_adc_downfolded(rsolver, homo_index, level='adc4', extra_leaves=None,
                               f_orb=None, tol=1e-7, max_outer=ADC_DOWNFOLD_MAX_OUTER,
                               c1r_module=None, c2r_module=None, s2cr_module=None,
                               k2r_module=None, u2r_module=None, davidson_tol=None,
                               u3_matrix_free=True, laplace_ntau=None,
                               verbose=False, v0=None, max_rank=None,
                               construction=None, on_shell=False, max_cycle=200):
    """TRUE DOWNFOLDED ADC(n) -- the downfolded ADC(n), which is
    mathematically IDENTICAL to full ADC(n), not an approximation.

    Davidson runs in the k<=1 space {orbital + 2h1p + 2p1h} only; the
    3-particle (k=2) manifold is folded out EXACTLY by its Schur complement

        M(omega) = A11 + A12 (omega - K2)^-1 A21

    which is exact because the (2,2) block of ADC(4) is order 0 -- i.e. K2 is
    DIAGONAL (adc_order_rule.block_order(4,2,2) == 0, see
    tests/test_adc_order_rule_manifold.py). At ADC(5) that block becomes order
    1 and this routine's `K2 diagonal` assumption STOPS BEING VALID; it asserts
    on that rather than silently returning a wrong number.

    **This is an EVEN-ORDER routine, generally.** The top manifold present at
    ADC(n) is kmax = n//2, and its self-block carries order
    `n - 2*kmax`, which is **0 for every even n and 1 for every odd n**. So the
    closed-form Schur above is exact for ADC(2), ADC(4), ADC(6), ... and invalid
    for ADC(3), ADC(5), ADC(7), ... -- not a special fact about ADC(4). At odd
    orders the folded manifold has a genuine C^(1) self-coupling, so
    `(omega - K2)^-1` becomes a real linear solve rather than a reciprocal, and
    the fold must be done iteratively (or the manifold kept explicit).

    Why it exists: `restricted_dyson_operator(level='adc4')` carries the k=2
    manifold explicitly in the Davidson SUBSPACE, so every subspace vector is
    (n_k1 + n_k2)-long -- Ar/aug-cc-pVTZ ran >1 h that way. Here the subspace
    vectors are only (norb + n_2h1p + n_2p1h)-long and the k=2 space is touched
    one transient vector at a time.

    NOT to be confused with `solve_dyson_adc4_downfold`, which additionally
    freezes the ADC(3) eigenvector -- that is the DIAGONAL approximation, the
    decisive one. This routine makes no such approximation: the k<=1 vector is
    fully relaxed at the ADC(4) level.

    Implementation note: A11/A12/A21 are obtained from the ALREADY-VALIDATED
    full operator by padding and slicing (one full matvec per block
    application), NOT re-derived. Two matvecs per application vs one, in
    exchange for zero new sign/convention risk -- the couplings and the k=2
    class-basis signs (K2_CLASS_SIGN) are exactly the ones the full operator
    already uses and the parity gates already cover.

    omega enters nonlinearly, so the eigenproblem is solved by outer
    self-consistency on omega with an inner Davidson at fixed omega.
    Returns dict with e (converged root), vec (k<=1 eigenvector), n_outer, and
    the k<=1/k=2 dimensions; schur_pole_clamped is True when an outer omega
    came within ADC_SCHUR_POLE_GUARD of a k=2 pole (warned once).

    v0: optional (n1,) seed vector, overriding the default Koopmans unit
    vector at homo_index -- e.g. an ADC(3) eigenvector for a satellite root
    (same k<=1 space, so no padding beyond the usual _pad/_pad2 needed).
    Without this, root-following can only ever reach states dominated by a
    single orbital's character, since |overlap|-based `follow` is biased
    toward whatever shares homo_index's character. Normalized internally.

    max_rank=2: forwarded to restricted_dyson_operator -- level='adc4' with
    every triples (t3/l3) amplitude dependence removed (its ONLY rank-3
    content is U^(3)'s two l3 stitches; see _sector_data's docstring for why
    this is the COMPLETE truncation, not a partial one). Still exact-shaped:
    the SAME k=2 Schur complement (the '5-particle resolvent') is folded in
    fully self-consistently -- only the amplitude RANK feeding the operator
    is truncated, not the manifold. This is the 'adc4t2' level.
    """

    n_order = {'adc3': 3, 'adc4': 4}.get(level)
    if n_order is not None and kmax(n_order) >= 2:
        # Guard only where there IS a k=2 manifold to fold. Testing
        # block_order(n,2,2) unconditionally rejected level='adc3', whose
        # kmax is 1 -- block_order(3,2,2) is -1, i.e. "no such block", not
        # "a nonzero one". Nothing to fold there, so nothing to guard.
        bo = block_order(n_order, 2, 2)
        if bo != 0:
            raise NotImplementedError(
                f"level={level!r} (ADC({n_order})) has (2,2) block order {bo}; "
                f"the k=2 manifold is no longer diagonal, so the closed-form "
                f"Schur complement used here is invalid. This routine is exact "
                f"for EVEN orders only (n - 2*(n//2) == 0); odd orders need an "
                f"iterative fold or an explicit k=2 manifold.")

    op, diag = restricted_dyson_operator(
        rsolver, level, extra_leaves=extra_leaves, f_orb=f_orb,
        c1r_module=c1r_module, c2r_module=c2r_module, s2cr_module=s2cr_module,
        k2r_module=k2r_module, u2r_module=u2r_module, laplace_ntau=laplace_ntau,
        u3_matrix_free=u3_matrix_free, max_rank=max_rank, construction=construction)
    norb = rsolver.norb
    nI = len(rsolver._sector_configs('IP')['K'])
    nE = len(rsolver._sector_configs('EA')['K'])
    n1 = norb + nI + nE
    n_tot = op.shape[0]
    n2 = n_tot - n1
    if n2 <= 0:
        raise ValueError(f"level={level!r} has no k=2 manifold to downfold")
    K2 = diag[n1:]
    diag1 = diag[:n1]

    def _pad(x1):
        v = np.zeros(n_tot)
        v[:n1] = x1
        return v

    def _pad2(y2):
        v = np.zeros(n_tot)
        v[n1:] = y2
        return v

    clamped = []

    def make_op(omega):
        shift = omega - K2
        # guard: a pole of the Schur term sitting on the current omega. The
        # guard keeps the side of the pole (copysign) and is a numerical
        # event: warned once, flagged as 'schur_pole_clamped'.
        near = np.abs(shift) < ADC_SCHUR_POLE_GUARD
        if near.any():
            if not clamped:
                warnings.warn(f"solve_dyson_adc_downfolded: omega = {omega:.12f} Ha sits "
                              f"within {ADC_SCHUR_POLE_GUARD:g} Ha of {int(near.sum())} k=2 "
                              f"pole(s); (omega - K2) is held at that distance "
                              f"(schur_pole_clamped)", RuntimeWarning, stacklevel=3)
            clamped.append(float(omega))
            shift = np.where(near, np.copysign(ADC_SCHUR_POLE_GUARD, shift), shift)

        def matvec(x1):
            x1 = np.asarray(x1).reshape(-1)
            full = op.matvec(_pad(x1))
            y1 = full[:n1]                      # A11 x1
            w2 = full[n1:]                      # A21 x1
            back = op.matvec(_pad2(w2 / shift))
            return y1 + back[:n1]               # + A12 (omega-K2)^-1 A21 x1

        return LinearOperator((n1, n1), matvec=matvec, dtype=float)

    v0 = koopmans_seed(n1, homo_index, v0, 'norb + n2h1p + n2p1h, the k<=1 space')
    dtol = davidson_tol if davidson_tol is not None else min(tol, ADC_DOWNFOLD_DAVIDSON_TOL_CAP)

    # seed omega from the k<=1-only problem (Schur term switched off)
    w, X, conv = follow_roots(LinearOperator((n1, n1),
                                             matvec=lambda x: op.matvec(_pad(np.asarray(x).reshape(-1)))[:n1],
                                             dtype=float),
                              diag1, v0, tol=dtol, max_cycle=max_cycle)
    omega, vec = float(w[0]), X[:, 0]

    if on_shell:
        max_outer = 1         # the on-shell scheme: one outer step, no self-consistency
    for it in range(max_outer):
        # WARM START: seed the subspace with the previous converged vector as
        # well as the HOMO unit vector. Re-seeding from the unit vector alone
        # made every outer iteration re-converge from scratch -- the dominant
        # cost of this solver. The unit vector is retained in the guess space
        # so `follow` still tracks the intended root.
        guess = np.column_stack([v0, vec]) if it else v0
        w, X, conv = follow_roots(make_op(omega), diag1, guess, tol=dtol,
                           max_cycle=max_cycle)
        new = float(w[0])
        vec = X[:, 0]
        if verbose:
            print(f"    outer {it + 1}: omega = {new:.10f} Ha "
                  f"(d = {(new - omega) * HARTREE_TO_EV * 1000:+.3f} meV)", flush=True)
        if abs(new - omega) < tol:
            omega = new
            outer_conv = True
            break
        omega = new
    else:
        it = max_outer - 1
        outer_conv = on_shell             # one step is the scheme, not a failure
    if not outer_conv:
        warnings.warn(f"solve_dyson_adc_downfolded: omega not self-consistent after "
                      f"{max_outer} outer iterations (tol {tol:g} Ha); 'e' is the last "
                      f"iterate (conv False)", RuntimeWarning, stacklevel=2)

    return {'e': omega, 'vec': vec, 'n_outer': it + 1,
            'n_k1': n1, 'n_k2': n2, 'weight': float(vec[:norb] @ vec[:norb]),
            'conv': bool(conv.all()) and outer_conv, 'on_shell': bool(on_shell),
            'schur_pole_clamped': bool(clamped)}


def solve_dyson_adc(rsolver, homo_index, level='adc5', extra_leaves=None,
                    f_orb=None, c1r_module=None, c2r_module=None, s2cr_module=None,
                    k2r_module=None, u2r_module=None, laplace_ntau=None,
                    u3_matrix_free=True, tol=1e-8, follow=True, verbose=False,
                    construction=None, v0=None, max_cycle=200, decoupling_ntau=None):
    """End-to-end matrix-free Dyson-ADC(n) by EXPLICIT-MANIFOLD eigensolve --
    the single-function entry point for ODD orders (ADC(5)) that the even-order
    fold routines cannot serve.

    solve_dyson_adc_downfolded and solve_dyson_adc4_downfold fold the top (k=kmax) manifold
    out with the CLOSED-FORM Schur complement A11 + A12 (omega - K2)^-1 A21,
    which is exact ONLY when K2 is diagonal -- i.e. block_order(n, kmax, kmax)==0,
    true for EVEN n and false for ODD n (adc_order_rule; the 3h2p/3p2h self-block
    of ADC(5) carries a genuine order-1 C^(1) coupling). Rather than an iterative
    fold, this routine keeps EVERY manifold explicit in the Davidson subspace and
    diagonalizes the full operator directly: restricted_dyson_operator(level)
    already assembles the complete two-sector supermatrix
    {orb, 2h1p, 2p1h}[, {3h2p, 3p2h}] matrix-free, it is FREQUENCY-INDEPENDENT
    (a fixed Hermitian matrix, no omega self-consistency), so its eigenvalues ARE
    the ADC(n) poles -- exact for every order, odd included. The trade-off vs the
    downfold routines is subspace length: vectors are (norb + n_k1 [+ n_k2])-long
    rather than k<=1-sized (the k=2 manifold is carried, not folded); every block
    application is still matrix-free (no (n_k)^2 object), so it scales.

    level: any restricted_dyson_operator level ('adc3'/'adc4_base'/'adc4'/'adc5');
        'adc5' is the reason this exists. homo_index: orbital-block index of the
        root to follow (e.g. HOMO for the IP). laplace_ntau/extra_leaves(+ _df
        modules): Laplace-fused and/or density-fitted exactly as the operator
        documents. v0: optional seed to follow (length dim; default the
        homo_index unit vector). construction, decoupling_ntau: as the operator's.
        Returns dict(e, vec, Z, weight, n_k1, n_k2, dim, conv)."""
    op, diag = restricted_dyson_operator(
        rsolver, level, extra_leaves=extra_leaves, f_orb=f_orb,
        c1r_module=c1r_module, c2r_module=c2r_module, s2cr_module=s2cr_module,
        k2r_module=k2r_module, u2r_module=u2r_module, laplace_ntau=laplace_ntau,
        u3_matrix_free=u3_matrix_free, construction=construction,
        decoupling_ntau=decoupling_ntau)
    norb = rsolver.norb
    nI = len(rsolver._sector_configs('IP')['K'])
    nE = len(rsolver._sector_configs('EA')['K'])
    n = op.shape[0]
    v0 = koopmans_seed(n, homo_index, v0, 'the full explicit-manifold space')
    w, X, conv = follow_roots(op, diag, v0, tol=tol, follow=follow, max_cycle=max_cycle)
    e = float(w[0])
    vec = X[:, 0]
    if verbose:
        print(f"solve_dyson_adc({level}): e = {e:.10f} Ha  "
              f"Z = {float(vec[homo_index] ** 2):.4f}  dim = {n}", flush=True)
    return {'e': e, 'vec': vec, 'Z': float(vec[homo_index] ** 2),
            'weight': float(vec[:norb] @ vec[:norb]),
            'n_k1': nI + nE, 'n_k2': n - norb - nI - nE, 'dim': n,
            'conv': bool(conv.all())}


# =====================================================================
# DF/RI module registration for the ORDER-GENERAL U/S stitch assembly.
#
# _u_block_modules/_resolve_struct intentionally list only the full-g modules
# (they define WHICH structure exists where -- a DF twin holds exactly the
# same function set, so listing both would double-resolve). The DF choice is
# therefore made at STITCH time, by the same auto-detect convention
# _u3_pieces already uses: the caller supplying the B_aa RI leaf selects the
# `<module>_df` twin. Twins exist for all three stitch sources
# (adc3_u_blocks_restricted_df, adc4_u3_blocks_restricted_df,
# adc5_u4_blocks_restricted_df -- the last from
# sigma_codegen.generate_adc5_u4_restricted_df, closing U^(4)'s DF gap).
# =====================================================================

def _df_twin_module(mod):
    """DF/RI twin (module name + '_df') of a generated restricted block
    module, or None when no twin has been generated on this machine: the
    naming convention every restricted block generation follows
    (adc3_u_blocks_restricted -> adc3_u_blocks_restricted_df, ...), read
    through generated_modules like every other generated module."""
    name = mod.__name__.rsplit('.', 1)[-1] + '_df'
    return generated(name) if is_generated(name) else None


# =====================================================================
# ADC(5) C^(3): the ORDER-3 class-class increment as a MATVEC.
#
# The dense reference (BuildSuperMatrixADCnRestricted.c_block_generated(sec, 3))
# forms the (n_k1, n_k1) class-class object -- the same shape as the ~17.5 GB
# aug-cc-pVTZ S^(2) blocker u3_dot_orb exists to avoid. This is the matrix-free
# transcription: raw C^(3) split applies at their amplitude-order assignments
# (adc_order_rule) + the ISR/Loewdin corrections with Delta S^(2)/Delta S^(3)
# applied as s2c matvecs. Nothing (n_k1)^2 is ever formed.
# =====================================================================

# C^(3) structures whose generated DENSE blocks exist but are IDENTICALLY ZERO
# on this code path: every term forces the
# Fock factor into the off-diagonal f[o,v] slice, which vanishes for canonical
# HF -- and the class blocks always see canonical f (rsolver._rargs pins
# f_aa = diag(eps); the f_orb hook touches only the orbital-block matvec).
# generate_adc5_c3_apply_restricted deliberately emits NO apply twins for them,
# so the matvec assembly must skip them EXPLICITLY -- otherwise the resolver
# would classify them "pruned", which is true numerically but would hide the
# real reason and break the audit trail against the dense term list.
_C3_F_OV_ZERO = ('l2ft3', 'l1ft2')


def _resolve_class_apply_struct(name, tag, kind, c2r_module, s2cr_module,
                                c3r_module):
    """(module, apply-name prefix) holding the class-class APPLY functions of
    tag structure `name`, or None -- the matrix-free twin of
    BuildSuperMatrixADCnRestricted._resolve_class_struct. kind 'c' = the K+C
    superoperator element, 's' = the within-class overlap.

    Order-2 structures live in the adc4_base apply modules
    (apply_c2_{tag}_{name}_*, apply_s2c_{tag}_{name}_*); order-3 C structures
    in the ADC(5) C^(3) apply module (apply_c3_{tag}_{name}_*). There is NO
    order-3 s module to consult: pdaggerq pruned every s3c split, so
    Delta S^(3) comes entirely from the order-2 s2c structure evaluated at
    higher amplitude orders -- the order rule finds
    that reuse by enumeration, not by a hand list. None is AMBIGUOUS (pruned
    vs ungenerated), exactly as the dense resolver documents; the caller
    separates the two via class_struct_ungenerated."""
    if kind == 'c':
        mods = ((c2r_module, f'apply_c2_{tag}_{name}_'),
                (c3r_module, f'apply_c3_{tag}_{name}_'))
    else:
        mods = ((s2cr_module, f'apply_s2c_{tag}_{name}_'),)
    for mod, prefix in mods:
        if mod is not None and any(a.startswith(prefix) for a in dir(mod)):
            return mod, prefix
    return None


def assembled_c3_matvec_restricted(rsolver, sector, v_cfg, c1r_module=None,
                                   c2r_module=None, s2cr_module=None,
                                   c3r_module=None, extra_leaves=None,
                                   strict=True, laplace_ntau=None):
    """ADC(5)'s ORDER-3 class-class increment as a matvec: y = C^(3) @ v_cfg,
    fully matrix-free, reproducing BuildSuperMatrixADCnRestricted.
    c_block_generated(sector, 3) with NO (n_k1, n_k1) object ever formed
    (gate: tests/test_sigma_adc5_c3.py, < 1e-11 vs dense on LiH/H2O).

    This is the ORDER-3 INCREMENT ONLY. The full excitation-space matvec at
    ADC(5) is  K*v + C^(1)v + C^(2)v + C^(3)v, where the first three already
    exist (diag K + restricted_class_matvec on the c1 self apply +
    assembled_c2_matvec_restricted); this supplies the last term, so the k=1
    self-block sum mirrors c_block_generated summed over n = 0..3.

    Assembly (== assemble_kplusc at n=3 with S^(1) = 0 => Y^(1) = 0):

        C^(3) v = raw3 v  -  N^(2) (C^(1) v)                [normalization]
                  - 1/2 ( C^(1)(DS2 v) + DS2(C^(1) v) )     [Y^(2) x C^(1)]
                  - 1/2 ( K*(DS3 v)    + DS3(K*v)    )      [Y^(3) x K]

        raw3 v : every (tag structure x amplitude-order assignment) of
                 adc_order_rule.u_order_terms(3), each applied matrix-free --
                 the order-2 C^(2) split applies REUSED at higher amplitude
                 orders (vt2@t2^2, ft1@t1^3, l2ft2@(l2^1,t2^2)+(l2^2,t2^1))
                 plus the new order-3 C^(3) split applies (l2vt2, vt1, l1v).
        DS2 v  : s2c matvec at (l2^1, t2^1) - N^(2) v.
        DS3 v  : s2c matvec at (l2^1, t2^2) + s2c matvec at (l2^2, t2^1) --
                 Delta S^(3) is the order-2 s2c structure at higher amplitude
                 orders, since pdaggerq pruned every s3c split.

    Both Loewdin cross terms use that DS2/DS3 are symmetric (overlap blocks),
    so one apply serves matrix and transpose -- the same symmetry
    assembled_c2_matvec_restricted and _u3_apply_bwd already rely on.

    N^(3) is OMITTED -- on purpose, from BOTH places the dense assembly
    carries it (raw3 -= N^(3) K and Delta S^(3) -= N^(3) I): the two cancel
    IDENTICALLY in the class-class block,

        -N3 (K*v)  +  1/2 ( K*(N3 v) + N3 (K*v) )  =  0,

    checked numerically (scaling N^(3) by 0, 1/2, 2, -1 moves
    C^(3) by <= 1.2e-17 -- the orthonormalized block is normalization-
    invariant). N^(3) is directly validated elsewhere (exact norm series,
    6.6e-11) and does not gate this matvec
    either way; it also feeds the orbital<->k1 U^(n) coupling, a different
    object. (N^(2) cancels the same way against the Y^(2) x C^(1) pair; it is
    KEPT to stay term-for-term parallel with the dense assembly -- dropping
    it would require dropping the -N^(2) I inside DS2 too, and the C^(2)
    machinery this composes with keeps both.)

    l2ft3/l1ft2 (dense survivors, f[o,v]-zero on this path) are
    skipped explicitly via _C3_F_OV_ZERO; see that constant's comment.

    rsolver: BuildSuperMatrixADCnRestricted, READ-ONLY (config machinery,
    _amps_order amplitude map, N^(2)). Modules default to the full-g apply
    modules; pass the *_df twins + extra_leaves={'B_aa','B_bb'} for DF/RI.
    strict: raise (rather than silently under-compute) when a structure's
    apply module is missing or an amplitude order is unavailable.

    laplace_ntau (int): the PRODUCTION-FLOOR amplitude route. C^(3)'s SURVIVING
    structures are all rank<=2 (the rank>=3 ones -- l2ft3/l1ft2 -- are
    _C3_F_OV_ZERO); the only reason the exact path materializes rank>=3 is that
    _amps_order(3) builds t3_2/t4_2 (incl. the O(no^4 nv^4) t4_2, 30 TB at
    CO2/aVTZ) as RSPT intermediates for the order-3 singles T1^(3). Passing an
    int supplies every amplitude C^(3) consumes from _u3_amps_laplace (rank<=2
    order<=2 + a Laplace T1^(3)) so NO rank>=3 array is ever formed.

    The result is BIT-EXACT, not ntau-approximate: the single order-3 amplitude
    C^(3) enumerates, T1^(3), enters ONLY through the f-contracted `ft1`
    structure, whose Fock factor lands in the off-diagonal f[o,v] slice and
    VANISHES by Brillouin on the class blocks (f_aa=diag(eps) there).
    Every amplitude C^(3) actually multiplies is
    rank<=2 order<=2, identical in both providers -- so C^(3) has ZERO
    sensitivity to the rank>=3 content that the low-rank provider drops, and
    the ntau value is immaterial to the answer (verified bit-identical on
    NH3/sto-3g, where t3_2/t4_2 are genuinely nonzero). This is why C^(3),
    unlike U^(4)/U^(3)_k2, needs NO block Laplace fusion -- only that the
    provider stop materializing amplitudes it never uses. T1^(3) is still
    supplied (Laplace-fused, unused) so the `strict` enumeration is satisfied
    rather than raising a spurious missing-amp. None (default) = the exact
    materialized path."""
    if c1r_module is None:
        c1r_module = generated('adc4_c1_self_apply_restricted_blocks')
    if c2r_module is None:
        c2r_module = generated('adc4_c2_apply_restricted_blocks')
    if s2cr_module is None:
        s2cr_module = generated('adc4_c2_s2c_apply_restricted_blocks')
    if c3r_module is None:
        c3r_module = generated('adc5_c3_apply_restricted_blocks')
    tag = '2h1p' if sector == 'IP' else '2p1h'
    no, nv = rsolver.nocc, rsolver.nvir
    cfg = rsolver._sector_configs(sector)
    K = cfg['K']
    v_cfg = np.asarray(v_cfg, float).reshape(-1)
    # PRODUCTION-FLOOR amplitude route: _u3_amps_laplace supplies C^(3)'s
    # entire consumed set {L1_2,T1_2,T1_3,L2_1,T2_1,L2_2,T2_2} with T1^(3)
    # minimax-fused and t3_2/t4_2 NEVER materialized (see docstring). The
    # `strict` missing-amp check below is the safety net: a key this provider
    # lacks RAISES rather than silently under-computing.
    A = (rsolver._u3_amps_laplace(laplace_ntau) if laplace_ntau is not None
         else rsolver._amps_order(max_order=3))
    base = {**rsolver._rargs, **(extra_leaves or {})}
    n2 = rsolver.n2_norm()

    def amps(j, a, k, b):
        """{leafname: array} for l_j^(a) / t_k^(b); None if unavailable --
        same keying as the dense _class_raw_S / u_dot_orb_order."""
        ds = {}
        for lead, rank, order in (('L', j, a), ('T', k, b)):
            if not rank:
                continue
            key = f'{lead}{rank}_{order}'
            if key not in A:
                return None
            ds.update(A[key])
        return ds

    missing_amp, ungenerated = [], []

    def apply_terms(terms, kind, x):
        """sum over the order rule's (structure x amplitude assignment) list
        of (block @ x), each structure applied matrix-free at its assignment.
        Skips: pdaggerq-pruned structures (null) and the _C3_F_OV_ZERO pair
        (identically zero here, see above); collects genuinely-missing pieces
        for the strict check instead of silently under-computing."""
        acc = np.zeros_like(x)
        for t in terms:
            name = t[0]
            j, a, k, b = ((t[1], t[4], t[3], t[5]) if kind == 'c'
                          else (t[1], t[3], t[2], t[4]))
            if kind == 'c' and name in _C3_F_OV_ZERO:
                continue
            res = _resolve_class_apply_struct(name, tag, kind, c2r_module,
                                              s2cr_module, c3r_module)
            if res is None:
                if BuildSuperMatrixADCn.class_struct_ungenerated(name, kind):
                    ungenerated.append(name)
                continue
            ds = amps(j, a, k, b)
            if ds is None:
                missing_amp.append(f"{kind}:{name}(l{j}^{a},t{k}^{b})")
                continue
            mod, prefix = res
            acc = acc + restricted_class_matvec(mod, prefix, x, cfg,
                                                {**base, **ds}, no, nv)
        return acc

    def ds2(x):
        return apply_terms(s_order_terms(2), 's', x) - n2 * x

    def ds3(x):
        # NO - N^(3) x here: N^(3) omitted from both sides (see docstring).
        return apply_terms(s_order_terms(3), 's', x)

    def c1(x):
        return restricted_class_matvec(c1r_module, f'apply_c1_{tag}_', x,
                                       cfg, base, no, nv)

    raw3_v = apply_terms(u_order_terms(3), 'c', v_cfg)
    c1_v = c1(v_cfg)
    # Orbital-class Gram-Schmidt cross term -(S2^T U1 + h.c.) as a matvec, the
    # matrix-free twin of BuildSuperMatrixADCn._orbital_gs_cross. Without it this
    # matvec reproduces the pre-fix dense C^(3) (missing the orbital-GS step,
    # up to 23% off the exact effective block on LiH). Kept matrix-free: only
    # norb-dim intermediates, never the (ncfg,ncfg) product. Both S2 and U1 are
    # generated blocks (rsolver._u2_and_s2 / _u_block).
    u1 = rsolver._u_block(sector)              # (ncfg, norb)
    _, s2 = rsolver._u2_and_s2(sector)         # (ncfg, norb)
    cross_v = -(s2 @ (u1.T @ v_cfg)) - (u1 @ (s2.T @ v_cfg))

    out = (raw3_v
           - n2 * c1_v
           - 0.5 * (c1(ds2(v_cfg)) + ds2(c1_v))
           - 0.5 * (K * ds3(v_cfg) + ds3(K * v_cfg))
           + cross_v)

    if strict and (missing_amp or ungenerated):
        bits = []
        if ungenerated:
            bits.append(f"apply module not generated for "
                        f"{sorted(set(ungenerated))} (run sigma_codegen."
                        f"generate_adc5_c3_apply_restricted)")
        if missing_amp:
            bits.append(f"no amplitude at the required order for "
                        f"{sorted(set(missing_amp))}")
        raise RuntimeError(
            f"assembled_c3_matvec_restricted({sector}) would be silently "
            f"INCOMPLETE -- " + "; ".join(bits) +
            ". Pass strict=False only if a partial sum is intended.")
    return out


def build_sigma_operator(solver, nocc, level='adc3', static_correction=None,
                         u2_denom_dress=None, delta_u3_dress=False,
                         construction=None):
    """Compose `solver` (a spin-orbital ADCSolver) into a matrix-free
    (LinearOperator, diag) pair for the requested level.

    Returns (op, diag, norb): `op` the supermatrix LinearOperator, `diag` its
    zeroth-order K diagonal (Davidson preconditioner / seed), `norb` the
    orbital-block size. static_correction: optional (norb, norb) added to the
    F block. u2_denom_dress: determinant-wise Epstein-Nesbet dressing of the
    U^(2) T2^(1) denominator, forwarded to BuildSuperMatrixADCn; level 'adc4'
    has no EN dressing hook. delta_u3_dress ('adc4' only): add the emitted
    diagram rows du3 to the k1 coupling blocks (the diagram-side evaluation
    of the diagrammatic ADC(4); see delta_u3_dressing.py).
    construction (required at 'adc4', resolve_construction): 'twosector', 'union' (the 2h1p x
    2p1h cross block X^(2) carried, union-space ADC(4)) or 'diagrammatic'
    (the block decoupled into its order-3 image on the k1 couplings,
    cross_block_decoupling.delta_u_rows_k1 -- the same rows delta_u3_dress
    evaluates from diagrams, so the two are not combined)."""
    if level != 'adc3' and u2_denom_dress is not None:
        raise ValueError("build_sigma_operator: u2_denom_dress is only wired "
                         "for level='adc3' (U^(3)/C^(2) at 'adc4' have no "
                         "dressing hook)")
    if delta_u3_dress and level != 'adc4':
        raise ValueError("build_sigma_operator: delta_u3_dress is the order-4 "
                         "defect correction -- level='adc4' only")
    construction = resolve_construction(level, construction, 'build_sigma_operator: ')
    if construction != 'twosector' and level != 'adc4':
        raise ValueError(f"build_sigma_operator: construction={construction!r} "
                         "carries the 2h1p x 2p1h cross block, which enters at "
                         "ADC(4) -- level='adc4' only")
    if construction == 'diagrammatic' and delta_u3_dress:
        raise ValueError("build_sigma_operator: delta_u3_dress and construction="
                         "'diagrammatic' are two evaluations of the same order-4 "
                         "rows -- pass one")
    # the sigma apply modules exist once GenerateRuntime has written order 4
    _c1ap = generated('adc4_c1_self_apply_blocks')
    if level == 'adc4':
        _c2ap = generated('adc4_c2_apply_blocks')
        _s2ap = generated('adc4_c2_s2c_apply_blocks')
        _k2ap = generated('adc4_k2_apply_blocks')
    eps, g, norb = solver.eps, solver.g, solver.norb
    no, nv = nocc, norb - nocc
    f_orb = None if static_correction is None else np.diag(eps) + static_correction
    f_diag = eps if f_orb is None else np.diag(f_orb)

    gen = BuildSuperMatrixADCn(eps, g, nocc, u2_denom_dress=u2_denom_dress)
    U1, U2 = gen.u_2h1p_adc3(), gen.u_2p1h_adc3()          # U through order 2

    if level == 'adc3':
        pool = {'f': np.diag(eps), 'g': g, 'kd': np.eye(norb),
                'o': slice(0, nocc), 'v': slice(nocc, norb), 'no': no, 'nv': nv}
        op = full_adc3_operator(U1, U2, pool, eps, nocc, norb, _c1ap, f_orb=f_orb)
        diag = np.concatenate([f_diag, diag_K(eps, nocc, norb, 'IP'),
                               diag_K(eps, nocc, norb, 'EA')])
        return op, diag, norb

    if level != 'adc4':
        raise ValueError(f"build_sigma_operator: level={level!r} not supported "
                         "(only 'adc3', 'adc4').")

    if level == 'adc4':
        U1 = U1 + gen.u3_generated('IP')                   # U^(3) 2h1p
        U2 = U2 + gen.u3_generated('EA')                   # U^(3) 2p1h
    if delta_u3_dress:                                     # emitted diagram rows
        du1, du2 = delta_u3_rows(eps, g, nocc)
        U1 = U1 + du1
        U2 = U2 + du2
    x_block = None
    if construction != 'twosector':
        X = gen.cross_block_generated(2)                   # (2h1p, 2p1h) X^(2)
        if construction == 'union':
            x_block = X
        else:                                              # decoupled: order-3 image
            du1, du2 = delta_u_rows_k1(gen.u_2h1p(), gen.u_2p1h(),
                                       diag_K(eps, nocc, norb, 'IP'),
                                       diag_K(eps, nocc, norb, 'EA'), X)
            U1 = U1 + du1
            U2 = U2 + du2
    n2 = gen.n2_norm()
    # u2_k2_generated returns (n_k2, norb); full_adc4_operator wants
    # (norb, n_k2), hence the transpose. The k1<->k2 coupling itself carries
    # a separate sector-phase convention (K2_CLASS_SIGN), untouched here.
    U2_3h2p = gen.u2_k2_generated('IP').T
    U2_3p2h = gen.u2_k2_generated('EA').T
    mpn = MPnDensityDriver(eps, g, nocc)
    t2 = mpn.compute_t2_1()
    t1_2, _, _, _ = mpn.compute_order2_amplitudes(t2, max_rank=1)
    pool = {'f': np.diag(eps), 'g': g, 'kd': np.eye(norb),
            'o': slice(0, nocc), 'v': slice(nocc, norb), 'no': no, 'nv': nv,
            't2': t2, 'l2': to_l(t2, 2), 't1': t1_2, 'l1': to_l(t1_2, 1)}
    op = full_adc4_operator(U1, U2, U2_3h2p, U2_3p2h, pool, eps, n2, nocc, norb,
                            _c1ap, _c2ap, _s2ap, _k2ap, f_orb=f_orb, x_block=x_block)
    diag = np.concatenate([f_diag, diag_K(eps, nocc, norb, 'IP'),
                           diag_K(eps, nocc, norb, 'EA'),
                           diag_K(eps, nocc, norb, 'IP', k=2),
                           diag_K(eps, nocc, norb, 'EA', k=2)])
    return op, diag, norb
