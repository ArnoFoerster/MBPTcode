def u3_k2_dot_orb(rsolver, sector, p_orb, module, s12r_module,
                  extra_leaves=None):
    """MATRIX-FREE ADC(5) U^(3)_orbital<->k2 INCREMENT @ p_orb, reproducing
    BuildSuperMatrixADCn.u3_k2_generated (the order-3 (0,2) coupling, added on
    top of the order-2 U^(2)_k2):

        sign * [ (raw3 - N^(2) raw1)@p  -  (S3 - N^(2) S1)@(eps o p)
                 -  S12^T @ (U1 @ p) ]

    raw3/S3/raw1/S1 via k2_raw_dot_orb (no dense (n_k2, norb) coupling);
    S12^T @ w via the apply_s12_{tag2}_{tag1} transpose (adc5_s12 module);
    U1 = rsolver._u_block (the k1 U^(1))."""
    tag1 = '2h1p' if sector == 'IP' else '2p1h'
    tag2 = '3h2p' if sector == 'IP' else '3p2h'
    no, nv = rsolver.nocc, rsolver.nvir
    A = rsolver._amps_order(max_order=4)
    n2 = rsolver.n2_norm()
    eps = rsolver.eps
    epsp = eps * p_orb
    raw3 = k2_raw_dot_orb(rsolver, sector, p_orb, 3, 'u', module, A, extra_leaves)
    raw1 = k2_raw_dot_orb(rsolver, sector, p_orb, 1, 'u', module, A, extra_leaves)
    S3 = k2_raw_dot_orb(rsolver, sector, epsp, 3, 's', module, A, extra_leaves)
    S1 = k2_raw_dot_orb(rsolver, sector, epsp, 1, 's', module, A, extra_leaves)
    U1p = rsolver._u_block(sector) @ p_orb
    cfg1 = rsolver._sector_configs(sector)
    cfg2 = rsolver._kconfigs(sector, 2)
    pool = {**rsolver._rargs, **rsolver._amplitude_pool(), **(extra_leaves or {})}
    s12t_u1p = restricted_class_matvec(s12r_module, f'apply_s12_{tag2}_{tag1}_',
                                       U1p, cfg2, pool, no, nv, cfg_ket=cfg1)
    return K2_CLASS_SIGN[sector] * ((raw3 - n2 * raw1) - (S3 - n2 * S1)
                                     - s12t_u1p)


