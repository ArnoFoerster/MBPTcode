# the three constructions of the Dyson supermatrix: two-sector (the D x C
# cross blocks deleted), union space (carried), diagrammatic (decoupled).
# Through ADC(3) they coincide; from ADC(4) on they differ, and a run names
# its construction: there is no default.
CONSTRUCTIONS = ('twosector', 'union', 'diagrammatic')
CONSTRUCTION_LEVELS = ('adc4', 'adc4t2', 'adc5')


def resolve_construction(level, construction, where=''):
    """The construction `level` runs. At ADC(4) and higher
    (CONSTRUCTION_LEVELS) the caller names one of CONSTRUCTIONS and a missing
    one is refused: 'twosector' is the incomplete ISR supermatrix, 'union' and
    'diagrammatic' the complete ones. Below ADC(4) the three coincide and None
    means the two-sector operator."""
    if construction is not None and construction not in CONSTRUCTIONS:
        raise ValueError(f"{where}construction={construction!r}; expected one of "
                         f"{CONSTRUCTIONS}")
    if construction is None:
        if level in CONSTRUCTION_LEVELS:
            raise ValueError(
                f"{where}level={level!r} needs construction= (one of {CONSTRUCTIONS}): "
                f"from ADC(4) on the constructions differ and none is the default; "
                f"'twosector' is the incomplete ISR one, 'union' and 'diagrammatic' "
                f"the complete ones")
        return 'twosector'
    return construction


def class_full_shape(nocc, nvirt, k, sector):
    """Full (redundant) tensor shape of precursor class k: one `nocc` axis per
    hole then one `nvirt` axis per particle (holes-then-particles, the
    class_letters / class_configs axis order the generated applies use)."""
    conv = class_index_convention(k, sector)
    return (nocc,) * conv['nh'] + (nvirt,) * conv['np']


def local_configs(nocc, norb, k, sector):
    """class_configs with virtual axes localized to 0-based within the vir
    block (the generated apply functions output/consume localized vir axes,
    matching adc_autogenerated._class_idx)."""
    cols = class_configs(nocc, norb, k, sector)
    return tuple(c - nocc if (len(c) and c.min() >= nocc) else c for c in cols)


def scatter_to_full(v_cfg, nocc, norb, k, sector):
    """Config-space vector -> full redundant class-k tensor, mass only at the
    canonical ordered configs (zero elsewhere -- see module docstring)."""
    x_full = np.zeros(class_full_shape(nocc, norb - nocc, k, sector))
    x_full[local_configs(nocc, norb, k, sector)] = v_cfg
    return x_full


def gather_from_full(y_full, nocc, norb, k, sector):
    """Full class-k bra tensor -> config-space vector (canonical configs)."""
    return y_full[local_configs(nocc, norb, k, sector)]


def sigma_matvec(apply_fn, apply_args, v_cfg, nocc, norb, bra_k, ket_k, sector):
    """y_cfg = block_cfg @ v_cfg via the generated matrix-free apply_fn.

    apply_fn: a generated apply_* function, signature (*leaf_args, x=trial).
    apply_args: the positional leaf args (f, g/B, kd[, amps], o, v, no, nv)
        apply_fn takes before its trailing x.
    v_cfg: (n_ket_cfg,) config-space trial vector.
    bra_k/ket_k: precursor class order of the block's bra/ket
        (1 for 2h1p/2p1h, 2 for 3h2p/3p2h).
    Returns (n_bra_cfg,).
    """
    x_full = scatter_to_full(v_cfg, nocc, norb, ket_k, sector)
    y_full = apply_fn(*apply_args, x=x_full)
    return gather_from_full(y_full, nocc, norb, bra_k, sector)


# ---------------------------------------------------------------------
# Assembled matrix-free C^(2): the full ISR-Loewdin-corrected 2h1p/2p1h
# self-block matvec, reproducing adc_autogenerated.BuildSuperMatrixADCn.
# c2_block_generated WITHOUT forming any (ncfg, ncfg) block. Composes the
# raw C^(2) split applies + within-class S^(2) split applies (both sigma-
# driven) with the diagonal K and the scalar N^(2):
#
#   C2 v = raw_nc v - 1/2 ( K (s2 v) + s2 (K v) )
#   raw_nc = raw - N2 K,   s2 = s2_raw - N2 I,   K = diag(sum eps_part - sum eps_hole)
#
# (the exact order-2 output of isr_engine.assemble_kplusc({0:K, 2:raw_nc},
# lowdin_sqrt_inv_series({2:s2}, 2)); see that module.)
# ---------------------------------------------------------------------

def diag_K(eps, nocc, norb, sector, k=1):
    """Diagonal zeroth-order K over the class-k configs. SECTOR-DEPENDENT sign
    (matching the generated k0 block, which uses the reversed commutator
    [C_J, H] for IP -- the Dyson hole-propagator convention, see
    generate_adcn.superop_element_terms):
        EA (k=1, 2p1h): + (sum eps_part - sum eps_hole)   e.g. eps_a + eps_b - eps_i
        IP (k=1, 2h1p): - (sum eps_part - sum eps_hole)   e.g. eps_i + eps_j - eps_a
    eps is spin-orbital, absolute-indexed. (Verified: with a single
    parts-minus-holes sign the assembled C^(2) matched for EA but was off by
    ~2*|K| for IP; the sector flip is the generated K's own convention.)

    k selects the precursor class: k=1 is the 2h1p/2p1h diagonal (the default,
    used by the C^(2) assembly and the ADC(3) operator); k=2 is the 3h2p/3p2h
    diagonal K needed by the ADC(4) multi-class operator. The SAME
    holes-minus-parts (IP) / parts-minus-holes (EA) convention carries to k=2
    unchanged -- verified == adc4_base.build_supermatrix_adc4_base's
    eps[i]+eps[j]+eps[k]-eps[a]-eps[b] (3h2p) / eps[a]+eps[b]+eps[c]-eps[i]-eps[j]
    (3p2h) diagonals to machine zero."""
    conv = class_index_convention(k, sector)
    cols = class_configs(nocc, norb, k, sector)
    holes, parts = cols[:conv['nh']], cols[conv['nh']:]
    dk = np.zeros(len(cols[0]))
    for p in parts:
        dk = dk + eps[p]
    for h in holes:
        dk = dk - eps[h]
    return -dk if sector == 'IP' else dk


def sum_split_matvec(module, prefix, v_cfg, pool, nocc, norb, sector):
    """Sum of sigma_matvec over every surviving k1xk1 split-apply function in
    `module` whose name starts with `prefix{tag}_`, each fed the leaf/amp args
    its signature asks for from `pool` (introspected -- the surviving split set
    is pdaggerq's pruning, not hard-coded). Matrix-free analog of
    adc_autogenerated._sum_gathered."""
    tag = '2h1p' if sector == 'IP' else '2p1h'
    total = np.zeros(len(class_configs(nocc, norb, 1, sector)[0]))
    for name in dir(module):
        if not name.startswith(f'{prefix}{tag}_'):
            continue
        fn = getattr(module, name)
        args = tuple(pool[p] for p in inspect.signature(fn).parameters if p != 'x')
        total = total + sigma_matvec(fn, args, v_cfg, nocc, norb, 1, 1, sector)
    return total


def assembled_c2_matvec(v_cfg, sector, pool, eps, n2, nocc, norb,
                        c2_module, s2c_module):
    """Full ISR-assembled C^(2) matvec y = C2 @ v_cfg, matrix-free. `pool`
    maps every leaf/amp name the split-apply functions take (f, g, kd, o, v,
    no, nv, t2, l2, t1, ...) to its array. `n2` is the N^(2) normalization
    scalar (adc_autogenerated.n2_norm). c2_module/s2c_module hold the generated
    apply_c2_* / apply_s2c_* functions."""
    dk = diag_K(eps, nocc, norb, sector)
    Kv = dk * v_cfg
    raw_v = sum_split_matvec(c2_module, 'apply_c2_', v_cfg, pool, nocc, norb, sector)
    raw_nc_v = raw_v - n2 * Kv
    s2_v = sum_split_matvec(s2c_module, 'apply_s2c_', v_cfg, pool, nocc, norb, sector) - n2 * v_cfg
    s2_Kv = sum_split_matvec(s2c_module, 'apply_s2c_', Kv, pool, nocc, norb, sector) - n2 * Kv
    return raw_nc_v - 0.5 * (dk * s2_v + s2_Kv)


def sector_operator(sector, U, pool, eps, n2, nocc, norb,
                    c1_module, c2_module, s2c_module):
    """A scipy LinearOperator for the single-sector ADC(4)-base supermatrix

        H = [[ diag(eps_orb) , U^T                 ],
             [ U             , K + C^(1) + C^(2)    ]]

    over {orbitals (norb)} + {2h1p or 2p1h configs}, with the (ncfg, ncfg)
    excitation-space block applied ENTIRELY MATRIX-FREE: K diagonal, C^(1)
    via the generated self-block apply (c1_module), C^(2) via the ISR-
    assembled matvec (assembled_c2_matvec). The orbital block and the
    U coupling (norb x ncfg -- small, norb tiny) are dense.

    U: (ncfg, norb) generated coupling (H[cls, orb] = U, H[orb, cls] = U^T).
    Returns a scipy.sparse.linalg.LinearOperator of size (norb + ncfg).
    """
    dk = diag_K(eps, nocc, norb, sector)
    ncfg = len(dk)
    n = norb + ncfg
    c1_fn = getattr(c1_module, f"apply_c1_{'2h1p' if sector == 'IP' else '2p1h'}")
    c1_args = tuple(pool[p] for p in ('f', 'g', 'kd', 'o', 'v', 'no', 'nv'))

    def matvec(x):
        x = np.asarray(x).reshape(-1)
        vo, vc = x[:norb], x[norb:]
        yo = eps * vo + U.T @ vc
        yc = (U @ vo + dk * vc
              + sigma_matvec(c1_fn, c1_args, vc, nocc, norb, 1, 1, sector)
              + assembled_c2_matvec(vc, sector, pool, eps, n2, nocc, norb,
                                    c2_module, s2c_module))
        return np.concatenate([yo, yc])

    return LinearOperator((n, n), matvec=matvec, dtype=float)


def full_adc3_operator(U_2h1p, U_2p1h, pool, eps, nocc, norb, c1_module, f_orb=None):
    """A scipy LinearOperator for the FULL two-sector ADC(3) supermatrix

        H = [[ F         , U_2h1p^T        , U_2p1h^T        ],
             [ U_2h1p    , K_2h1p + C1_2h1p, 0               ],
             [ U_2p1h    , 0               , K_2p1h + C1_2p1h]]

    -- the level production ADCSolver.build_supermatrix builds (U through
    order 2, K + first-order C^(1), NO C^(2), no 3h2p). Both class-class
    blocks are applied MATRIX-FREE (K diagonal, C^(1) via the generated
    self-block applies); the orbital block and U couplings are dense (small).
    U_2h1p/U_2p1h: (ncfg, norb) generated U through order 2 (must match
    production's U -- e.g. BuildSuperMatrixADCn.u_*_adc3). Used by the
    read-only matrix-free-vs-production parity benchmark.

    f_orb: optional (norb, norb) orbital (F) block. Default (None) is the bare
    Koopmans diagonal diag(eps); pass diag(eps)+static_correction for the
    production ADC(3) F block (the static Sigma(infinity) term)."""
    dk1 = diag_K(eps, nocc, norb, 'IP')
    dk2 = diag_K(eps, nocc, norb, 'EA')
    n1, n2 = len(dk1), len(dk2)
    n = norb + n1 + n2
    c1_args = tuple(pool[p] for p in ('f', 'g', 'kd', 'o', 'v', 'no', 'nv'))
    c1_ip = getattr(c1_module, 'apply_c1_2h1p')
    c1_ea = getattr(c1_module, 'apply_c1_2p1h')
    fmv = (lambda vo: f_orb @ vo) if f_orb is not None else (lambda vo: eps * vo)

    def matvec(x):
        x = np.asarray(x).reshape(-1)
        vo = x[:norb]
        v1 = x[norb:norb + n1]
        v2 = x[norb + n1:]
        yo = fmv(vo) + U_2h1p.T @ v1 + U_2p1h.T @ v2
        y1 = (U_2h1p @ vo + dk1 * v1
              + sigma_matvec(c1_ip, c1_args, v1, nocc, norb, 1, 1, 'IP'))
        y2 = (U_2p1h @ vo + dk2 * v2
              + sigma_matvec(c1_ea, c1_args, v2, nocc, norb, 1, 1, 'EA'))
        return np.concatenate([yo, y1, y2])

    return LinearOperator((n, n), matvec=matvec, dtype=float)


def full_adc4_operator(U_2h1p, U_2p1h, U2_3h2p, U2_3p2h, pool, eps, n2,
                       nocc, norb, c1_module, c2_module, s2c_module, k2_module,
                       f_orb=None, x_block=None):
    """A scipy LinearOperator for the FULL multi-class ADC(4)
    supermatrix -- the biggest matrix-free gap over full_adc3_operator: it
    ADDS the 3h2p/3p2h precursor class and the C^(2) self-correction, matching
    adc4_base.build_supermatrix_adc4_base's layout (Schirmer-Cederbaum-Walter PRA 28,
    1237, Table I item (4) + Eq. B5b/B7/B8-9):

        H = | F        U_2h1p^T   U_2p1h^T   U2_3h2p    U2_3p2h  |
            | U_2h1p    A_2h1p     0          C1         0        |
            | U_2p1h    0          A_2p1h     0          C1       |
            | U2_3h2p^T C1^T       0          K_3h2p     0        |
            | U2_3p2h^T 0          C1^T       0          K_3p2h   |

    with A_{2h1p/2p1h} = K + C^(1) + C^(2) applied ENTIRELY matrix-free (K
    diagonal, C^(1) via the self-block apply, C^(2) via the ISR-assembled
    matvec). The 3h2p/3p2h self-block is EXACTLY the diagonal K_3h2p/K_3p2h
    (the class-class interaction is zero in strict ADC(4), Eq. 51), so it is
    applied as a plain diagonal and NEVER materialized. The 2h1p<->3h2p /
    2p1h<->3p2h coupling C^(1) is applied matrix-free in BOTH directions from
    k2_module (apply_c1_2h1p_3h2p forward, apply_c1_3h2p_2h1p transpose) -- the
    (n2h1p, n3h2p) dense coupling is the ~16 GB Ne/aVDZ wall, so neither
    direction is formed. Only the orbital block, the U couplings to the k=1
    classes, and U2_3h2p/3p2h (orbital x class, norb rows -- thin) are dense.

    ADC LEVEL is chosen by the caller via the U couplings passed in:
      * ADC(4)-base == build_supermatrix_adc4_base: U_2h1p/U_2p1h at order 2
        (BuildSuperMatrixADCn.u_*_adc3);
      * ADC(4) == build_supermatrix_adc4: add the generated U^(3) correction
        to the 2p1h coupling (U_2p1h = u_2p1h_adc3 + u3_generated('EA')), the
        lambda-oracle arbiter that supersedes the printed B3.
    (The C^(2) self-block is always the GENERATED ISR arbiter, which
    deliberately differs from production's Q4 form -- see the parity note in
    tests/test_sigma_adc4_full.py.)

    U_2h1p/U_2p1h: (ncfg1, norb) k=1 couplings. U2_3h2p/U2_3p2h: (norb, ncfg2)
    orbital->3h2p/3p2h couplings (adc4_base._U2_orbital_3h2p/3p2h). pool/eps/n2 as
    in assembled_c2_matvec. Returns a scipy LinearOperator of size
    norb + n2h1p + n2p1h + n3h2p + n3p2h.

    x_block: optional (n2h1p, n2p1h) union-space cross block X^(2) = (D|H^|C)
    (BuildSuperMatrixADCn.cross_block_generated) coupling the two k=1 classes,
    inserted as the (2h1p, 2p1h) block and its transpose: the union-space
    ADC(4) of Tarantelli and Cederbaum, PRA 45, 2790 (1992), exact through
    lambda^4. None (default) is the two-sector supermatrix above, bit for bit.
    """
    dk1 = diag_K(eps, nocc, norb, 'IP')
    dk2 = diag_K(eps, nocc, norb, 'EA')
    dkm1 = diag_K(eps, nocc, norb, 'IP', k=2)
    dkm2 = diag_K(eps, nocc, norb, 'EA', k=2)
    n1, ne2, m1, m2 = len(dk1), len(dk2), len(dkm1), len(dkm2)
    n = norb + n1 + ne2 + m1 + m2
    c1_ip = getattr(c1_module, 'apply_c1_2h1p')
    c1_ea = getattr(c1_module, 'apply_c1_2p1h')
    coup_ip = getattr(k2_module, 'apply_c1_2h1p_3h2p')      # 2h1p <- 3h2p
    coup_ipT = getattr(k2_module, 'apply_c1_3h2p_2h1p')     # 3h2p <- 2h1p (C1^T)
    coup_ea = getattr(k2_module, 'apply_c1_2p1h_3p2h')
    coup_eaT = getattr(k2_module, 'apply_c1_3p2h_2p1h')
    c1_args = tuple(pool[p] for p in ('f', 'g', 'kd', 'o', 'v', 'no', 'nv'))
    k2_args = tuple(pool[p] for p in inspect.signature(coup_ip).parameters if p != 'x')
    # The generated k=1<->k=2 coupling apply carries a uniform sector phase
    # relative to production's adc4_base._coupling_2h1p_3h2p/_2p1h_3p2h: IP gen =
    # -prod, EA gen = +prod (verified == to machine zero;
    # gauge-invariant in isolation, but the 3h2p sector coupling C^(1)
    # and the orbital->3h2p coupling U2_3h2p must share ONE 3h2p-basis
    # orientation to be mutually consistent). U2_3h2p/3p2h here is production's,
    # so we restore production's coupling convention -> the assembled supermatrix
    # is internally consistent AND matches build_supermatrix_adc4_base elementwise.
    # Both directions get the same phase (block + transpose flip together), so
    # the operator stays symmetric.
    ph_ip, ph_ea = -1.0, 1.0
    fmv = (lambda vo: f_orb @ vo) if f_orb is not None else (lambda vo: eps * vo)

    def matvec(x):
        x = np.asarray(x).reshape(-1)
        o0 = norb
        o1 = o0 + n1
        o2 = o1 + ne2
        o3 = o2 + m1
        vo = x[:o0]
        v1 = x[o0:o1]
        v2 = x[o1:o2]
        vm1 = x[o2:o3]
        vm2 = x[o3:]
        yo = (fmv(vo) + U_2h1p.T @ v1 + U_2p1h.T @ v2
              + U2_3h2p @ vm1 + U2_3p2h @ vm2)
        y1 = (U_2h1p @ vo + dk1 * v1
              + sigma_matvec(c1_ip, c1_args, v1, nocc, norb, 1, 1, 'IP')
              + assembled_c2_matvec(v1, 'IP', pool, eps, n2, nocc, norb,
                                    c2_module, s2c_module)
              + ph_ip * sigma_matvec(coup_ip, k2_args, vm1, nocc, norb, 1, 2, 'IP'))
        y2 = (U_2p1h @ vo + dk2 * v2
              + sigma_matvec(c1_ea, c1_args, v2, nocc, norb, 1, 1, 'EA')
              + assembled_c2_matvec(v2, 'EA', pool, eps, n2, nocc, norb,
                                    c2_module, s2c_module)
              + ph_ea * sigma_matvec(coup_ea, k2_args, vm2, nocc, norb, 1, 2, 'EA'))
        if x_block is not None:                       # union-space cross block
            y1 = y1 + x_block @ v2
            y2 = y2 + x_block.T @ v1
        ym1 = (U2_3h2p.T @ vo + dkm1 * vm1
               + ph_ip * sigma_matvec(coup_ipT, k2_args, v1, nocc, norb, 2, 1, 'IP'))
        ym2 = (U2_3p2h.T @ vo + dkm2 * vm2
               + ph_ea * sigma_matvec(coup_eaT, k2_args, v2, nocc, norb, 2, 1, 'EA'))
        return np.concatenate([yo, y1, y2, ym1, ym2])

    return LinearOperator((n, n), matvec=matvec, dtype=float)


# =====================================================================
# RESTRICTED (spin-free / RHF) config-space matrix-free driver.
#
# The restricted config space (BuildSuperMatrixADCnRestricted._sector_configs)
# is the alpha-Dyson sector: each config is a spatial (holes, particles) tuple
# PLUS a per-index spin pattern, and the generated restricted apply functions
# are one-per-Ms-conserving-spin-assignment (apply_c2_2h1p_vt2_aabaab, etc.).
# So a restricted class-class matvec dispatches per spin pattern: it is the
# faithful transcription of the dense BuildSuperMatrixADCnRestricted.
# _class_block_sum, with the "materialize the spatial block then index it at
# the config positions" step replaced by "scatter the trial onto the canonical
# spatial ket positions -> apply -> gather at the bra positions". No sign /
# multiplicity bookkeeping: distinct configs in one spin group have distinct
# spatial tuples (injective scatter), so the fold reproduces the dense
# gather exactly (same argument as the spin-orbital scatter, per spin block).
#
# These functions consume the front track's config machinery READ-ONLY -- the
# caller passes `cfg` (= rsolver._sector_configs(sector)) and `pool` (=
# {**rsolver._rargs, **rsolver._amplitude_pool()}); nothing in adc_autogenerated.py
# is edited (the spin-orbital half likewise imports class_configs read-only).
# =====================================================================

def _restricted_suffix(spin_row):
    """Spin pattern int row (0=alpha,1=beta) -> 'a'/'b' string, matching
    BuildSuperMatrixADCnRestricted._suffix (the generated apply-name suffix)."""
    return ''.join('a' if s == 0 else 'b' for s in spin_row)


def _cfg_cols(cfg):
    nh, npart = cfg['hole_sp'].shape[1], cfg['part_sp'].shape[1]
    return [cfg['hole_sp'][:, k] for k in range(nh)] + \
           [cfg['part_sp'][:, k] for k in range(npart)]


def restricted_class_matvec(module, prefix, v_cfg, cfg_bra, pool, no, nv, cfg_ket=None):
    """y_cfg = block_cfg @ v_cfg for a restricted class-class (or class-class
    COUPLING) block, fully matrix-free. Sums every surviving generated apply in
    `module` whose name is `{prefix}{suffix(bra_pat)}{suffix(ket_pat)}` (any
    split), dispatched per (bra spin pattern, ket spin pattern) exactly as
    BuildSuperMatrixADCnRestricted._class_block_sum / .coupling_k1_k2_generated,
    but folding the trial vector instead of forming the spatial block.

    module/prefix: e.g. (adc4_c2_apply_restricted_blocks, 'apply_c2_2h1p_') for
        the k=1 self-block, or (adc4_k2_apply_restricted_blocks,
        'apply_c1_2h1p_3h2p_') for the k=1<->k=2 coupling.
    cfg_bra: the OUTPUT (bra) class configs (rsolver._sector_configs / _kconfigs).
    cfg_ket: the folded (ket) class configs; defaults to cfg_bra (self-block).
        For a coupling, cfg_bra != cfg_ket (e.g. bra=k1, ket=k2) -- the trial is
        scattered onto the KET class's spatial tensor and gathered at the BRA
        class's positions. NO sign phase here (the caller applies
        K2_CLASS_SIGN); NO sign/multiplicity bookkeeping (injective scatter).
    pool: {leaf/amp name -> array}. no/nv: spatial occ/vir counts.
    v_cfg may carry trailing column axes when `module` is a batched twin
    (batched_apply.restricted_class_matmat); y_cfg then carries them too.
    """
    if cfg_ket is None:
        cfg_ket = cfg_bra
    v_cfg = np.asarray(v_cfg)
    bcols, kcols = _cfg_cols(cfg_bra), _cfg_cols(cfg_ket)
    knh = cfg_ket['hole_sp'].shape[1]
    knpart = cfg_ket['part_sp'].shape[1]
    shape = (no,) * knh + (nv,) * knpart + v_cfg.shape[1:]
    y_cfg = np.zeros((len(cfg_bra['K']),) + v_cfg.shape[1:])
    ub, ib = np.unique(cfg_bra['spins'], axis=0, return_inverse=True)
    uk, ik = np.unique(cfg_ket['spins'], axis=0, return_inverse=True)
    fns = [n for n in dir(module) if n.startswith(prefix)]
    for gj, kp in enumerate(uk):
        krows = np.where(ik == gj)[0]
        x_full = np.zeros(shape)
        x_full[tuple(c[krows] for c in kcols)] = v_cfg[krows]
        for gi, bp in enumerate(ub):
            brows = np.where(ib == gi)[0]
            tail = _restricted_suffix(bp) + _restricted_suffix(kp)
            y_full = None
            for name in fns:
                if not name.endswith(tail):
                    continue
                fn = getattr(module, name)
                args = [pool[p] for p in inspect.signature(fn).parameters if p != 'x']
                yf = fn(*args, x=x_full)
                y_full = yf if y_full is None else y_full + yf
            if y_full is not None:
                y_cfg[brows] += y_full[tuple(c[brows] for c in bcols)]
    return y_cfg


def assembled_c2_matvec_restricted(v_cfg, cfg, pool, n2, no, nv,
                                   c2r_module, s2cr_module, tag):
    """Restricted twin of assembled_c2_matvec: the full ISR-Loewdin C^(2)
    matvec y = C2 @ v_cfg, matrix-free, reproducing
    BuildSuperMatrixADCnRestricted.c2_block_generated WITHOUT forming any
    (ncfg, ncfg) block:

        C2 v = (raw - N^(2) K) v - 1/2 ( K (s2 v) + s2 (K v) )
        s2 = s2_raw - N^(2) I,   K = cfg['K'] (restricted sector diagonal)

    tag: '2h1p' (IP) or '2p1h' (EA) -- selects the apply-name prefix.
    """
    K = cfg['K']
    Kv = K * v_cfg
    raw_v = restricted_class_matvec(c2r_module, f'apply_c2_{tag}_', v_cfg, cfg, pool, no, nv)
    raw_nc_v = raw_v - n2 * Kv
    s2_v = restricted_class_matvec(s2cr_module, f'apply_s2c_{tag}_', v_cfg, cfg, pool, no, nv) - n2 * v_cfg
    s2_Kv = restricted_class_matvec(s2cr_module, f'apply_s2c_{tag}_', Kv, cfg, pool, no, nv) - n2 * Kv
    return raw_nc_v - 0.5 * (K * s2_v + s2_Kv)


def restricted_sector_operator(sector, rsolver, U, c1r_module, c2r_module, s2cr_module,
                               extra_leaves=None, f_orb=None):
    """SINGLE-SECTOR restricted block operator -- NOT a physical Dyson IP/EA
    supermatrix. WARNING: this couples the orbital (F) block to ONLY ONE k1
    class (2h1p for IP, 2p1h for EA), so its eigenvalues are NOT the physical
    IP/EA poles -- a Dyson pole needs the orbital coupled to BOTH 2h1p and 2p1h
    (the self-energy has hole AND particle parts). Using it as a solver gives
    ~ADC(2) energies (e.g. Ne/aVDZ 2p: 19.9 eV instead of the correct 21.4).
    For physical poles use restricted_dyson_operator (two-sector). This block
    operator is retained only as a validated building block / for the assembled
    C^(2) unit tests.

    A scipy LinearOperator for the single-sector RESTRICTED (spin-free) ADC(4)-base
    block over {spatial orbitals} + {alpha-sector 2h1p or 2p1h configs}, with the
    excitation-space block (K + C^(1) + C^(2)) applied ENTIRELY matrix-free via
    the restricted config-space driver:

        H = [[ diag(eps) , U^T                 ],
             [ U         , K + C^(1) + C^(2)    ]]

    rsolver: an BuildSuperMatrixADCnRestricted (used READ-ONLY for its config
        machinery + amplitude/leaf pool + N^(2)). U: (ncfg, norb) restricted
        coupling in the alpha-sector config order (e.g. rsolver.u_adc3(sector)
        for ADC(3), + rsolver.u3_generated(sector) for the ADC(4) 2p1h arbiter).
    c1r/c2r/s2cr_module: adc4_c1_self_apply_restricted_blocks,
        adc4_c2_apply_restricted_blocks, adc4_c2_s2c_apply_restricted_blocks
        (or their *_df_blocks twins for the DF path).
    extra_leaves: optional {name -> array} merged into the leaf pool, e.g.
        {'B_aa': ..., 'B_bb': ...} to drive the DF apply modules (whose funcs
        pull B_aa/B_bb instead of g_ssss). The full-g leaves stay in the pool
        too and are simply not referenced by the DF functions -- so passing the
        *_df_blocks modules + B here runs the whole excitation-space matvec off
        the RI factor with no (nso^4) g tensor touched. See test_sigma_
        restricted_df.py (spectrum == full-g with an exact RI factor).
    Returns a scipy LinearOperator of size norb + ncfg (spatial norb).
    """
    tag = '2h1p' if sector == 'IP' else '2p1h'
    eps = rsolver.eps
    norb = rsolver.norb
    no, nv = rsolver.nocc, rsolver.nvir
    cfg = rsolver._sector_configs(sector)
    pool = {**rsolver._rargs, **rsolver._amplitude_pool(), **(extra_leaves or {})}
    n2 = rsolver.n2_norm()
    K = cfg['K']
    ncfg = len(K)
    n = norb + ncfg
    fmv = (lambda vo: f_orb @ vo) if f_orb is not None else (lambda vo: eps * vo)

    def matvec(x):
        x = np.asarray(x).reshape(-1)
        vo, vc = x[:norb], x[norb:]
        yo = fmv(vo) + U.T @ vc
        yc = (U @ vo + K * vc
              + restricted_class_matvec(c1r_module, f'apply_c1_{tag}_', vc, cfg, pool, no, nv)
              + assembled_c2_matvec_restricted(vc, cfg, pool, n2, no, nv,
                                               c2r_module, s2cr_module, tag))
        return np.concatenate([yo, yc])

    return LinearOperator((n, n), matvec=matvec, dtype=float)




def restricted_full_operator(sector, rsolver, U1, U2_k2, k2r_module,
                             c1r_module, c2r_module, s2cr_module, extra_leaves=None,
                             f_orb=None):
    """SINGLE-SECTOR restricted multi-class block operator -- NOT a physical
    Dyson supermatrix (see restricted_sector_operator's warning: the orbital
    block couples to only one k1 class, so poles are ~ADC(2), not the physical
    IP/EA). For physical Dyson-ADC(4) poles use restricted_dyson_
    operator (two-sector) / solve_dyson_adc4_downfold. Retained as a building
    block.

    A scipy LinearOperator for the single-sector RESTRICTED (spin-free) FULL
    multi-class block -- restricted_sector_operator extended with the 3h2p/3p2h
    precursor class (the single-sector analog of full_adc4_operator):

        H = | diag(eps)  U1^T          U2_k2^T |
            | U1         K1+C^(1)+C^(2) C       |
            | U2_k2      C^T            K2       |

    K2 (= rsolver._kconfigs(sector,2)['K']) is the diagonal 3h2p/3p2h block (the
    class-class interaction is zero in strict ADC(4)); the k=1<->k=2 coupling C
    is applied matrix-free BOTH ways (apply_c1_{tag}_{tag2} forward,
    apply_c1_{tag2}_{tag} transpose) times K2_CLASS_SIGN[sector], matching
    rsolver.coupling_k1_k2_generated; the orbital<->k=2 U2_k2 (=
    rsolver.u2_k2_generated(sector), (n_k2, norb)) stays dense. Nothing in the
    (n_k2)^2 space is ever formed.

    U1: (n_k1, norb) restricted k=1 coupling (rsolver.u_adc3(sector), + u3 for
    ADC(4)-2p1h). rsolver: BuildSuperMatrixADCnRestricted, READ-ONLY.
    extra_leaves: optional {name -> array} merged into the leaf pool -- pass
    {'B_aa':..., 'B_bb':...} together with the *_df_blocks modules (c1r/c2r/
    s2cr/k2r) to run the FULL multi-class matvec off the RI factor (no g).
    Returns a scipy LinearOperator of size norb + n_k1 + n_k2.
    """
    tag = '2h1p' if sector == 'IP' else '2p1h'
    tag2 = '3h2p' if sector == 'IP' else '3p2h'
    eps = rsolver.eps
    norb = rsolver.norb
    no, nv = rsolver.nocc, rsolver.nvir
    cfg1 = rsolver._sector_configs(sector)
    cfg2 = rsolver._kconfigs(sector, 2)
    pool = {**rsolver._rargs, **rsolver._amplitude_pool(), **(extra_leaves or {})}
    n2 = rsolver.n2_norm()
    K1, K2 = cfg1['K'], cfg2['K']
    n1, nk2 = len(K1), len(K2)
    n = norb + n1 + nk2
    ph = K2_CLASS_SIGN[sector]
    fmv = (lambda vo: f_orb @ vo) if f_orb is not None else (lambda vo: eps * vo)

    def matvec(x):
        x = np.asarray(x).reshape(-1)
        vo = x[:norb]
        v1 = x[norb:norb + n1]
        v2 = x[norb + n1:]
        yo = fmv(vo) + U1.T @ v1 + U2_k2.T @ v2
        y1 = (U1 @ vo + K1 * v1
              + restricted_class_matvec(c1r_module, f'apply_c1_{tag}_', v1, cfg1, pool, no, nv)
              + assembled_c2_matvec_restricted(v1, cfg1, pool, n2, no, nv,
                                               c2r_module, s2cr_module, tag)
              + ph * restricted_class_matvec(k2r_module, f'apply_c1_{tag}_{tag2}_',
                                             v2, cfg1, pool, no, nv, cfg_ket=cfg2))
        y2 = (U2_k2 @ vo + K2 * v2
              + ph * restricted_class_matvec(k2r_module, f'apply_c1_{tag2}_{tag}_',
                                             v1, cfg2, pool, no, nv, cfg_ket=cfg1))
        return np.concatenate([yo, y1, y2])

    return LinearOperator((n, n), matvec=matvec, dtype=float)


# =====================================================================
# RESTRICTED TWO-SECTOR (Dyson) operator -- the PHYSICALLY CORRECT restricted
# IP/EA supermatrix.  The restricted_sector_operator / restricted_full_operator
# above are SINGLE-SECTOR (orbital + one k1 class): they omit the opposite
# sector's coupling to the shared orbital (F) block, so their poles are NOT the
# physical Dyson IP/EA (the orbital self-energy Sigma(w) has BOTH a hole (2h1p)
# and a particle (2p1h) part). A Dyson pole needs the orbital coupled to BOTH
# 2h1p AND 2p1h at once, exactly as BuildSuperMatrixADCnRestricted.
# build_supermatrix_adc3 (dim = norb + n2h1p + n2p1h) and the spin-orbital
# full_adc3_operator/full_adc4_operator do. This builds that two-sector operator
# matrix-free, optionally with C^(2), the 3h2p/3p2h class, and U^(3).
# =====================================================================

def _cross_pieces(rsolver, pair, order, df=False, extra_leaves=None):
    """[(module, forward prefix, transpose prefix, pool)] of the raw union-space
    D x C cross block `pair` at `order`: every u_order_terms(order) structure from
    its home module (searched from `order` down to the pair's leading order), with
    the restricted amplitudes of its order-rule assignment. The forward apply maps
    the C-type (EA) class onto the D-type (IP) class, the transpose back."""
    k_i, k_j = CROSS_PAIRS[pair]
    tag_d, tag_c = CLASS_TAGS[k_i]['IP'], CLASS_TAGS[k_j]['EA']
    lead = cross_block_leading_order(k_i, k_j)
    mods = [(o, cross_block_module(o, pair, df=df, apply=True))
            for o in range(order, lead - 1, -1)]
    A = rsolver._amps_order(max_order=max(order, 2))
    base = {**rsolver._rargs, **(extra_leaves or {})}
    pieces = []
    for nm, j, ham, k, a, b in u_order_terms(order):
        home = next(((o, mod) for o, mod in mods
                     if any(f.startswith(f'apply_x{o}_{tag_d}_{tag_c}_{nm}_') for f in dir(mod))),
                    None)
        if home is None:
            continue
        o, mod = home
        pool = dict(base)
        for lead_, rank, ordr in (('L', j, a), ('T', k, b)):
            if rank:
                leaves = A.get(f'{lead_}{rank}_{ordr}')
                if leaves is None:
                    raise RuntimeError(f"cross block {pair} order {order}: no restricted "
                                       f"amplitude {lead_}{rank}_{ordr} for {nm}")
                pool.update(leaves)
        pieces.append((mod, f'apply_x{o}_{tag_d}_{tag_c}_{nm}_',
                       f'apply_x{o}_{tag_c}_{tag_d}_{nm}_', pool))
    return pieces


def _cross_apply(pieces, direction, v_cfg, cfg_bra, cfg_ket, no, nv):
    """Sum of the cross-block pieces applied to a class trial: direction 0 the
    forward map (C-type ket onto the D-type bra), 1 its transpose."""
    return sum(restricted_class_matvec(mod, prefixes[direction], v_cfg, cfg_bra, pool, no, nv,
                                       cfg_ket=cfg_ket)
               for mod, *prefixes, pool in pieces)


def _map(x_map, n_out, n_in):
    """The linear map v -> x_map(v, False) (adjoint x_map(v, True)) as an
    (n_out, n_in) LinearOperator."""
    return LinearOperator((n_out, n_in), matvec=lambda v: x_map(np.ravel(v), False),
                          rmatvec=lambda v: x_map(np.ravel(v), True), dtype=float)


def _laplace_pair(K_d, K_c, ntau):
    """(K_d, K_c, tau, w, mu): the minimax fit 1/(K_c[b] - K_d[a]) = sum_t w_t
    exp(-tau_t (mu - K_d[a])) exp(-tau_t (K_c[b] - mu)) over the D x C pair's
    denominator range, mu in the gap so both factors stay <= 1."""
    lo, hi = float(K_c.min() - K_d.max()), float(K_c.max() - K_d.min())
    tau, w = minimax_time_grid(ntau, lo, hi)
    return K_d, K_c, tau, w, 0.5 * (float(K_d.max()) + float(K_c.min()))


def _decouple(grid, x_map, v, adj):
    """S v (C onto D) or S^T v (D onto C) of the decoupling amplitude
    S = X / (K_C - K_D), X applied by x_map(v, adj): ntau scaled applications."""
    K_d, K_c, tau, w, mu = grid
    out = 0.0
    for t, wt in zip(tau, w):
        e_d, e_c = np.exp(-t * (mu - K_d)), np.exp(-t * (K_c - mu))
        out = out + (wt * e_c * x_map(e_d * v, True) if adj
                     else wt * e_d * x_map(e_c * v, False))
    return out


def _decoupling_maps(rsolver, c1r_module, k2r_module, u2r_module, extra_leaves=None):
    """The linear maps the ADC(5) union and diagrammatic constructions are built
    from, each v -> block v (adj: block^T v), D = IP-type (2h1p, 3h2p) and C =
    EA-type (2p1h, 3p2h) classes:

        x2_11, x3_11   the effective 2h1p x 2p1h blocks at orders 2 and 3 (the order-3
                       one minus its class Gram-Schmidt S^(2) U^(1)^T + U^(1) S^(2)^T)
        x12, x21       the effective 2h1p x 3p2h and 3h2p x 2p1h blocks at order 2
                       (minus U^(1) S^(1)_k2^T: k2 overlaps the orbitals from order 1)
        c1, c1_12, c1_21   the first-order k1-k1 block and the k1 <- k2, k2 <- k1
                       couplings of one sector, k2 class phase included

    plus U^(1), U^(2) (n_k1, norb), the configs and their K."""
    no, nv = rsolver.nocc, rsolver.nvir
    pool = {**rsolver._rargs, **rsolver._amplitude_pool(), **(extra_leaves or {})}
    cfg1 = {sec: rsolver._sector_configs(sec) for sec in ('IP', 'EA')}
    cfg2 = {sec: rsolver._kconfigs(sec, 2) for sec in ('IP', 'EA')}
    ph = K2_CLASS_SIGN
    tag1 = {'IP': '2h1p', 'EA': '2p1h'}
    tag2 = {'IP': '3h2p', 'EA': '3p2h'}
    p11_2 = _cross_pieces(rsolver, 'k1k1', 2, extra_leaves=extra_leaves)
    p11_3 = _cross_pieces(rsolver, 'k1k1', 3, extra_leaves=extra_leaves)
    p12 = _cross_pieces(rsolver, 'k1k2', 2, extra_leaves=extra_leaves)
    p21 = _cross_pieces(rsolver, 'k2k1', 2, extra_leaves=extra_leaves)
    U1 = {sec: rsolver._u_block(sec) for sec in ('IP', 'EA')}
    S2o = {sec: rsolver._u2_and_s2(sec)[1] for sec in ('IP', 'EA')}

    def s1k2(sec, p):
        return s1_k2_dot_orb(rsolver, sec, p, u2r_module, extra_leaves)

    def s1k2_t(sec, v2):
        return orb_dot_s1_k2(rsolver, sec, v2, u2r_module, extra_leaves)

    def x2_11(v, adj):
        if adj:
            return _cross_apply(p11_2, 1, v, cfg1['EA'], cfg1['IP'], no, nv)
        return _cross_apply(p11_2, 0, v, cfg1['IP'], cfg1['EA'], no, nv)

    def x3_11(v, adj):
        if adj:
            return (_cross_apply(p11_3, 1, v, cfg1['EA'], cfg1['IP'], no, nv)
                    - U1['EA'] @ (S2o['IP'].T @ v) - S2o['EA'] @ (U1['IP'].T @ v))
        return (_cross_apply(p11_3, 0, v, cfg1['IP'], cfg1['EA'], no, nv)
                - S2o['IP'] @ (U1['EA'].T @ v) - U1['IP'] @ (S2o['EA'].T @ v))

    def x12(v, adj):
        if adj:
            return (ph['EA'] * _cross_apply(p12, 1, v, cfg2['EA'], cfg1['IP'], no, nv)
                    - s1k2('EA', U1['IP'].T @ v))
        return (ph['EA'] * _cross_apply(p12, 0, v, cfg1['IP'], cfg2['EA'], no, nv)
                - U1['IP'] @ s1k2_t('EA', v))

    def x21(v, adj):
        if adj:
            return (ph['IP'] * _cross_apply(p21, 1, v, cfg1['EA'], cfg2['IP'], no, nv)
                    - U1['EA'] @ s1k2_t('IP', v))
        return (ph['IP'] * _cross_apply(p21, 0, v, cfg2['IP'], cfg1['EA'], no, nv)
                - s1k2('IP', U1['EA'].T @ v))

    def c1(sec, v):
        return restricted_class_matvec(c1r_module, f'apply_c1_{tag1[sec]}_', v, cfg1[sec],
                                       pool, no, nv)

    def c1_12(sec, v2):
        return ph[sec] * restricted_class_matvec(
            k2r_module, f'apply_c1_{tag1[sec]}_{tag2[sec]}_', v2, cfg1[sec], pool, no, nv,
            cfg_ket=cfg2[sec])

    def c1_21(sec, v1):
        return ph[sec] * restricted_class_matvec(
            k2r_module, f'apply_c1_{tag2[sec]}_{tag1[sec]}_', v1, cfg2[sec], pool, no, nv,
            cfg_ket=cfg1[sec])

    return dict(x2_11=x2_11, x3_11=x3_11, x12=x12, x21=x21, c1=c1, c1_12=c1_12, c1_21=c1_21,
                U1=U1, U2={sec: rsolver.u_adc3(sec) - U1[sec] for sec in ('IP', 'EA')},
                K1={sec: cfg1[sec]['K'] for sec in cfg1},
                K2={sec: cfg2[sec]['K'] for sec in cfg2})


def _diagrammatic_adc5_rows(rsolver, c1r_module, k2r_module, u2r_module, extra_leaves=None,
                            laplace_ntau=None, decoupling_ntau=None):
    """Coupling rows that turn the two-sector ISR-ADC(5) supermatrix into
    diagrammatic ADC(5): the union-space cross blocks decoupled order by order by
    W = exp(S), S antisymmetric on the D x C positions with S^(m)_ab = R^(m)_ab /
    (K_b - K_a) (Tarantelli and Cederbaum, PRA 45, 2790 (1992)). Through the
    orders ADC(5) carries, W^T D W keeps every same-sector block and B W only adds

        k1 rows:  B^(1) S^(2)  (order 3)  +  B^(2) S^(2) + B^(1) S^(3)  (order 4)
        k2 rows:  B^(1) S^(2)  (order 3)

    with S^(2) from the effective X^(2) of the k1-k1, k1-k2 and k2-k1 pairs and, on
    k1-k1, R^(3) = X_eff^(3) + S^(2)^T C^(1) + C^(1) S^(2) (C^(1) the first-order
    class block, k1<->k2 coupling included); see _decoupling_maps. Returns
    {(sector, 1): (n_k1, norb), (sector, 2): (n_k2, norb)} in the operator's config
    orders, built one orbital column at a time.

    decoupling_ntau: None forms the S^(m) densely, exact (validation scale: the
    2h1p x 3p2h block is n_2h1p x n_3p2h); an int applies every S as the minimax
    Laplace quadrature of 1/(K_C - K_D) on that many points (_decouple), so no
    D x C block is formed and S^(3), whose R^(3) holds S^(2), costs ntau^2 block
    applications per column. The quadrature converges with ntau to the exact rows."""
    m = _decoupling_maps(rsolver, c1r_module, k2r_module, u2r_module, extra_leaves)
    x2_11, x3_11, x12, x21 = m['x2_11'], m['x3_11'], m['x12'], m['x21']
    c1, c1_12, c1_21 = m['c1'], m['c1_12'], m['c1_21']
    U1, U2, K1, K2 = m['U1'], m['U2'], m['K1'], m['K2']
    norb = rsolver.norb
    n1 = {sec: len(K1[sec]) for sec in K1}
    n2 = {sec: len(K2[sec]) for sec in K2}
    if decoupling_ntau is None:
        D11 = K1['EA'][None, :] - K1['IP'][:, None]
        S11 = dense_of(_map(x2_11, n1['IP'], n1['EA']), (n1['IP'], n1['EA'])) / D11
        S12 = (dense_of(_map(x12, n1['IP'], n2['EA']), (n1['IP'], n2['EA']))
               / (K2['EA'][None, :] - K1['IP'][:, None]))
        S21 = (dense_of(_map(x21, n2['IP'], n1['EA']), (n2['IP'], n1['EA']))
               / (K1['EA'][None, :] - K2['IP'][:, None]))
        R3 = (dense_of(_map(x3_11, n1['IP'], n1['EA']), (n1['IP'], n1['EA']))
              - np.array([c1('EA', row) for row in S11])
              - np.array([c1_12('EA', row) for row in S12])
              + np.column_stack([c1('IP', col) for col in S11.T])
              + np.column_stack([c1_12('IP', col) for col in S21.T]))
        S3 = R3 / D11
        del R3

        def dense(S):
            return lambda v, adj: S.T @ v if adj else S @ v
        s2_11, s2_12, s2_21, s3_11 = dense(S11), dense(S12), dense(S21), dense(S3)
    else:
        g11 = _laplace_pair(K1['IP'], K1['EA'], decoupling_ntau)
        g12 = _laplace_pair(K1['IP'], K2['EA'], decoupling_ntau)
        g21 = _laplace_pair(K2['IP'], K1['EA'], decoupling_ntau)

        def s2_11(v, adj):
            return _decouple(g11, x2_11, v, adj)

        def s2_12(v, adj):
            return _decouple(g12, x12, v, adj)

        def s2_21(v, adj):
            return _decouple(g21, x21, v, adj)

        def r3(v, adj):
            if adj:
                return (x3_11(v, True) - c1('EA', s2_11(v, True)) - c1_12('EA', s2_12(v, True))
                        + s2_11(c1('IP', v), True) + s2_21(c1_21('IP', v), True))
            return (x3_11(v, False) - s2_11(c1('EA', v), False) - s2_12(c1_21('EA', v), False)
                    + c1('IP', s2_11(v, False)) + c1_12('IP', s2_21(v, False)))

        def s3_11(v, adj):
            return _decouple(g11, r3, v, adj)

    rows = {(sec, k): np.empty(((n1 if k == 1 else n2)[sec], norb))
            for sec in ('IP', 'EA') for k in (1, 2)}
    e = np.zeros(norb)
    for p in range(norb):
        e[p] = 1.0
        u1 = {sec: U1[sec][:, p] for sec in ('IP', 'EA')}
        y = {sec: u1[sec] + U2[sec][:, p] for sec in ('IP', 'EA')}
        rows[('EA', 1)][:, p] = (s2_11(y['IP'], True) + s3_11(u1['IP'], True)
                                 + s2_21(u2_k2_dot_orb(rsolver, 'IP', e, u2r_module,
                                                       extra_leaves, laplace_ntau), True))
        rows[('IP', 1)][:, p] = -(s2_11(y['EA'], False) + s3_11(u1['EA'], False)
                                  + s2_12(u2_k2_dot_orb(rsolver, 'EA', e, u2r_module,
                                                        extra_leaves, laplace_ntau), False))
        rows[('EA', 2)][:, p] = s2_12(u1['IP'], True)
        rows[('IP', 2)][:, p] = -s2_21(u1['EA'], False)
        e[p] = 0.0
    return rows


def _sector_data(rsolver, sector, level, extra_leaves, s2cr_module=None,
                 laplace_ntau=None, u3_matrix_free=True, max_rank=None):
    """Per-sector pieces for the two-sector Dyson operator: k1 configs/K, the
    order-2 (+U^(3) for adc4/EA) U coupling, and -- for adc4_base/adc4 -- the k2
    (3h2p/3p2h) configs/K and the class phase. The orbital<->k2 U^(2) coupling
    is NOT built here -- `matvec` applies it matrix-free in both directions
    (u2_k2_dot_orb / orb_dot_u2_k2) so the dense
    (n_k2, norb) object (and its (k2_spatial, norb) build transient -- the
    ~500 GB peak the profiler traced to this line) is never formed.

    max_rank=2: passed straight through to _u3_pieces -- drops U^(3)'s two
    l3-consuming stitches (its ONLY rank-3 content; see u3_dot_orb). Nothing
    ELSE in this operator ever touches t3/l3: C^(2) (assembled_c2_matvec_
    restricted) is rank<=2 pure by construction, the orbital<->k2 U^(2)
    coupling (u2_k2_dot_orb/orb_dot_u2_k2) consumes ONLY L2_1/L1_2/L2_2 (see
    its docstring), and the k1<->k2 C^(1) coupling + K2 diagonal are
    amplitude-free entirely (bare Hamiltonian matrix elements) -- so
    max_rank=2 here is already the COMPLETE 'no triples anywhere' truncation
    of the full ADC(4) operator, not a partial one."""
    tag = '2h1p' if sector == 'IP' else '2p1h'
    tag2 = '3h2p' if sector == 'IP' else '3p2h'
    cfg1 = rsolver._sector_configs(sector)
    U1 = rsolver.u_adc3(sector)
    if level in ('adc4', 'adc5'):
        # U^(3) on BOTH sectors. This was previously 2p1h(EA)-only, which made
        # 'adc4' a PARTIAL ADC(4): for an IP the dominant 2h1p sector was left at
        # adc4_base order while only 2p1h carried the order-3 U. The 2h1p U^(3)
        # blocks exist (54 u3_2h1p_* functions) and are codegen-validated for
        # both sectors by test_sigma_dyson_parity (u3_dot_orb == u3_generated
        # @p_orb, ~1e-19, IP and EA), so this is completing unfinished wiring.
        if not u3_matrix_free or s2cr_module is None:
            if max_rank is not None:
                raise NotImplementedError(
                    "max_rank is matrix-free-only (no rank-truncated dense "
                    "U^(3) fallback); set u3_matrix_free=True")
            # DENSE fallback: u3_generated materializes the (n_k1, n_k1) class-GS
            # S^(2) (~17.5 GB at aug-cc-pVTZ) purely to form -1/2 (S2C @ U1).
            U1 = U1 + rsolver.u3_generated(sector)
        else:
            # MATRIX-FREE (default when the operator supplies s2cr_module):
            # U^(3) is applied via its cheap (n_k1, norb) stitches in BOTH
            # directions -- see _u3_pieces / _u3_apply_fwd / _u3_apply_bwd.
            # Nothing (n_k1)^2 is ever formed, which is what lets full/downfolded
            # ADC(4) run at production basis sets (matrix-free).
            d_u3 = _u3_pieces(rsolver, sector, s2cr_module, extra_leaves,
                              laplace_ntau, max_rank=max_rank)
    d = dict(tag=tag, tag2=tag2, cfg1=cfg1, K1=cfg1['K'], U1=U1)
    if level in ('adc4', 'adc5') and u3_matrix_free and s2cr_module is not None:
        d['u3'] = d_u3
    if level == 'adc5':
        # U^(4), the ADC(5) (0,1) increment, by the order-general matrix-free
        # ISR layer (_un_pieces / _un_apply_fwd / _un_apply_bwd): the Loewdin
        # convolution runs as Delta S matvecs, so no (n_k1, n_k1) object is
        # formed. laplace_ntau routes the raw^(m)/S^(m) rank>=3 structures
        # through their fused twins.
        if s2cr_module is None:
            raise ValueError("level='adc5' applies U^(4) matrix-free and needs "
                             "s2cr_module")
        d['u4'] = _un_pieces(rsolver, sector, 4, extra_leaves, laplace_ntau)
    if level in ('adc4', 'adc5'):
        d['cfg2'] = rsolver._kconfigs(sector, 2)
        d['K2'] = d['cfg2']['K']
        d['ph'] = K2_CLASS_SIGN[sector]
    return d


def restricted_dyson_operator(rsolver, level='adc3', extra_leaves=None, f_orb=None,
                              c1r_module=None, c2r_module=None, s2cr_module=None,
                              k2r_module=None, u2r_module=None, laplace_ntau=None,
                              u3_matrix_free=True, max_rank=None, construction=None,
                              decoupling_ntau=None):
    """The restricted TWO-SECTOR (Dyson) IP/EA supermatrix as a matrix-free
    LinearOperator over {orbital} + {2h1p} + {2p1h} [+ {3h2p} + {3p2h}]:

        H = | F          U_IP^T        U_EA^T        U2_3h2p    U2_3p2h  |
            | U_IP        K+C1[+C2]_IP  0             C_IP        0       |
            | U_EA        0             K+C1[+C2]_EA  0           C_EA    |
            | U2_3h2p^T   C_IP^T        0             K_3h2p      0       |
            | U2_3p2h^T   0             C_EA^T        0           K_3p2h  |

    level: 'adc3'  = K + first-order C^(1) + order-2 U, NO C^(2)/3h2p (==
               BuildSuperMatrixADCnRestricted.build_supermatrix_adc3 -> the
               exact Dyson-ADC(3) IP/EA the downfolded ADC(4) is built on);
           'adc4_base' = + C^(2) + the 3h2p/3p2h class (coupled);
           'adc4'  = + U^(3) (BOTH sectors -- full ADC(4); was 2p1h-only).
    f_orb: (norb,norb) F block (diag(eps)+static); default diag(eps).
    extra_leaves: {'B_aa','B_bb'} + *_df modules -> DF matrix-free.
    Modules default to the full-g restricted apply modules if not given.
    The U2_3h2p/U2_3p2h coupling is applied via u2_k2_dot_orb (forward) /
    orb_dot_u2_k2 (adjoint) -- NO dense (n_k2, norb)
    object is ever formed, closing the ~500 GB memory peak profiled in
    solve_dyson_adc_downfolded (this operator's caller).
    max_rank=2: forwarded to _sector_data (see its docstring) -- level='adc4'
    with every triples (t3/l3) dependence removed, the 'adc4t2' level's
    operator. Returns (op, diag): the LinearOperator and its zeroth-order K
    diagonal.
    construction (required for 'adc4' and 'adc5', resolve_construction):
    'twosector' (the supermatrix above, bit for bit),
    'union' (adds the union-space D x C cross blocks and their transposes,
    applied matrix-free from the generated apply_x modules: the union-space
    ADC(n) of Tarantelli and Cederbaum, PRA 45, 2790 (1992); at 'adc4' the
    2h1p x 2p1h X^(2), at 'adc5' also its effective X^(3) and the effective
    2h1p x 3p2h and 3h2p x 2p1h X^(2), see _decoupling_maps) or 'diagrammatic'
    (the cross blocks decoupled: at 'adc4' the order-3 image delta u =
    U^(1) X^(2)/(K_C - K_D) on both k1 couplings, cross_block_decoupling.
    delta_u_rows_k1 -- Schirmer's diagrammatic ADC(4); at 'adc5' the rows of
    _diagrammatic_adc5_rows on the k1 and k2 couplings). Both need level 'adc4'
    or 'adc5': the k1-k1 cross block enters at fourth order. The ADC(5) cross
    blocks have no DF twins: with DF leaves they are refused.
    decoupling_ntau: diagrammatic 'adc5' only; None forms the decoupling
    amplitudes densely (exact, validation scale), an int applies them by the
    minimax Laplace quadrature of 1/(K_C - K_D) on that many points.
    """
    construction = resolve_construction(level, construction)
    if construction != 'twosector' and level not in ('adc4', 'adc5'):
        raise NotImplementedError(
            f"construction={construction!r} is wired for 'adc4' and 'adc5' (got "
            f"level={level!r}): the 2h1p x 2p1h cross block first enters at fourth "
            f"order, below which the three supermatrices coincide.")
    if decoupling_ntau is not None and (level, construction) != ('adc5', 'diagrammatic'):
        raise ValueError(f"decoupling_ntau applies to diagrammatic ADC(5) only (got "
                         f"level={level!r}, construction={construction!r})")
    df = bool(extra_leaves and 'B_aa' in extra_leaves)
    if df and level == 'adc5' and construction != 'twosector':
        raise ValueError(f"construction={construction!r} at ADC(5) reads the X^(3)_k1k1, "
                         f"X^(2)_k1k2 and X^(2)_k2k1 cross blocks, which have no DF twins: "
                         f"run it on dense g")
    if c1r_module is None:
        # extra_leaves carrying B_aa IS the DF request -- pick the *_df twins,
        # so a g-free rsolver (BuildSuperMatrixADCnRestricted(B_aa=...))
        # never has a dense g asked of it. Previously the dense modules were
        # taken unconditionally, which made DF here a matvec-only saving.
        if df:
            c1r_module = generated('adc4_c1_self_apply_restricted_df_blocks')
            c2r_module = generated('adc4_c2_apply_restricted_df_blocks')
            s2cr_module = generated('adc4_c2_s2c_apply_restricted_df_blocks')
            k2r_module = generated('adc4_k2_apply_restricted_df_blocks')
            u2r_module = generated('adc4_u2_k2_apply_restricted_df_blocks')
        else:
            c1r_module = generated('adc4_c1_self_apply_restricted_blocks')
            c2r_module = generated('adc4_c2_apply_restricted_blocks')
            s2cr_module = generated('adc4_c2_s2c_apply_restricted_blocks')
            k2r_module = generated('adc4_k2_apply_restricted_blocks')
            u2r_module = generated('adc4_u2_k2_apply_restricted_blocks')
    has_c3 = has_u4 = has_adc5 = (level == 'adc5')
    if has_adc5:
        # the ADC(5) blocks pick their DF twins on the same rule as the ADC(4)
        # ones above: with them the whole excitation-space matvec runs off B_aa
        # and no norb^4 g is ever asked of the solver
        if df:
            u3k2r_module = generated('adc5_u3_k2_apply_restricted_df_blocks')
            c12r_module = generated('adc5_c12_apply_restricted_df_blocks')
            s12r_module = generated('adc5_s12_apply_restricted_df_blocks')
            k2k2r_module = generated('adc5_k2k2_apply_restricted_df_blocks')
        else:
            u3k2r_module = generated('adc5_u3_k2_apply_restricted_blocks')
            c12r_module = generated('adc5_c12_apply_restricted_blocks')
            s12r_module = generated('adc5_s12_apply_restricted_blocks')
            k2k2r_module = generated('adc5_k2k2_apply_restricted_blocks')
    union4 = construction == 'union' and level == 'adc4'
    union5 = construction == 'union' and level == 'adc5'
    if union4:
        xmod = cross_block_module(2, 'k1k1', df=df, apply=True)
    if union5:
        # k1-k1 through order 3, k1-k2 and k2-k1 through order 2 (manifold rule),
        # each the raw block minus its class Gram-Schmidt terms
        xm = _decoupling_maps(rsolver, c1r_module, k2r_module, u2r_module, extra_leaves)
    eps = rsolver.eps
    norb = rsolver.norb
    no, nv = rsolver.nocc, rsolver.nvir
    pool = {**rsolver._rargs, **rsolver._amplitude_pool(), **(extra_leaves or {})}
    n2 = rsolver.n2_norm()
    has_c2 = level in ('adc4', 'adc5')
    has_k2 = level in ('adc4', 'adc5')
    S = {sec: _sector_data(rsolver, sec, level, extra_leaves,
                           s2cr_module=s2cr_module, laplace_ntau=laplace_ntau,
                           u3_matrix_free=u3_matrix_free, max_rank=max_rank)
         for sec in ('IP', 'EA')}
    if construction == 'diagrammatic' and level == 'adc5':
        # the cross blocks decoupled through fifth order: rows on both couplings
        rows = _diagrammatic_adc5_rows(rsolver, c1r_module, k2r_module, u2r_module,
                                       extra_leaves=extra_leaves, laplace_ntau=laplace_ntau,
                                       decoupling_ntau=decoupling_ntau)
        for sec in ('IP', 'EA'):
            S[sec]['U1'] = S[sec]['U1'] + rows[(sec, 1)]
            S[sec]['dU_k2'] = rows[(sec, 2)]
    elif construction == 'diagrammatic':
        # the cross block decoupled: its order-3 image on the k1 couplings
        # (the dense alpha-sector X^(2) is affordable for a k1-k1 block)
        x_dense = rsolver.cross_block_generated(
            2, module=cross_block_module(2, 'k1k1', df=df, restricted=True),
            extra_leaves=extra_leaves)
        du_ip, du_ea = delta_u_rows_k1(rsolver._u_block('IP'), rsolver._u_block('EA'),
                                       S['IP']['K1'], S['EA']['K1'], x_dense)
        S['IP']['U1'] = S['IP']['U1'] + du_ip
        S['EA']['U1'] = S['EA']['U1'] + du_ea
    nI, nE = len(S['IP']['K1']), len(S['EA']['K1'])
    off = {'orb': 0, 'IP': norb, 'EA': norb + nI}
    if has_k2:
        mI, mE = len(S['IP']['K2']), len(S['EA']['K2'])
        off['IP2'] = norb + nI + nE
        off['EA2'] = norb + nI + nE + mI
        n = norb + nI + nE + mI + mE
        diag = np.concatenate([np.diag(f_orb) if f_orb is not None else eps,
                               S['IP']['K1'], S['EA']['K1'], S['IP']['K2'], S['EA']['K2']])
    else:
        n = norb + nI + nE
        diag = np.concatenate([np.diag(f_orb) if f_orb is not None else eps,
                               S['IP']['K1'], S['EA']['K1']])
    fmv = (lambda vo: f_orb @ vo) if f_orb is not None else (lambda vo: eps * vo)

    def matvec(x):
        x = np.asarray(x).reshape(-1)
        vo = x[:norb]
        v = {sec: x[off[sec]:off[sec] + len(S[sec]['K1'])] for sec in ('IP', 'EA')}
        nz = {sec: bool(v[sec].any()) for sec in ('IP', 'EA')}
        vo_nz = bool(vo.any())
        yo = fmv(vo) + S['IP']['U1'].T @ v['IP'] + S['EA']['U1'].T @ v['EA']
        for sec in ('IP', 'EA'):                      # U^(3)^T, matrix-free
            if 'u3' in S[sec] and nz[sec]:
                M3, U13, n23, cfg3, pool3, tag3 = S[sec]['u3']
                yo = yo + _u3_apply_bwd(M3, U13, n23, cfg3, pool3, s2cr_module,
                                        tag3, no, nv, v[sec])
        if has_u4:                                    # U^(4)^T
            for sec in ('IP', 'EA'):
                if nz[sec]:
                    yo = yo + _un_apply_bwd(rsolver, sec, S[sec]['u4'],
                                            s2cr_module, v[sec], extra_leaves)
        y = {}
        for sec in ('IP', 'EA'):
            d = S[sec]
            if 'u3' in d and vo_nz:                   # U^(3), matrix-free
                M3, U13, n23, cfg3, pool3, tag3 = d['u3']
                u3v = _u3_apply_fwd(M3, U13, n23, cfg3, pool3, s2cr_module,
                                    tag3, no, nv, vo)
            else:
                u3v = 0.0
            yc = (d['U1'] @ vo + u3v + d['K1'] * v[sec]
                  + restricted_class_matvec(c1r_module, f"apply_c1_{d['tag']}_",
                                            v[sec], d['cfg1'], pool, no, nv))
            if has_u4 and vo_nz:                       # U^(4), matrix-free
                yc = yc + _un_apply_fwd(rsolver, sec, d['u4'], s2cr_module,
                                        vo, extra_leaves)
            if has_c2:
                yc = yc + assembled_c2_matvec_restricted(
                    v[sec], d['cfg1'], pool, n2, no, nv, c2r_module, s2cr_module, d['tag'])
            if has_c3:                                 # C^(3), matrix-free
                yc = yc + assembled_c3_matvec_restricted(
                    rsolver, sec, v[sec], extra_leaves=extra_leaves,
                    laplace_ntau=laplace_ntau)
            y[sec] = yc
        if union4:                                    # X^(2) and its transpose
            if nz['EA']:
                y['IP'] = y['IP'] + restricted_class_matvec(
                    xmod, 'apply_x2_2h1p_2p1h_', v['EA'], S['IP']['cfg1'], pool, no, nv,
                    cfg_ket=S['EA']['cfg1'])
            if nz['IP']:
                y['EA'] = y['EA'] + restricted_class_matvec(
                    xmod, 'apply_x2_2p1h_2h1p_', v['IP'], S['EA']['cfg1'], pool, no, nv,
                    cfg_ket=S['IP']['cfg1'])
        if union5:                                    # X_k1k1 through order 3
            if nz['EA']:
                y['IP'] = y['IP'] + xm['x2_11'](v['EA'], False) + xm['x3_11'](v['EA'], False)
            if nz['IP']:
                y['EA'] = y['EA'] + xm['x2_11'](v['IP'], True) + xm['x3_11'](v['IP'], True)
        if not has_k2:
            return np.concatenate([yo, y['IP'], y['EA']])
        v2 = {'IP': x[off['IP2']:off['EA2']], 'EA': x[off['EA2']:]}
        v2_nz = {sec: bool(v2[sec].any()) for sec in ('IP', 'EA')}
        y2 = {}
        for sec in ('IP', 'EA'):
            d = S[sec]
            if v2_nz[sec]:                             # U2k2^T, matrix-free
                yo = yo + orb_dot_u2_k2(rsolver, sec, v2[sec], u2r_module,
                                        extra_leaves, laplace_ntau)
                if has_adc5:                           # U3k2^T, matrix-free
                    yo = yo + orb_dot_u3_k2(rsolver, sec, v2[sec], u3k2r_module,
                                            s12r_module, extra_leaves)
                if 'dU_k2' in d:                       # decoupling rows^T
                    yo = yo + d['dU_k2'].T @ v2[sec]
            # (1,2): order-1 k1<->k2 coupling [+ order-2 C12 at adc5]
            y[sec] = y[sec] + d['ph'] * restricted_class_matvec(
                k2r_module, f"apply_c1_{d['tag']}_{d['tag2']}_", v2[sec], d['cfg1'],
                pool, no, nv, cfg_ket=d['cfg2'])
            if has_adc5 and v2_nz[sec]:
                y[sec] = y[sec] + c12_dot_k2(rsolver, sec, v2[sec], c12r_module,
                                             s12r_module, u2r_module, extra_leaves)
            u2v = (u2_k2_dot_orb(rsolver, sec, vo, u2r_module, extra_leaves,
                                 laplace_ntau) if vo_nz else 0.0)
            if has_adc5 and vo_nz:                      # U3k2 forward
                u2v = u2v + u3_k2_dot_orb(rsolver, sec, vo, u3k2r_module,
                                          s12r_module, extra_leaves)
            if 'dU_k2' in d and vo_nz:                  # decoupling rows
                u2v = u2v + d['dU_k2'] @ vo
            y2sec = (u2v + d['K2'] * v2[sec]            # U2k2, matrix-free
                     + d['ph'] * restricted_class_matvec(
                         k2r_module, f"apply_c1_{d['tag2']}_{d['tag']}_", v[sec],
                         d['cfg2'], pool, no, nv, cfg_ket=d['cfg1']))
            if has_adc5 and nz[sec]:                    # (2,1): C12^T
                y2sec = y2sec + k1_dot_c12(rsolver, sec, v[sec], c12r_module,
                                           s12r_module, u2r_module, extra_leaves)
            if has_adc5 and v2_nz[sec]:                 # (2,2): C^(1)_k2
                y2sec = y2sec + restricted_class_matvec(
                    k2k2r_module, f"apply_c1_{d['tag2']}_", v2[sec], d['cfg2'],
                    pool, no, nv)
            y2[sec] = y2sec
        if union5:                                    # X_k1k2 and X_k2k1 at order 2
            if v2_nz['EA']:
                y['IP'] = y['IP'] + xm['x12'](v2['EA'], False)
            if nz['IP']:
                y2['EA'] = y2['EA'] + xm['x12'](v['IP'], True)
            if nz['EA']:
                y2['IP'] = y2['IP'] + xm['x21'](v['EA'], False)
            if v2_nz['IP']:
                y['EA'] = y['EA'] + xm['x21'](v2['IP'], True)
        return np.concatenate([yo, y['IP'], y['EA'], y2['IP'], y2['EA']])

    return LinearOperator((n, n), matvec=matvec, dtype=float), diag


def u2_k2_dot_orb(rsolver, sector, p_orb, module, extra_leaves=None,
                  laplace_ntau=None):
    """MATRIX-FREE U^(2)_orbital<->k2 contracted with an orbital trial:

        (u2_k2_generated(sector) @ p_orb)   without forming the (n_k2, norb)
                                             coupling or its (k2_spatial, norb)
                                             build intermediate.

    Folds p_orb over the single orbital index of each orbital-folded apply
    (adc4_base_u2_k2_apply_restricted[_df]_blocks) and gathers at the k2 configs,
    per Ms-conserving spin pattern -- the Dyson-ADC(4) 3h2p/3p2h Schur downfold
    weight w = U2_k2 @ p_orb (the ~16 GB aug-cc-pVTZ 3p2h blocker as a dense
    build). Mirrors BuildSuperMatrixADCnRestricted.u2_k2_generated's exact split
    set (l2v@L2_1, l1f@L1_2, l2f@L2_2 for U^(2); l2@L2_2 for the class-GS S^(2),
    which folds eps*p_orb since (eps_p S2) @ p_orb = S2 @ (eps o p_orb)); missing
    splits are skipped exactly as _stitch_k2r's getattr(..., None) does."""
    no = rsolver.nocc
    eps = rsolver.eps
    # Only the rank<=2 blocks (L2_1/L1_2/L2_2) are consumed here; in Laplace
    # mode use the t3/l3-free amps so this 3h2p/3p2h sweep never rebuilds the
    # O(no^3 nv^3) triples (the exact _u3_amps() would).
    A = rsolver._u3_amps_laplace(laplace_ntau) if laplace_ntau is not None \
        else rsolver._u3_amps()

    def fold(kind, split, amps, t_occ, t_vir):
        return _k2_orb_fold(rsolver, sector, module, kind, split, amps, t_occ, t_vir,
                            extra_leaves)

    occ, vir = p_orb[:no], p_orb[no:]
    ep = eps * p_orb
    raw = (fold('u2', 'l2v', A['L2_1'], occ, vir)
           + fold('u2', 'l1f', A['L1_2'], occ, vir)
           + fold('u2', 'l2f', A['L2_2'], occ, vir))
    s2 = fold('s2', 'l2', A['L2_2'], ep[:no], ep[no:])
    return K2_CLASS_SIGN[sector] * (raw - s2)


def orb_dot_u2_k2(rsolver, sector, v_k2, module, extra_leaves=None,
                  laplace_ntau=None):
    """MATRIX-FREE ADJOINT of u2_k2_dot_orb:

        u2_k2_generated(sector).T @ v_k2    (== U2k2.T @ v_k2, the orbital-
                                             shaped output the ADC(4)
                                             matrix-free operator needs for
                                             its orbital row, sigma_driver.py
                                             ~:729/:733 -- previously the
                                             ONLY consumer of the dense
                                             u2_k2_generated build)

    without forming the (n_k2, norb) coupling. Folds v_k2 (a k2-config-shaped
    trial) over the class axis of each apply_{u2,s2}T split (adc4_base_u2_k2_
    apply_restricted[_df]_blocks' TRANSPOSE functions, apply_{u2,s2}t_*) and
    scatters into the (norb,) output -- the exact transpose of
    u2_k2_dot_orb's forward fold (same splits, same amplitude orders,
    generated from the SAME term lists -- see
    generate_u2_k2_apply_restricted's bidirectional emission). Validated
    against the dense u2_k2_generated(sector).T @ v_k2 to machine zero
    (tests/test_sigma_u2_k2_transpose.py)."""
    eps = rsolver.eps
    A = rsolver._u3_amps_laplace(laplace_ntau) if laplace_ntau is not None \
        else rsolver._u3_amps()
    v_k2 = np.asarray(v_k2, float).reshape(-1)

    def fold(kind, split, amps):
        return _k2_orb_fold_adj(rsolver, sector, module, kind, split, amps, v_k2,
                                extra_leaves)

    raw = (fold('u2', 'l2v', A['L2_1']) + fold('u2', 'l1f', A['L1_2'])
           + fold('u2', 'l2f', A['L2_2']))
    s2 = fold('s2', 'l2', A['L2_2'])
    sign = K2_CLASS_SIGN[sector]
    return sign * raw - sign * eps * s2


def _k2_groups(rsolver, sector):
    """[(rows, spin suffix, gather index)] of the k2 configs per spin pattern,
    cached on the solver (the k2 configs are fixed at construction)."""
    cache = rsolver.__dict__.setdefault('_k2_group_cache', {})
    if sector not in cache:
        cfg2 = rsolver._kconfigs(sector, 2)
        cols = _cfg_cols(cfg2)
        uniq, inv = np.unique(cfg2['spins'], axis=0, return_inverse=True)
        out = []
        for gi, pat in enumerate(uniq):
            rows = np.where(inv == gi)[0]
            out.append((rows, _restricted_suffix(pat) + 'a', tuple(c[rows] for c in cols)))
        cache[sector] = out
    return cache[sector]


def _k2_orb_fold(rsolver, sector, module, kind, split, amps, t_occ, t_vir, extra_leaves=None):
    """One orbital-folded k2 split of `module` (apply_{kind}_{3h2p|3p2h}_{occ|vir}_
    {split}_*) at amplitude leaves `amps`, gathered at the k2 configs: the
    occupied and virtual orbital trials t_occ, t_vir folded per spin pattern."""
    tag2 = '3h2p' if sector == 'IP' else '3p2h'
    pool = {**rsolver._rargs, **(extra_leaves or {}), **amps}
    y = np.zeros(len(rsolver._kconfigs(sector, 2)['K']))
    for rows, suffix, idx in _k2_groups(rsolver, sector):
        for row, t in (('occ', t_occ), ('vir', t_vir)):
            fn = getattr(module, f'apply_{kind}_{tag2}_{row}_{split}_{suffix}', None)
            if fn is None:
                continue
            args = [pool[p] for p in inspect.signature(fn).parameters if p != 'x']
            y[rows] += fn(*args, x=t)[idx]
    return y


def _k2_orb_fold_adj(rsolver, sector, module, kind, split, amps, v_k2, extra_leaves=None):
    """Adjoint of _k2_orb_fold: the k2 trial v_k2 scattered per spin pattern and
    folded by the transpose applies (apply_{kind}t_*) onto the occupied and the
    virtual orbitals, as one (norb,) vector."""
    tag2 = '3h2p' if sector == 'IP' else '3p2h'
    no, nv = rsolver.nocc, rsolver.nvir
    cfg2 = rsolver._kconfigs(sector, 2)
    shape = (no,) * cfg2['hole_sp'].shape[1] + (nv,) * cfg2['part_sp'].shape[1]
    pool = {**rsolver._rargs, **(extra_leaves or {}), **amps}
    occ_out, vir_out = np.zeros(no), np.zeros(nv)
    for rows, suffix, idx in _k2_groups(rsolver, sector):
        x = np.zeros(shape)
        x[idx] = v_k2[rows]
        for row, out in (('occ', occ_out), ('vir', vir_out)):
            fn = getattr(module, f'apply_{kind}t_{tag2}_{row}_{split}_{suffix}', None)
            if fn is None:
                continue
            args = [pool[p] for p in inspect.signature(fn).parameters if p != 'x']
            out += fn(*args, x=x)
    return np.concatenate([occ_out, vir_out])


def _s1_k2_folds(rsolver, sector, module):
    """[(structure, amplitude leaves)] of the first-order overlap S^(1) of the k2
    class with the orbital operators: the s_order_terms(1) structures the
    orbital<->k2 apply module carries (as its s2 splits), at their amplitudes."""
    tag2 = '3h2p' if sector == 'IP' else '3p2h'
    A = rsolver._amps_order(max_order=2)
    out = []
    for nm, j, k, a, b in s_order_terms(1):
        if not any(f.startswith(f'apply_s2_{tag2}_{row}_{nm}_')
                   for row in ('occ', 'vir') for f in dir(module)):
            continue
        amps = {}
        for lead, rank, ordr in (('L', j, a), ('T', k, b)):
            if rank:
                amps.update(A[f'{lead}{rank}_{ordr}'])
        out.append((nm, amps))
    return out


def s1_k2_dot_orb(rsolver, sector, p_orb, module, extra_leaves=None):
    """First-order overlap S^(1) of the k2 class (3h2p-dagger IP / 3p2h EA) with
    the orbital operators, times an orbital trial, in the operator's k2 basis
    (K2_CLASS_SIGN). Nonzero already at first order (a doubles element), unlike
    the k1 overlap; the two-sector coupling never needs it (its first-order raw
    k2 coupling cancels -eps S^(1) identically), the union cross blocks do."""
    no = rsolver.nocc
    y = np.zeros(len(rsolver._kconfigs(sector, 2)['K']))
    for nm, amps in _s1_k2_folds(rsolver, sector, module):
        y += _k2_orb_fold(rsolver, sector, module, 's2', nm, amps, p_orb[:no], p_orb[no:],
                          extra_leaves)
    return K2_CLASS_SIGN[sector] * y


def orb_dot_s1_k2(rsolver, sector, v_k2, module, extra_leaves=None):
    """Adjoint of s1_k2_dot_orb: S^(1)_k2^T v_k2 over the orbitals."""
    v_k2 = np.asarray(v_k2, float).reshape(-1)
    y = np.zeros(rsolver.norb)
    for nm, amps in _s1_k2_folds(rsolver, sector, module):
        y += _k2_orb_fold_adj(rsolver, sector, module, 's2', nm, amps, v_k2, extra_leaves)
    return K2_CLASS_SIGN[sector] * y


def _k2_amp_leaves(A, j, a, k, b):
    """Merged restricted spin-blocked amplitude dict for the (l_j^(a), t_k^(b))
    assignment, from the _amps_order map (keys 'L{j}_{a}'/'T{k}_{b}'); None if
    an amplitude at the required order is unavailable (skip, like _amp_pair)."""
    d = {}
    for lead, rank, order in (('L', j, a), ('T', k, b)):
        if not rank:
            continue
        key = f'{lead}{rank}_{order}'
        if key not in A:
            return None
        d.update(A[key])
    return d


def _resolve_k2_apply(module, kindpref, tag2, row, name, suffix, transpose=False):
    """The apply function for orbital<->k2 structure `name` at `row`/`suffix`,
    searching home-order prefixes apply_{kindpref}{o}[t]_{tag2}_{row}_{name}_
    {suffix} for o in 1..3 (the incremental-cache resolution _resolve_k2_struct
    uses for the dense blocks). `transpose` selects the ...t_ adjoint form."""
    t = 't' if transpose else ''
    for o in (1, 2, 3):
        fn = getattr(module, f'apply_{kindpref}{o}{t}_{tag2}_{row}_{name}_{suffix}',
                     None)
        if fn is not None:
            return fn
    return None


def k2_raw_dot_orb(rsolver, sector, trial, n, kind, module, A, extra_leaves=None):
    """ORDER-GENERAL matrix-free fold of the orbital<->k2 raw coupling ('u')
    or overlap ('s') at order n against an orbital trial:

        (raw^(n) @ trial)[k2]   or   (S^(n) @ trial)[k2]

    the apply twin of BuildSuperMatrixADCn._k2_raw_S's forward action -- loops
    the SAME adc_order_rule.{u,s}_order_terms(n) (structure x amplitude-order
    assignment), folds `trial` over the single orbital index per row via the
    generated apply functions (adc5_u3_k2_apply_restricted[_df]_blocks), and
    gathers at the k2 configs. Generalizes u2_k2_dot_orb (which is the n=2 'u'
    case with the 3 hardcoded splits) to any order. A = rsolver._amps_order().
    NO K2_CLASS_SIGN, NO normalization -- the raw precursor fold; the ISR
    corrections are the caller's (u3_k2_dot_orb)."""
    tag2 = '3h2p' if sector == 'IP' else '3p2h'
    no = rsolver.nocc
    cfg2 = rsolver._kconfigs(sector, 2)
    cols = _cfg_cols(cfg2)
    uniq, inv = np.unique(cfg2['spins'], axis=0, return_inverse=True)
    groups = [(np.where(inv == gi)[0], _restricted_suffix(pat) + 'a')
              for gi, pat in enumerate(uniq)]
    base = {**rsolver._rargs, **(extra_leaves or {})}
    terms = u_order_terms(n) if kind == 'u' else s_order_terms(n)
    t_occ, t_vir = trial[:no], trial[no:]
    y = np.zeros(len(cfg2['K']))
    for t in terms:
        name = t[0]
        j, a, k, b = ((t[1], t[4], t[3], t[5]) if kind == 'u'
                      else (t[1], t[3], t[2], t[4]))
        amps = _k2_amp_leaves(A, j, a, k, b)
        if amps is None:
            continue
        pool = {**base, **amps}
        for rows, suffix in groups:
            idx = tuple(c[rows] for c in cols)
            for row, tt in (('occ', t_occ), ('vir', t_vir)):
                fn = _resolve_k2_apply(module, kind, tag2, row, name, suffix)
                if fn is None:
                    continue
                args = [pool[p] for p in inspect.signature(fn).parameters
                        if p != 'x']
                y[rows] += fn(*args, x=tt)[idx]
    return y


