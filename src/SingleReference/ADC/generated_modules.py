# Non-Dyson (single-sector) ISR blocks, adc{N}_nd{order}_k{ki}k{kj} with
# N = max(order + ki + kj, 2): the dense spin-orbital ones of nondyson_isr
# (NonDysonISR, N <= 4) and the restricted apply ones of nondyson_restricted
# (NonDysonRestricted, N <= 5).
_ND_PAIRS = ((0, 0, range(0, 6)), (0, 1, range(1, 5)), (1, 1, range(0, 4)),
             (0, 2, range(1, 4)), (1, 2, range(1, 3)), (2, 2, range(0, 2)))
for _ki, _kj, _orders in _ND_PAIRS:
    for _o in _orders:
        _n = max(_o + _ki + _kj, 2)
        if _n <= 4:
            RUNTIME_MODULES[f'adc{_n}_nd{_o}_k{_ki}k{_kj}_blocks'] = (
                _n, _p('generate_adcn.generate_nondyson_pair', order=_o, k_i=_ki, k_j=_kj))
        RUNTIME_MODULES[f'adc{_n}_nd{_o}_k{_ki}k{_kj}_apply_restricted_blocks'] = (
            _n, _p('sigma_codegen.generate_nondyson_pair_apply_restricted', order=_o, k_i=_ki,
                   k_j=_kj, df=False))
del _ki, _kj, _orders, _o, _n


def dotted(name):
    """Full module path of a generated module named as in RUNTIME_MODULES
    ('adc4_u3_blocks' lives in generatedADC/adc4/, 'diagrammatic.m4_blocks' in
    generatedADC/diagrammatic/)."""
    if '.' in name:
        return f'{_PKG}.{name}'
    return f'{_PKG}.{name.split("_")[0]}.{name}'


def producer_text(name):
    """The call that writes `name`, for an error message."""
    if name not in RUNTIME_MODULES:
        return 'GenerateRuntime (no producer is registered for it)'
    order, (func, kwargs) = RUNTIME_MODULES[name]
    args = ', '.join(f'{k}={v!r}' for k, v in kwargs.items())
    return (f"src.CodeGeneration.{func}({args}), or GenerateRuntime(orders=(..., {order})) "
            f"from src.CodeGeneration.generate_adc")


def is_generated(name):
    """True when `name` exists on this machine (does not import it)."""
    try:
        return importlib.util.find_spec(dotted(name)) is not None
    except ModuleNotFoundError:
        return False


def generated(name):
    """Import a generated module; a missing one raises ImportError naming its producer."""
    path = dotted(name)
    if not is_generated(name):
        raise ImportError(f"{path} is not generated on this machine; write it with "
                          f"{producer_text(name)}.")
    return importlib.import_module(path)


class lazy:
    """A generated module imported at its first attribute access. Missing, the
    access raises ImportError (not AttributeError), so a getattr(mod, x, None)
    call site sees 'not generated' rather than a legitimately pruned block."""

    def __init__(self, name):
        self._name = name
        self._mod = None

    def _load(self):
        if self._mod is None:
            self._mod = generated(self._name)
        return self._mod

    def __getattr__(self, attr):
        return getattr(self._load(), attr)

    def __dir__(self):
        return dir(self._load())

    def __repr__(self):
        state = 'loaded' if self._mod is not None else 'not loaded'
        return f'<generated module {dotted(self._name)} ({state})>'
