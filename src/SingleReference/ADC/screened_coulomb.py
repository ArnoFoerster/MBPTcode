"""Static (omega=0) RPA-screened Coulomb interaction W for the "screened MCDE"
/ screened ADC(2)-x method of Romaniello & Berger (arXiv:2603.27329).

Implementation
--------------
c1_2h1p reads only g[o,o,o,o] (ladder) and g[o,v,v,o] (ring); c1_2p1h reads
only g[o,v,v,o] (ring) and g[v,v,v,v] (ladder).  Because these slices are
disjoint we can hand the *unmodified* generated c1 functions a single
pre-screened tensor g_c1 built from the bare antisymmetrized g with

    g_c1[o,o,o,o] = gW[o,o,o,o]
    g_c1[v,v,v,v] = gW[v,v,v,v]
    g_c1[o,v,v,o] = gmix[o,v,v,o]

and every other slice left bare (unused by c1).  No generated code is edited.
"""
import numpy as np

from src.SingleReference.LinearResponse.linear_response import (
    static_screened_coulomb_chemist, static_screened_coulomb_aux)
from src.Base.pyscf_interface import (get_orbital_energies,
                                      get_two_electron_integrals_chemist,
                                      get_antisymmetrized_spin_eri,
                                      get_spin_orbital_eri_physicist)
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCn


def _screen_slices(eri_chemist, W_chemist, nocc, gw_slices, gmix_slices):
    """
    Spin-orbital antisymmetrized tensor equal to the bare g everywhere, except

      * `gw_slices`   -> fully screened antisymmetrized gW  (both direct and
                         exchange integrals screened -- a LADDER);
      * `gmix_slices` -> gmix = direct bare, exchange screened (an e-h RING,
                         whose direct/RPA-bubble integral must stay bare).

    Slices are given as 4-tuples of 'o'/'v' (e.g. ('o','o','o','o')). 
    """
    vpr = get_spin_orbital_eri_physicist(eri_chemist)       
    wpr = get_spin_orbital_eri_physicist(W_chemist)  
    wpr_x = wpr.transpose(0, 1, 3, 2)  

    g_anti = vpr - vpr.transpose(0, 1, 3, 2)      
    gW = wpr - wpr_x            
    gmix = vpr - wpr_x 

    no = 2 * nocc
    sl = {'o': slice(0, no), 'v': slice(no, g_anti.shape[0])}
    out = g_anti.copy()
    for a, b, c, d in gw_slices:
        out[sl[a], sl[b], sl[c], sl[d]] = gW[sl[a], sl[b], sl[c], sl[d]]
    for a, b, c, d in gmix_slices:
        out[sl[a], sl[b], sl[c], sl[d]] = gmix[sl[a], sl[b], sl[c], sl[d]]
    return out


def screened_c1_tensor(eri_chemist, W_chemist, nocc):
    """Screened tensor for the ADC(2)-x / screened-MCDE C^(1) block (feeds the
    unmodified generated c1_2h1p / c1_2p1h).  Paper Eq. 12: hh/pp LADDERS
    ([o,o,o,o],[v,v,v,v]) fully screened; e-h RING ([o,v,v,o]) exchange-only
    (direct bare).  eri/W: spatial-MO chemist tensors; nocc: occ *spatial*
    orbital count."""
    return _screen_slices(eri_chemist, W_chemist, nocc,
                          gw_slices=[('o', 'o', 'o', 'o'), ('v', 'v', 'v', 'v')],
                          gmix_slices=[('o', 'v', 'v', 'o')])


def solve_screened_adc(mf, mol=None, level='adc2x', screening='rpa', z_threshold=0.0):
    """Screened (or bare) ADC = screened multichannel Dyson equation of
    Romaniello & Berger (arXiv:2603.27329) for an RHF reference `mf`.

    level: 'adc2x' or 'adc3'. Screening enters the C^(1) 2h1p/2p1h block only;
        the U^(2) coupling vertex is always bare.
    screening: 'rpa' (static-RPA W) or 'none'/'bare' (ordinary method). Any
        other value is treated as a precomputed spatial-MO chemist W tensor.
    z_threshold: keep only poles whose 1p (quasiparticle) weight Z exceeds this.

    Returns a dict with 'energies' (Ha, ascending), 'Z' (1p pole strength),
    'chempot' (HOMO/LUMO midpoint), 'H'. Spin-orbital build (all spin
    multiplicities present); physical IP/EA doublet poles have sizeable Z.
    """
    mol = mol if mol is not None else mf.mol
    nocc = mol.nelectron // 2
    eps = get_orbital_energies(mf, representation='spatial')
    eri = get_two_electron_integrals_chemist(mol, mf)

    if isinstance(screening, str) and screening.lower() in ('none', 'bare', 'off'):
        g_c1 = None
    else:
        W = (static_screened_coulomb_chemist(eps, eri, nocc)
             if isinstance(screening, str) else np.asarray(screening))
        g_c1 = screened_c1_tensor(eri, W, nocc)

    eps_spin = np.repeat(eps, 2)
    g_spin = get_antisymmetrized_spin_eri(eri)
    solver = BuildSuperMatrixADCn(eps_spin, g_spin, 2 * nocc, g_c1=g_c1)
    if level == 'adc2x':
        H = solver.build_supermatrix_adc2x()
    elif level == 'adc3':
        H = solver.build_supermatrix_adc3()
    else:
        raise ValueError(f"level={level!r}; expected 'adc2x' or 'adc3'")
    norb = 2 * len(eps)
    w, vecs = np.linalg.eigh(H)
    Z = np.sum(vecs[:norb, :] ** 2, axis=0)          # 1p (orbital-block) weight
    keep = Z >= z_threshold
    chempot = 0.5 * (eps[nocc - 1] + eps[nocc]) if nocc < len(eps) else eps[nocc - 1]
    return {'energies': w[keep], 'Z': Z[keep], 'chempot': chempot, 'H': H}
