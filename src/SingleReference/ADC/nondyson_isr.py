"""Non-Dyson IP- and EA-ADC(n) from the generated single-sector ISR blocks.

The intermediate-state representation of one particle-number sector
(Schirmer, Trofimov and Stelter, J. Chem. Phys. 109, 4734 (1998)): precursor
states E_J |Psi0> with E_J the (k+1)h kp operators (IP, class k = 0 is a_i)
or the (k+1)p kh operators (EA, class 0 is a+_a), the ORDINARY overlap
<Psi0|E_I^dag E_J|Psi0> as metric and <Psi0|E_I^dag (H - E0) E_J|Psi0> as
the operator, orthonormalized class by class (Gram-Schmidt against the lower
classes, Loewdin within the class) as series in the perturbation. The
eigenvalues of the resulting matrix are the ionization potentials
(IP) or electron affinities (EA); there is no second sector and hence no
cross block. Blocks are carried through order n - k_I - k_J (the same
manifold rule as the Dyson supermatrix, classes 2k <= n), n <= 4.

Raw blocks come from the generated modules adc{N}_nd{m}_k{i}k{j}_blocks
(generate_adcn.generate_nondyson_pair): one function per dressing structure
(l_j, f|v, t_k), evaluated at the amplitude orders of u_order_terms /
s_order_terms; the E0 series (E^(0) = sum_k eps_k, E^(1) = 1/2 sum_kl
<kl||kl>, E^(c>=2) the MP correlation energies) times the lower-order raw
overlaps is subtracted, and the ground-state norm series is divided out
inside the Loewdin engine (isr_assembly.isr_effective_blocks). Dense
spin-orbital tensors: the validation-grade reference of the construction.
"""
import inspect

import numpy as np

from src.SingleReference.ADC.adc_order_rule import (
    u_order_terms, s_order_terms, kmax, block_order)
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCn
from src.SingleReference.ADC.generated_modules import generated
from src.SingleReference.ADC.isr_assembly import isr_effective_blocks
from src.SingleReference.ADC.precursor_classes import (
    class_configs, class_dimension, CLASS_TAGS, nondyson_module_name)
from src.SingleReference.DensityMatrix.mpn_density_driver import MPnDensityDriver

# highest non-Dyson order: n = 5 reads the order-5 MP amplitudes (see raw_series)
MAX_NONDYSON_ORDER = 4


def nondyson_module(order, k_i, k_j):
    """The generated non-Dyson block module of class pair (k_i, k_j) at
    `order`; absence raises, naming the generator call (never a zero block)."""
    return generated(nondyson_module_name(order, k_i, k_j)[:-3])


class NonDysonISR:
    """Non-Dyson ISR of one sector ('IP' or 'EA') over the spin-orbital
    (eps, g, nocc) reference; the matrix at ADC(n) and its eigenvalues."""

    def __init__(self, eps, g, nocc, sector):
        if sector not in ('IP', 'EA'):
            raise ValueError(f"sector must be 'IP' or 'EA', got {sector!r}")
        self.eps = np.asarray(eps, dtype=float)
        self.g = g
        self.nocc = nocc
        self.norb = len(self.eps)
        self.sector = sector
        self.gen = BuildSuperMatrixADCn(self.eps, g, nocc)
        self.mpn = MPnDensityDriver(self.eps, g, nocc)
        self._mods = {}

    # ----- classes and configurations --------------------------------------
    def dim(self, k):
        return class_dimension(self.nocc, self.norb - self.nocc, k, self.sector)

    def classes(self, n):
        """Classes present at ADC(n): 2k <= n and a nonempty configuration space."""
        return [k for k in range(kmax(n) + 1) if self.dim(k) > 0]

    def configs(self, k):
        """Index arrays of class k in the generated tensors' axis order
        (holes ascending, particles ascending; virtual axes local)."""
        cols = class_configs(self.nocc, self.norb, k, self.sector)
        return tuple(c - self.nocc if (len(c) and c.min() >= self.nocc) else c for c in cols)

    @staticmethod
    def leading_order(k_i, k_j):
        return 0 if k_i == k_j else 1

    # ----- generated structures --------------------------------------------
    def _module(self, order, k_i, k_j):
        key = (order, k_i, k_j)
        if key not in self._mods:
            self._mods[key] = nondyson_module(order, k_i, k_j)
        return self._mods[key]

    def _resolve(self, kind, name, order, k_i, k_j):
        """Generated function of structure `name` for the pair at `order`:
        searched from the order-`order` module down to the pair's leading
        order (a structure lives at its home order). Every module in that
        range must exist, so None means the structure pruned to zero."""
        tag_i, tag_j = CLASS_TAGS[k_i][self.sector], CLASS_TAGS[k_j][self.sector]
        prefix = 'nd' if kind == 'u' else 'nds'
        for o in range(order, self.leading_order(k_i, k_j) - 1, -1):
            fn = getattr(self._module(o, k_i, k_j), f'{prefix}{o}_{tag_i}_{tag_j}_{name}', None)
            if fn is not None:
                return fn
        return None

    # ----- ground-state energy series ---------------------------------------
    def mp_energy(self, c):
        """E^(c) of the Moeller-Plesset series in the partitioning H = f + v
        of the generated elements: E^(0) = <Phi0|f|Phi0> = sum_k eps_k, E^(1)
        = <Phi0|v|Phi0> = -1/2 sum_kl <kl||kl> = E_HF - sum_k eps_k, E^(c>=2)
        = 1/4 <ij||ab> t2^(c-1)."""
        o = slice(0, self.nocc)
        if c == 0:
            return float(np.sum(self.eps[o]))
        if c == 1:
            return -0.5 * float(np.einsum('klkl->', self.g[o, o, o, o]))
        return float(self.mpn.compute_E(self.gen._amp_at(2, c - 1)))

    # ----- raw and effective blocks -----------------------------------------
    def raw_block(self, k_i, k_j, m, strict=True):
        """(<E_I^dag H E_J>^(m), <E_I^dag E_J>^(m)) over the class configs,
        raw (no E0 subtraction, no norm division)."""
        ci, cj = self.configs(k_i), self.configs(k_j)
        bra = tuple(x[:, None] for x in ci)
        ket = tuple(x[None, :] for x in cj)
        shape = (len(ci[0]), len(cj[0]))
        base = dict(self.gen._args())
        H = np.zeros(shape)
        S = np.eye(shape[0]) if (m == 0 and k_i == k_j) else np.zeros(shape)
        missing = []

        def accumulate(kind, terms, out):
            for t in terms:
                name = t[0]
                j, k, a, b = (t[1], t[3], t[4], t[5]) if kind == 'u' else (t[1], t[2], t[3], t[4])
                fn = self._resolve(kind, name, m, k_i, k_j)
                if fn is None:
                    continue
                ds = self.gen._amp_pair(j, a, k, b)
                if ds is None:
                    missing.append(f"{name}(l{j}^{a},t{k}^{b})")
                    continue
                pool = dict(base)
                pool.update(ds)
                out += fn(**{p: pool[p] for p in inspect.signature(fn).parameters})[bra + ket]

        accumulate('u', u_order_terms(m), H)
        if m > 0:
            accumulate('s', s_order_terms(m), S)
        if strict and missing:
            raise RuntimeError(f"non-Dyson {self.sector} block ({k_i},{k_j}) order {m} "
                               f"incomplete -- no amplitude for {sorted(set(missing))}")
        return H, S

    @staticmethod
    def top_order(n, k_i, k_j, extra):
        """Order through which block (k_i, k_j) is carried at ADC(n): the
        manifold rule n - k_i - k_j, raised by `extra` = {(k_i,k_j): order}
        (ADC(2)-x carries the (1,1) block through first order)."""
        extra = extra or {}
        return max(block_order(n, k_i, k_j), extra.get((k_i, k_j), -1), extra.get((k_j, k_i), -1))

    def raw_series(self, n, extra=None, strict=True):
        """{(k_i,k_j): {m: block}} for H = <E^dag (H - E0) E> and S, every
        pair k_i <= k_j through its carried order, plus the class dimensions
        -- the input of the Loewdin engine.

        n <= 4: at n = 5 the (0,0) block reads MP5-level amplitudes (the
        order-5 numerators), which the generators do not emit (they count as
        ADC(6) content), so n = 5 is refused before anything is built."""
        if n > MAX_NONDYSON_ORDER:
            raise ValueError(f"non-Dyson ADC({n}): orders above {MAX_NONDYSON_ORDER} need "
                             "the MP5 amplitude numerators (mpn_amp_numerators_o5), which "
                             "the generators do not emit")
        cls = self.classes(n)
        dims = {k: self.dim(k) for k in cls}
        H, S = {}, {}
        for i, k_i in enumerate(cls):
            for k_j in cls[i:]:
                Hs, Ss = {}, {}
                for m in range(0, self.top_order(n, k_i, k_j, extra) + 1):
                    Hs[m], Ss[m] = self.raw_block(k_i, k_j, m, strict)
                for m in Hs:                      # <E^dag (H - E0) E>: subtract the E0 series
                    for c in range(0, m + 1):
                        if np.any(Ss[m - c]):
                            Hs[m] = Hs[m] - self.mp_energy(c) * Ss[m - c]
                H[(k_i, k_j)] = {m: A for m, A in Hs.items() if np.any(A) or m == 0}
                S[(k_i, k_j)] = {m: A for m, A in Ss.items() if np.any(A)}
        return H, S, dims

    def norm(self, n):
        return {0: 1.0, **{m: self.gen.n_norm_order(m) for m in range(2, n + 1)}}

    def effective_blocks(self, n, extra=None, strict=True):
        """Orthonormalized (class-GS + Loewdin) blocks {(k_i,k_j): {m: A}} and dims."""
        H, S, dims = self.raw_series(n, extra, strict)
        blocks, _ = isr_effective_blocks(H, S, dims, n, norm=self.norm(n))
        return blocks, dims

    # ----- the ADC(n) matrix ------------------------------------------------
    def matrix_series(self, n, extra=None, strict=True):
        """[M^(0), ..., M^(n)] of the non-Dyson ADC(n) matrix (block (I,J)
        through order n - k_I - k_J; `extra` = {(k_i,k_j): order} raises a
        block's order, e.g. {(1, 1): 1} for ADC(2)-x) and the class offsets."""
        blocks, dims = self.effective_blocks(n, extra, strict)
        cls = list(dims)
        offs, off = {}, 0
        for k in cls:
            offs[k] = off
            off += dims[k]
        M = [np.zeros((off, off)) for _ in range(n + 1)]
        for k_i in cls:
            for k_j in cls:
                top = self.top_order(n, k_i, k_j, extra)
                for m, A in blocks[(k_i, k_j)].items():
                    if m <= top and m <= n:
                        M[m][offs[k_i]:offs[k_i] + dims[k_i], offs[k_j]:offs[k_j] + dims[k_j]] = A
        return M, dims, offs

    def matrix(self, n, extra=None, strict=True):
        M, dims, offs = self.matrix_series(n, extra, strict)
        return sum(M), dims, offs

    def eigenpairs(self, n, extra=None, strict=True):
        """(eigenvalues ascending, class-0 strengths, eigenvectors) of the
        symmetrized ADC(n) matrix: the IPs or EAs and their pole strengths."""
        M, dims, offs = self.matrix(n, extra, strict)
        w, V = np.linalg.eigh(0.5 * (M + M.T))
        n0 = dims[0]
        strength = np.sum(V[offs[0]:offs[0] + n0] ** 2, axis=0)
        return w, strength, V
