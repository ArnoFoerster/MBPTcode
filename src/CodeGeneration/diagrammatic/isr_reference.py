"""ISR-side reference for the delta = diagram - ISR comparison.

Analytic lambda-order coefficients M(omega; n), n = 2..4, of the PRODUCTION
ISR-ADC(4) content: resolvent expansion of the generated-supermatrix fold

    U(l)^T (omega - K - l*C1 - l^2*C2 - l*C135)^-1 U(l),
    U = l*U1 + l^2*U2 + l^3*U3  (k1),   l^2*U2k2  (k2),

with every block from the pdaggerq generator (BuildSuperMatrixADCn) -- no
hand-written ADC objects.  This is the ISR side the diagram engine is
differenced against; per the diagram-primary rule it is an EXTERNAL
cross-check layer, never part of the derivation.

Basis contract: eps/g/nocc are spin-orbital occupied-first arrays -- the
exact_oracle.spinorb_system layout feeds in unchanged (identity mapping,
gated at n=2/3 against the diagram engine in tests/test_diagram_delta.py;
both sides go through machine precision there, which pins the mapping
before order 4 is trusted).

Validated against the numerical lambda-fold of the full generated adc4
supermatrix at the Taylor-fit floor and self-contained on purpose.
"""
import numpy as np

from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCn
from src.SingleReference.ADC.sigma_driver import diag_K


class ISRBlocks:
    """Per-order generated ADC(4) blocks + analytic lambda^n fold."""

    def __init__(self, eps, g, nocc):
        self.eps, self.g, self.nocc = np.asarray(eps, float), g, nocc
        self.norb = norb = len(eps)
        gen = BuildSuperMatrixADCn(eps, g, nocc)
        self.U1_2h = gen.u_2h1p().T                      # (norb, n2h1p)
        self.U1_2p = gen.u_2p1h().T
        self.U2_2h = gen.u_2h1p_adc3().T - self.U1_2h    # order-2 increment
        self.U2_2p = gen.u_2p1h_adc3().T - self.U1_2p
        self.U3_2h = gen.u3_generated('IP').T
        self.U3_2p = gen.u3_generated('EA').T
        self.K_2h = np.diag(gen.k_block('IP'))
        self.K_2p = np.diag(gen.k_block('EA'))
        self.C1_2h = gen.c1_block('IP')
        self.C1_2p = gen.c1_block('EA')
        self.C2_2h = gen.c2_block_generated('IP')
        self.C2_2p = gen.c2_block_generated('EA')
        self.K_3h = np.asarray(diag_K(self.eps, nocc, norb, 'IP', k=2))
        self.K_3p = np.asarray(diag_K(self.eps, nocc, norb, 'EA', k=2))
        self.U2_3h = gen.u2_k2_generated('IP').T         # (norb, n3h2p)
        self.U2_3p = gen.u2_k2_generated('EA').T
        self.C135_2h = gen.coupling_k1_k2_generated('IP')
        self.C135_2p = gen.coupling_k1_k2_generated('EA')

    def m_orders(self, omega):
        """{2: M2, 3: M3, 4: M4} at one (complex) omega, complex-safe."""
        norb = self.norb
        m = {n: np.zeros((norb, norb), complex) for n in (2, 3, 4)}
        for (U1, U2, U3, C1, C2, K1, U2k2, C135, K2) in (
                (self.U1_2h, self.U2_2h, self.U3_2h, self.C1_2h, self.C2_2h,
                 self.K_2h, self.U2_3h, self.C135_2h, self.K_3h),
                (self.U1_2p, self.U2_2p, self.U3_2p, self.C1_2p, self.C2_2p,
                 self.K_2p, self.U2_3p, self.C135_2p, self.K_3p)):
            G1 = 1.0 / (omega - K1)
            m[2] += (U1 * G1) @ U1.T
            X = (U2 * G1) @ U1.T
            m[3] += X + X.T
            m[3] += (U1 * G1) @ C1 @ (U1 * G1).T
            m[4] += (U2 * G1) @ U2.T
            X = (U1 * G1) @ C1 @ (U2 * G1).T
            m[4] += X + X.T
            m[4] += (U1 * G1) @ C2 @ (U1 * G1).T
            T = C1 * G1[None, :]
            m[4] += (U1 * G1) @ T @ T @ U1.T
            X = (U1 * G1) @ U3.T
            m[4] += X + X.T
            if len(K2):
                G2 = 1.0 / (omega - K2)
                m[4] += (U2k2 * G2) @ U2k2.T
                X = (U2k2 * G2) @ C135.T @ (U1 * G1).T
                m[4] += X + X.T
                m[4] += ((U1 * G1) @ C135 * G2) @ C135.T @ (U1 * G1).T
        return m
