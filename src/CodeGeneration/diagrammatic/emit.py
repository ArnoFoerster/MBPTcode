"""Code emitter for the diagram-ADC track.

Turns the Goldstone engine's skeleton/ordering data into standalone generated
Python modules (numpy-only) that evaluate the dynamic-self-energy blocks
M_block(omega; n) for one PT order.  Emitted into
src/SingleReference/ADC/generatedADC/diagrammatic/ (module m{n}_blocks.py) with
one function per external block plus an assemble_m{n}() composing the full
matrix.  The value rule is the calibrated one from goldstone.py
(value = coeff/n_ext * sigma_ket * prod 1/(dir*omega + sum eps_h - sum eps_p));
each ordering is emitted as one einsum numerator plus broadcast reciprocal
denominators, so the generated code IS the Goldstone diagram sum, readable
term by term (the source comments carry the diagram: factors, ordering,
cuts, sector).
"""
