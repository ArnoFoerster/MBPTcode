def _cut_energy_terms(cut, axis_of, ndim):
    """Source expression for sum eps(holes) - sum eps(particles) of a cut,
    broadcast over the numerator axes."""
    _, holes, particles = cut
    terms = []
    for lbl in holes + particles:
        ax = axis_of[lbl]
        shape = ['1'] * ndim
        shape[ax] = '-1'
        fam = 'o' if lbl in OCC_LETTERS else 'v'
        sign = '' if lbl in holes else '- '
        terms.append(f"{sign}eps[sl['{fam}']].reshape({', '.join(shape)})")
    return ' + '.join(terms).replace('+ -', '-')


