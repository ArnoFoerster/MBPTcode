    skels, _ = build_skeletons(4, block)
    bname = f"du3_{block[0]}{block[1]}"
    body = []
    count = 0
    for skel in skels:
        for ordering in skel.orderings:
            out = _du3_classify(skel, ordering)
            if out is None:
                continue
            count += 1
            j, vstar, sector, cuts = out
            side = 'bra' if vstar == skel.bra_vertex else 'ket'
            strip_lbl = skel.bra_label if side == 'bra' else skel.ket_label
            ext_lbl = skel.ket_label if side == 'bra' else skel.bra_label
            ext_fam = block[1] if side == 'bra' else block[0]
            xi, cfg_lbls = _du3_strip_factor(
                skel.factors[vstar], strip_lbl, sector)

            rest = sorted({ln.idx for ln in skel.lines} - set(cfg_lbls))
            axis_of = {l: i for i, l in enumerate(
                list(cfg_lbls) + [ext_lbl] + rest)}
            ndim = 4 + len(rest)

