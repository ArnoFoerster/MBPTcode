def _subscripts(labels, axis_of):
    return ''.join(chr(97 + axis_of[l]) for l in labels)


def _emit_block(order, block):
    """Source lines for one block function m{order}_{b}{k}(eps, g, nocc, omega)."""
    skels, census = build_skeletons(order, block)
    bname = f"m{order}_{block[0]}{block[1]}"
    src = []
    src.append(f"def {bname}(eps, g, nocc, omega):")
    src.append(f'    """M(omega; {order}) {block} block; '
               f'{sum(s.n_ext for s in skels)} Goldstone diagrams '
               f'({len(skels)} typed skeletons)."""')
    src.append("    norb = len(eps)")
    src.append("    o, v = slice(0, nocc), slice(nocc, norb)")
    src.append("    sl = {'o': o, 'v': v}")
    src.append("    nb = nocc if '%s' == 'o' else norb - nocc" % block[0])
    src.append("    nk = nocc if '%s' == 'o' else norb - nocc" % block[1])
    src.append("    out = np.zeros((nb, nk), dtype=complex)")

    for skel in skels:
        dummies = sorted({ln.idx for ln in skel.lines})
        axis_of = {skel.bra_label: 0, skel.ket_label: 1}
        for i, d in enumerate(dummies):
            axis_of[d] = 2 + i
        subs = []
        slices = []
        for created, annihilated in skel.factors:
            labels = list(created) + list(annihilated)
            subs.append(_subscripts(labels, axis_of))
            sl = ', '.join("sl['%s']" % ('o' if l in OCC_LETTERS else 'v')
                           for l in labels)
            slices.append(f"g[{sl}]")
        out_sub = ''.join(chr(97 + i) for i in range(2 + len(dummies)))
        sig = ','.join(subs) + '->' + out_sub

        src.append(f"    # skeleton: {skel.raw}   (n_orderings={skel.n_ext})")
        src.append(f"    _num = np.einsum('{sig}', {', '.join(slices)}, optimize=True)")
        for ordering in skel.orderings:
            sec = ordering_sector(skel, ordering)
            w = (skel.coeff / skel.n_ext) * ordering_sign(skel, sec)
            cuts = _ordering_cuts(skel, ordering)
            cut_desc = ' '.join(
                f"[{'w' if d != 0 else 'free'}{'+' if d > 0 else '-' if d < 0 else ''}"
                f" {len(h)}h{len(p)}p]" for d, h, p in cuts)
            src.append(f"    #   ordering {ordering} sector {sec:+d}: {cut_desc}")
            src.append("    _v = _num.astype(complex)")
            for (d, holes, particles) in cuts:
                terms = []
                if d != 0:
                    terms.append(f"{d}*omega" if d != 1 else "omega")
                for lbl in holes:
                    ax = axis_of[lbl]
                    shape = ['1'] * (2 + len(dummies))
                    shape[ax] = '-1'
                    fam = 'o' if lbl in OCC_LETTERS else 'v'
                    terms.append(f"eps[sl['{fam}']].reshape({', '.join(shape)})")
                for lbl in particles:
                    ax = axis_of[lbl]
                    shape = ['1'] * (2 + len(dummies))
                    shape[ax] = '-1'
                    fam = 'o' if lbl in OCC_LETTERS else 'v'
                    terms.append(f"- eps[sl['{fam}']].reshape({', '.join(shape)})")
            # join with + but keep the leading '-' of particle terms intact
                expr = ' + '.join(terms).replace('+ -', '-')
                src.append(f"    _v = _v / ({expr})")
            sum_axes = tuple(range(2, 2 + len(dummies)))
            src.append(f"    out += {w!r} * _v.sum(axis={sum_axes})")
    src.append("    return out")
    src.append("")
    src.append("")
    return src, bname


def emit_order(order, out_dir):
    """Write m{order}_blocks.py into out_dir; returns the module path."""
    refuse_above_max_order(order, 'emit_order')
    src = [_HEADER.format(order=order)]
    names = {}
    for block in _BLOCKS:
        lines, bname = _emit_block(order, block)
        src.extend(lines)
        names[block] = bname

    src.append(f"def assemble_m{order}(eps, g, nocc, omega):")
    src.append(f'    """Full M(omega; {order}) matrix from the four blocks."""')
    src.append("    norb = len(eps)")
    src.append("    out = np.zeros((norb, norb), dtype=complex)")
    src.append("    o, v = slice(0, nocc), slice(nocc, norb)")
    for block, bname in names.items():
        rb = 'o' if block[0] == 'o' else 'v'
        rk = 'o' if block[1] == 'o' else 'v'
        src.append(f"    out[{rb}, {rk}] = {bname}(eps, g, nocc, omega)")
    src.append("    return out")
    src.append("")

    os.makedirs(out_dir, exist_ok=True)
    init = os.path.join(out_dir, '__init__.py')
    if not os.path.exists(init):
        open(init, 'w').close()
    path = os.path.join(out_dir, f"m{order}_blocks.py")
    with open(path, 'w') as fh:
        fh.write('\n'.join(src))
    return path


