def _du3_laplace_term(skel, ordering, j, vstar, sector, cuts, cfg_lbls,
                      ext_lbl, w_eff, tag, ext_fam):
    """Emitted source lines for ONE 6f ordering in the Laplace form."""
    mid_cut, far_cut = cuts[1], cuts[2 - j]
    assert len(mid_cut[1]) == 3 and len(mid_cut[2]) == 3, \
        f"middle cut not 3h3p: {skel.raw}"
    assert len(far_cut[1]) == 2 and len(far_cut[2]) == 2, \
        f"far cut not 2h2p: {skel.raw}"
    v_far = ordering[-1] if j == 0 else ordering[0]
    ext2 = skel.ket_vertex if vstar == skel.bra_vertex else skel.bra_vertex
    v_mid = next(v for v in range(4) if v not in (vstar, ext2, v_far))

    def labels_of(v):
        c, a = skel.factors[v]
        return list(c) + list(a)

    lx, lm, lf = labels_of(ext2), labels_of(v_mid), labels_of(v_far)
    u_lbls = [l for l in lx if l != ext_lbl]
    assert len(u_lbls) == 3
    shared_mid = len(set(u_lbls) & set(lm))
    shared_far = len(set(u_lbls) & set(lf))
    # contract the external factor first with the W factor sharing more
    # u-lines (>= 2 always: 3 u-lines over two factors)
    first_far = shared_far >= shared_mid
    assert max(shared_mid, shared_far) >= 2

    # subscript letters: cfg -> a,b,c ; ext -> d ; the rest e..h
    sub = {cfg_lbls[0]: 'a', cfg_lbls[1]: 'b', cfg_lbls[2]: 'c',
           ext_lbl: 'd'}
    for l in sorted({ln.idx for ln in skel.lines} - set(cfg_lbls)):
        sub[l] = chr(ord('e') + len(sub) - 4)

    def gslice(lbls):
        sl = ', '.join("sl['%s']" % ('o' if l in OCC_LETTERS else 'v')
                       for l in lbls)
        return f"g[{sl}]"

    # which factor gets which mid-cut label's weight: u-lines -> external
    # factor; cfg lines + s -> the W factor that carries them (each cfg
    # line sits on exactly one W factor; s is not a mid-cut line)
    def wx(lbls, owner):
        mid_lines = set(mid_cut[1]) | set(mid_cut[2])
        keep = []
        for ax, l in enumerate(lbls):
            if l not in mid_lines:
                continue
            if owner == 'x' and l not in u_lbls:
                continue
            if owner != 'x' and l in u_lbls:
                continue
            arr = '_eo' if l in OCC_LETTERS else '_ev'
            shape = ['1'] * 4
            shape[ax] = '-1'
            keep.append(f"{arr}[_k].reshape({', '.join(shape)})")
        return keep

    src = []
    # t2-like far amplitude (rank 4, one-time)
    ax_far = {l: i for i, l in enumerate(lf)}
    src.append(f"    _tf = {gslice(lf)} / "
               f"({_cut_energy_terms(far_cut, ax_far, 4)})")
    # per-tau weighted slices + two chained einsums
    x_w = ' * '.join(wx(lx, 'x'))
    m_w = ' * '.join(wx(lm, 'w'))
    f_w = ' * '.join(wx(lf, 'w'))
    sx = ''.join(sub[l] for l in lx)
    sm = ''.join(sub[l] for l in lm)
    sf = ''.join(sub[l] for l in lf)
    first_s, first_var = (sf, '_ff') if first_far else (sm, '_fm')
    second_s, second_var = (sm, '_fm') if first_far else (sf, '_ff')
    t1_out = ''.join(ch for ch in sorted(set(sx + first_s))
                     if (sx + first_s).count(ch) == 1)
    out_axes = 'abcd'
    src.append("    for _k in range(len(_taus)):")
    src.append(f"        _fx = {gslice(lx)}" + (f" * {x_w}" if x_w else ""))
    src.append(f"        _fm = {gslice(lm)}" + (f" * {m_w}" if m_w else ""))
    src.append(f"        _ff = _tf" + (f" * {f_w}" if f_w else ""))
    src.append(f"        _t1 = np.einsum('{sx},{first_s}->{t1_out}', "
               f"_fx, {first_var})")
    src.append(f"        _t2 = np.einsum('{t1_out},{second_s}->{out_axes}', "
               f"_t1, {second_var})")
    src.append(f"        {tag}[:, :, :, sl['{ext_fam}']] -= "
               f"(_wts[_k] * {w_eff!r}) * _t2")
    # rank guards: t1 <= 4 axes; the pair (t1, second) closes on exactly abcd
    assert len(t1_out) <= 4, f"rank-{len(t1_out)} intermediate: {skel.raw}"
    shared2 = set(t1_out) & set(second_s)
    assert (set(t1_out) | set(second_s)) - shared2 == set('abcd'), skel.raw
    return src


def _emit_du3_laplace_block(block):
    """Source lines for du3l_{b}{k}(eps, g, nocc, _taus, _wts)."""
    skels, _ = build_skeletons(4, block)
    bname = f"du3l_{block[0]}{block[1]}"
    body = []
    count = 0
    for skel in skels:
        for ordering in skel.orderings:
            out = _du3_classify(skel, ordering)
            if out is None:
                continue
            count += 1
            j, vstar, sector, cuts = out
            side = 'bra' if vstar == skel.bra_vertex else 'ket'
            strip_lbl = skel.bra_label if side == 'bra' else skel.ket_label
            ext_lbl = skel.ket_label if side == 'bra' else skel.bra_label
            ext_fam = block[1] if side == 'bra' else block[0]
            xi, cfg_lbls = _du3_strip_factor(
                skel.factors[vstar], strip_lbl, sector)
            w_eff = ((skel.coeff / skel.n_ext) * ordering_sign(skel, sector)
                     * xi / cuts[j][0])
            tag = ('t_p_' if sector == +1 else 't_m_') + side[0]
            body.append(f"    # 6f: {skel.raw}   ordering {ordering} "
                        f"sector {sector:+d} {side}-stripped")
            body.extend(_du3_laplace_term(
                skel, ordering, j, vstar, sector, cuts, cfg_lbls,
                ext_lbl, w_eff, tag, ext_fam))

    src = [f"def {bname}(eps, g, nocc, _taus, _wts):"]
    src.append(f'    """delta-U3 6f-class grids, Laplace form, {block} '
               f'block; {count} orderings, rank <= 4 intermediates."""')
    src.append("    norb = len(eps)")
    src.append("    nvir = norb - nocc")
    src.append("    o, v = slice(0, nocc), slice(nocc, norb)")
    src.append("    sl = {'o': o, 'v': v}")
    src.append("    _eo = np.exp(np.multiply.outer(_taus, eps[o]))")
    src.append("    _ev = np.exp(-np.multiply.outer(_taus, eps[v]))")
    src.append("    t_p_b = np.zeros((nocc, nvir, nvir, norb))")
    src.append("    t_p_k = np.zeros((nocc, nvir, nvir, norb))")
    src.append("    t_m_b = np.zeros((nvir, nocc, nocc, norb))")
    src.append("    t_m_k = np.zeros((nvir, nocc, nocc, norb))")
    src.extend(body)
    src.append("    return t_p_b, t_p_k, t_m_b, t_m_k")
    src.append("")
    src.append("")
    return src, bname, count


def emit_delta_u3_laplace_order4(out_dir):
    """Write delta_u3_laplace_blocks.py (the PRODUCTION rank<=4 form)."""
    src = [_DU3L_HEADER]
    names = []
    total = 0
    for block in _BLOCKS:
        lines, bname, count = _emit_du3_laplace_block(block)
        src.extend(lines)
        names.append(bname)
        total += count
    if total != 144:
        raise RuntimeError(f"6f census broke at emission: {total} != 144")
    src.append("def assemble_du3_laplace(eps, g, nocc, ntau=14):")
    src.append('    """Canonical delta-U3 rows (du3_p, du3_m), Laplace')
    src.append('    production form; == delta_u3_blocks.assemble_du3 to')
    src.append('    minimax accuracy in ntau (machine floor ~ntau 14)."""')
    src.append("    norb = len(eps)")
    src.append("    _taus, _wts = tau_grid(eps, nocc, ntau)")
    src.append("    acc_p, acc_m = 0.0, 0.0")
    src.append(f"    for fn in ({', '.join(names)}):")
    src.append("        tpb, tpk, tmb, tmk = fn(eps, g, nocc, _taus, _wts)")
    src.append("        acc_p = acc_p + tpb + tpk")
    src.append("        acc_m = acc_m + tmb + tmk")
    src.append("    return (_pack(acc_p / 4.0, nocc, norb, +1),")
    src.append("            _pack(acc_m / 4.0, nocc, norb, -1))")
    src.append("")
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "delta_u3_laplace_blocks.py")
    with open(path, 'w') as fh:
        fh.write('\n'.join(src))
    return path


