"""The ADC(5)-level accessors of the generated runtime stay exact on a
quintuple-capable system (>= 5 occupied and >= 5 virtual spin orbitals;
BeH2/sto-3g is the smallest closed-shell arbiter).

The MPn amplitude census truncates at rank 4: order-4 amplitudes of rank 3
and 4 lack their V.t5_3 / V.t6_3 rungs there, and the amplitude driver
refuses them (pinned in test_compute_order_amplitudes). An ADC(5) consumer
never asks for them: the order-general class-class C^(3), the cross-class
overlaps, the k2 couplings and the norm series through N^(5) read orders <= 3
at any rank and order 4 at rank <= 2 only, so on BeH2 nothing raises or warns.
"""
import os
import sys
import warnings

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
import pytest
from pyscf import gto, scf

from src.SingleReference.ADC.adc_autogenerated import (
    BuildSuperMatrixADCn, BuildSuperMatrixADCnRestricted)
from src.SingleReference.DensityMatrix.mpn_density_driver import MPnDensityDriver
from src.SingleReference.ADC.isr_assembly import collect_spinorbital_raw
from src.Base.pyscf.pyscf_interface import (
    get_orbital_energies, get_antisymmetrized_spin_integrals,
    get_antisymmetrized_spin_block_eri)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(5)

BEH2 = 'Be 0 0 0; H 0 0 1.3; H 0 0 -1.3'


def _build(atom):
    mol = gto.M(atom=atom, basis='sto-3g', verbose=0)
    mf = scf.RHF(mol)
    mf.conv_tol = 1e-13
    mf.run()
    n = mf.mo_coeff.shape[1]
    from pyscf import ao2mo
    eri = ao2mo.kernel(mol, mf.mo_coeff, compact=False).reshape(n, n, n, n)
    h1_mo = mf.mo_coeff.T @ (mol.intor('int1e_kin') + mol.intor('int1e_nuc')) @ mf.mo_coeff
    _, g = get_antisymmetrized_spin_integrals(h1_mo, eri)
    eps = get_orbital_energies(mf, representation='spin')
    eps_sp = get_orbital_energies(mf, representation='spatial')
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf, eri_chemist=eri)
    return dict(eps=eps, g=g, nocc=mol.nelectron, eps_sp=eps_sp, ga=ga, gb=gb,
                gab=gab, nsp=mol.nelectron // 2)


@pytest.fixture(scope='module')
def beh2():
    return _build(BEH2)


def test_beh2_is_quintuple_capable(beh2):
    mpn = MPnDensityDriver(beh2['eps'], beh2['g'], beh2['nocc'])
    assert min(mpn.no, mpn.nv) >= 5, (mpn.no, mpn.nv)


def test_adc5_level_consumers_do_not_raise_on_beh2(beh2):
    gen = BuildSuperMatrixADCn(beh2['eps'], beh2['g'], beh2['nocc'])
    with warnings.catch_warnings():
        warnings.simplefilter('error')
        assert gen.amp_at(2, 4) is not None
        assert gen.amp_at(4, 3) is not None
        n5 = gen.n_norm_order(5)
        assert np.isfinite(n5) and abs(n5) > 0
        c3 = gen.c_block_generated('IP', 3)
        assert np.max(np.abs(c3)) > 1e-8
        # the whole ADC(5) raw block series of the spin-orbital solver
        H, S, dims, norm = collect_spinorbital_raw(gen, 'IP')
        assert 3 in H[(1, 1)] and 3 in H[(0, 2)] and set(norm) >= {2, 3, 4, 5}
    with pytest.raises(RuntimeError, match='rank truncation'):
        gen.amp_at(3, 4)          # what no ADC(5) accessor asks for: refused, not truncated
