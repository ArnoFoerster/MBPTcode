"""GATE for the Laplace-fused order-3 doubles amplitude T2^(3)/L2^(3):
MPnDensityDriverRestricted.compute_t2_3_laplace and the ADC provider
BuildSuperMatrixADCnRestricted._amps_order_lowrank_laplace, which build t2_3 with
NONE of the O(no^3 nv^3) t3_2 / O(no^4 nv^4) t4_2 tensors materialized.

  * compute_t2_3_laplace == the materialized compute_order3_amplitudes' t2_3, to
    the ntau minimax accuracy (converges: ntau=6 ~1e-9, ntau=10 ~1e-13).
  * _amps_order_lowrank_laplace(ntau)['L2_3'] == _amps_order(3)['L2_3'] (the
    exact provider) -- i.e. the ADC-side amplitude the U^(4) low-rank structures
    consume is Laplace-correct, and the provider carries NO rank>=3 key.

NH3/sto-3g (5 occ / 3 vir): smallest system with t3_2 AND t4_2 genuinely nonzero
(asserted), so the split really replaces nonzero tensors
(LiH/H2O zero t3_aaaaaa -> vacuous).

Run:  ~/anaconda3/envs/py310/bin/python -u tests/test_mp4_t2_3_amplitude.py
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.Base.pyscf_interface import (get_orbital_energies,
                                      get_antisymmetrized_spin_block_eri)
from src.SingleReference.DensityMatrix.mpn_density_driver_restricted import (
    MPnDensityDriverRestricted)
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)

_RANK_GE3 = ('L3', 'L4', 'T3', 'T4', 'L5', 'T5')


def _check(ok, msg):
    print(f"[{'OK' if ok else 'FAIL'}] {msg}")
    return ok


def main():
    mol = gto.M(atom='N 0 0 0; H 0 0 1.01; H 0.95 0 -0.3; H -0.48 0.82 -0.3',
                basis='sto-3g', verbose=0)
    mf = scf.RHF(mol); mf.conv_tol = 1e-13; mf.run()
    eps = get_orbital_energies(mf, representation='spatial')
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
    nocc = mol.nelectron // 2
    print(f"NH3/sto-3g norb={len(eps)} nocc={nocc} nvir={len(eps) - nocc}")
    all_ok = True

    # --- driver level: compute_t2_3_laplace vs materialized t2_3 ---
    d = MPnDensityDriverRestricted(np.diag(eps), ga, gab, gb, nocc)
    t2_1a, t2_1b = d.compute_t2_1()
    o2 = d.compute_order2_amplitudes(t2_1a, t2_1b, max_rank=4)
    t1_2a, t2_2a, t2_2b = o2[0], o2[1], o2[2]
    t3_2, t4_2 = o2[3:6], o2[6:10]
    mx3 = max(float(np.abs(x).max()) for x in t3_2)
    mx4 = max(float(np.abs(x).max()) for x in t4_2)
    all_ok &= _check(mx3 > 1e-8 and mx4 > 1e-8,
                     f"t3_2 (|max|={mx3:.2e}) AND t4_2 (|max|={mx4:.2e}) nonzero "
                     f"-- the split replaces real tensors")
    E2 = d.compute_E(t2_1a, t2_1b)
    _, ta_ex, tb_ex, *_ = d.compute_order3_amplitudes(
        t1_2a, t2_2a, t2_2b, *t3_2, *t4_2, t2_1a, t2_1b, E2)
    prev = None
    for ntau in (6, 10):
        ta, tb = d.compute_t2_3_laplace(t1_2a, t2_2a, t2_2b, t2_1a, t2_1b, E2, ntau)
        err = max(float(np.abs(ta - ta_ex).max()), float(np.abs(tb - tb_ex).max()))
        all_ok &= _check(err < (1e-8 if ntau == 6 else 1e-11),
                         f"compute_t2_3_laplace(ntau={ntau}) == materialized t2_3 "
                         f"({err:.2e})")
        if prev is not None:
            all_ok &= _check(err < prev,
                             f"  converges with ntau ({err:.2e} < {prev:.2e}) "
                             f"-- minimax quadrature, not a fixed offset")
        prev = err

    # --- ADC provider level: L2_3 correct + no rank>=3 key ---
    r = BuildSuperMatrixADCnRestricted(eps, ga, gab, gb, nocc)
    lap = r._amps_order_lowrank_laplace(6)
    exact = r._amps_order(max_order=3)
    bad = [k for k in lap if any(k.startswith(p) for p in _RANK_GE3)]
    all_ok &= _check(not bad,
                     f"_amps_order_lowrank_laplace carries NO rank>=3 key "
                     f"(keys={sorted(lap)})")
    for key in ('L2_3', 'T2_3'):
        worst = max(float(np.abs(lap[key][leaf] - exact[key][leaf]).max())
                    for leaf in lap[key])
        all_ok &= _check(worst < 1e-8,
                         f"provider {key} == _amps_order(3) {key} ({worst:.2e})")

    print('\nALL OK' if all_ok else '\nFAILURES')
    return 0 if all_ok else 1


def test_main():
    assert not main(), 'main() returned a nonzero exit code'


if __name__ == '__main__':
    sys.exit(main())
