pytestmark = requires_runtime(4)


@pytest.fixture(scope='module')
def water():
    mol = gto.M(atom='O 0 0 0.117; H 0 0.757 -0.469; H 0 -0.757 -0.469',
                basis='6-31g', verbose=0)
    mf = scf.RHF(mol)
    mf.conv_tol = 1e-12          # fov noise leaks straight into T1^(2)
    mf.run()
    return mf


def test_supermatrix_stays_hermitian_under_the_substitution(water):
    """The point of using t-adjoints (not CC Lambdas) in the bra slots: the
    ADC(3) supermatrix stays symmetric, so the poles stay real and Z stays a
    genuine norm."""
    mf = water
    nocc = mf.mol.nelectron // 2
    eps = get_orbital_energies(mf, representation='spatial')
    eri = get_two_electron_integrals_chemist(mf.mol, mf, representation='spatial')
    gen = BuildSuperMatrixADCn(np.repeat(eps, 2), get_antisymmetrized_spin_eri(eri),
                               2 * nocc, amplitudes=cc_amplitudes_spinorbital(mf))
    H = gen.build_supermatrix_adc3()
    assert np.abs(H - H.T).max() < 1e-12 * max(1.0, np.abs(H).max())


def test_restricted_and_spinorbital_hooks_give_the_same_ip(water):
    """The spin-block CC-ADC(3) is the alpha-Dyson block of the spin-orbital
    one, substitution included."""
    mf = water
    nocc = mf.mol.nelectron // 2
    sc = build_static_correction(mf, kind='mp2_relaxed')

    e, _ = ADCSolver(mf, level='adc3', pdaggerq=True,
                     amplitudes=cc_amplitudes_restricted(mf)
                     ).solve(static_correction=sc)
    ip_restricted = -e[0] * HARTREE_TO_EV

    eps = get_orbital_energies(mf, representation='spatial')
    eri = get_two_electron_integrals_chemist(mf.mol, mf, representation='spatial')
    gen = BuildSuperMatrixADCn(np.repeat(eps, 2), get_antisymmetrized_spin_eri(eri),
                               2 * nocc, amplitudes=cc_amplitudes_spinorbital(mf))
    H = gen.build_supermatrix_adc3(
        static_correction=ADCSolverRestricted.embed_static_correction_spin(sc))
    w, v = np.linalg.eigh(H)
    Z = np.sum(v[:2 * len(eps), :] ** 2, axis=0)
    ip_spinorbital = min(-x for x, z in zip(w, Z) if -x > 0 and z > QP_WINDOW_Z_MIN) * HARTREE_TO_EV
    assert abs(ip_restricted - ip_spinorbital) < 1e-6


def test_substituting_the_mbpt_pool_back_reproduces_plain_adc3(water):
    """The null test of the whole hook: inject the amplitudes the solver would
    have built anyway and ADC(3) must come back bit-for-bit."""
    mf = water
    sc = build_static_correction(mf, kind='mp2_relaxed')
    e_ref, _ = ADCSolver(mf, level='adc3', pdaggerq=True).solve(static_correction=sc)
    e_inj, _ = ADCSolver(mf, level='adc3', pdaggerq=True,
                         amplitudes=mbpt_amplitudes_restricted(mf)
                         ).solve(static_correction=sc)
    assert abs(e_ref[0] - e_inj[0]) < 1e-10


@pytest.mark.parametrize('opts, match', [
    (dict(level='adc3'), 'pdaggerq=True'),
    (dict(level='adc4', pdaggerq=True, construction='diagrammatic'), "level='adc3' only"),
    (dict(level='adc3', pdaggerq=True, en_dress={'hh': True}), 'pass one'),
])
def test_inapplicable_combinations_raise(water, opts, match):
    """Every combination the substitution is not defined for RAISES rather
    than silently computing something else -- in particular the hand-written
    branch, whose merged U^(2) would quietly apply a different linear map."""
    with pytest.raises(ValueError, match=match):
        ADCSolver(water, amplitudes=cc_amplitudes_restricted(water), **opts)


def test_gfree_df_route_equals_the_dense_route_on_the_same_integrals(water_df):
    """The g-free DF CC-ADC(3) -- the only route that fits aug-cc-pVQZ, where
    the dense spin-block ERI is 15-115 GB. Compared against the DENSE route
    fed the exact RI 4-index tensor B.B, so the only thing under test is the
    *_df generated twins, not the RI approximation itself."""
    mf = water_df
    nocc = mf.mol.nelectron // 2
    eps = get_orbital_energies(mf, representation='spatial')
    B = DFIntegrals.from_scf(mf.mol, mf).B_aa
    amps = cc_amplitudes_restricted(mf)
    sc = build_static_correction(mf, kind='mp2_relaxed')

    df = ADCSolver(mf, level='adc3', pdaggerq=True, df=True, amplitudes=amps)
    gen = df._generated()
    assert gen.g_aaaa is None                      # nothing norb^4 was formed
    assert gen._genr.__name__.endswith('_df')
    assert gen._genr3.__name__.endswith('_df')
    e_df, _ = df.solve(static_correction=sc)

    eri_ri = np.einsum('Qpq,Qrs->pqrs', B, B, optimize=True)
    dense = ADCSolverRestricted.from_arrays(eps, eri_ri, nocc=nocc, level='adc3',
                                            pdaggerq=True, amplitudes=amps)
    e_dense, _ = dense.solve(static_correction=sc)
    assert abs(e_df[0] - e_dense[0]) * HARTREE_TO_EV < 1e-8   # eV


def test_gfree_construction_refuses_what_it_cannot_do(water_df):
    """g-free means no EN dressing (the EN shifts read dense g slices): it must
    raise at construction, not compute something else. The MBPT amplitude
    pool is no longer refused: a g-free solver builds it from the DF
    numerators."""
    eps = get_orbital_energies(water_df, representation='spatial')
    B = DFIntegrals.from_scf(water_df.mol, water_df).B_aa
    nocc = water_df.mol.nelectron // 2
    BuildSuperMatrixADCnRestricted(eps, None, None, None, nocc, B_aa=B)
    with pytest.raises(ValueError, match='no EN hook'):
        BuildSuperMatrixADCnRestricted(eps, None, None, None, nocc, B_aa=B,
                                       u2_denom_dress={'hh': True})
    with pytest.raises(ValueError, match='pass one'):
        BuildSuperMatrixADCnRestricted(
            eps, None, None, None, nocc, B_aa=B,
            amplitudes=cc_amplitudes_restricted(water_df),
            u2_denom_dress={'hh': True})
    with pytest.raises(ValueError, match='either dense spin-block g or a DF'):
        BuildSuperMatrixADCnRestricted(eps, None, None, None, nocc)
