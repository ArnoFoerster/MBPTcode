"""Increment 2 gate of the spin-free ADC(2)-(5) plan
the restricted
(spin-blocked, RHF) BuildSuperMatrixADCnRestricted assembles the alpha-Dyson
sector purely from SPATIAL spin-block tensors, and must reproduce the
spin-orbital BuildSuperMatrixADCn's physics:

1. Self-energy oracle (config-ordering-free): the spatial ADC(2) self-energy
   Sigma_alpha(omega) equals the alpha-spatial block Sigma_spin[0::2, 0::2]
   of the spin-orbital self-energy at arbitrary omega. This is the
   MP2 self-energy oracle in spatial form.

2. Poles: every eigenvalue of the alpha-sector spatial supermatrix is an
   eigenvalue of the full spin-orbital ADC(2) supermatrix (the alpha-Dyson
   sector is exactly one of the two identical spin blocks the spin-orbital
   matrix factors into for a closed-shell reference).

H2O/sto-3g decisive; H2/sto-3g smoke.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.SingleReference.ADC.adc_autogenerated import (
    BuildSuperMatrixADCn, BuildSuperMatrixADCnRestricted)
from src.Base.pyscf_interface import (
    get_orbital_energies, get_two_electron_integrals_chemist,
    get_antisymmetrized_spin_eri, get_antisymmetrized_spin_block_eri)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)


def check(label, diff, tol=1e-11):
    ok = diff < tol
    print(f"[{'OK' if ok else 'FAIL'}] {label}: {diff:.3e}")
    return ok


def _subset_diff(sub, full, tol=1e-9):
    """Max distance from each value in `sub` to the nearest value in `full`."""
    full = np.sort(full)
    worst = 0.0
    for x in sub:
        j = np.searchsorted(full, x)
        cand = [full[k] for k in (j - 1, j) if 0 <= k < len(full)]
        worst = max(worst, min(abs(x - c) for c in cand))
    return worst


def main():
    all_ok = True

    for atom, basis, label in [
        ('H 0 0 0; H 0 0 0.74', 'sto-3g', 'H2/sto-3g (smoke)'),
        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g (decisive)'),
    ]:
        mol = gto.M(atom=atom, basis=basis, verbose=0)
        mf = scf.RHF(mol).run()
        nocc_sp = mol.nelectron // 2
        eps_sp = get_orbital_energies(mf, representation='spatial')

        # spin-orbital reference
        nocc = 2 * nocc_sp
        eps = get_orbital_energies(mf, representation='spin')
        eri = get_two_electron_integrals_chemist(mol, mf, representation='spatial')
        g = get_antisymmetrized_spin_eri(eri)
        so = BuildSuperMatrixADCn(eps, g, nocc)

        # restricted spatial solver
        g_aaaa, g_bbbb, g_abab = get_antisymmetrized_spin_block_eri(mol, mf)
        r = BuildSuperMatrixADCnRestricted(eps_sp, g_aaaa, g_abab, g_bbbb, nocc_sp)

        print(f"\n=== {label} ===")

        # 1. self-energy oracle
        for omega in (0.15, -0.35, 0.85):
            sig_r = r.sigma_dynamic(omega)
            sig_so = so.sigma_dynamic(omega)[0::2, 0::2]
            all_ok &= check(f"Sigma_alpha(omega={omega:+.2f}) == spin-orbital[0::2,0::2]",
                            np.abs(sig_r - sig_so).max())

        # 2. poles: alpha-sector eigenvalues subset of spin-orbital ADC(2) eigenvalues
        H_r = r.build_supermatrix_adc2()
        H_so = so.build_supermatrix_adc2()
        all_ok &= check("H_alpha symmetric", np.abs(H_r - H_r.T).max())
        e_r = np.linalg.eigvalsh(H_r)
        e_so = np.linalg.eigvalsh(H_so)
        all_ok &= check("eig(H_alpha) subset of eig(H_spinorbital)", _subset_diff(e_r, e_so))

    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
