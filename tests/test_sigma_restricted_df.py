"""DF end-to-end through the RESTRICTED matrix-free operator (item #3): the
whole excitation-space matvec (C^(1) self, C^(2) via the Loewdin-assembled
raw+s2c, and the k=1<->k=2 coupling) runs off the RI factor B_aa/B_bb with no
(nso^4) g tensor -- by passing the *_df_blocks apply modules + {'B_aa','B_bb'}
as extra leaves to restricted_sector_operator / restricted_full_operator.

With an EXACT RI factor (naux = norb^2, get_density_fitting_coefficients, no
fitting error) the DF operator must equal the full-g operator to machine
precision. Validated both ways -- random-vector matvec equality AND spectrum
(eigsh) equality -- for the ADC(4)-base sector operator and the FULL multi-class
operator, both sectors, on LiH/H2O.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf
from scipy.sparse.linalg import eigsh

from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.SingleReference.ADC.generated_modules import lazy
c1r = lazy('adc4_c1_self_apply_restricted_blocks')
c2r = lazy('adc4_c2_apply_restricted_blocks')
s2r = lazy('adc4_c2_s2c_apply_restricted_blocks')
k2r = lazy('adc4_k2_apply_restricted_blocks')
c1rd = lazy('adc4_c1_self_apply_restricted_df_blocks')
c2rd = lazy('adc4_c2_apply_restricted_df_blocks')
s2rd = lazy('adc4_c2_s2c_apply_restricted_df_blocks')
k2rd = lazy('adc4_k2_apply_restricted_df_blocks')
from src.SingleReference.ADC.sigma_driver import (
    restricted_sector_operator, restricted_full_operator)
from src.Base.pyscf.pyscf_interface import (
    get_orbital_energies, get_antisymmetrized_spin_block_eri,
    get_density_fitting_coefficients)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)


# eigsh does many matvecs; the DF k=2 coupling matvec is heavier (extra naux
# contraction), so only run the spectrum comparison on the small dims -- the
# random-vector matvec equality already proves the two operators are IDENTICAL
# (a linear operator is fixed by its action; DF==full-g to ~1e-15 => same
# spectrum), the eigsh check is just an explicit confirmation.
_EIG_MAX_DIM = 75


def compare(op_g, op_df, label, all_ok):
    n = op_g.shape[0]
    rng = np.random.default_rng(0)
    mvdiff = 0.0
    for _ in range(5):
        r = rng.standard_normal(n)
        mvdiff = max(mvdiff, np.abs(op_g.matvec(r) - op_df.matvec(r)).max())
    if n <= _EIG_MAX_DIM:
        k = min(6, n - 2)
        wg = np.sort(eigsh(op_g, k=k, which='SA', return_eigenvectors=False))
        wdf = np.sort(eigsh(op_df, k=k, which='SA', return_eigenvectors=False))
        eigdiff = np.abs(wg - wdf).max()
        spec = f", spectrum {eigdiff:.2e}"
    else:
        eigdiff, spec = 0.0, " (eigsh skipped, dim large)"
    ok = mvdiff < 1e-10 and eigdiff < 1e-9
    print(f"    [{'OK' if ok else 'FAIL'}] {label} (dim {n}): "
          f"DF vs full-g matvec {mvdiff:.2e}{spec}")
    return all_ok and ok


def main():
    all_ok = True
    for atom, basis, label in [
        ('Li 0 0 0; H 0 0 1.6', 'sto-3g', 'LiH/sto-3g'),
        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g'),
    ]:
        mol = gto.M(atom=atom, basis=basis, verbose=0)
        mf = scf.RHF(mol).run()
        nocc_sp = mol.nelectron // 2
        eps_sp = get_orbital_energies(mf, representation='spatial')
        g_aaaa, g_bbbb, g_abab = get_antisymmetrized_spin_block_eri(mol, mf)
        r = BuildSuperMatrixADCnRestricted(eps_sp, g_aaaa, g_abab, g_bbbb, nocc_sp)
        B_aa = get_density_fitting_coefficients(mol, mf, representation='spatial')  # exact
        B = {'B_aa': B_aa, 'B_bb': B_aa}                                           # RHF twin

        print(f"\n=== {label}  (naux={B_aa.shape[0]}) ===")
        for sector in ('IP', 'EA'):
            U = r.u_adc3(sector)
            # ADC(4)-base sector operator: full-g vs DF
            op_g = restricted_sector_operator(sector, r, U, c1r, c2r, s2r)
            op_df = restricted_sector_operator(sector, r, U, c1rd, c2rd, s2rd, extra_leaves=B)
            all_ok = compare(op_g, op_df, f"{sector} ADC(4)-base sector op", all_ok)

            # FULL multi-class operator: full-g vs DF (skip if no k2 configs)
            if len(r._kconfigs(sector, 2)['K']) == 0:
                print(f"    (skip {sector} full op: no 3h2p/3p2h configs)")
                continue
            U2_k2 = r.u2_k2_generated(sector)
            op_gf = restricted_full_operator(sector, r, U, U2_k2, k2r, c1r, c2r, s2r)
            op_dff = restricted_full_operator(sector, r, U, U2_k2, k2rd, c1rd, c2rd, s2rd,
                                              extra_leaves=B)
            all_ok = compare(op_gf, op_dff, f"{sector} FULL multi-class op", all_ok)

    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
