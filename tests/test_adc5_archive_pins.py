"""ADC(5) in the constructions behind the published SupInf IP-ADC numbers,
pinned to the code that produced them (an earlier tree of this code):
the
dense spectra of union-space, diagrammatic (exact and Laplace decoupling at
8 points) and two-sector Dyson ADC(5) on linear H4 (r = 1.0) and of
non-Dyson IP/EA-ADC(5) on LiH, all in sto-3g with diag(eps) as the orbital
block. The pins are the three lowest and the highest eigenvalue (Ha); MBPTcode
reproduced the archive operators there to 6e-16 relative on random vectors and
the spectra to 1e-13 Ha. Unlike test_adc5_union_poles this gate needs no
lambda oracle.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
import pytest
from pyscf import gto, scf

from src.Base.pyscf.pyscf_interface import get_orbital_energies, get_antisymmetrized_spin_block_eri
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.SingleReference.ADC.nondyson_restricted import NonDysonRestricted
from src.SingleReference.ADC.sigma_driver import restricted_dyson_operator
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(5)

TOL = 1e-9
H4 = 'H 0 0 0; H 0 0 1.0; H 0 0 2.0; H 0 0 3.0'
LIH = 'Li 0 0 0; H 0 0 1.6'
DYSON5_H4 = {
    'twosector': [-2.5413993890434714, -2.4489611585195146, -2.1103452381574814, 2.6440530419828416],
    'union': [-2.541697505450587, -2.4493061247341466, -2.1105518994601846, 2.644307232388845],
    'diagrammatic': [-2.541395960790056, -2.448957787507576, -2.1103297630791844, 2.644051996288431],
    'diagrammatic_ntau8': [-2.5413959607900583, -2.4489577875075956, -2.1103297630792537,
                           2.6440519962884417],
}
NONDYSON5_LIH = {
    'IP': [0.26739475656555095, 0.7096251085739467, 0.7210853522632918, 6.795594175961393],
    'EA': [0.07571572995355622, 0.15667283387980607, 0.156672833879808, 6.399703386349527],
}


def _solver(atom):
    mol = gto.M(atom=atom, basis='sto-3g', verbose=0)
    mf = scf.RHF(mol)
    mf.conv_tol, mf.conv_tol_grad = 1e-13, 1e-10
    mf.run()
    eps = get_orbital_energies(mf, representation='spatial')
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
    return BuildSuperMatrixADCnRestricted(eps, ga, gab, gb, mol.nelectron // 2)


def _pins(op):
    M = np.column_stack([op.matvec(e) for e in np.eye(op.shape[0])])
    w = np.linalg.eigvalsh(0.5 * (M + M.T))
    return float(np.max(np.abs(M - M.T))), np.array([w[0], w[1], w[2], w[-1]])


@pytest.mark.parametrize('variant', sorted(DYSON5_H4))
def test_dyson_adc5_h4(variant):
    construction, _, ntau = variant.partition('_ntau')
    kw = dict(decoupling_ntau=int(ntau)) if ntau else {}
    asym, w = _pins(restricted_dyson_operator(_solver(H4), 'adc5', construction=construction,
                                              **kw)[0])
    d = float(np.max(np.abs(w - DYSON5_H4[variant])))
    print(f"H4 ADC(5) {variant}: |MBPTcode - archive| {d:.1e} Ha, asymmetry {asym:.1e}")
    assert asym <= 1e-12, asym
    assert d <= TOL, d


@pytest.mark.parametrize('sector', ['IP', 'EA'])
def test_nondyson_adc5_lih(sector):
    asym, w = _pins(NonDysonRestricted(_solver(LIH), sector).operator(5)[0])
    d = float(np.max(np.abs(w - NONDYSON5_LIH[sector])))
    print(f"LiH non-Dyson {sector}-ADC(5): |MBPTcode - archive| {d:.1e} Ha, asymmetry {asym:.1e}")
    assert asym <= 1e-12, asym
    assert d <= TOL, d


def main():
    for variant in sorted(DYSON5_H4):
        test_dyson_adc5_h4(variant)
    for sector in ('IP', 'EA'):
        test_nondyson_adc5_lih(sector)
    print('\nALL OK')
    return True


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
