"""Gate for the ADC(5) (2,2) block -- the k=2 class-class self-coupling.

`adc_order_rule.block_order(n, 2, 2)` is 0 at ADC(4) and 1 at ADC(5), so this
first-order 3h2p x 3h2p / 3p2h x 3p2h coupling is the block that makes ADC(5)
structurally different from ADC(4). More generally the top manifold's
self-block carries order `n - 2*(n//2)`: **0 for every even n, 1 for every odd
n**. So this is the generic odd-order object, and the closed-form Schur
complement in `solve_dyson_adc_downfolded` is exact for ADC(2)/(4)/(6)/... and
invalid for ADC(3)/(5)/(7)/...

The generation was recorded in plans as blocked on an index-budget risk (6 free
occ + 4 free vir exceed the historic 6-letter pool). That is stale --
`precursor_classes._label_pool` is unbounded, and both sectors derive in <0.1 s
(15 f-terms, 26 v-terms).

Checks
------
1. **k0 (f part) diagonal == sigma_driver.diag_K(..., k=2).** A free end-to-end
   check on the class enumeration, the bra/ket letter offsets and the sector
   sign -- three things that have each been a real bug in this generator, and
   that no amount of internal consistency would catch.
2. **k0 is EXACTLY diagonal.** The order-0 property that makes the even-order
   downfold's `(omega - K2)^-1` a reciprocal rather than a linear solve.
3. **C^(1)_k2 is Hermitian** -- not imposed by the assembly, so a real check.
4. **C^(1)_k2 has genuine off-diagonal weight**, i.e. ADC(5) really does break
   the diagonal-K assumption. If it did not, the downfold guard would be
   pointless and the (2,2) block would be a no-op.
5. **The downfold guard** rejects a nonzero-(2,2) level and does not
   reject `level='adc3'` (whose kmax is 1 -- there is no k=2
   manifold to fold, so `block_order(3,2,2) == -1` means "no such block", not
   "a nonzero one").
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np

from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCn
from src.SingleReference.ADC.sigma_driver import diag_K
from src.SingleReference.ADC.adc_order_rule import block_order, kmax
from tests.adc_common import spin_orbital_sto3g
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(5)

SYSTEMS = [('H4/sto-3g', 'H 0 0 0; H 0 0 0.80; H 0 0 1.75; H 0 0 2.60'),
           ('LiH/sto-3g', 'Li 0 0 0; H 0 0 1.6')]


def _check(ok, msg):
    print(f"[{'OK' if ok else 'FAIL'}] {msg}")
    return ok


def main():
    all_ok = True

    # the order-rule statement this block exists to satisfy
    print("=== order rule: top-manifold self-block order ===")
    ev = [n for n in range(2, 13) if block_order(n, kmax(n), kmax(n)) == 0]
    od = [n for n in range(2, 13) if block_order(n, kmax(n), kmax(n)) == 1]
    all_ok &= _check(ev == list(range(2, 13, 2)) and od == list(range(3, 13, 2)),
                     f"order 0 (diagonal K, closed-form Schur exact) for even "
                     f"n={ev}; order 1 for odd n={od}")

    for label, atom in SYSTEMS:
        eps, g, nocc = spin_orbital_sto3g(atom)
        gen = BuildSuperMatrixADCn(eps, g, nocc)
        print(f"\n=== {label} ===")
        for sec in ('IP', 'EA'):
            K0 = gen.k2_self_block_generated(sec, ham='f')
            C1 = gen.k2_self_block_generated(sec, ham='v')
            Kref = np.asarray(diag_K(eps, nocc, len(eps), sec, k=2))

            d = np.max(np.abs(np.diag(K0) - Kref))
            all_ok &= _check(d < 1e-12, f"{sec} k0 diagonal == diag_K(k=2) "
                                        f"({d:.1e}, n_k2={K0.shape[0]})")
            off = np.max(np.abs(K0 - np.diag(np.diag(K0))))
            all_ok &= _check(off == 0.0, f"{sec} k0 is EXACTLY diagonal ({off:.1e}) "
                                         f"-- the order-0 property the even-order "
                                         f"downfold Schur relies on")
            scale = max(np.max(np.abs(C1)), 1e-30)
            h = np.max(np.abs(C1 - C1.T)) / scale
            all_ok &= _check(h < 1e-12, f"{sec} C^(1)_k2 Hermitian ({h:.1e} rel), "
                                        f"|C^(1)_k2|max={scale:.4e}")
            offw = np.max(np.abs(C1 - np.diag(np.diag(C1)))) / scale
            all_ok &= _check(offw > 1e-3,
                             f"{sec} C^(1)_k2 has real off-diagonal weight "
                             f"({100 * offw:.1f}% of max) -- ADC(5) genuinely "
                             f"breaks the diagonal-K assumption")

    # the downfold guard
    print("\n=== solve_dyson_adc_downfolded guard ===")
    all_ok &= _check(block_order(4, 2, 2) == 0 and block_order(5, 2, 2) == 1,
                     "guard predicate: (2,2) order is 0 at ADC(4), 1 at ADC(5)")
    all_ok &= _check(kmax(3) < 2,
                     "level='adc3' has kmax=1, so there is NO k=2 manifold to "
                     "fold -- block_order(3,2,2)=-1 means 'no such block' and "
                     "must not trip the guard")

    print('\nALL OK' if all_ok else '\nFAILURES')
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
