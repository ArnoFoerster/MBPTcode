"""Increment 3 gate of the spin-free ADC(2)-(5) plan
the restricted
(spin-blocked, RHF) BuildSuperMatrixADCnRestricted.build_supermatrix_adc3
assembles the alpha-Dyson-sector Dyson-ADC(3) supermatrix -- F + U through
order 2 (the spin-blocked order-2 dressed U^(2) splits + the same class-GS
-eps_p S^(2) rule) + K diagonal + first-order C^(1) class blocks -- purely
from SPATIAL spin-block tensors and restricted MPn amplitudes.

Validated against TWO independent references:
1. The spin-orbital GENERATED ADC(3) supermatrix
   (BuildSuperMatrixADCn.build_supermatrix_adc3, itself == the validated
   adc_spinorbital at 1e-15): every restricted alpha-sector eigenvalue is
   a spin-orbital ADC(3) pole.
2. restricted.py's validated CSF-basis ADC(3) supermatrix: every CSF
   pole is an eigenvalue of the restricted determinant-basis matrix (the
   alpha-sector determinant space contains the doublet CSF space).

The order-2 amplitude convention is the crux (fixed here): the l1/l2 dressed
splits index the lambda amplitudes in the pdaggerq 'l{rank}' tag layout
(to_l: pure blocks reverse the vir side + sign, mixed blocks a
plain occ<->vir transpose) -- a plain transpose is wrong for abab.

H2O/sto-3g decisive; H2/sto-3g smoke.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.SingleReference.ADC.adc_autogenerated import (
    BuildSuperMatrixADCn, BuildSuperMatrixADCnRestricted)
from src.SingleReference.ADC import ADCSolverRestricted
from src.Base.pyscf.pyscf_interface import (
    get_orbital_energies, get_two_electron_integrals_chemist,
    get_antisymmetrized_spin_eri, get_antisymmetrized_spin_block_eri)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)


def check(label, diff, tol=1e-9):
    ok = diff < tol
    print(f"[{'OK' if ok else 'FAIL'}] {label}: {diff:.3e}")
    return ok


def _subset_diff(sub, full):
    full = np.sort(full)
    worst = 0.0
    for x in sub:
        j = np.searchsorted(full, x)
        cand = [full[k] for k in (j - 1, j) if 0 <= k < len(full)]
        worst = max(worst, min(abs(x - c) for c in cand))
    return worst


def main():
    all_ok = True

    for atom, basis, label in [
        ('H 0 0 0; H 0 0 0.74', 'sto-3g', 'H2/sto-3g (smoke)'),
        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g (decisive)'),
    ]:
        mol = gto.M(atom=atom, basis=basis, verbose=0)
        mf = scf.RHF(mol).run()
        nocc_sp = mol.nelectron // 2
        eps_sp = get_orbital_energies(mf, representation='spatial')
        eri = get_two_electron_integrals_chemist(mol, mf, representation='spatial')

        # spin-orbital generated ADC(3) reference
        nocc = 2 * nocc_sp
        eps = get_orbital_energies(mf, representation='spin')
        g = get_antisymmetrized_spin_eri(eri)
        so = BuildSuperMatrixADCn(eps, g, nocc)

        # restricted spatial ADC(3)
        g_aaaa, g_bbbb, g_abab = get_antisymmetrized_spin_block_eri(mol, mf)
        r = BuildSuperMatrixADCnRestricted(eps_sp, g_aaaa, g_abab, g_bbbb, nocc_sp)

        print(f"\n=== {label} ===")
        H_r = r.build_supermatrix_adc3()
        all_ok &= check("H_r(adc3) symmetric", np.abs(H_r - H_r.T).max(), tol=1e-10)
        e_r = np.linalg.eigvalsh(H_r)

        e_so = np.linalg.eigvalsh(so.build_supermatrix_adc3())
        all_ok &= check("eig(H_r) subset spin-orbital generated ADC(3)",
                        _subset_diff(e_r, e_so))

        csf = ADCSolverRestricted.from_arrays(eps_sp, eri)
        e_csf = np.linalg.eigvalsh(csf.build_supermatrix(nocc_sp))
        all_ok &= check("restricted CSF poles subset eig(H_r)",
                        _subset_diff(e_csf, e_r))

    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
