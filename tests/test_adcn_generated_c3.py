"""Gate for the ORDER-GENERAL class-class C^(n) assembly (ADC(5)'s C^(3)).

`adc5_c3_blocks` had been generated for some time but NOTHING consumed it --
the driver had a hand-written order-2 `c2_block_generated` and no order-general
path, so ADC(5)'s C^(3) did not exist as a runnable object.
`BuildSuperMatrixADCn.c_block_generated(sector, n)` supplies it, with the order
bookkeeping taken from `adc_order_rule` (every tag structure x amplitude-order
assignment with a + b + [ham == 'v'] == n) rather than a per-order hand list.

What each check is for
----------------------
1. **n=2 == c2_block_generated, BIT-EXACT.** The certifying check. It exercises
   the whole machinery -- structure resolution across modules, class gathering,
   the N^(m) normalization, and the ISR/Loewdin convolution -- against an
   independently-written, already-validated implementation. Nothing about n=3
   is trustworthy unless n=2 reproduces exactly.
2. **Hermiticity of C^(3).** NOT imposed anywhere in the assembly (same as
   C^(2) -- see c2_block_generated's docstring), so it is a real check on the
   bra/ket dressing and the gathering, not a tautology.
3. **N^(3) invariance.** Scaling N^(3) leaves C^(3) unchanged to machine
   precision: `raw3 -= N^(3) K` is exactly undone by `S^(3) -= N^(3) I` acting
   through the Loewdin y3. The orthonormalized block is normalization-
   invariant, so N^(3) is NOT a free parameter here. This matters because
   N^(3) is directly validated elsewhere (exact norm series, 6.6e-11)
   -- this check shows the CLASS-CLASS block does not even
   depend on that value, only on N^(3) cancelling consistently between raw and
   S.
4. **lambda^5 pole-order gate** (needs the git-ignored `validation/`, skipped
   otherwise). The decisive physics check -- see below.

Why the pole-order gate works without order-4 amplitudes
--------------------------------------------------------
A complete ADC(5) also needs U^(4), which does not exist yet (no t2_4/t3_4).
But the two enter the lambda^5 fold coefficient with DIFFERENT pole orders at
the k=1 config energies:

    U^(4):  (U1 G3) U4^T + h.c.            -> SINGLE pole
    C^(3):  (U1 G3) C^(3) (G3 U1)^T        -> DOUBLE pole

and every other order-5 double/triple-pole term is built from blocks already
validated at lambda^4 (C^(1), C^(2), U^(2), U^(3)). So a CORRECT C^(3) must
collapse the c5 mismatch to a pure single pole, which shows up as the mismatch
scaling exactly as 1/delta as omega -> K. Measured on H2/sto-3g:

    C^(3) scale   0.0    0.5    0.9   *1.0*   1.1    1.5
    ratio/halving 3.03   2.69   2.19  *2.00*  1.77   0.22

Exactly 2.000 at scale 1, and a sharp function of the scale either side -- so
the test both passes and demonstrably discriminates (a +-10% error is resolved).

H2/sto-3g is the right arbiter HERE even though it is insufficient in general:
it has no 5-line manifold, so it is untouched by
the open lambda^4 3h2p defect that would otherwise contaminate c5, and its
C^(2) is identically zero while its C^(3) is NOT -- so this isolates C^(3).
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np

from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCn
from tests.generated_runtime import requires_runtime
from src.SingleReference.ADC.generated_modules import generated

pytestmark = requires_runtime(5)

SYSTEMS = [
    ('H2/sto-3g', 'H 0 0 0; H 0 0 0.74'),
    ('H4/sto-3g', 'H 0 0 0; H 0 0 0.80; H 0 0 1.75; H 0 0 2.60'),
    ('LiH/sto-3g', 'Li 0 0 0; H 0 0 1.6'),
]


def _build(atom, basis='sto-3g'):
    from pyscf import gto, scf, ao2mo
    from src.Base.pyscf_interface import (get_orbital_energies,
                                          get_antisymmetrized_spin_integrals)
    mol = gto.M(atom=atom, basis=basis, verbose=0)
    mf = scf.RHF(mol)
    mf.conv_tol = 1e-13
    mf.run()
    n = mf.mo_coeff.shape[1]
    eri = ao2mo.kernel(mol, mf.mo_coeff, compact=False).reshape(n, n, n, n)
    h1_mo = mf.mo_coeff.T @ (mol.intor('int1e_kin')
                             + mol.intor('int1e_nuc')) @ mf.mo_coeff
    h1, g = get_antisymmetrized_spin_integrals(h1_mo, eri)
    eps = get_orbital_energies(mf, representation='spin')
    return eps, h1, g, mol.nelectron


def _check(ok, msg):
    print(f"[{'OK' if ok else 'FAIL'}] {msg}")
    return ok


def main():
    all_ok = True

    for label, atom in SYSTEMS:
        eps, h1, g, nocc = _build(atom)
        gen = BuildSuperMatrixADCn(eps, g, nocc)
        print(f"\n=== {label} ===")

        # 1. n=2 must reproduce the hand-written order-2 assembly exactly
        for sec in ('IP', 'EA'):
            d = np.max(np.abs(gen.c_block_generated(sec, 2)
                              - gen.c2_block_generated(sec)))
            all_ok &= _check(d == 0.0, f"{sec} c_block_generated(n=2) == "
                                       f"c2_block_generated bit-exact ({d:.1e})")

        # N^(2) from the general norm formula must equal the validated n2_norm
        d = abs(gen.n_norm_order(2) - gen.n2_norm())
        all_ok &= _check(d == 0.0, f"N^(2) general == n2_norm() ({d:.1e})")

        for sec in ('IP', 'EA'):
            c3 = gen.c_block_generated(sec, 3)
            scale = max(np.max(np.abs(c3)), 1e-30)

            # 2. Hermiticity -- not imposed, so a real check
            h = np.max(np.abs(c3 - c3.T)) / scale
            all_ok &= _check(h < 1e-12, f"{sec} C^(3) Hermitian ({h:.1e} rel), "
                                        f"|C^(3)|max={scale:.3e}")

            # 3. N^(3) is a normalization convention and must cancel
            worst = 0.0
            for s in (0.0, 0.5, 2.0, -1.0):
                gb = BuildSuperMatrixADCn(eps, g, nocc)
                t = gb.n_norm_order
                gb.n_norm_order = (
                    lambda m, _t=t, _s=s: (_t(m) * _s if m == 3 else _t(m)))
                worst = max(worst,
                            np.max(np.abs(gb.c_block_generated(sec, 3) - c3)))
            all_ok &= _check(worst / scale < 1e-12,
                             f"{sec} C^(3) invariant under N^(3) rescaling "
                             f"({worst:.1e})")

    # 5. RESTRICTED twin -- and the Delta S^(n) series that
    #    sigma_driver.u_dot_orb_isr hard-fails on for n >= 4
    print("\n=== restricted twin ===")
    from pyscf import gto, scf
    from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
    from src.SingleReference.ADC.precursor_classes import class_configs
    from src.Base.pyscf_interface import (
        get_orbital_energies, get_two_electron_integrals_chemist,
        get_antisymmetrized_spin_eri, get_antisymmetrized_spin_block_eri)
    from test_adcn_generated_c2_restricted import _alpha_to_class_index

    # H2 is listed but NOT asked for a nonzero Delta S^(3): there the raw
    # order-3 class overlap is exactly N^(3) * I, so the normalization-corrected
    # Delta S^(3) vanishes identically (same on the spin-orbital side). That is
    # physics, not an assembly failure -- it is one more face of
    # H2's blind spots, and the reason the nonzero check has to run on
    # a system with a genuinely multi-dimensional class space.
    for atom, label, want_nonzero in [
            ('H 0 0 0; H 0 0 0.74', 'H2/sto-3g', False),
            ('Li 0 0 0; H 0 0 1.6', 'LiH/sto-3g', True),
            ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'H2O/sto-3g', True)]:
        mol = gto.M(atom=atom, basis='sto-3g', verbose=0)
        mf = scf.RHF(mol).run()
        nocc_sp = mol.nelectron // 2
        nocc = 2 * nocc_sp
        eps = get_orbital_energies(mf, representation='spin')
        g = get_antisymmetrized_spin_eri(
            get_two_electron_integrals_chemist(mol, mf, representation='spatial'))
        so = BuildSuperMatrixADCn(eps, g, nocc)
        eps_sp = get_orbital_energies(mf, representation='spatial')
        g_aaaa, g_bbbb, g_abab = get_antisymmetrized_spin_block_eri(mol, mf)
        r = BuildSuperMatrixADCnRestricted(eps_sp, g_aaaa, g_abab, g_bbbb, nocc_sp)
        print(f"\n--- {label} ---")
        for sec in ('IP', 'EA'):
            d = np.max(np.abs(r.c_block_generated(sec, 2)
                              - r.c2_block_generated(sec)))
            all_ok &= _check(d == 0.0, f"{sec} restricted n=2 == "
                                       f"c2_block_generated bit-exact ({d:.1e})")
            cols = class_configs(nocc, len(eps), 1, sector=sec)
            idx = _alpha_to_class_index(r, r._sector_configs(sec), sec, cols, nocc)
            c3r = r.c_block_generated(sec, 3)
            c3so = so.c_block_generated(sec, 3)
            d = np.max(np.abs(c3r - c3so[np.ix_(idx, idx)]))
            all_ok &= _check(d < 1e-11, f"{sec} restricted C^(3) == spin-orbital "
                                        f"C^(3) at the alpha configs ({d:.1e})")
            Ss = r.class_overlap_series(sec, 3)
            m3 = np.max(np.abs(Ss[3]))
            ok = set(Ss) == {2, 3} and (m3 > 1e-12 if want_nonzero else m3 < 1e-14)
            all_ok &= _check(ok, f"{sec} Delta S series orders {sorted(Ss)}, "
                                 f"|dS^(3)|max={m3:.3e} "
                                 f"({'nonzero' if want_nonzero else 'zero by H2 degeneracy'})"
                                 f" -- what u_dot_orb_isr(n>=4) needs and refuses "
                                 f"to run without")

    # 6. The payoff: Delta S^(3) is what unblocked the order-general U^(n) ISR
    #    at n=4. u_dot_orb_isr used to REFUSE n>=4 ("would be silently
    #    TRUNCATED"); it now runs in strict mode, and n=3 must be untouched.
    print("\n=== u_dot_orb_isr at n=4 (U^(4), the last ADC(5) coupling) ===")
    from src.SingleReference.ADC.sigma_driver import u_dot_orb_isr, u3_dot_orb
    s2r = generated('adc4_c2_s2c_apply_restricted_blocks')

    for atom, label in [('Li 0 0 0; H 0 0 1.6', 'LiH/sto-3g'),
                        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'H2O/sto-3g')]:
        mol = gto.M(atom=atom, basis='sto-3g', verbose=0)
        mf = scf.RHF(mol).run()
        eps_sp = get_orbital_energies(mf, representation='spatial')
        g_aaaa, g_bbbb, g_abab = get_antisymmetrized_spin_block_eri(mol, mf)
        r = BuildSuperMatrixADCnRestricted(eps_sp, g_aaaa, g_abab, g_bbbb,
                                          mol.nelectron // 2)
        pv = np.random.default_rng(3).standard_normal(r.norb)
        for sec in ('IP', 'EA'):
            d = np.max(np.abs(u_dot_orb_isr(r, sec, pv, 3, s2r)
                              - u3_dot_orb(r, sec, pv, s2r)))
            all_ok &= _check(d < 1e-12, f"{label} {sec} n=3 ISR unchanged "
                                        f"(== u3_dot_orb, {d:.1e})")
            try:
                v = u_dot_orb_isr(r, sec, pv, 4, s2r, strict=True)
                all_ok &= _check(np.isfinite(v).all(),
                                 f"{label} {sec} n=4 ISR runs in STRICT mode: "
                                 f"|U^(4).p|max={np.max(np.abs(v)):.6e}")
            except Exception as e:
                all_ok &= _check(False, f"{label} {sec} n=4: "
                                        f"{type(e).__name__}: {str(e)[:120]}")

    # 4. lambda^5 pole-order gate (needs the git-ignored validation/)
    print("\n=== lambda^5 pole-order gate (H2/sto-3g) ===")
    vdir = os.path.abspath(os.path.join(os.path.dirname(__file__), '..',
                                        'validation', 'lambda_oracle'))
    sys.path.insert(0, vdir)
    try:
        from lambda_oracle import LambdaSelfEnergyOracle
        from adc_fold_oracle import ADCFoldOracle
        from generated_blocks import generated_supermatrix, GeneratedADCBlocks
    except ImportError:
        print("SKIP: validation/lambda_oracle not present (git-ignored); "
              "C^(3) has NO physics gate without it")
        print('\nALL OK' if all_ok else '\nFAILURES')
        return all_ok

    class _Fold(ADCFoldOracle):
        def __init__(self, *a, c3s=1.0, **kw):
            self.c3s = c3s
            super().__init__(*a, **kw)
            self.degree = 5

        def supermatrix(self, lam):
            gl = lam * self.g
            H = generated_supermatrix(self.eps, gl, self.nocc,
                                      level=self.level,
                                      u3_sectors=self.u3_sectors)
            if self.c3s:
                gn = BuildSuperMatrixADCn(self.eps, gl, self.nocc)
                b = GeneratedADCBlocks(self.eps, gl, self.nocc)
                o1i = self.norb
                o1e = o1i + b.d['n2h1p']
                for sec, lo, hi in (('IP', o1i, o1e),
                                    ('EA', o1e, o1e + b.d['n2p1h'])):
                    H[lo:hi, lo:hi] += self.c3s * gn.c_block_generated(sec, 3)
            return H

    eps, h1, g, nocc = _build('H 0 0 0; H 0 0 0.74')
    orc = LambdaSelfEnergyOracle(eps, h1, g, nocc)
    b = GeneratedADCBlocks(eps, g, nocc)
    Kall = np.unique(np.round(np.concatenate([b.K_2h, b.K_2p]), 8))
    gaps = np.min(np.abs(Kall[:, None] - Kall[None, :])
                  + np.eye(len(Kall)) * 1e9, axis=1)
    K0 = Kall[np.argmax(gaps)]

    def ratios(c3s):
        f = _Fold(eps, g, nocc, level='adc4', c3s=c3s)
        f.super_coeffs()
        v = []
        for d in (0.20, 0.10, 0.05, 0.025):
            ck, _, _ = orc.taylor_coeffs(K0 + d, r=min(0.02, d / 4), npts=32,
                                         kmax=8)
            v.append(np.max(np.abs(ck[5] - f.fold_coeffs(K0 + d, kmax=5)[5])))
        return [v[i + 1] / v[i] for i in range(3)]

    r1 = ratios(1.0)
    all_ok &= _check(max(abs(x - 2.0) for x in r1) < 0.02,
                     f"C^(3) collapses the c5 mismatch to a PURE SINGLE pole "
                     f"(ratios {', '.join(f'{x:.3f}' for x in r1)}; 2.000 = "
                     f"single pole, only U^(4) missing)")

    # the control: the gate must FAIL for a wrong C^(3), else it proves nothing
    r0 = ratios(0.0)
    all_ok &= _check(max(abs(x - 2.0) for x in r0) > 0.3,
                     f"control -- WITHOUT C^(3) a double/triple pole survives "
                     f"(ratios {', '.join(f'{x:.3f}' for x in r0)})")
    r11 = ratios(1.1)
    all_ok &= _check(max(abs(x - 2.0) for x in r11) > 0.05,
                     f"control -- a +10% C^(3) error is RESOLVED "
                     f"(ratios {', '.join(f'{x:.3f}' for x in r11)})")

    print('\nALL OK' if all_ok else '\nFAILURES')
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
