"""Lambda-scaled exact self-energy oracle and the lambda-Taylor fold of a
generated ADC supermatrix.

What it computes. For a small molecule in the Moller-Plesset partitioning
H(lambda) = F + lambda (H - F), with F = diag(eps) held in the canonical HF
spin-orbital basis at lambda = 1:

  * LambdaSelfEnergyOracle: the exact dynamic self-energy
    Sigma_dyn(omega, lambda) = G0^-1 - G^-1 - Sigma_inf(lambda), with G the
    Lehmann Green's function from full diagonalization of the N and N+-1
    determinant sectors (src.SingleReference.CC.determinant_space) and the
    static part removed analytically by the exact sum rule
    Sigma_inf(lambda) = lambda v[gamma(lambda) - gamma_HF] (for canonical HF
    the one-body part of H(lambda) is F + lambda (h - F) with h - F = -v[gamma_HF];
    the constructor checks that h, g and eps are canonical-HF consistent).
    Its lambda-Taylor coefficients come from the Cauchy integral on a circle in
    the complex lambda plane (analytic continuation with transposes, never
    conjugates). The sector bases (bN, bM, bP), the annihilation and creation
    matrices (A, Cr) and the zeroth-order and full sector Hamiltonians
    (Hf, Hfull) are exposed for the exact intermediate-state construction
    (tests/exact_isr_oracle.py).
  * ADCFoldOracle: the lambda-Taylor coefficients of the ADC fold
    B (omega - D)^-1 B^T of a supermatrix assembled from the generated blocks
    at coupling lambda g. The supermatrix is a polynomial in lambda (every
    amplitude enters at a fixed order, every denominator is lambda-free), so it
    is interpolated exactly on Chebyshev nodes and the fold is expanded as a
    formal power series: R_0 = A_0^-1, R_m = A_0^-1 sum_j D_j R_{m-j},
    c_k = sum_{a+b+c=k} B_a R_b B_c^T.

What it is for. The defining property of ADC(n),
M_ADC(omega, lambda) = Sigma_dyn,exact(omega, lambda) + O(lambda^(n+1)),
checked coefficient by coefficient, and the determinant-space reference the
exact intermediate-state gates build on (sto-3g systems only: dense sector
diagonalization).

How it is checked. exact_M agrees with the independently written
src.CodeGeneration.diagrammatic.exact_oracle.ExactSelfEnergy to 1e-14 (H4),
taylor_coeffs with its contour coefficients to 4e-12 at order 2 (2e-7 at order
5, the precision of the radius-0.02 circle), and the gates that use it
reproduce their recorded numbers.
"""
import numpy as np
import scipy.sparse as sp
from scipy.linalg import eig, eigh
from pyscf import gto, scf, ao2mo

