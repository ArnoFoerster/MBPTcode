class GeneratedADCBlocks:
    """Zeroth-order configuration energies and class sizes of the generated
    spin-orbital ADC (orbital <-> k1 and k2 classes)."""

    def __init__(self, eps, g, nocc):
        self.eps, self.g, self.nocc = np.asarray(eps), np.asarray(g), nocc
        self.gen = BuildSuperMatrixADCn(eps, g, nocc)
        self.norb = norb = len(eps)
        self.K_2h = _diag(self.gen.k_block('IP'))
        self.K_2p = _diag(self.gen.k_block('EA'))
        self.K_3h = np.asarray(diag_K(self.eps, nocc, norb, 'IP', k=2))
        self.K_3p = np.asarray(diag_K(self.eps, nocc, norb, 'EA', k=2))
        self.d = {'n2h1p': len(self.K_2h), 'n2p1h': len(self.K_2p),
                  'n3h2p': len(self.K_3h), 'n3p2h': len(self.K_3p)}


def _diag(x):
    x = np.asarray(x)
    return np.diag(x) if x.ndim == 2 else x


def generated_supermatrix(eps, g, nocc, level='adc4', u3_sectors=('IP', 'EA')):
    """Dense spin-orbital ADC supermatrix from the generated blocks, layout

        | F          U_2h1p^T   U_2p1h^T   U2_3h2p    U2_3p2h  |
        | U_2h1p     K+C1+C2    0          C135       0        |
        | U_2p1h     0          K+C1+C2    0          C135'    |
        | U2_3h2p^T  C135^T     0          K_3h2p     0        |
        | U2_3p2h^T  0          C135'^T    0          K_3p2h   |

    level 'adc3': F, U through order 2, K + C^(1) (no C^(2), no k = 2);
    'adc4_base': + C^(2) and the k = 2 manifold; 'adc4': the same, and U^(3)
    is added on every sector in `u3_sectors` at any level. F = diag(eps) is
    held at its lambda = 1 value; the caller scales g."""
    b = GeneratedADCBlocks(eps, g, nocc)
    gen = b.gen
    norb = b.norb
    n1i, n1e = b.d['n2h1p'], b.d['n2p1h']
    has_k2 = level in ('adc4_base', 'adc4')
    n2i, n2e = (b.d['n3h2p'], b.d['n3p2h']) if has_k2 else (0, 0)
    o1i, o1e = norb, norb + n1i
    o2i, o2e = o1e + n1e, o1e + n1e + n2i
    nH = o1e + n1e + n2i + n2e
    H = np.zeros((nH, nH))
    H[:norb, :norb] = np.diag(np.asarray(eps))
    for sec, lo, hi in (('IP', o1i, o1e), ('EA', o1e, o1e + n1e)):
        U = gen.u_2h1p_adc3() if sec == 'IP' else gen.u_2p1h_adc3()  # (ncfg, norb)
        if sec in u3_sectors:
            U = U + gen.u3_generated(sec)
        H[lo:hi, :norb] = U
        H[:norb, lo:hi] = U.T
        K = b.K_2h if sec == 'IP' else b.K_2p
        C = gen.c1_block(sec)
        if has_k2:
            C = C + gen.c2_block_generated(sec)
        H[lo:hi, lo:hi] = np.diag(K) + C
    if has_k2:
        for sec, k1lo, k1hi, k2lo, k2hi in (('IP', o1i, o1e, o2i, o2e),
                                            ('EA', o1e, o1e + n1e, o2e, nH)):
            U2k2 = gen.u2_k2_generated(sec)                 # (n_k2, norb)
            H[k2lo:k2hi, :norb] = U2k2
            H[:norb, k2lo:k2hi] = U2k2.T
            C135 = gen.coupling_k1_k2_generated(sec)        # (n_k1, n_k2), class sign applied
            H[k1lo:k1hi, k2lo:k2hi] = C135
            H[k2lo:k2hi, k1lo:k1hi] = C135.T
            H[k2lo:k2hi, k2lo:k2hi] = np.diag(b.K_3h if sec == 'IP' else b.K_3p)
    return H


_LEVEL_DEGREE = {'adc2': 2, 'adc3': 3, 'adc4_base': 4, 'adc4': 4, 'adc5': 6}


class ADCFoldOracle:
    """lambda-Taylor coefficients of the ADC fold B (omega - D)^-1 B^T of
    supermatrix(lam) (generated_supermatrix at coupling lam * g; a subclass may
    override supermatrix). `degree` is the polynomial degree of the
    supermatrix in lambda."""

    def __init__(self, eps, g, nocc, level='adc4_base', u3_sectors=('IP', 'EA'), degree=None):
        self.eps = np.asarray(eps, dtype=float)
        self.g = np.asarray(g, dtype=float)
        self.nocc = nocc
        self.norb = len(self.eps)
        self.level = level
        self.u3_sectors = tuple(u3_sectors)
        self.degree = degree if degree is not None else _LEVEL_DEGREE[level]
        self._coeffs = None

    def supermatrix(self, lam):
        return generated_supermatrix(self.eps, lam * self.g, self.nocc, level=self.level,
                                     u3_sectors=self.u3_sectors)

    def super_coeffs(self, check_tol=1e-10):
        """H(lambda) = sum_m lambda^m H_m interpolated on Chebyshev nodes in
        [-1, 1] (real lambda only), checked at held-out points."""
        if self._coeffs is not None:
            return self._coeffs
        n = self.degree + 1
        nodes = np.cos(np.pi * (2 * np.arange(n) + 1) / (2 * n))
        vals = np.array([self.supermatrix(l) for l in nodes])
        V = np.vander(nodes, n, increasing=True)
        flat = np.linalg.solve(V, vals.reshape(n, -1))
        H = flat.reshape((n,) + vals.shape[1:])
        scale = max(np.max(np.abs(H)), 1e-300)
        worst = 0.0
        for lt in (0.37, -0.61, 0.83):
            pred = sum(H[m] * lt ** m for m in range(n))
            worst = max(worst, np.max(np.abs(pred - self.supermatrix(lt))))
        if worst / scale > check_tol:
            raise RuntimeError(f"supermatrix is not polynomial in lambda to degree {self.degree}: "
                               f"held-out residual {worst:.3e} (rel {worst / scale:.3e}) "
                               "-- raise `degree`")
        self._coeffs = H
        self._interp_resid = worst / scale
        return H

    def fold_coeffs(self, omega, kmax=5):
        """c_0..c_kmax (array (kmax+1, norb, norb)) of the fold at real omega."""
        H = self.super_coeffs()
        norb = self.norb
        B = [Hm[:norb, norb:] for Hm in H]
        D = [Hm[norb:, norb:] for Hm in H]
        deg = len(H) - 1
        ncfg = D[0].shape[0]
        A0 = omega * np.eye(ncfg) - D[0]
        offdiag = np.max(np.abs(A0 - np.diag(np.diag(A0))))
        if offdiag > 1e-10 * max(np.max(np.abs(A0)), 1.0):
            A0inv = np.linalg.inv(A0)
        else:
            A0inv = np.diag(1.0 / np.diag(A0))
        R = [A0inv]
        for m in range(1, kmax + 1):
            acc = np.zeros((ncfg, ncfg))
            for j in range(1, min(m, deg) + 1):
                acc += D[j] @ R[m - j]
            R.append(A0inv @ acc)
        out = np.zeros((kmax + 1, norb, norb))
        for k in range(kmax + 1):
            acc = np.zeros((norb, norb))
            for a in range(min(k, deg) + 1):
                if not np.any(B[a]):
                    continue
                for c in range(min(k - a, deg) + 1):
                    b = k - a - c
                    if b < 0 or b > kmax:
                        continue
                    acc += B[a] @ R[b] @ B[c].T
            out[k] = acc
        return out
