def build_system(atom, basis='sto-3g', charge=0):
    """RHF (conv_tol 1e-13) -> spin-orbital (eps, h1, g, nocc), the oracle's input."""
    mol = gto.M(atom=atom, basis=basis, charge=charge, verbose=0)
    mf = scf.RHF(mol)
    mf.conv_tol = 1e-13
    mf.run()
    n = mf.mo_coeff.shape[1]
    eri = ao2mo.kernel(mol, mf.mo_coeff, compact=False).reshape(n, n, n, n)
    h1_mo = mf.mo_coeff.T @ (mol.intor('int1e_kin') + mol.intor('int1e_nuc')) @ mf.mo_coeff
    h1, g = get_antisymmetrized_spin_integrals(h1_mo, eri)
    eps = get_orbital_energies(mf, representation='spin')
    return eps, h1, g, mol.nelectron


def _op_matrix(basis_to, basis_from, p, mode):
    """Sparse matrix of a_p ('ann') or a^dag_p ('cre') mapping basis_from ->
    basis_to determinant spaces."""
    fn = apply_annihilation if mode == 'ann' else apply_creation
    rows, cols, vals = [], [], []
    for col, det in enumerate(basis_from.dets):
        r = fn(det, p)
        if r is None:
            continue
        ph, nd = r
        rows.append(basis_to.index[nd])
        cols.append(col)
        vals.append(float(ph))
    return sp.csr_matrix((vals, (rows, cols)), shape=(basis_to.dim, basis_from.dim))


class LambdaSelfEnergyOracle:
    """Exact Sigma_dyn(omega, lambda) of one small system (see the module docstring)."""

    def __init__(self, eps, h1, g, nocc):
        self.eps = np.asarray(eps, dtype=float)
        self.h1 = np.asarray(h1, dtype=float)
        self.g = np.asarray(g, dtype=float)
        self.nocc = nocc
        norb = len(self.eps)
        self.norb = norb
        # canonical-HF consistency: h1 + v[gamma_HF] must equal diag(eps), the
        # premise of the analytic Sigma_inf
        occ = np.arange(nocc)
        f_chk = self.h1 + np.einsum('piqi->pq', self.g[:, occ][:, :, :, occ])
        err = np.max(np.abs(f_chk - np.diag(self.eps)))
        if err > 1e-7:
            raise ValueError(f"h1/g/eps not canonical-HF consistent: {err:.2e}")
        self.bN = SectorBasis(norb, nocc, nocc)
        self.bM = SectorBasis(norb, nocc - 1, nocc)
        self.bP = SectorBasis(norb, nocc + 1, nocc)
        self.A = [_op_matrix(self.bM, self.bN, p, 'ann') for p in range(norb)]
        self.Cr = [_op_matrix(self.bP, self.bN, p, 'cre') for p in range(norb)]
        zg = np.zeros_like(self.g)
        deps = np.diag(self.eps)
        self.Hfull, self.Hf = {}, {}
        for key, b in (('N', self.bN), ('M', self.bM), ('P', self.bP)):
            self.Hfull[key] = build_hamiltonian(b, self.h1, self.g).toarray()
            self.Hf[key] = build_hamiltonian(b, deps, zg).toarray()
        self.gamma_hf = np.diag((np.arange(norb) < nocc).astype(float))
        self._sector_cache = {}

    def _sectors(self, lam):
        if lam not in self._sector_cache:
            out = {}
            for key in ('N', 'M', 'P'):
                Hl = self.Hf[key] + lam * (self.Hfull[key] - self.Hf[key])
                w, v = eigh(Hl)
                out[key] = (w, v)
            wN, vN = out['N']
            psi0 = vN[:, 0]
            E0 = wN[0]
            X = np.array([Ap @ psi0 for Ap in self.A])
            Y = np.array([Cp @ psi0 for Cp in self.Cr])
            wM, vM = out['M']
            wP, vP = out['P']
            self._sector_cache[lam] = dict(E0=E0, Xe=X @ vM, Ye=Y @ vP, wM=wM, wP=wP,
                                           gamma=X @ X.T)
        return self._sector_cache[lam]

    def exact_M(self, omega, lam):
        """Exact dynamic self-energy M(omega, lambda) = Sigma - Sigma_inf,
        (norb, norb)."""
        s = self._sectors(lam)
        E0, Xe, Ye, wM, wP = s['E0'], s['Xe'], s['Ye'], s['wM'], s['wP']
        Gp = (Ye / (omega - (wP - E0))[None, :]) @ Ye.T
        Gm = (Xe / (omega - (E0 - wM))[None, :]) @ Xe.T
        G = Gp + Gm
        Sigma = np.diag(omega - self.eps) - np.linalg.inv(G)
        dg = s['gamma'] - self.gamma_hf
        Sigma_inf = lam * np.einsum('rs,prqs->pq', dg, self.g)
        return Sigma - Sigma_inf

    def _sectors_complex(self, lam):
        """Analytic continuation of the sector data to complex lambda.
        Only the N-sector ground eigenpair is obtained by (complex) eig -- an
        isolated eigenvalue, hence well-conditioned; the N+-1 sectors are kept
        as full matrices and handled by direct linear solves in exact_M_complex
        (robust under the exact spin degeneracies that break complex-orthogonal
        eigenvector normalization). Transposes everywhere, never conjugation:
        the unique analytic continuation of the real-lambda formulas."""
        key = ('c', lam)
        if key not in self._sector_cache:
            hf_idx = self.bN.index[(1 << self.nocc) - 1]
            HlN = self.Hf['N'] + lam * (self.Hfull['N'] - self.Hf['N'])
            w, Vv = eig(HlN.astype(complex))
            i0 = np.argmax(np.abs(Vv[hf_idx, :]))
            psi0 = Vv[:, i0]
            psi0 = psi0 / np.sqrt(psi0 @ psi0)
            E0 = w[i0]
            X = np.array([Ap @ psi0 for Ap in self.A])
            Y = np.array([Cp @ psi0 for Cp in self.Cr])
            HlM = self.Hf['M'] + lam * (self.Hfull['M'] - self.Hf['M'])
            HlP = self.Hf['P'] + lam * (self.Hfull['P'] - self.Hf['P'])
            self._sector_cache[key] = dict(E0=E0, X=X, Y=Y, gamma=X @ X.T,
                                           HM=HlM.astype(complex), HP=HlP.astype(complex))
        return self._sector_cache[key]

    def exact_M_complex(self, omega, lam):
        """exact_M for complex lambda (real omega), via direct solves:
        G^-_pq = X_q^T (omega - E0 + H_M)^-1 X_p,
        G^+_pq = Y_p^T (omega + E0 - H_P)^-1 Y_q."""
        s = self._sectors_complex(lam)
        E0, X, Y = s['E0'], s['X'], s['Y']
        dimM, dimP = s['HM'].shape[0], s['HP'].shape[0]
        AM = (omega - E0) * np.eye(dimM, dtype=complex) + s['HM']
        Gm = X @ np.linalg.solve(AM, X.T)
        AP = (omega + E0) * np.eye(dimP, dtype=complex) - s['HP']
        Gp = Y @ np.linalg.solve(AP, Y.T)
        G = Gp + Gm
        Sigma = np.diag(omega - self.eps).astype(complex) - np.linalg.inv(G)
        dg = s['gamma'] - self.gamma_hf
        Sigma_inf = lam * np.einsum('rs,prqs->pq', dg, self.g)
        return Sigma - Sigma_inf

    def taylor_coeffs(self, omega, r=0.025, npts=24, kmax=8):
        """Taylor coefficients c_0..c_kmax of M_exact(omega, .) around lambda = 0
        by the Cauchy integral on the circle |lambda| = r (DFT over npts points).
        Returns (coeffs, tail, imag_err): coeffs[k] real (norb, norb);
        tail = max_{k in [kmax, kmax+3]} |fft_k| / (|c_2| r^2), large when the
        radius exceeds the local convergence radius (discard this omega);
        imag_err = largest imaginary part left in the low coefficients
        (machine noise, M being real-analytic in lambda)."""
        lams = r * np.exp(2j * np.pi * np.arange(npts) / npts)
        vals = np.array([self.exact_M_complex(omega, l) for l in lams])
        fft = np.fft.fft(vals, axis=0) / npts
        coeffs = np.array([np.real(fft[k]) / r ** k for k in range(kmax + 1)])
        imag_err = max(np.max(np.abs(np.imag(fft[k]))) / r ** k for k in range(kmax + 1))
        scale = max(np.max(np.abs(coeffs[2])) * r ** 2, 1e-300)
        tail = max(np.max(np.abs(fft[k]))
                   for k in range(kmax, min(npts - 1, kmax + 4))) / scale
        return coeffs, tail, imag_err


