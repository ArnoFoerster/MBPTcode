"""Non-Dyson IP/EA-ADC(2)/(3) on a DF (g-free) restricted solver against the
same construction on dense g.

The DF factor is an exact factorization of the MO integrals (eigen-decomposition
of the (pq|rs) matrix, no fitting error), so the two routes must give the same
matrix to rounding. Gates on LiH and H2O in sto-3g and H2O in 6-31g:
  1. the ADC(2) and ADC(3) matrices of both sectors agree element by element;
  2. the ground-state energies E^(0..3) agree;
  3. the l-convention views of the DF amplitude provider equal mp_amplitudes.to_l
     (same-spin to rounding, mixed-spin exactly);
  4. ADC(4) on a DF solver refuses.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
import pytest
from pyscf import ao2mo, gto, scf

from src.Base.pyscf.pyscf_interface import get_orbital_energies, get_antisymmetrized_spin_block_eri
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.SingleReference.ADC.nondyson_restricted import NonDysonRestricted
from src.SingleReference.common.mp_amplitudes import to_l
from tests.generated_runtime import requires_runtime

SYSTEMS = [('LiH', 'Li 0 0 0; H 0 0 1.6', 'sto-3g'),
           ('H2O', 'O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g'),
           ('H2O', 'O 0 0 0; H 0 0 0.96; H 0.96 0 0', '6-31g')]
TOL = 1e-10


def _solvers(atom, basis):
    mol = gto.M(atom=atom, basis=basis, verbose=0)
    mf = scf.RHF(mol).run(conv_tol=1e-12)
    eps = get_orbital_energies(mf, representation='spatial')
    nocc, n = mol.nelectron // 2, len(eps)
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
    dense = BuildSuperMatrixADCnRestricted(eps, ga, gab, gb, nocc)
    eri = ao2mo.restore(1, ao2mo.kernel(mol, mf.mo_coeff), n).reshape(n * n, n * n)
    w, V = np.linalg.eigh(eri)
    keep = w > 1e-14 * w.max()
    B = (np.sqrt(w[keep]) * V[:, keep]).T.reshape(-1, n, n)
    df = BuildSuperMatrixADCnRestricted(eps, None, None, None, nocc, B_aa=B)
    return dense, df


def _dense(op):
    return np.column_stack([op.matvec(e) for e in np.eye(op.shape[0])])


@requires_runtime(3)
@pytest.mark.parametrize('label,atom,basis', SYSTEMS)
@pytest.mark.parametrize('sector', ['IP', 'EA'])
def test_df_matches_dense(label, atom, basis, sector):
    dense, df = _solvers(atom, basis)
    nd_g, nd_b = NonDysonRestricted(dense, sector), NonDysonRestricted(df, sector)
    for c in range(4):
        e_g, e_b = nd_g.mp_energy(c), nd_b.mp_energy(c)
        print(f"{label}/{basis} E^({c}): dense {e_g:.14f} DF {e_b:.14f}")
        assert abs(e_g - e_b) < TOL
    for n in (2, 3):
        M_g, M_b = _dense(nd_g.operator(n)[0]), _dense(nd_b.operator(n)[0])
        d = float(np.max(np.abs(M_g - M_b)))
        w_g, w_b = np.linalg.eigvalsh(0.5 * (M_g + M_g.T)), np.linalg.eigvalsh(0.5 * (M_b + M_b.T))
        print(f"{label}/{basis} {sector} ADC({n}): dim {M_g.shape[0]}, max |M_dense - M_DF| {d:.1e}, "
              f"lowest roots dense {w_g[:3]} DF {w_b[:3]}")
        assert d < TOL


@requires_runtime(3)
def test_df_l_views_equal_to_l():
    _, df = _solvers('O 0 0 0; H 0 0 0.96; H 0.96 0 0', '6-31g')
    A = NonDysonRestricted(df, 'IP')._amps(3)
    for o in (1, 2):
        T, L = A[f'T2_{o}'], A[f'L2_{o}']
        # the same-spin view relies on t2_aaaa's virtual antisymmetry, exact to rounding
        assert np.max(np.abs(L['l2_aaaa'] - to_l(T['t2_aaaa'], 2, 'aaaa'))) < 1e-15
        assert np.array_equal(L['l2_abab'], to_l(T['t2_abab'], 2, 'abab'))
    assert np.array_equal(A['L1_2']['l1_aa'], to_l(A['T1_2']['t1_aa'], 1, 'aa'))


@requires_runtime(3)
def test_df_refuses_adc4():
    _, df = _solvers('Li 0 0 0; H 0 0 1.6', 'sto-3g')
    with pytest.raises(ValueError, match='rank-3'):
        NonDysonRestricted(df, 'IP').raw_series(4)
