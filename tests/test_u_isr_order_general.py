TOL_ALGEBRA = 1e-12       # relative to the block's largest element; FP re-association only
TOL_PARITY = 1e-12        # absolute; matvecs vs the dense oracle, same terms
TOL_ENGINE = 1e-11        # absolute; dense engine vs matvecs over the same raws
DEFECT_MIN = 1e-8         # an omitted term must move the block by at least this


# ---------------------------------------------------------------------------
# 1. algebra
# ---------------------------------------------------------------------------

def _sym(rng, d, scale):
    a = rng.standard_normal((d, d)) * scale
    return a + a.T


def _synthetic(nmax=6, norb=5, n1=7, seed=7):
    rng = np.random.default_rng(seed)
    eps = np.sort(rng.standard_normal(norb))
    raws = {m: 0.4 ** m * rng.standard_normal((n1, norb)) for m in range(1, nmax + 1)}
    S = {m: 0.4 ** m * rng.standard_normal((n1, norb)) for m in range(2, nmax + 1)}
    S11 = {m: _sym(rng, n1, 0.4 ** m) for m in range(2, nmax)}
    V00 = {m: _sym(rng, norb, 0.4 ** m) for m in range(3, nmax)}
    return eps, raws, S, S11, V00, norb, n1


def _engine_u(eps, raws, S, S11, V00, norb, n1, nmax):
    """(n_k1, norb) U^(n) for n = 1..nmax from the dense engine."""
    H = {(0, 0): {0: np.diag(eps), **V00}, (0, 1): {m: r.T for m, r in raws.items()}}
    Sm = {(0, 0): {0: np.eye(norb)}, (0, 1): {m: s.T for m, s in S.items()},
          (1, 1): {0: np.eye(n1), **S11}}
    blocks, _ = isr_effective_blocks(H, Sm, {0: norb, 1: n1}, nmax)
    return {n: blocks[(0, 1)][n].T for n in blocks[(0, 1)]}


def _class_apply(S11):
    def ds_class(m, w):
        return S11[m] @ w if m in S11 else np.zeros_like(w)
    return ds_class


def _fwd_matrix(n, raws, S, eps, V00, ds_class, norb, n1):
    return np.column_stack([_isr_coupling_fwd(n, raws, S, eps, V00, ds_class, e, n1)
                            for e in np.eye(norb)])


def test_lowdin_apply_equals_the_series():
    rng = np.random.default_rng(11)
    d, nmax = 6, 7
    ds = {m: _sym(rng, d, 0.5 ** m) for m in range(2, nmax + 1)}
    y = lowdin_sqrt_inv_series(ds, nmax)
    v = rng.standard_normal(d)
    for a in range(nmax + 1):
        got = _lowdin_apply(_class_apply(ds), a, v)
        d_ = float(np.max(np.abs(got - y[a] @ v)))
        print(f"  Y^({a}) v: matvec vs series {d_:.2e}")
        assert d_ < TOL_ALGEBRA * max(1.0, float(np.max(np.abs(y[a] @ v)))), (a, d_)


def test_coupling_equals_engine_through_order6():
    nmax = 6
    eps, raws, S, S11, V00, norb, n1 = _synthetic(nmax)
    ref = _engine_u(eps, raws, S, S11, V00, norb, n1, nmax)
    ds_class = _class_apply(S11)
    for n in range(2, nmax + 1):
        U = ref[n]
        scale = float(np.max(np.abs(U)))
        fwd = _fwd_matrix(n, raws, S, eps, V00, ds_class, norb, n1)
        bwd = np.column_stack([_isr_coupling_bwd(n, raws, S, eps, V00, ds_class, e, norb)
                               for e in np.eye(n1)])
        df, db = float(np.max(np.abs(fwd - U))), float(np.max(np.abs(bwd - U.T)))
        print(f"  n={n}: |U| {scale:.2e}, forward {df:.2e}, adjoint {db:.2e}")
        assert scale > 1e-8
        assert df < TOL_ALGEBRA * max(1.0, scale), (n, df)
        assert db < TOL_ALGEBRA * max(1.0, scale), (n, db)


def test_order5_terms_are_seen():
    """Each term that first acts at order 5 moves U^(5): V_00, the orbital
    projection of the class metric, and the (Delta S^(2))^2 Loewdin term."""
    nmax = 5
    eps, raws, S, S11, V00, norb, n1 = _synthetic(nmax)
    U5 = _engine_u(eps, raws, S, S11, V00, norb, n1, nmax)[5]
    ds_class = _class_apply(S11)

    no_v00 = _fwd_matrix(5, raws, S, eps, {}, ds_class, norb, n1)

    # the class metric without its orbital projection: cancel -S_10 S_01 in ds_class
    def ds_unprojected(m, w):
        out = ds_class(m, w)
        for i in range(2, m - 1):
            out = out + S[i] @ (S[m - i].T @ w)
        return out
    no_proj = _fwd_matrix(5, raws, S, eps, V00, ds_unprojected, norb, n1)
    # the quadratic Loewdin term's share of U^(5): 3/8 Delta S^(2) Delta S^(2) raw^(1)
    y4_quadratic = 0.375 * S11[2] @ (S11[2] @ raws[1])

    for label, d_ in (('V_00 dropped', float(np.max(np.abs(no_v00 - U5)))),
                      ('orbital projection dropped', float(np.max(np.abs(no_proj - U5)))),
                      ('3/8 (Delta S^(2))^2 dropped', float(np.max(np.abs(y4_quadratic))))):
        print(f"  U^(5) with {label}: off by {d_:.2e}")
        assert d_ > DEFECT_MIN, (label, d_)


