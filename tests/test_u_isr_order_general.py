def _restricted(atom):
    mol = gto.M(atom=atom, basis='sto-3g', verbose=0)
    mf = scf.RHF(mol)
    mf.conv_tol = 1e-12
    mf.run()
    eps = get_orbital_energies(mf, representation='spatial')
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
    return BuildSuperMatrixADCnRestricted(eps, ga, gab, gb, mol.nelectron // 2)


@pytest.fixture(scope='module', params=sorted(SYSTEMS))
def system(request):
    r = _restricted(SYSTEMS[request.param])
    pieces = {sec: _un_pieces(r, sec, 4) for sec in ('IP', 'EA')}
    dense = {sec: u_dot_orb_isr(r, sec, None, 4, s2r) for sec in ('IP', 'EA')}
    series = {sec: u_raw_series(r, sec, 4) for sec in ('IP', 'EA')}
    return request.param, r, pieces, dense, series


def test_un_apply_equals_the_dense_u4(system):
    label, r, pieces, dense, _ = system
    rng = np.random.default_rng(5)
    for sec in ('IP', 'EA'):
        n1 = len(r._sector_configs(sec)['K'])
        for _ in range(2):
            p, w = rng.standard_normal(r.norb), rng.standard_normal(n1)
            f_new = _un_apply_fwd(r, sec, pieces[sec], s2r, p)
            f_old = dense[sec] @ p
            b_new = _un_apply_bwd(r, sec, pieces[sec], s2r, w)
            b_old = dense[sec].T @ w
            df = float(np.max(np.abs(f_new - f_old)))
            db = float(np.max(np.abs(b_new - b_old)))
            adj = abs(float(w @ f_new) - float(b_new @ p))
            print(f"  {label} {sec}: |U4 p| {np.max(np.abs(f_old)):.2e}; forward {df:.2e}, "
                  f"adjoint {db:.2e}, <w,Up> - <U^T w,p> {adj:.2e}")
            assert np.max(np.abs(f_old)) > 1e-8
            assert df < TOL_PARITY and db < TOL_PARITY, (sec, df, db)
            assert adj < TOL_PARITY * max(1.0, float(np.linalg.norm(w) * np.linalg.norm(p)))


def test_un_apply_equals_engine_orders_2_to_4(system):
    label, r, pieces, _, series = system
    norb = r.norb
    for sec in ('IP', 'EA'):
        raws, Ss = series[sec]
        n1 = raws[1].shape[0]
        normr = {0: 1.0, 2: r.n_norm_order(2), 3: r.n_norm_order(3)}
        H = {(0, 0): {m: v * np.diag(r.eps) for m, v in normr.items()},
             (0, 1): {m: raws[m].T for m in raws if raws[m] is not None}}
        S = {(0, 0): {m: v * np.eye(norb) for m, v in normr.items()},
             (0, 1): {m: Ss[m].T for m in Ss if Ss[m] is not None},
             (1, 1): {0: np.eye(n1)}}
        for m in (2, 3):
            _, S_m = r._class_raw_S(sec, m)
            if S_m is not None:
                S[(1, 1)][m] = S_m
        blk, _ = isr_effective_blocks(H, S, {0: norb, 1: n1}, 4, norm=normr)
        for n in (2, 3, 4):
            pc = dict(pieces[sec], n=n)
            got = np.column_stack([_un_apply_fwd(r, sec, pc, s2r, e) for e in np.eye(norb)])
            d_ = float(np.max(np.abs(got - blk[(0, 1)][n].T)))
            print(f"  {label} {sec} (0,1)@{n}: matrix-free vs engine {d_:.2e}")
            assert d_ < TOL_ENGINE, (sec, n, d_)


def test_u_dot_orb_order_is_u4_at_order4(system):
    label, r, _, dense, series = system
    rng = np.random.default_rng(9)
    A = r._amps_order(max_order=4)
    for sec in ('IP', 'EA'):
        p = rng.standard_normal(r.norb)
        got = u_dot_orb_order(r, sec, p, 4, s2r)
        ref = dense[sec] @ p
        d_ = float(np.max(np.abs(got - ref)))
        # the order-3 ISR tail u_dot_orb_order applied at every n before
        raws, Ss = series[sec]
        u1p = raws[1] @ p
        old = ((raws[4] - r.n2_norm() * raws[1] - r.eps[None, :] * Ss[4]) @ p
               - 0.5 * _delta_s_apply(r, sec, 2, u1p, s2r, A))
        defect = float(np.max(np.abs(old - ref)))
        print(f"  {label} {sec}: u_dot_orb_order(4) vs U^(4) {d_:.2e}; the order-3 "
              f"tail was off by {defect:.2e}")
        assert d_ < TOL_PARITY, (sec, d_)
        assert defect > DEFECT_MIN, (sec, defect)


