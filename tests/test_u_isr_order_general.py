"""The order-general matrix-free ISR layer of the (0,1) orbital<->k1 coupling,
sigma_driver._isr_coupling_fwd/_bwd (U^(n) at any n), against the dense
blockwise engine isr_assembly.isr_effective_blocks.

Two layers:
  1. ALGEBRA (synthetic norm-divided series, pure numpy): the Loewdin matvec
     == lowdin_sqrt_inv_series through order 7, and the forward and adjoint
     coupling == the engine's (0,1) block at n = 2..6. Orders 5 and 6 are where
     the class metric's orbital projection -S_10 S_01, the V_00 channel of the
     orbital block and 3/8 (Delta S^(2))^2 first act; each is switched off once
     to show the gate sees it.
  2. MOLECULES (linear H4 and LiH / sto-3g, generated restricted blocks):
     _un_apply_fwd/_bwd == the dense oracle u_dot_orb_isr at n = 4, the engine's
     (0,1)@2..4 built from the same restricted raws, the adjoint identity, and
     u_dot_orb_order(n=4) == U^(4). u_dot_orb_order does not apply the order-3
     ISR tail at every n; that tail is evaluated here at n = 4 and must differ,
     so the gate can fail. n = 5 refuses to run without V_00 on both routes.
"""
