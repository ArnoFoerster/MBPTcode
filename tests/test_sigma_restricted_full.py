"""Restricted (spin-free / RHF) FULL multi-class matrix-free operator
(sigma_driver.restricted_full_operator) -- the spin-free analog of
full_adc4_operator, closing item #2 of the matrix-free plan.

Extends restricted_sector_operator with the 3h2p/3p2h precursor class:
diagonal K2, the k=1<->k=2 coupling applied matrix-free BOTH directions
(apply_c1_{tag}_{tag2} / apply_c1_{tag2}_{tag} times _K2_CLASS_SIGN), and the
dense orbital<->k=2 U^(2). Validated == the dense restricted supermatrix

    H = | diag(eps)  U1^T          U2_k2^T |
        | U1         K1+C^(1)+C^(2) C       |
        | U2_k2      C^T            K2       |

assembled entirely from BuildSuperMatrixADCnRestricted's own dense blocks
(u_adc3, _c1_block, c2_block_generated, coupling_k1_k2_generated,
u2_k2_generated, _kconfigs K), plus eigsh == eigh. Both sectors, LiH/H2O
(H2 has no 3h2p/3p2h configs). All READ-ONLY off the restricted solver.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf
from scipy.sparse.linalg import eigsh

from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.SingleReference.ADC.generated_modules import lazy
c1r = lazy('adc4_c1_self_apply_restricted_blocks')
c2r = lazy('adc4_c2_apply_restricted_blocks')
s2r = lazy('adc4_c2_s2c_apply_restricted_blocks')
k2r = lazy('adc4_k2_apply_restricted_blocks')
from src.SingleReference.ADC.sigma_driver import restricted_full_operator
from src.Base.pyscf.pyscf_interface import (
    get_orbital_energies, get_antisymmetrized_spin_block_eri)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)


def main():
    all_ok = True
    for atom, basis, label in [
        ('Li 0 0 0; H 0 0 1.6', 'sto-3g', 'LiH/sto-3g'),
        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g'),
    ]:
        mol = gto.M(atom=atom, basis=basis, verbose=0)
        mf = scf.RHF(mol).run()
        nocc_sp = mol.nelectron // 2
        eps_sp = get_orbital_energies(mf, representation='spatial')
        g_aaaa, g_bbbb, g_abab = get_antisymmetrized_spin_block_eri(mol, mf)
        r = BuildSuperMatrixADCnRestricted(eps_sp, g_aaaa, g_abab, g_bbbb, nocc_sp)
        norb = r.norb

        print(f"\n=== {label} ===")
        for sector in ('IP', 'EA'):
            cfg1 = r._sector_configs(sector)
            cfg2 = r._kconfigs(sector, 2)
            n1, nk2 = len(cfg1['K']), len(cfg2['K'])
            U1 = r.u_adc3(sector)                    # (n1, norb)
            U2_k2 = r.u2_k2_generated(sector)        # (nk2, norb)
            Ccoup = r.coupling_k1_k2_generated(sector)   # (n1, nk2), ×sign
            c1 = r._c1_block(sector)
            c2 = r.c2_block_generated(sector)

            n = norb + n1 + nk2
            H = np.zeros((n, n))
            o1, o2 = norb, norb + n1
            H[:norb, :norb] = np.diag(eps_sp)
            H[o1:o2, :norb] = U1
            H[:norb, o1:o2] = U1.T
            H[o2:, :norb] = U2_k2
            H[:norb, o2:] = U2_k2.T
            H[o1:o2, o1:o2] = np.diag(cfg1['K']) + c1 + c2
            H[o2:, o2:] = np.diag(cfg2['K'])
            H[o1:o2, o2:] = Ccoup
            H[o2:, o1:o2] = Ccoup.T

            op = restricted_full_operator(sector, r, U1, U2_k2, k2r, c1r, c2r, s2r)
            recon = np.column_stack([op.matvec(e) for e in np.eye(n)])
            opdiff = np.abs(recon - H).max()
            opsym = np.abs(recon - recon.T).max()
            k = min(6, n - 2)
            w_mf = np.sort(eigsh(op, k=k, which='SA', return_eigenvectors=False))
            w_d = np.sort(np.linalg.eigvalsh(H))[:k]
            eigdiff = np.abs(w_mf - w_d).max()

            ok = opdiff < 1e-10 and eigdiff < 1e-8
            all_ok &= ok
            print(f"  {sector} (n1 {n1}, nk2 {nk2}, dim {n}, sym {opsym:.1e}):")
            print(f"    [{'OK' if opdiff < 1e-10 else 'FAIL'}] full operator == dense restricted assembly: {opdiff:.2e}")
            print(f"    [{'OK' if eigdiff < 1e-8 else 'FAIL'}] lowest-{k} eigenvalues: {eigdiff:.2e}  (lowest {w_mf[0]:.6f} Ha)")

    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
