"""Gate for the ORDER-GENERAL ISR wiring (sigma_driver.u_dot_orb_isr): the
Loewdin/ISR layer from isr_engine.py -- previously validated ONLY against
synthetic blocks (see its docstring) -- driving REAL generated ADC blocks.

    U^(n) = sum_{p+q=n} Y^(p).T @ raw^(q)     (Loewdin, isr_engine)
            - sum_{m>=2} N^(m) raw^(n-m)       (GS normalization)
            - eps_p S^(n)                      (class-GS subtraction)

At n=3, Delta S^(1)=0 => Y^(1)=0 and Y^(2)=-1/2 Delta S^(2), so this must
collapse onto u3_dot_orb's hand-derived, lambda-oracle-validated form. That
identity is the whole point of this gate: it validates the order-general ISR
structure (and the (ncfg,norb) vs (norb,ncfg) transpose convention) against
known-good physics before it is ever used at n=4.
"""
import os, sys
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))
import numpy as np
from pyscf import gto, scf
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.SingleReference.ADC.sigma_driver import u3_dot_orb, u_dot_orb_isr
from src.SingleReference.ADC.generated_modules import lazy
s2r = lazy('adc4_c2_s2c_apply_restricted_blocks')
from src.Base.pyscf_interface import get_orbital_energies, get_antisymmetrized_spin_block_eri
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)

def main():
    all_ok = True
    for atom, basis, lab in [('Li 0 0 0; H 0 0 1.6', 'sto-3g', 'LiH/sto-3g'),
                             ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g')]:
        mol = gto.M(atom=atom, basis=basis, verbose=0); mf = scf.RHF(mol).run()
        ns = mol.nelectron // 2
        eps = get_orbital_energies(mf, representation='spatial')
        ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
        r = BuildSuperMatrixADCnRestricted(eps, ga, gab, gb, ns)
        pv = np.random.default_rng(5).standard_normal(r.norb)
        for sec in ('IP', 'EA'):
            ref = u3_dot_orb(r, sec, pv, s2r)
            isr = u_dot_orb_isr(r, sec, pv, 3, s2r)
            d = np.abs(isr - ref).max()
            ok = d < 1e-12; all_ok &= ok
            print(f"[{'OK' if ok else 'FAIL'}] {lab} {sec}: ISR(n=3) == u3_dot_orb: {d:.2e}")
    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
