"""Validation of the generated ADC(2) blocks (generate_adcn.py ->
generatedADC/adc2_blocks.py -> adc_autogenerated.BuildSuperMatrixADCn) against
two INDEPENDENT references, per the ADC(n)-generator plan's Phase 2 gate:

1. adc_spinorbital.py's validated first-order pieces (term0 U formulas,
   K diagonals, _C_2h1p_block/_C_2p1h_block) -- exact equality at +1
   everywhere, now that the generator uses the sector-dependent commutator
   direction ([C_J, H] for IP classes -- Dyson hole-propagator
   convention, see superop_element_terms' docstring; the first run of
   this test with [H, C_J] for both sectors showed every IP element off
   by exactly -1, which is how that convention was pinned).
2. The textbook MP2 self-energy formula (hand-written HERE, independently)
   -- Sigma_ADC2(omega) must equal it at arbitrary omega
   (MP2 self-energy oracle). This is the external
   check that the assembled generated blocks give the right PHYSICS, not
   just the right tensors.

H2O/sto-3g is the decisive system (H2/sto-3g's occ-row 2h1p couplings
vanish identically by g/u parity -- degenerate test);
H2/sto-3g kept as a smoke case.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.SingleReference.ADC import ADCSolverUnrestricted
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCn
from src.Base.pyscf.pyscf_interface import (
    get_orbital_energies, get_two_electron_integrals_chemist,
    get_antisymmetrized_spin_eri)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)


def mp2_self_energy(eps, g, nocc, omega):
    """Textbook spin-orbital MP2 self-energy (independent reference, written
    from the standard formula -- NOT from any ADC code):
    Sigma_pq(w) = 1/2 sum_{ija} <pa||ij><qa||ij>/(w + e_a - e_i - e_j)
                + 1/2 sum_{iab} <pi||ab><qi||ab>/(w + e_i - e_a - e_b)."""
    norb = len(eps)
    occ = np.arange(nocc)
    virt = np.arange(nocc, norb)
    eps_o, eps_v = eps[occ], eps[virt]

    g_pa_ij = g[np.ix_(np.arange(norb), virt, occ, occ)]   # <pa||ij>
    d1 = omega + eps_v[:, None, None] - eps_o[None, :, None] - eps_o[None, None, :]
    sig1 = 0.5 * np.einsum('paij,qaij->pq', g_pa_ij / d1[None], g_pa_ij, optimize=True)

    g_pi_ab = g[np.ix_(np.arange(norb), occ, virt, virt)]  # <pi||ab>
    d2 = omega + eps_o[:, None, None] - eps_v[None, :, None] - eps_v[None, None, :]
    sig2 = 0.5 * np.einsum('piab,qiab->pq', g_pi_ab / d2[None], g_pi_ab, optimize=True)
    return sig1 + sig2


def check(label, diff, tol=1e-12):
    ok = diff < tol
    print(f"[{'OK' if ok else 'FAIL'}] {label}: max diff = {diff:.3e}")
    return ok


def main():
    all_ok = True

    for atom, basis, label in [
        ('H 0 0 0; H 0 0 0.74', 'sto-3g', 'H2/sto-3g (smoke)'),
        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g (decisive)'),
    ]:
        mol = gto.M(atom=atom, basis=basis, verbose=0)
        mf = scf.RHF(mol).run()
        nocc = 2 * (mol.nelectron // 2)
        eps = get_orbital_energies(mf, representation='spin')
        eri = get_two_electron_integrals_chemist(mol, mf, representation='spatial')
        g = get_antisymmetrized_spin_eri(eri)
        norb = len(eps)
        occ, virt = np.arange(nocc), np.arange(nocc, norb)

        gen_solver = BuildSuperMatrixADCn(eps, g, nocc)
        adc3 = ADCSolverUnrestricted.from_arrays(eps, g)

        print(f"\n=== {label} ===")

        # --- 1a. U^(1) vs adc3's term0 formulas (exact, +1) ---
        i_2h, j_2h, a_2h = adc3._configs_2h1p(nocc)
        U1_ref = g[i_2h[:, None], j_2h[:, None], np.arange(norb)[None, :], a_2h[:, None]]
        all_ok &= check("U_2h1p == adc3 term0", np.abs(gen_solver.u_2h1p() - U1_ref).max())

        i_2p, a_2p, b_2p = adc3._configs_2p1h(nocc)
        U2_ref = g[a_2p[:, None], b_2p[:, None], np.arange(norb)[None, :], i_2p[:, None]]
        all_ok &= check("U_2p1h == adc3 term0", np.abs(gen_solver.u_2p1h() - U2_ref).max())

        # --- 1b. K blocks: diagonal, equal to adc3's eps sums, off-diag 0 ---
        K1 = gen_solver.k_block('IP')
        K1_expected = eps[i_2h] + eps[j_2h] - eps[a_2h]
        all_ok &= check("K_2h1p diag == eps_i+eps_j-eps_a", np.abs(np.diag(K1) - K1_expected).max())
        all_ok &= check("K_2h1p off-diagonal == 0", np.abs(K1 - np.diag(np.diag(K1))).max())
        K2 = gen_solver.k_block('EA')
        K2_expected = eps[a_2p] + eps[b_2p] - eps[i_2p]
        all_ok &= check("K_2p1h diag == eps_a+eps_b-eps_i", np.abs(np.diag(K2) - K2_expected).max())
        all_ok &= check("K_2p1h off-diagonal == 0", np.abs(K2 - np.diag(np.diag(K2))).max())

        # --- 1c. C^(1) blocks vs adc3's validated _C_2h1p_block/_C_2p1h_block ---
        C1_ref = adc3._C_2h1p_block(nocc, np.arange(len(i_2h)))
        all_ok &= check("C1_2h1p == adc3 _C_2h1p_block", np.abs(gen_solver.c1_block('IP') - C1_ref).max())
        C2_ref = adc3._C_2p1h_block(nocc, np.arange(len(i_2p)))
        all_ok &= check("C1_2p1h == adc3 _C_2p1h_block", np.abs(gen_solver.c1_block('EA') - C2_ref).max())

        # --- 1d. S^(0) gathers to the identity (orthonormal metric at 0th order) ---
        all_ok &= check("S0_2h1p == identity", np.abs(gen_solver.s0_block('IP') - np.eye(len(i_2h))).max())
        all_ok &= check("S0_2p1h == identity", np.abs(gen_solver.s0_block('EA') - np.eye(len(i_2p))).max())

        # --- 2. THE oracle: Sigma_ADC2(omega) == textbook MP2 self-energy ---
        for omega in (0.15, -0.35, 0.85):
            sig_gen = gen_solver.sigma_dynamic(omega)
            sig_ref = mp2_self_energy(eps, g, nocc, omega)
            all_ok &= check(f"Sigma(omega={omega:+.2f}) == MP2 self-energy",
                            np.abs(sig_gen - sig_ref).max())

        # --- 3. supermatrix sanity: symmetric ---
        H = gen_solver.build_supermatrix_adc2()
        all_ok &= check("ADC(2) supermatrix symmetric", np.abs(H - H.T).max())

    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
