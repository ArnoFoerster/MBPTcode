"""GATE for wall #2's AMPLITUDE side: the ISR Delta S (class_overlap_series /
_class_raw_S) in the dense oracle u_dot_orb_isr must stop materializing rank>=3
amplitudes when laplace_ntau is given, WITHOUT changing the answer.

class_overlap_series feeds the Loewdin layer of the order-general U^(n) ISR its
class-class overlap Delta S^(m). The exact path builds those amps from
_amps_order(m), which materializes t3_2/t4_2/t3_3; laplace mode routes through
_amps_order_lowrank_laplace instead. This is BIT-EXACT (not ntau-approximate):
Delta S^(m) is assembled entirely from the l2t2 structure at rank<=2 order<=2
(identical in both providers), and the class-class raw's only rank>=3 structure
(l2ft3 -> t3_2) has its Fock factor in f[o,v] and vanishes by Brillouin,
so dropping it (the low-rank provider omits t3_2)
changes nothing.

NH3/sto-3g (5 occ / 3 vir): the ONLY system here where t3_2 AND t4_2 are
genuinely nonzero, so the exact path really materializes them and the laplace
path really skips them -- a `0.0` on LiH/H2O would be two-zeros-compared.

The dense (n_k1)^2 Delta S MATRIX itself is NOT addressed here (that is the
matrix-free-ISR follow-on); this gate is only the amplitude-materialization side.

Run:  ~/anaconda3/envs/py310/bin/python -u tests/test_sigma_class_overlap_laplace.py
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.Base.pyscf.pyscf_interface import (get_orbital_energies,
                                            get_antisymmetrized_spin_block_eri)
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)

TOL = 1e-12          # BIT-EXACT: Delta S has zero sensitivity to the dropped amps
_RANK_GE3 = ('L3', 'L4', 'T3', 'T4', 'L5', 'T5')


def _check(ok, msg):
    print(f"[{'OK' if ok else 'FAIL'}] {msg}")
    return ok


def main():
    mol = gto.M(atom='N 0 0 0; H 0 0 1.01; H 0.95 0 -0.3; H -0.48 0.82 -0.3',
                basis='sto-3g', verbose=0)
    mf = scf.RHF(mol); mf.conv_tol = 1e-13; mf.run()
    eps = get_orbital_energies(mf, representation='spatial')
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
    r = BuildSuperMatrixADCnRestricted(eps, ga, gab, gb, mol.nelectron // 2)
    print(f"NH3/sto-3g norb={r.norb} nocc={r.nocc} nvir={r.nvir}")
    all_ok = True

    A = r._amps_order(max_order=3)
    mx3 = max(float(np.abs(v).max()) for v in A['T3_2'].values())
    mx4 = max(float(np.abs(v).max()) for v in A['T4_2'].values())
    all_ok &= _check(mx3 > 1e-8 and mx4 > 1e-8,
                     f"t3_2 (|max|={mx3:.2e}) AND t4_2 (|max|={mx4:.2e}) nonzero "
                     f"-- the exact path really materializes what laplace skips")

    lap_keys = set(r._amps_order_lowrank_laplace(6))
    bad = [k for k in lap_keys if any(k.startswith(p) for p in _RANK_GE3)]
    all_ok &= _check(not bad,
                     f"the ISR-Delta-S provider carries NO rank>=3 key "
                     f"(keys={sorted(lap_keys)})")

    for sector in ('IP', 'EA'):
        ex = r.class_overlap_series(sector, 3)
        lp = r.class_overlap_series(sector, 3, laplace_ntau=6)
        all_ok &= _check(set(ex) == set(lp) and len(ex) > 0,
                         f"{sector}: same orders assembled {sorted(ex)}")
        mag = max(float(np.abs(ex[m]).max()) for m in ex)
        all_ok &= _check(mag > 1e-8, f"{sector}: Delta S NONZERO (|max|={mag:.3e})")
        worst = max(float(np.abs(ex[m] - lp[m]).max()) for m in ex)
        all_ok &= _check(worst < TOL,
                         f"{sector}: class_overlap_series(laplace) == exact, "
                         f"BIT-EXACT ({worst:.2e} < {TOL:.0e})")

    print('\nALL OK' if all_ok else '\nFAILURES')
    return 0 if all_ok else 1


def test_main():
    assert not main(), 'main() returned a nonzero exit code'


if __name__ == '__main__':
    sys.exit(main())
