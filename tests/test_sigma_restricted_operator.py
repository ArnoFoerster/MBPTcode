"""Restricted (spin-free / RHF) matrix-free config-space driver: the
sigma-vector twin of BuildSuperMatrixADCnRestricted, dispatched per spin
pattern.

Two gates:
  1. assembled_c2_matvec_restricted == BuildSuperMatrixADCnRestricted.
     c2_block_generated @ v  (the restricted ISR/Loewdin C^(2) with no
     (ncfg,ncfg) block), both sectors.
  2. restricted_sector_operator reconstruction == the dense restricted
     ADC(4)-base single-sector supermatrix [[diag(eps), U^T],[U, K + C^(1) +
     C^(2)]] and eigsh == eigh, both sectors.

Everything (config enumeration, amplitude/leaf pool, N^(2)) is taken from
BuildSuperMatrixADCnRestricted READ-ONLY; the matrix-free path only folds the
trial vector over the generated restricted apply modules.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf
from scipy.sparse.linalg import eigsh

from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.SingleReference.ADC.generated_modules import lazy
c1r = lazy('adc4_c1_self_apply_restricted_blocks')
c2r = lazy('adc4_c2_apply_restricted_blocks')
s2r = lazy('adc4_c2_s2c_apply_restricted_blocks')
from src.SingleReference.ADC.sigma_driver import (
    assembled_c2_matvec_restricted, restricted_sector_operator)
from src.Base.pyscf.pyscf_interface import (
    get_orbital_energies, get_antisymmetrized_spin_block_eri)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)


def main():
    all_ok = True
    for atom, basis, label in [
        ('H 0 0 0; H 0 0 0.74', 'sto-3g', 'H2/sto-3g'),
        ('Li 0 0 0; H 0 0 1.6', 'sto-3g', 'LiH/sto-3g'),
        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g'),
    ]:
        mol = gto.M(atom=atom, basis=basis, verbose=0)
        mf = scf.RHF(mol).run()
        nocc_sp = mol.nelectron // 2
        eps_sp = get_orbital_energies(mf, representation='spatial')
        g_aaaa, g_bbbb, g_abab = get_antisymmetrized_spin_block_eri(mol, mf)
        r = BuildSuperMatrixADCnRestricted(eps_sp, g_aaaa, g_abab, g_bbbb, nocc_sp)
        pool = {**r.rargs, **r.amplitude_pool()}
        n2 = r.n2_norm()
        norb, no, nv = r.norb, r.nocc, r.nvir
        rng = np.random.default_rng(0)

        print(f"\n=== {label} ===")
        for sector, tag in (('IP', '2h1p'), ('EA', '2p1h')):
            cfg = r.sector_configs(sector)
            ncfg = len(cfg['K'])

            # -- gate 1: assembled C^(2) matvec == dense c2_block_generated --
            C2 = r.c2_block_generated(sector)
            v = rng.standard_normal(ncfg)
            y_mf = assembled_c2_matvec_restricted(v, cfg, pool, n2, no, nv, c2r, s2r, tag)
            c2diff = np.abs(y_mf - C2 @ v).max()

            # -- gate 2: restricted sector operator == dense ADC(4)-base assembly --
            U = r.u_adc3(sector)                       # (ncfg, norb) order-2 U
            n = norb + ncfg
            Href = np.zeros((n, n))
            Href[:norb, :norb] = np.diag(eps_sp)
            Href[norb:, :norb] = U
            Href[:norb, norb:] = U.T
            Href[norb:, norb:] = np.diag(cfg['K']) + r._c1_block(sector) + C2
            op = restricted_sector_operator(sector, r, U, c1r, c2r, s2r)
            recon = np.column_stack([op.matvec(e) for e in np.eye(n)])
            opdiff = np.abs(recon - Href).max()
            opsym = np.abs(recon - recon.T).max()
            k = min(6, n - 2)
            w_mf = np.sort(eigsh(op, k=k, which='SA', return_eigenvectors=False))
            w_d = np.sort(np.linalg.eigvalsh(Href))[:k]
            eigdiff = np.abs(w_mf - w_d).max()

            ok = c2diff < 1e-11 and opdiff < 1e-10 and eigdiff < 1e-8
            all_ok &= ok
            print(f"  {sector} (ncfg {ncfg}, dim {n}, sym {opsym:.1e}):")
            print(f"    [{'OK' if c2diff < 1e-11 else 'FAIL'}] assembled C^(2) matvec == c2_block_generated@v: {c2diff:.2e}")
            print(f"    [{'OK' if opdiff < 1e-10 else 'FAIL'}] operator == dense ADC(4)-base assembly: {opdiff:.2e}")
            print(f"    [{'OK' if eigdiff < 1e-8 else 'FAIL'}] lowest-{k} eigenvalues: {eigdiff:.2e}  (lowest {w_mf[0]:.6f} Ha)")

    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
