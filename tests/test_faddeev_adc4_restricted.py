"""Restricted matrix-free Faddeev-ADC(4) (ADC/adc_r_faddeev4.py): the gates.

What pins what:

1. The CSF isometry. W (alpha-sector determinants x adc_r_faddeev CSFs) is an
   isometry, and W^T (restricted ADC(3) of the generated determinant
   operator) W equals the CSF ADC(3) supermatrix of adc_r_dense_full, with
   no coupling from the CSFs to the rest of the determinant sector.
2. The lambda^5 limit, restricted. v -> lambda v at fixed orbital energies, H2O and LiH
   in STO-3G and LiH in 6-31+G: the dynamic self-energy differs from the
   restricted diagrammatic ADC(4)'s (sigma_driver.restricted_dyson_operator)
   as lambda^5, on the RPA route ('riccati', the production one) and on the
   CCD route; without dC as lambda^4.
3. Restricted against spin-orbital (adc_u_faddeev4) at lambda = 1, both
   routes: the alpha block of the self-energy to 1e-12, and the principal
   IPs of the matrix-free downfold (FaddeevADC4Operator.solve) to 1e-10;
   the 'riccati' route, whose ladder amplitudes are converged to
   RICCATI_CONV_TOL, to that bar, and it agrees with 'phonon' to it.
4. DF. On H2O/6-31G the DF operator (B_aa and the ADC(4) DF leaves) equals
   the dense-integral operator built from the same factor.

The self-energy is evaluated from the dense blocks with the k2 space folded
exactly (K2 diagonal):
    Sigma(w) = U3^T g U3 + B^T (w - A11 - E^T g E)^{-1} B,
    g = (w - K2)^{-1},  B = C + E^T g U3.

Run: python tests/test_faddeev_adc4_restricted.py, or under pytest.
"""
