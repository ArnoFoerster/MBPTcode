MOLS = {'h2o': 'O 0 0 0.1173; H 0 0.7572 -0.4692; H 0 -0.7572 -0.4692',
        'lih': 'Li 0 0 0; H 0 0 1.595'}
LAMBDAS = (0.08, 0.04, 0.02)
OMEGAS = np.array([-0.6 + 0.4j, -0.2 + 0.4j, 0.4 + 0.4j, 1.0 + 0.4j])
RATIO_5 = 28.0
RATIO_4 = (13.0, 20.0)
TOL_SIGMA = 1e-12
TOL_IP = 1e-10


def check(ok, label, detail=''):
    print(f"  [{'ok' if ok else 'FAIL'}] {label}" + (f'   ({detail})' if detail else ''))
    return bool(ok)


def scf_run(name, basis, df=False):
    mol = gto.M(atom=MOLS[name], basis=basis, verbose=0)
    mf = scf.RHF(mol)
    if df:
        mf = mf.density_fit()
    mf.conv_tol, mf.conv_tol_grad, mf.max_cycle = 1e-13, 1e-10, 300
    mf.run()
    return mol, mf


class System:
    """eps, the chemist tensor (or DF factor) and the spin blocks, scalable
    by lambda."""

    def __init__(self, name, basis, df=False):
        self.mol, self.mf = scf_run(name, basis, df)
        self.eps = self.mf.mo_energy
        self.nocc = self.mol.nelectron // 2
        self.norb = len(self.eps)
        if df:
            self.B = DFIntegrals.from_scf(self.mol, self.mf).B_aa
            self.eri = np.einsum('Qpq,Qrs->pqrs', self.B, self.B, optimize=True)
        else:
            self.B = None
            n = self.norb
            self.eri = self.mol.ao2mo(self.mf.mo_coeff, compact=False).reshape((n,) * 4)

    def solvers(self, lam=1.0, df=False):
        """(Faddeev solver, generated ADC(4) solver, extra_leaves) at v -> lam v."""
        eps, nocc = self.eps, self.nocc
        vpr = lam * self.eri.transpose(0, 2, 1, 3)               # <pq|rs>
        ga = vpr - vpr.transpose(0, 1, 3, 2)
        if df:
            B = np.sqrt(lam) * self.B
            s = ADCSolverRestricted.from_arrays(eps, B_aa=B, nocc=nocc)
            leaves = {'B_aa': B, 'B_bb': B}
        else:
            s = ADCSolverRestricted.from_arrays(eps, eri_chemist=lam * self.eri, nocc=nocc)
            leaves = None
        return s, BuildSuperMatrixADCnRestricted(eps, ga, vpr, ga, nocc), leaves

    def spin_orbital(self, lam=1.0):
        return ADCSolverUnrestricted.from_arrays(
            np.repeat(self.eps, 2), get_antisymmetrized_spin_eri(lam * self.eri),
            nocc=2 * self.nocc)

    def ccd(self, lam):
        """(alpha-beta CCD amplitude, alpha-beta second-order doubles) at lam,
        from the spin-orbital CCD (interleaved spin orbitals)."""
        so = self.spin_orbital(lam)
        t = ccd_spin_orbital(so.eps, so.g, so.nocc, tol=1e-14)[0]
        t2 = F4.second_order_doubles(so.eps, so.g, so.nocc)
        ab = lambda x: x[0::2, 1::2, 0::2, 1::2].copy()
        return ab(t), ab(t2)


def faddeev(sysd, lam, route, df=False, line_dressing=True):
    s, gen, leaves = sysd.solvers(lam, df)
    kw = {}
    if route == 'ccd':
        t, t2 = sysd.ccd(lam)
        kw = dict(channels=FR.ccd_channels(s.eps, sysd.nocc, t, s.B_aa,
                                           None if df else lam * sysd.eri),
                  t2_second=t2)
    return R4.FaddeevADC4Operator(s, gen, sysd.nocc, route=route, extra_leaves=leaves,
                                  line_dressing=line_dressing, **kw)


def adc4_blocks(sysd, lam):
    """The restricted diagrammatic ADC(4) in the same block form (built once
    per system and lambda)."""
    cache = sysd.__dict__.setdefault('_adc4', {})
    if lam not in cache:
        cache[lam] = _adc4_blocks(sysd, lam)
    return cache[lam]


def _adc4_blocks(sysd, lam):
    _, gen, _ = sysd.solvers(lam)
    op, diag = restricted_dyson_operator(gen, 'adc4', construction='diagrammatic')
    B = op.blocks
    norb = sysd.norb
    nI, nE = len(B.K1['IP']), len(B.K1['EA'])
    n1, ntot = nI + nE, op.shape[0]
    A11 = np.empty((n1, n1))
    for c in range(n1):
        x = np.zeros(ntot)
        x[norb + c] = 1.0
        A11[:, c] = op.matvec(x)[norb:norb + n1]
    eye = np.eye(norb)
    C = np.column_stack([np.concatenate([B.u_k1('IP', e), B.u_k1('EA', e)]) for e in eye])
    U3 = np.column_stack([np.concatenate([B.u_k2('IP', e), B.u_k2('EA', e)]) for e in eye])
    mI = len(B.K2['IP'])
    E = np.zeros((len(diag) - norb - n1, n1))
    for c in range(nI):
        E[:mI, c] = B.e3('IP', np.eye(nI)[c])
    for c in range(nE):
        E[mI:, nI + c] = B.e3('EA', np.eye(nE)[c])
    return {'F': np.diag(sysd.eps), 'C': C, 'A11': 0.5 * (A11 + A11.T), 'E': E,
            'U3': U3, 'K2': np.concatenate([B.K2['IP'], B.K2['EA']])}


def sigma_folded(b, omegas=OMEGAS):
    out = []
    for w in omegas:
        g = 1.0 / (w - b['K2'])
        Bm = b['C'] + b['E'].T @ (g[:, None] * b['U3'])
        S = w * np.eye(len(b['A11'])) - b['A11'] - b['E'].T @ (g[:, None] * b['E'])
        out.append(b['U3'].T @ (g[:, None] * b['U3']) + Bm.T @ np.linalg.solve(S, Bm))
    return np.array(out)


def full_dense(b):
    """The symmetric supermatrix from the blocks (orbitals, k1, k2)."""
    norb, n1, n2 = len(b['F']), len(b['A11']), len(b['K2'])
    M = np.zeros((norb + n1 + n2,) * 2)
    o, k1, k2 = slice(0, norb), slice(norb, norb + n1), slice(norb + n1, None)
    M[o, o] = b['F']
    M[k1, o], M[o, k1] = b['C'], b['C'].T
    M[k2, o], M[o, k2] = b['U3'], b['U3'].T
    M[k1, k1] = b['A11']
    M[k2, k1], M[k1, k2] = b['E'], b['E'].T
    M[k2, k2] = np.diag(b['K2'])
    return M


