def check_isometry(sysd):
    eps, nocc, norb = sysd.eps, sysd.nocc, sysd.norb
    _, gen, _ = sysd.solvers()
    Md = gen.build_supermatrix_adc3()
    sr = ADCSolverRestricted.from_arrays(eps, eri_chemist=sysd.eri, nocc=nocc)
    Mc = adc_r_dense_full.build_supermatrix(sr, nocc)
    Ws = [R4.csf_isometry(gen.sector_configs(sec), nocc, norb - nocc, sec).toarray()
          for sec in ('IP', 'EA')]
    W = np.zeros((Md.shape[0], Mc.shape[0]))
    W[:norb, :norb] = np.eye(norb)
    r, c = norb, norb
    for w in Ws:
        W[r:r + w.shape[0], c:c + w.shape[1]] = w
        r, c = r + w.shape[0], c + w.shape[1]
    ok = check(np.abs(W.T @ W - np.eye(W.shape[1])).max() < 1e-14, 'W is an isometry')
    d = np.abs(W.T @ Md @ W - Mc).max()
    ok &= check(d < 1e-12, 'W^T ADC(3)_det W == ADC(3)_CSF', f'{d:.1e}')
    leak = np.abs((np.eye(len(Md)) - W @ W.T) @ Md @ W).max()
    ok &= check(leak < 1e-12, 'the CSFs do not couple to the rest of the sector', f'{leak:.1e}')
    return ok


def _ratios(rows, col):
    return [rows[n - 1][col] / rows[n][col] for n in range(1, len(rows))]


def check_gate(label, sysd, route):
    rows = []
    for lam in LAMBDAS:
        sR = sigma_folded(adc4_blocks(sysd, lam))
        P = sigma_folded(faddeev(sysd, lam, route).dense_blocks())
        P0 = sigma_folded(faddeev(sysd, lam, route, line_dressing=False).dense_blocks())
        rows.append((lam, np.abs(P - sR).max(), np.abs(P0 - sR).max()))
    print(f"   {label} {route!r}: " + "  ".join(
        f"lam {r[0]:.2f}: {r[1]:.3e} / no dC {r[2]:.3e}" for r in rows))
    rp, r0 = _ratios(rows, 1), _ratios(rows, 2)
    ok = check(rp[-1] > RATIO_5, f'{label} {route}: restricted Faddeev-ADC(4) - ADC(4) ~ lambda^5',
               f'ratios {np.round(rp, 1)}')
    ok &= check(RATIO_4[0] < r0[-1] < RATIO_4[1], f'{label} {route}: without dC ~ lambda^4',
                f'ratios {np.round(r0, 1)}')
    return ok


def check_against_spin_orbital(label, sysd):
    norb, nocc = sysd.norb, sysd.nocc
    alpha = 2 * np.arange(norb)
    so = sysd.spin_orbital()
    A4 = F4.adc4_supermatrix(so, 2 * nocc)
    ok = True
    blocks = {}
    for route in ('riccati', 'phonon', 'ccd'):
        t = None
        if route == 'ccd':
            t = ccd_spin_orbital(so.eps, so.g, so.nocc, tol=1e-14)[0]
        Mso = F4.build_supermatrix(so, 2 * nocc, route='phonon' if route == 'riccati' else route,
                                   t=t, adc4=A4)
        op = faddeev(sysd, 1.0, route)
        b = blocks[route] = op.dense_blocks()
        Sr = sigma_folded(b)
        Ss = sigma_dyn(Mso, 2 * norb, OMEGAS)[:, alpha][:, :, alpha]
        d = np.abs(Sr - Ss).max()
        tol = RICCATI_CONV_TOL if route == 'riccati' else TOL_SIGMA
        ok &= check(d < tol, f'{label} {route}: Sigma restricted == spin-orbital (alpha)',
                    f'{d:.1e}')
        w, V = np.linalg.eigh(Mso)
        st = np.sum(V[:2 * norb] ** 2, axis=0)
        ref = w[(w < 0) & (st > 0.5)]
        for k in (nocc - 1, nocc - 2):
            e = op.solve(k, tol=1e-11, davidson_tol=1e-9)['e']
            dk = np.abs(ref - e).min()
            ok &= check(dk < TOL_IP, f'{label} {route}: downfold root from orbital {k} '
                        f'== a principal spin-orbital pole', f'{e:.10f} Eh, {dk:.1e}')
    d = np.abs(sigma_folded(blocks['riccati']) - sigma_folded(blocks['phonon'])).max()
    ok &= check(d < RICCATI_CONV_TOL, f'{label}: phonon route == riccati route', f'{d:.1e}')
    return ok


def check_df():
    sysd = System('h2o', '6-31g', df=True)
    ok = True
    for route in ('riccati', 'ccd'):
        if route == 'ccd':
            t, t2 = sysd.ccd(1.0)

            def mk(df):
                s, gen, leaves = sysd.solvers(1.0, df)
                ch = FR.ccd_channels(sysd.eps, sysd.nocc, t, s.B_aa,
                                     None if df else sysd.eri)
                return R4.FaddeevADC4Operator(s, gen, sysd.nocc, route='ccd', channels=ch,
                                              t2_second=t2, extra_leaves=leaves)
        else:
            def mk(df):
                return faddeev(sysd, 1.0, route, df=df)
        a, b = mk(True), mk(False)
        d = np.abs(sigma_folded(a.dense_blocks()) - sigma_folded(b.dense_blocks())).max()
        ok &= check(d < TOL_SIGMA, f'h2o/6-31g {route}: DF operator == dense operator',
                    f'{d:.1e}')
        ea = a.solve(sysd.nocc - 1, tol=1e-11, davidson_tol=1e-9)['e']
        eb = b.solve(sysd.nocc - 1, tol=1e-11, davidson_tol=1e-9)['e']
        ok &= check(abs(ea - eb) < TOL_IP, f'h2o/6-31g {route}: DF HOMO == dense HOMO',
                    f'{ea:.10f} Eh, {abs(ea - eb):.1e}')
    return ok


SYSTEMS = (('h2o', 'sto-3g'), ('lih', 'sto-3g'), ('lih', '6-31+g'))


def run(which=None):
    warnings.simplefilter('ignore')
    ok = True
    for name, basis in SYSTEMS:
        label = f'{name}/{basis}'
        if which and label not in which:
            continue
        sysd = System(name, basis)
        print(f"\n== {label}: norb {sysd.norb}, nocc {sysd.nocc}")
        ok &= check_isometry(sysd)
        for route in ('riccati', 'ccd'):
            ok &= check_gate(label, sysd, route)
        if basis == 'sto-3g':
            ok &= check_against_spin_orbital(label, sysd)
    if not which or 'df' in which:
        print('\n== DF (h2o/6-31g)')
        ok &= check_df()
    print('\nALL PASSED' if ok else '\nFAILURES DETECTED')
    return ok


@pytest.mark.parametrize('which', ['h2o/sto-3g', 'lih/sto-3g', 'lih/6-31+g', 'df'])
def test_faddeev_adc4_restricted(which):
    assert run((which,))


if __name__ == '__main__':
    sys.exit(0 if run(tuple(sys.argv[1:]) or None) else 1)
