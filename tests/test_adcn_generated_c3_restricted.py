pytestmark = requires_runtime(5)
from src.SingleReference.ADC.generated_modules import lazy
genc3so = lazy('adc5_c3_blocks')
genc3r = lazy('adc5_c3_blocks_restricted')


def _alpha_idx(cfg, sector, cols, nocc):
    idx = []
    for c in range(len(cfg['K'])):
        hs, ps, sp = cfg['hole_sp'][c], cfg['part_sp'][c], cfg['spins'][c]
        if sector == 'IP':
            hso = sorted([2 * hs[0] + sp[0], 2 * hs[1] + sp[1]]); pso = [nocc + 2 * ps[0] + sp[2]]
            m = np.where((cols[0] == hso[0]) & (cols[1] == hso[1]) & (cols[2] == pso[0]))[0]
        else:
            hso = [2 * hs[0] + sp[0]]; pso = sorted([nocc + 2 * ps[0] + sp[1], nocc + 2 * ps[1] + sp[2]])
            m = np.where((cols[0] == hso[0]) & (cols[1] == pso[0]) & (cols[2] == pso[1]))[0]
        idx.append(m[0])
    return np.array(idx)


def _inject_l3_t3(so, r, eps, g, eps_sp, ga, gab, gbb, nsp):
    """Add l3/t3 leaves (absent from _amplitude_pool) to both drivers' cached
    pools, from their own order-2 MP amplitudes -- consistent by construction."""
    mpn = MPnDensityDriver(eps, g, 2 * nsp)
    _, _, t3_2, _ = mpn.compute_order2_amplitudes(mpn.compute_t2_1())
    so._amplitude_pool(); so._amp_pool.update({'l3': to_l(t3_2, 3), 't3': t3_2})
    mr = MPnDensityDriverRestricted(np.diag(eps_sp), ga, gab, gbb, nsp)
    t2a, t2b = mr.compute_t2_1()
    o2 = mr.compute_order2_amplitudes(t2a, t2b, max_rank=3)
    t3a, t3ab, t3abb = o2[3], o2[4], o2[5]
    r._amplitude_pool(); r._amp_pool.update({
        'l3_aaaaaa': to_l(t3a, 3, 'aaaaaa'), 'l3_aabaab': to_l(t3ab, 3, 'aabaab'),
        'l3_abbabb': to_l(t3abb, 3, 'abbabb'), 'l3_bbbbbb': to_l(t3a, 3, 'aaaaaa'),
        't3_aaaaaa': t3a, 't3_aabaab': t3ab, 't3_abbabb': t3abb, 't3_bbbbbb': t3a})


def main():
    all_ok = True
    for atom, basis, label in [('H 0 0 0; H 0 0 0.74', 'sto-3g', 'H2/sto-3g (smoke)'),
                               ('Li 0 0 0; H 0 0 1.6', 'sto-3g', 'LiH/sto-3g (decisive)')]:
        mol = gto.M(atom=atom, basis=basis, verbose=0); mf = scf.RHF(mol).run()
        nsp = mol.nelectron // 2; nocc = 2 * nsp
        eps = get_orbital_energies(mf, representation='spin')
        g = get_antisymmetrized_spin_eri(get_two_electron_integrals_chemist(mol, mf, representation='spatial'))
        so = BuildSuperMatrixADCn(eps, g, nocc)
        eps_sp = get_orbital_energies(mf, representation='spatial')
        ga, gbb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
        r = BuildSuperMatrixADCnRestricted(eps_sp, ga, gab, gbb, nsp)
        _inject_l3_t3(so, r, eps, g, eps_sp, ga, gab, gbb, nsp)

        print(f"\n=== {label} ===")
        for sector in ('IP', 'EA'):
            tag = '2h1p' if sector == 'IP' else '2p1h'
            cols = class_configs(nocc, len(eps), 1, sector)
            idx = _alpha_idx(r._sector_configs(sector), sector, cols, nocc)
            C3r = r._class_block_sum(genc3r, f'c3_{tag}_', sector)
            C3so = so._sum_gathered(genc3so, f'c3_{tag}_', sector)
            d = np.abs(C3r - C3so[np.ix_(idx, idx)]).max()
            S3r = r._class_block_sum(genc3r, f's3c_{tag}_', sector)
            S3so = so._sum_gathered(genc3so, f's3c_{tag}_', sector)
            ds = (np.abs(S3r - S3so[np.ix_(idx, idx)]).max() if S3so is not None
                  else (0.0 if S3r is None or np.abs(S3r).max() < 1e-14 else np.abs(S3r).max()))
            ok = d < 1e-11 and ds < 1e-11; all_ok &= ok
            print(f"[{'OK' if ok else 'FAIL'}] C^(3) {sector} restricted==spin-orbital: {d:.2e}  S^(3)c: {ds:.2e}")

    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
