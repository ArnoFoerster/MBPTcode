"""ADC(5) increment 2a gate: the restricted (spin-blocked, RHF) order-3
class-class C^(3) + within-class S^(3) blocks (adc5_c3_blocks_restricted,
generate_adc5_c3_restricted) must equal their SPIN-ORBITAL reference
(adc5_c3_blocks, generate_adc5_c3) at the corresponding alpha-sector configs
-- the block-level spin-blocking oracle, the C^(3) analog of
test_adcn_generated_c2_restricted (which does the same for C^(2)).

C^(3) is spin-conserving, so its alpha sub-block is self-contained. Both sides
are gathered to the (ncfg, ncfg) class-class space via the drivers' own
gather (_class_block_sum / _sum_gathered), fed the SAME underlying MP
amplitudes (l1/l2/l3 lambda + t1/t2/t3, restricted = spin-block slice of the
spin-orbital ones) -- the amplitude ORDER is irrelevant to a spin-blocking
check, only that both sides use corresponding amps. Machine precision expected.

H2/sto-3g smoke; LiH/sto-3g decisive.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.SingleReference.ADC.adc_autogenerated import (
    BuildSuperMatrixADCn, BuildSuperMatrixADCnRestricted)
from src.SingleReference.ADC.precursor_classes import class_configs
from src.SingleReference.DensityMatrix.mpn_density_driver import MPnDensityDriver
from src.SingleReference.DensityMatrix.mpn_density_driver_restricted import MPnDensityDriverRestricted
from src.SingleReference.common.mp_amplitudes import to_l
from src.Base.pyscf.pyscf_interface import (
    get_orbital_energies, get_two_electron_integrals_chemist,
    get_antisymmetrized_spin_eri, get_antisymmetrized_spin_block_eri)
