"""READ-ONLY parity benchmark: the generated matrix-free ADC(3) operator
(sigma_driver.full_adc3_operator) vs the production dense ADC(3) supermatrix
(ADCSolver.build_supermatrix -- the hand-written spin-orbital reference
production actually runs). Touches NO production code; instantiates the real
solver read-only and prints both spectra side by side.

The matrix-free operator applies both class-class blocks (K + C^(1)) entirely
matrix-free (K diagonal, C^(1) via the generated self-block applies); U through
order 2 is the generated BuildSuperMatrixADCn.u_*_adc3 (validated == production's
hand-written U). Level = ADC(3) exactly (no C^(2), no 3h2p) to match what
build_supermatrix builds. This is the gate you would want BEFORE ever making
the matrix-free path a production default.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf
from scipy.sparse.linalg import eigsh

from src.SingleReference.ADC import ADCSolverUnrestricted
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCn
from src.SingleReference.ADC.generated_modules import lazy
c1ap = lazy('adc4_c1_self_apply_blocks')
from src.SingleReference.ADC.sigma_driver import full_adc3_operator
from src.Base.pyscf.pyscf_interface import (
    get_orbital_energies, get_two_electron_integrals_chemist,
    get_antisymmetrized_spin_eri)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(5)


def main():
    all_ok = True
    for atom, basis, label in [
        ('Li 0 0 0; H 0 0 1.6', 'sto-3g', 'LiH/sto-3g'),
        ('H 0 0 0; H 0 0 0.74; H 0 0 1.5; H 0 0 2.2', 'sto-3g', 'H4/sto-3g'),
        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g'),
    ]:
        mol = gto.M(atom=atom, basis=basis, verbose=0)
        mf = scf.RHF(mol).run()
        nocc = 2 * (mol.nelectron // 2)
        eps = get_orbital_energies(mf, representation='spin')
        eri = get_two_electron_integrals_chemist(mol, mf, representation='spatial')
        g = get_antisymmetrized_spin_eri(eri)
        norb = len(eps)

        # --- production dense ADC(3) supermatrix (what production runs) ---
        adc = ADCSolverUnrestricted.from_arrays(eps, g)
        H_prod = adc.build_supermatrix(nocc)
        w_prod = np.linalg.eigvalsh(H_prod)

        # --- generated matrix-free ADC(3) operator ---
        gen = BuildSuperMatrixADCn(eps, g, nocc)
        U1, U2 = gen.u_2h1p_adc3(), gen.u_2p1h_adc3()      # U through order 2
        pool = {'f': np.diag(eps), 'g': g, 'kd': np.eye(norb),
                'o': slice(0, nocc), 'v': slice(nocc, norb),
                'no': nocc, 'nv': norb - nocc}
        op = full_adc3_operator(U1, U2, pool, eps, nocc, norb, c1ap)
        n = op.shape[0]

        # full spectrum via reconstruction (rigor) + eigsh lowest-k (matrix-free)
        recon = np.column_stack([op.matvec(e) for e in np.eye(n)])
        w_mf_full = np.linalg.eigvalsh(0.5 * (recon + recon.T))
        specdiff = np.abs(np.sort(w_mf_full) - np.sort(w_prod)).max()
        k = min(6, n - 2)
        w_mf = np.sort(eigsh(op, k=k, which='SA', return_eigenvectors=False))
        opsym = np.abs(recon - recon.T).max()

        ok = specdiff < 1e-9
        all_ok &= ok
        print(f"\n=== {label}  (dim {n}) ===")
        print(f"  matrix-free operator symmetric: {opsym:.1e}")
        print(f"  {'lowest 6 eigenvalues (Ha)':<34}  {'production':>14}  {'matrix-free':>14}")
        for pe, me in zip(np.sort(w_prod)[:6], w_mf[:6]):
            print(f"  {'':<34}  {pe:>14.8f}  {me:>14.8f}")
        print(f"  [{'OK' if ok else 'FAIL'}] full-spectrum max|matrix-free - production| = {specdiff:.2e}")

    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
