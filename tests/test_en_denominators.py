def test_generated_restricted_en_matches_spinorbital(label, atom, basis, dress):
    """THE production EN route: the generated restricted solver must reproduce
    the generated spin-orbital one for every EN channel.

    It builds the alpha-Dyson sector, so every restricted eigenvalue must be a
    spin-orbital eigenvalue. This holds because the generated blocks take
    l2_aaaa and l2_abab as SEPARATE arguments -- no spin-block merge, hence no
    decomposition ambiguity (contrast the hand-written CSF solver's xfail
    below). Three systems with different O/V balance: an exact linear identity
    cannot hold accidentally across all of them."""
    mol = gto.M(atom=atom, basis=basis, verbose=0)
    mf = scf.RHF(mol).run(conv_tol=1e-12)
    nocc = mol.nelectron // 2
    eps = get_orbital_energies(mf, representation='spatial')
    eri = get_two_electron_integrals_chemist(mol, mf, representation='spatial')
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
    eps_so = np.zeros(2 * len(eps)); eps_so[0::2] = eps; eps_so[1::2] = eps

    sr = BuildSuperMatrixADCnRestricted(eps, ga, gab, gb, nocc, u2_denom_dress=dress)
    er = np.sort(np.linalg.eigvalsh(sr.build_supermatrix_adc3()))
    sg = BuildSuperMatrixADCn(eps_so, get_antisymmetrized_spin_eri(eri),
                             2 * nocc, u2_denom_dress=dress)
    eg = np.sort(np.linalg.eigvalsh(sg.build_supermatrix_adc3()))
    md = max(abs(eg[np.argmin(np.abs(eg - x))] - x) for x in er)
    assert md < 1e-10, f"{label} dress={dress}: max|match| = {md:.3e}"


def test_en_first_order_wavefunction_is_spin_contaminated():
    """EN partitioning breaks the closed-shell singlet relation
    t_aaaa == t_abab - t_abab^T, because the two spin blocks get different
    denominators. This is a genuine property of the method (present in the
    spin-orbital formulation too), NOT an artifact of spin-blocking -- and it
    is exactly why the hand-written CSF code, which builds its amplitudes
    assuming that relation, cannot represent the dressed U^(2)."""
    from src.SingleReference.DensityMatrix.mpn_density_driver_restricted import (
        MPnDensityDriverRestricted)
    from src.SingleReference.EpsteinNesbet import build_dressed_e_abij
    mol = gto.M(atom='O 0 0 0; H 0 -0.757 0.587; H 0 0.757 0.587',
                basis='6-31g', verbose=0)
    mf = scf.RHF(mol).run(conv_tol=1e-12)
    nocc = mol.nelectron // 2
    eps = get_orbital_energies(mf, representation='spatial')
    eri = get_two_electron_integrals_chemist(mol, mf, representation='spatial')
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
    O, V = nocc, len(eps) - nocc

    def residual(e_abij):
        drv = MPnDensityDriverRestricted(np.diag(eps), ga, gab, gb, nocc,
                                         e_abij=e_abij)
        t_aaaa, t_abab = drv.compute_t2_1()
        return np.abs(t_aaaa - (t_abab - t_abab.transpose(1, 0, 2, 3))).max()

    assert residual(None) < 1e-12                      # bare: relation holds
    assert residual(build_dressed_e_abij(DRESS_DET, eps, O, V,
                                          eri_chemist=eri)) > 1e-4   # det-wise EN: broken
    assert residual(build_dressed_e_abij(DRESS, eps, O, V,
                                          eri_chemist=eri)) < 1e-12  # spin-adapted: preserved


