def test_spinorbital_solver_refuses_u2_denom_dress(h2o):
    """ADCSolver's U^(2) blocks are undressed; setting the flag used to be a
    silent no-op that produced bare ADC(3) masquerading as EN-ADC(3)."""
    mol, mf, nocc, eps, eri = h2o
    eps_so = np.zeros(2 * len(eps)); eps_so[0::2] = eps; eps_so[1::2] = eps
    solver = ADCSolverUnrestricted.from_arrays(eps_so, get_antisymmetrized_spin_eri(eri))
    with pytest.raises(NotImplementedError, match='u2_denom_dress'):
        solver.u2_denom_dress = DRESS
    solver.u2_denom_dress = None        # clearing it stays allowed
    assert solver.u2_denom_dress is None


@pytest.mark.parametrize('label,atom', [
    ('H2O', 'O 0 0 0; H 0 -0.757 0.587; H 0 0.757 0.587'),
    ('LiH', 'Li 0 0 0; H 0 0 1.6'),
])
@pytest.mark.parametrize('dress,pure', [
    ({'hh': True}, True),
    ({'hh': True, 'pp': True}, True),
    ({'hh': True, 'spin_adapted': False}, False),
    ({'hh': True, 'pp': True, 'spin_adapted': False}, False),
])
def test_spin_adapted_en_is_spin_pure(label, atom, dress, pure):
    """DEFINING PROPERTY of the spin-adapted EN method.

    Spin-adapted (default): one averaged shift per channel -> a single
    symmetric denominator -> the closed-shell singlet relation
    t_aaaa == t_abab - t_abab^T survives, and U^(2) stays entirely inside the
    doublet-CSF span. That is exactly what makes the CSF solver a COMPLETE
    basis for the method, hence usable.

    Determinant-wise (spin_adapted=False, Jiang & Engel): the two spin cases
    get different denominators, the relation breaks, and U^(2) acquires
    components on QUARTET (S=3/2) configurations the CSF basis does not
    contain. That variant therefore REQUIRES a spin-blocked solver -- it is not
    a bug here, it is why the CSF route cannot serve it.
    """
    from src.SingleReference.ADC.spin_adapt import build_T
    from src.SingleReference.EpsteinNesbet import build_dressed_e_abij
    from src.SingleReference.DensityMatrix.mpn_density_driver_restricted import (
        MPnDensityDriverRestricted)
    mol = gto.M(atom=atom, basis='sto-3g', verbose=0)
    mf = scf.RHF(mol).run(conv_tol=1e-12)
    O = mol.nelectron // 2
    eps = get_orbital_energies(mf, representation='spatial')
    eri = get_two_electron_integrals_chemist(mol, mf, representation='spatial')
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
    V = len(eps) - O

    e = build_dressed_e_abij(dress, eps, O, V, eri_chemist=eri)
    t_aaaa, t_abab = MPnDensityDriverRestricted(
        np.diag(eps), ga, gab, gb, O, e_abij=e).compute_t2_1()
    singlet = np.abs(t_aaaa - (t_abab - t_abab.transpose(1, 0, 2, 3))).max()

    eps_so = get_orbital_energies(mf, representation='spin')
    T = build_T(ADCSolverUnrestricted.from_arrays(eps_so, get_antisymmetrized_spin_eri(eri)), 2 * O)
    r = BuildSuperMatrixADCnRestricted(eps, ga, gab, gb, O, u2_denom_dress=dress)
    perp = []
    for sec in ('IP', 'EA'):
        U = r.u_adc3(sec)
        Q, _ = np.linalg.qr(r._T_alpha(T, sec))
        perp.append(np.linalg.norm(U - Q @ (Q.T @ U)))

    if pure:
        assert singlet < 1e-12, f"{label}: singlet relation broken ({singlet:.2e})"
        assert max(perp) < 1e-12, f"{label}: U leaked out of the CSF span ({max(perp):.2e})"
    else:
        assert singlet > 1e-9, f"{label}: determinant-wise EN should break spin purity"
        assert max(perp) > 1e-9, f"{label}: determinant-wise EN should leak to quartets"


@pytest.mark.parametrize('dress', [
    {'hh': True},                                   # consistent,   hh
    {'hh': True, 'pp': True},                       # consistent,   hh+pp
    {'hh': True, 'singles': False},                 # doubles-only, hh
    {'hh': True, 'pp': True, 'singles': False},     # doubles-only, hh+pp
])
def test_en_matrix_free_and_df_agree(dress):
    """The four production variants: the matrix-free operator must reproduce
    the dense supermatrix, and the DF build must reproduce the dense-ERI build.
    These are the two properties the acene runs depend on."""
    from src.Base.pyscf.pyscf_interface import DFIntegrals
    mol = gto.M(atom='O 0 0 0; H 0 -0.757 0.587; H 0 0.757 0.587',
                basis='6-31g', verbose=0)
    mf = scf.RHF(mol).run(conv_tol=1e-12)
    nocc = mol.nelectron // 2
    eps = get_orbital_energies(mf, representation='spatial')
    eri = get_two_electron_integrals_chemist(mol, mf, representation='spatial')
    B = DFIntegrals.from_scf(mol, mf, exact=True).B_aa
    rng = np.random.default_rng(0)
    H = {}
    for tag, e_, b_ in (('dense', eri, None), ('DF', None, B)):
        s = ADCSolverRestricted.from_arrays(eps, e_, level='adc3', B_aa=b_)
        s.u2_denom_dress = dress
        H[tag] = s.build_supermatrix(nocc)
        aop, _, _ = s.build_matrix_free_operator(nocc)
        z = rng.standard_normal(H[tag].shape[0])
        assert np.abs(aop(z) - H[tag] @ z).max() < 1e-9, f"{tag}: matrix-free != dense"
    assert np.abs(H['DF'] - H['dense']).max() < 1e-9, "DF != dense-ERI"


