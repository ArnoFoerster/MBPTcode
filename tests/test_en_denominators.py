"""Epstein-Nesbet (u2_denom_dress) denominator regression tests.

The u2_denom_dress feature is covered by these tests alone; they pin three
defects that no other test sees. Reference: Jiang & Engel, JCP 125,
184108 (2006).

Covered here:
  1. the EN SINGLES denominator equals -(CIS diagonal in the DETERMINANT
     basis), three independent ways -- this is the sign that was inverted;
  2. the restricted and UHF static-correction paths agree on it;
  3. the dense and DF branches agree on it;
  4. the hand-written spin-orbital ADCSolver REFUSES u2_denom_dress instead
     of silently ignoring it;
  5. KNOWN DEFECT, documented not asserted-away: the restricted CSF EN is a
     different spin-adaptation from the spin-orbital formula.
"""
