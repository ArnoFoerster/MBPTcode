def test_en_doubles_denominator_spin_blocks_differ():
    """Guard that the two doubles denominators really are distinct once EN is
    on (a regression here would silently restore the one-array behaviour), and
    that they are identical when it is off."""
    from src.SingleReference.EpsteinNesbet import build_dressed_e_abij
    mol = gto.M(atom='O 0 0 0; H 0 -0.757 0.587; H 0 0.757 0.587',
                basis='6-31g', verbose=0)
    mf = scf.RHF(mol).run(conv_tol=1e-12)
    nocc = mol.nelectron // 2
    eps = get_orbital_energies(mf, representation='spatial')
    eri = get_two_electron_integrals_chemist(mol, mf, representation='spatial')
    O, V = nocc, len(eps) - nocc
    aaaa, abab = build_dressed_e_abij(DRESS_DET, eps, O, V, eri_chemist=eri)
    assert np.abs(aaaa - abab).max() > 1e-3
    # spin-adapted: ONE denominator, so the two blocks coincide exactly
    sa_a, sa_b = build_dressed_e_abij(DRESS, eps, O, V, eri_chemist=eri)
    assert sa_a is sa_b or np.abs(sa_a - sa_b).max() == 0.0
    # the opposite-spin hh shift keeps its i==j diagonal; same-spin does not
    from src.SingleReference.EpsteinNesbet import (
        epstein_nesbet_shift_restricted_spinresolved as en_sr)
    g = eri.transpose(0, 2, 1, 3)
    same, opp = en_sr(g_same=g[:O, :O, :O, :O])
    assert np.allclose(np.diag(same), 0.0)
    assert np.all(np.abs(np.diag(opp)) > 1e-6)


