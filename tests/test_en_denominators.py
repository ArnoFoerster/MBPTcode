def test_handwritten_spinorbital_u2_is_a_merged_form_and_refuses_en():
    """The hand-written spin-orbital U^(2) may NOT be EN-dressed, and this pins
    the measurement that decided it (2026-07-27).

    Dressing the denominators there is trivial -- two arrays, no spin-adaptation
    ambiguity, since every spin-orbital amplitude is a named object. The blocker
    is the CONTRACTION PATTERN: feed the hand-written U_2h1p and the generated
    (pdaggerq) U^(2) the SAME amplitude and compare the permutation-invariant
    Gram U U^T. They agree to machine precision for the bare MP1 amplitude and
    disagree by ~1e-2 for a general antisymmetric one, i.e. they are DIFFERENT
    LINEAR MAPS that happen to coincide on the bare amplitude. So the
    hand-written form silently relies on a property EN destroys -- the same
    class of defect as the restricted CSF U^(2), and being in the determinant
    basis does not save it.

    Consequence: EN goes through the generated solvers only. If someone later
    implements dressing in adc_spinorbital.py, this test fails first.
    """
    from src.SingleReference.ADC import ADCSolverUnrestricted
    from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCn
    from src.SingleReference.common.mp_amplitudes import to_l

    mol = gto.M(atom='Li 0 0 0; H 0 0 1.595', basis='sto-3g', verbose=0)
    mf = scf.RHF(mol).run(conv_tol=1e-12)
    nocc = mol.nelectron // 2
    eps = get_orbital_energies(mf, representation='spatial')
    eri = get_two_electron_integrals_chemist(mf=mf, mol=mol, representation='spatial')
    eps_so = np.zeros(2 * len(eps)); eps_so[0::2] = eps; eps_so[1::2] = eps
    g = get_antisymmetrized_spin_eri(eri)
    no, norb = 2 * nocc, len(eps_so)
    nv = norb - no

    hand = ADCSolverUnrestricted.from_arrays(eps_so, g)
    n2h = hand.dimensions(no)['n2h1p']
    occ, virt, p_ = np.arange(no), np.arange(no, norb), np.arange(norb)
    iu, ju = np.triu_indices(no, k=1)
    term0 = np.transpose(g[np.ix_(occ, occ, p_, p_)][:, :, :, virt], (0, 1, 3, 2))
    g_cdpa = g[np.ix_(virt, virt, p_, p_)][:, :, :, virt]
    g_cXpk = g[np.ix_(virt, occ, p_, occ)]

    def hand_U(t2):                      # the three U^(2) terms, verbatim
        cd = 0.5 * np.einsum('ijcd,cdpa->ijap', t2, g_cdpa, optimize=True)
        k1 = -np.einsum('ikca,cjpk->ijap', t2, g_cXpk, optimize=True)
        k2 = np.einsum('jkca,cipk->ijap', t2, g_cXpk, optimize=True)
        return (term0 + cd + k1 + k2)[iu, ju, :, :].reshape(n2h, norb).T

    def gen_U(t2):
        sg = BuildSuperMatrixADCn(eps_so, g, no)
        t2p = t2.transpose(2, 3, 0, 1)
        pool = dict(sg._amplitude_pool()); pool['t2'] = t2p; pool['l2'] = to_l(t2p, 2)
        sg._u2_amplitude_pool = lambda _p=pool: dict(_p)
        return sg.build_supermatrix_adc3()[:norb, norb:norb + n2h]

    def gram_diff(t2):
        a, b = hand_U(t2), gen_U(t2)
        return abs(a @ a.T - b @ b.T).max()

    D = (eps_so[occ][:, None, None, None] + eps_so[occ][None, :, None, None]
         - eps_so[virt][None, None, :, None] - eps_so[virt][None, None, None, :])
    bare = gram_diff(g[np.ix_(occ, occ, virt, virt)] / D)
    rng = np.random.default_rng(0)
    r = rng.normal(size=(no, no, nv, nv))
    r = r - r.transpose(1, 0, 2, 3); r = r - r.transpose(0, 1, 3, 2)
    general = gram_diff(0.05 * r)

    assert bare < 1e-12, f'bare control broken: {bare:.2e}'
    assert general > 1e-4, (f'hand-written and generated U^(2) now agree for a '
                            f'general amplitude ({general:.2e}) -- if the blocks '
                            f'were re-derived, EN dressing may now be safe here')

    with pytest.raises(NotImplementedError, match='merged form'):
        ADCSolverUnrestricted.from_arrays(eps_so, g).u2_denom_dress = {'hh': True}
