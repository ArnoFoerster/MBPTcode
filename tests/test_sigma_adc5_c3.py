"""GATE for the matrix-free ADC(5) C^(3) class-class increment.

sigma_driver.assembled_c3_matvec_restricted must reproduce the dense
order-general assembly BuildSuperMatrixADCnRestricted.c_block_generated(sector,
3) as a matvec -- WITHOUT forming any (n_k1, n_k1) object. The dense reference
is itself gated (n=2 bit-exact vs c2_block_generated; n=3 == spin-orbital twin,
tests/test_adcn_generated_c3*.py), so this closes the chain
dense-spin-orbital == dense-restricted == MATRIX-FREE-restricted.

Primary gate (task spec): LiH/sto-3g and H2O/sto-3g, BOTH sectors, 3 random
trial vectors each: max |matvec - dense @ x| < 1e-11.

The matvec deliberately OMITS N^(3) (it cancels identically in the class-class
block) while the dense reference CARRIES it, so this
gate simultaneously re-checks that cancellation through a completely
independent code path: a wrong omission would show up as an N^(3)-sized
mismatch (~1e-5), 6 orders above the tolerance.

Guards baked in (known traps):
  * the dense C^(3) is asserted NONZERO first -- a matvec check against a zero
    block proves nothing (section 19's Laplace lesson);
  * DF/RI secondary check with an EXACT RI factor (naux = norb^2,
    DFIntegrals.from_scf(exact=True)): the *_df apply modules + B leaves must
    match the same dense reference, so any deviation is codegen/plumbing, not
    fitting error.

Run:  ~/anaconda3/envs/py310/bin/python -u tests/test_sigma_adc5_c3.py
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.Base.pyscf_interface import (get_orbital_energies,
                                      get_antisymmetrized_spin_block_eri,
                                      DFIntegrals)
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.SingleReference.ADC.sigma_driver import assembled_c3_matvec_restricted
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(5)
from src.SingleReference.ADC.generated_modules import lazy
c1df = lazy('adc4_c1_self_apply_restricted_df_blocks')
c2df = lazy('adc4_c2_apply_restricted_df_blocks')
s2cdf = lazy('adc4_c2_s2c_apply_restricted_df_blocks')
c3df = lazy('adc5_c3_apply_restricted_df_blocks')

TOL = 1e-11          # primary gate (task spec)
TOL_DF = 1e-8        # DF with an EXACT B factor -- plumbing, not fitting

SYSTEMS = [('LiH/sto-3g', 'Li 0 0 0; H 0 0 1.6'),
           ('H2O/sto-3g', 'O 0 0 0; H 0 0 0.96; H 0.96 0 0')]


def _check(ok, msg):
    print(f"[{'OK' if ok else 'FAIL'}] {msg}")
    return ok


def main():
    rng = np.random.default_rng(7)
    all_ok = True
    for label, atom in SYSTEMS:
        mol = gto.M(atom=atom, basis='sto-3g', verbose=0)
        mf = scf.RHF(mol)
        mf.conv_tol = 1e-13
        mf.run()
        ns = mol.nelectron // 2
        eps = get_orbital_energies(mf, representation='spatial')
        g_aaaa, g_bbbb, g_abab = get_antisymmetrized_spin_block_eri(mol, mf)
        r = BuildSuperMatrixADCnRestricted(eps, g_aaaa, g_abab, g_bbbb, ns)
        dfi = DFIntegrals.from_scf(mol, mf, exact=True)
        B = {'B_aa': dfi.B_aa, 'B_bb': dfi.B_bb}
        print(f"\n=== {label} (norb={r.norb}, naux={dfi.naux_aa}) ===")

        for sector in ('IP', 'EA'):
            C3 = r.c_block_generated(sector, 3)      # dense reference (carries N^(3))
            ncfg = C3.shape[0]
            nz = float(np.abs(C3).max())
            all_ok &= _check(nz > 1e-10,
                             f"{sector}: dense C^(3) NONZERO (|max| = {nz:.3e}) "
                             f"-- a zero-block comparison would prove nothing")
            worst, worst_df = 0.0, 0.0
            for _ in range(3):
                x = rng.standard_normal(ncfg)
                y_ref = C3 @ x
                y_mv = assembled_c3_matvec_restricted(r, sector, x)
                worst = max(worst, float(np.abs(y_mv - y_ref).max()))
                y_df = assembled_c3_matvec_restricted(
                    r, sector, x, c1r_module=c1df, c2r_module=c2df,
                    s2cr_module=s2cdf, c3r_module=c3df, extra_leaves=B)
                worst_df = max(worst_df, float(np.abs(y_df - y_ref).max()))
            all_ok &= _check(worst < TOL,
                             f"{sector}: matvec == dense c_block_generated(., 3) @ x, "
                             f"3 random x, max dev {worst:.3e} (< {TOL:.0e})")
            all_ok &= _check(worst_df < TOL_DF,
                             f"{sector}: DF/RI matvec (exact B) == same dense, "
                             f"max dev {worst_df:.3e} (< {TOL_DF:.0e})")

    print('\nALL OK' if all_ok else '\nFAILURES')
    return 0 if all_ok else 1


def test_main():
    assert not main(), 'main() returned a nonzero exit code'


if __name__ == '__main__':
    sys.exit(main())
