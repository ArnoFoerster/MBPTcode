"""Downfolded ADC(4) must equal FULL ADC(4) to solver precision.

This is not an approximation check -- it is an identity check. The order rule
gives block_order(4, 2, 2) == 0, i.e. the 3-particle (k=2) diagonal block of
ADC(4) is exactly K. A Schur complement over a diagonal block is exact, so

    Davidson over {orb + 2h1p + 2p1h} with A12 (omega-K2)^-1 A21 folded in
      ==  Davidson over {orb + 2h1p + 2p1h + 3h2p + 3p2h}

with no physics lost. If these two ever disagree beyond solver tolerance, either
the fold is wrong or the (2,2) block has stopped being diagonal (which is what
happens at ADC(5) -- solve_dyson_adc_downfolded asserts on that case).

Why it matters: the full path carries every k=2 configuration in the Davidson
SUBSPACE (Ar/aug-cc-pVTZ ran >1 h before being killed); the downfolded path
keeps the subspace in k<=1 and touches k=2 one transient vector at a time.

Contrast with `solve_dyson_adc4_downfold`, which ALSO freezes the ADC(3)
eigenvector -- that one IS an approximation (the diagonal approximation) and is
expected to differ; the third check below quantifies that difference rather than
asserting it away.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.Base.pyscf.pyscf_interface import (get_orbital_energies,
                                            get_antisymmetrized_spin_block_eri)
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.SingleReference.ADC.sigma_driver import (restricted_dyson_operator,
                                                  solve_dyson_adc_downfolded,
                                                  solve_dyson_adc4_downfold)
from src.SingleReference.ADC.solve import follow_roots
from src.Base.numerics.constants import HARTREE_TO_EV, HARTREE_TO_MEV
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)

TOL_EV = 1e-4     # downfolded vs full, in eV


def main():
    all_ok = True

    mol = gto.M(atom='O 0 0 0; H 0 0 0.96; H 0.93 0 -0.24', basis='sto-3g', verbose=0)
    mf = scf.RHF(mol).run()
    ns = mol.nelectron // 2
    eps = get_orbital_energies(mf, representation='spatial')
    homo = ns - 1
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
    r = BuildSuperMatrixADCnRestricted(eps, ga, gab, gb, ns)

    for level in ('adc4',):
        # ---- full: k=2 explicitly in the Davidson subspace ----
        op, dg = restricted_dyson_operator(r, level, construction='twosector')
        v0 = np.zeros(op.shape[0]); v0[homo] = 1.0
        wf, Xf, conv = follow_roots(op, dg, v0, tol=1e-9)
        assert conv.all()
        e_full = float(wf[0])

        # ---- downfolded: k=2 folded out exactly ----
        d = solve_dyson_adc_downfolded(r, homo, level=level, tol=1e-10, construction='twosector')
        e_df = d['e']

        diff_ev = abs(e_df - e_full) * HARTREE_TO_EV
        ok = diff_ev < TOL_EV
        print(f"[{'OK' if ok else 'FAIL'}] {level}: downfolded "
              f"{-e_df*HARTREE_TO_EV:.6f} eV == "
              f"full {-e_full*HARTREE_TO_EV:.6f} eV  (diff {diff_ev:.2e} eV, "
              f"{d['n_outer']} outer, subspace {d['n_k1']} vs {op.shape[0]})")
        all_ok &= ok

    # ---- the downfolded subspace must actually be smaller ----
    ok = d['n_k1'] < d['n_k1'] + d['n_k2']
    print(f"[{'OK' if ok else 'FAIL'}] k=2 manifold ({d['n_k2']}) kept OUT of the "
          f"Davidson subspace ({d['n_k1']})")
    all_ok &= ok

    # ---- and the DIAGONAL approximation should differ (it is an approximation) ----
    dd = solve_dyson_adc4_downfold(r, homo, tol=1e-9, laplace_ntau=20)
    gap_mev = (dd['e_downfold'] - e_full) * HARTREE_TO_MEV
    print(f"[info] diagonal approximation differs from exact ADC(4) by "
          f"{gap_mev:+.1f} meV (frozen-eigenvector error; expected nonzero)")

    print('ALL OK' if all_ok else 'FAILURES')
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
