"""Which ADC(5) structures actually need Laplace fusion -- pinned.

Every block is to be Laplace-transformed, but Laplace fusion exists for
exactly one purpose: to avoid materializing a rank>=3 amplitude (O(no^3 nv^3)
and worse). A structure needs it only if it CONSUMES such an amplitude AND is
nonzero. This test pins both halves of that, because both are easy to get
wrong in opposite directions -- building a fuser for a block that is
identically zero (wasted, and it makes Laplace look "done"), or missing one
that is large.

THE BRILLOUIN MECHANISM. The class-class C blocks force their Fock factor into
the OFF-DIAGONAL occ-virt slice f[o,v], which vanishes in canonical HF. This is
STRUCTURAL here, not an input coincidence: BuildSuperMatrixADCnRestricted._rargs
sets f_aa = diag(eps) unconditionally, and the `f_orb` hook (non-canonical /
QP-consistent Fock) is applied only to the ORBITAL block matvec in
sigma_driver, never to the class blocks. So every f[o,v]-only structure is
identically zero on this code path. The same mechanism holds for
t2_2/l2ft2.

CONSEQUENCE, measured below on NH3/sto-3g (5 occ / 3 vir -- chosen because it
is the smallest system here where t3 AND t4 are genuinely nonzero; LiH and H2O
both zero t3_aaaaaa for want of 3 same-spin occ or vir orbitals, and would make
this whole test vacuous):

  * C^(3) needs NO Laplace. Its only rank-3 consumer, l2ft3, is f[o,v]-zero,
    as is l1ft2. The survivors -- l1v, vt1, l2vt2 -- are all rank <= 2.
  * U^(4) DOES need it, for l2vt3 (t3), l3vt2 (l3), l4vt2 (l4) and l4ft3
    (l4 AND t3 -- two amplitudes in one term, which the current single-tag
    fuser cannot do in one pass). l1ft1, l3ft3 and l4ft4 are f[o,v]-zero.

If a future change wires a non-canonical Fock into the class blocks, the
f[o,v]-zero assertions here fail loudly -- which is the correct outcome, since
the Laplace requirement for those structures would revive with it.
"""
import inspect
import os
import re
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.SingleReference.ADC.generated_modules import lazy
c3d = lazy('adc5_c3_blocks_restricted')
u4d = lazy('adc5_u4_blocks_restricted')
from src.Base.pyscf.pyscf_interface import (get_orbital_energies,
                                            get_antisymmetrized_spin_block_eri)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(5)

# 5 occ / 3 vir: the smallest system here with t3 AND t4 genuinely nonzero.
ATOM = 'N 0 0 0; H 0 0 1.02; H 0.96 0 -0.34; H -0.48 -0.83 -0.34'

C3_ZERO = ['l1ft2', 'l2ft3']
C3_LIVE = ['l1v', 'vt1', 'l2vt2']
U4_ZERO = ['l1ft1', 'l3ft3', 'l4ft4']
U4_LAPLACE = ['l2vt3', 'l3vt2', 'l4ft3', 'l4vt2']   # rank >= 3 AND nonzero


def _check(ok, msg):
    print(f"[{'OK' if ok else 'FAIL'}] {msg}")
    return ok


def _struct_max(mod, pattern, pool):
    """{structure: max |block|} over every spin block of that structure."""
    out = {}
    for nm in dir(mod):
        m = re.match(pattern, nm)
        if not m:
            continue
        fn = getattr(mod, nm)
        val = fn(*[pool[p] for p in inspect.signature(fn).parameters])
        out[m.group(1)] = max(out.get(m.group(1), 0.0), np.max(np.abs(val)))
    return out


def main():
    all_ok = True
    mol = gto.M(atom=ATOM, basis='sto-3g', verbose=0)
    mf = scf.RHF(mol)
    mf.conv_tol = 1e-13
    mf.run()
    ns = mol.nelectron // 2
    eps = get_orbital_energies(mf, representation='spatial')
    g_aaaa, g_bbbb, g_abab = get_antisymmetrized_spin_block_eri(mol, mf)
    r = BuildSuperMatrixADCnRestricted(eps, g_aaaa, g_abab, g_bbbb, ns)
    print(f"NH3/sto-3g: {ns} occ / {len(eps) - ns} vir")

    # the structural reason the f-family vanishes
    f = r._rargs['f_aa']
    off = np.max(np.abs(f - np.diag(np.diag(f))))
    all_ok &= _check(off == 0.0,
                     f"class-block Fock is diagonal ({off:.1e}) => f[o,v] == 0 "
                     f"identically; `f_orb` never reaches the class blocks")

    A = r._amps_order(max_order=4)
    pool = dict(r._rargs)
    for v in A.values():
        pool.update(v)

    # the test would be vacuous on a system that zeroes t3/t4 for want of
    # enough same-spin orbitals -- assert we did not pick one
    for key in ('T3_2', 'T4_2'):
        m = max(np.max(np.abs(x)) for x in A[key].values())
        all_ok &= _check(m > 1e-8, f"{key} genuinely nonzero ({m:.2e}) -- the "
                                   f"rank census below is not vacuous")

    c3 = _struct_max(c3d, r'^c3_2h1p_([a-z0-9]+)_[ab]{6}$', pool)
    print("\n=== C^(3) (class-class) ===")
    for s in sorted(c3):
        print(f"    {s:8s} |block|max = {c3[s]:.3e}")
    for s in C3_ZERO:
        all_ok &= _check(c3.get(s, 1.0) == 0.0,
                         f"C^(3) {s} is IDENTICALLY zero (f[o,v]-only)")
    for s in C3_LIVE:
        all_ok &= _check(c3.get(s, 0.0) > 1e-10, f"C^(3) {s} is nonzero")
    all_ok &= _check(all(max([int(c) for c in s if c.isdigit()] + [0]) <= 2
                         for s in C3_LIVE),
                     "every surviving C^(3) structure is rank <= 2 "
                     "=> C^(3) needs NO Laplace fusion")

    u4 = _struct_max(u4d, r'^u4_2h1p_occ_([a-z0-9]+)_[ab]{4}$', pool)
    print("\n=== U^(4) (orbital<->k1, occ rows) ===")
    for s in sorted(u4):
        print(f"    {s:8s} |block|max = {u4[s]:.3e}")
    for s in U4_ZERO:
        all_ok &= _check(u4.get(s, 1.0) == 0.0,
                         f"U^(4) {s} is IDENTICALLY zero (f[o,v]-only)")
    for s in U4_LAPLACE:
        all_ok &= _check(u4.get(s, 0.0) > 1e-10,
                         f"U^(4) {s} is nonzero and rank >= 3 "
                         f"=> a REAL Laplace target")

    print("\nADC(5) Laplace targets: " + ", ".join(U4_LAPLACE)
          + "  (l4ft3 needs l4 AND t3 fused in one term -- beyond the current "
            "single-tag fuser)")
    print('\nALL OK' if all_ok else '\nFAILURES')
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
