"""Gate of the spin-free generated C^(2) block: the restricted
(spin-blocked, RHF) BuildSuperMatrixADCnRestricted.c2_block_generated
assembles the disputed order-2 class-class C^(2) block (the ADC(4) arbiter
that beat the printed SCW83 B7 by 4 orders in the lambda-oracle) purely from
SPATIAL spin-block tensors + restricted MPn amplitudes, with the SAME ISR
class-GS assembly (N^(2) normalization, Loewdin assemble_kplusc) as the
spin-orbital BuildSuperMatrixADCn.c2_block_generated.

Oracle: the spin-orbital GENERATED C^(2) block (itself the lambda-oracle-
validated arbiter). The restricted alpha-sector-gathered C^(2) must equal
the spin-orbital C^(2) at the corresponding alpha-sector configs (C^(2) is
spin-conserving, so its alpha sub-block is self-contained). Also checks
N^(2) equality.

H2O/sto-3g decisive; H2/sto-3g smoke.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.SingleReference.ADC.adc_autogenerated import (
    BuildSuperMatrixADCn, BuildSuperMatrixADCnRestricted, _sval)
from src.SingleReference.ADC.precursor_classes import class_configs
from src.Base.pyscf.pyscf_interface import (
    get_orbital_energies, get_two_electron_integrals_chemist,
    get_antisymmetrized_spin_eri, get_antisymmetrized_spin_block_eri)
from tests.adc_common import alpha_to_class_index
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)


def check(label, diff, tol=1e-11):
    ok = diff < tol
    print(f"[{'OK' if ok else 'FAIL'}] {label}: {diff:.3e}")
    return ok


def main():
    all_ok = True

    for atom, basis, label in [
        ('H 0 0 0; H 0 0 0.74', 'sto-3g', 'H2/sto-3g (smoke)'),
        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g (decisive)'),
    ]:
        mol = gto.M(atom=atom, basis=basis, verbose=0)
        mf = scf.RHF(mol).run()
        nocc_sp = mol.nelectron // 2
        nocc = 2 * nocc_sp
        eps = get_orbital_energies(mf, representation='spin')
        eri = get_two_electron_integrals_chemist(mol, mf, representation='spatial')
        g = get_antisymmetrized_spin_eri(eri)
        so = BuildSuperMatrixADCn(eps, g, nocc)

        eps_sp = get_orbital_energies(mf, representation='spatial')
        g_aaaa, g_bbbb, g_abab = get_antisymmetrized_spin_block_eri(mol, mf)
        r = BuildSuperMatrixADCnRestricted(eps_sp, g_aaaa, g_abab, g_bbbb, nocc_sp)

        print(f"\n=== {label} ===")
        all_ok &= check("N^(2) restricted == spin-orbital", abs(r.n2_norm() - so.n2_norm()))

        for sector in ('IP', 'EA'):
            C2r = r.c2_block_generated(sector)
            C2so = so.c2_block_generated(sector)
            cols = class_configs(nocc, len(eps), 1, sector)
            cfg = r.sector_configs(sector)
            idx = alpha_to_class_index(cfg, sector, cols, nocc)
            diff = np.abs(C2r - C2so[np.ix_(idx, idx)]).max()
            all_ok &= check(f"C^(2) {sector} restricted == spin-orbital generated", diff)

    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
