"""GATE for the PRODUCTION-FLOOR C^(3) amplitude route
(assembled_c3_matvec_restricted(laplace_ntau=...)).

The exact C^(3) matvec pulls its amplitudes from _amps_order(3), which builds
the rank>=3 RSPT intermediates t3_2 (O(no^3 nv^3)) and t4_2 (O(no^4 nv^4), ~30
TB at CO2/aug-cc-pVTZ) -- purely as recursion by-products, because C^(3)'s only
order-3 dependence, the singles T1^(3), enters through the f-contracted `ft1`
structure whose Fock factor lands in the off-diagonal f[o,v] slice and VANISHES
by Brillouin on the class blocks. So C^(3) needs
NO block Laplace fusion -- only that the provider stop materializing amplitudes
it never multiplies. laplace_ntau routes to _u3_amps_laplace (rank<=2 order<=2,
plus a Laplace T1^(3) that C^(3) does not use), which never forms a rank>=3
array. The result is therefore BIT-EXACT, not ntau-approximate.

THE ZERO-COMPARISON TRAP:
LiH/H2O/H4 have t3_aaaaaa == 0, so on them the two providers agree
trivially -- "two zeros compared, not a real check". The PRIMARY system here is
NH3/sto-3g (5 occ / 3 vir), the smallest with t3_2 AND t4_2 genuinely nonzero;
the test ASSERTS they are nonzero before trusting the agreement, and asserts the
low-rank provider structurally carries no rank>=3 key.

Run:  ~/anaconda3/envs/py310/bin/python -u tests/test_sigma_c3_laplace.py
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.Base.pyscf_interface import (get_orbital_energies,
                                      get_antisymmetrized_spin_block_eri)
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.SingleReference.ADC.sigma_driver import assembled_c3_matvec_restricted
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(5)

TOL = 1e-13          # BIT-EXACT: C^(3) has zero sensitivity to the dropped amps

# (label, atom, t3_must_be_nonzero) -- NH3 is the meaningful arbiter; LiH/H2O
# are kept as secondary coverage but flagged as t3-blind (agreement there is
# necessary, not sufficient).
SYSTEMS = [('NH3/sto-3g', 'N 0 0 0; H 0 0 1.01; H 0.95 0 -0.3; H -0.48 0.82 -0.3', True),
           ('LiH/sto-3g', 'Li 0 0 0; H 0 0 1.6', False),
           ('H2O/sto-3g', 'O 0 0 0; H 0 0 0.96; H 0.96 0 0', False)]

_RANK_GE3 = ('L3', 'L4', 'T3', 'T4', 'L5', 'T5')


def _check(ok, msg):
    print(f"[{'OK' if ok else 'FAIL'}] {msg}")
    return ok


def main():
    rng = np.random.default_rng(11)
    all_ok = True

    # structural: the low-rank Laplace provider must never carry a rank>=3 block
    mol = gto.M(atom=SYSTEMS[0][1], basis='sto-3g', verbose=0)
    mf = scf.RHF(mol); mf.conv_tol = 1e-13; mf.run()
    eps = get_orbital_energies(mf, representation='spatial')
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
    r0 = BuildSuperMatrixADCnRestricted(eps, ga, gab, gb, mol.nelectron // 2)
    lap_keys = set(r0._u3_amps_laplace(6))
    bad = [k for k in lap_keys if any(k.startswith(p) for p in _RANK_GE3)]
    all_ok &= _check(not bad,
                     f"_u3_amps_laplace carries NO rank>=3 key (keys={sorted(lap_keys)})")

    for label, atom, t3_nonzero in SYSTEMS:
        mol = gto.M(atom=atom, basis='sto-3g', verbose=0)
        mf = scf.RHF(mol); mf.conv_tol = 1e-13; mf.run()
        eps = get_orbital_energies(mf, representation='spatial')
        ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
        r = BuildSuperMatrixADCnRestricted(eps, ga, gab, gb, mol.nelectron // 2)
        print(f"\n=== {label} (norb={r.norb}, nocc={r.nocc}, nvir={r.nvir}) ===")

        if t3_nonzero:
            A = r._amps_order(max_order=3)
            mx3 = max(float(np.abs(v).max()) for v in A['T3_2'].values())
            mx4 = max(float(np.abs(v).max()) for v in A['T4_2'].values())
            all_ok &= _check(mx3 > 1e-8 and mx4 > 1e-8,
                             f"t3_2 (|max|={mx3:.2e}) AND t4_2 (|max|={mx4:.2e}) "
                             f"genuinely NONZERO -- the agreement below is a real check")

        for sector in ('IP', 'EA'):
            C3 = r.c_block_generated(sector, 3)     # dense reference
            ncfg = C3.shape[0]
            nz = float(np.abs(C3).max())
            all_ok &= _check(nz > 1e-10,
                             f"{sector}: dense C^(3) NONZERO (|max| = {nz:.3e})")
            worst_ex, worst_lap = 0.0, 0.0
            for _ in range(4):
                x = rng.standard_normal(ncfg)
                ref = C3 @ x
                y_ex = assembled_c3_matvec_restricted(r, sector, x)
                y_lap = assembled_c3_matvec_restricted(r, sector, x, laplace_ntau=6)
                worst_ex = max(worst_ex, float(np.abs(y_ex - ref).max()))
                worst_lap = max(worst_lap, float(np.abs(y_lap - y_ex).max()))
            all_ok &= _check(worst_ex < TOL,
                             f"{sector}: exact matvec == dense c_block_generated "
                             f"({worst_ex:.2e})")
            all_ok &= _check(worst_lap < TOL,
                             f"{sector}: production-floor (rank<=2) matvec == exact, "
                             f"BIT-EXACT ({worst_lap:.2e} < {TOL:.0e})")

    print('\nALL OK' if all_ok else '\nFAILURES')
    return 0 if all_ok else 1


def test_main():
    assert not main(), 'main() returned a nonzero exit code'


if __name__ == '__main__':
    sys.exit(main())
