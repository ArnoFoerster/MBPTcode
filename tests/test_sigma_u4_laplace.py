"""GATE for the auto-Laplace block-routing DRIVER on the U^(4)
rank>=3 family -- sigma_driver._LAP_RANK3_ROUTE + _lap_rank3_stitch, wired into
_assemble_raw_S(laplace_ntau=...).

Every rank>=3 (>4-index) structure of the (0,1) orbital<->k1 coupling at order 4
has a Laplace-fused twin that consumes ONLY order<=2 rank<=2 leaves (t2_1/l2_1/
t2_2/t1_2 + the outer ket t2), so l3/l4/t3/t4 are NEVER materialized inside the
block. This gate checks the DRIVER routes each structure to the RIGHT fused
block (correct module / name / combo suffix / pool) by comparing the fused
stitch to the exact MATERIALIZED stitch (same amplitude assignment) -- the fused
block's own correctness is gated separately (tests/test_laplace_nested_fusion.py;
worst per-block err 1.76e-15).

WHY ONLY THE SINGLE-FUSION + combo-22 STRUCTURES ARE EVALUATED HERE: the nested
double-tau blocks (l4ft3, l4t3, and the l3ft2/l3t2 (3,1) combo) integrate
ntau^2 points over ~10^4 fused terms and take MINUTES each to evaluate even on
H4 -- inherent Python term-loop overhead, not a correctness issue. Their routing
is checked STRUCTURALLY (the fused block resolves) here and NUMERICALLY in
test_laplace_nested_fusion. The single-fusion representatives below exercise all
three module families (u4_laplace, l3_higherorder, both okind prefixes) and the
combo suffix, at machine precision in ~30 s.

H4/sto-3g is the arbiter: smallest system with t3_2 AND t4_2 genuinely nonzero
(asserted), so a mis-routed block (wrong module/amps) gives a real mismatch, not
a zero-vs-zero pass.

Run:  ~/anaconda3/envs/py310/bin/python -u tests/test_sigma_u4_laplace.py
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.Base.pyscf.pyscf_interface import (get_orbital_energies,
                                            get_antisymmetrized_spin_block_eri)
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.SingleReference.ADC.sigma_driver import (_LAP_RANK3_ROUTE,
                                                  _lap_rank3_module,
                                                  _lap_rank3_stitch,
                                                  _resolve_struct)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(5)

TOL = 1e-9          # fused == materialized to the ntau=6 quadrature accuracy


def _check(ok, msg):
    print(f"[{'OK' if ok else 'FAIL'}] {msg}")
    return ok


def _struct_rows(name, kind, tag, fam, suffix):
    okind = 'u4' if kind == 'u' else 's4'
    mod = _lap_rank3_module('l3ho' if fam == 'l3ho' else fam)
    return [row for row in ('occ', 'vir')
            if any(a.startswith(f'{okind}_{tag}_{row}_{name}{suffix}_')
                   for a in dir(mod))]


def main():
    all_ok = True

    # 1) STRUCTURAL completeness: every mapped rank>=3 structure resolves to a
    #    fused block (right module / name / combo) for BOTH sectors -- no eval.
    combos = {'l3ft2': ['_22', '_31'], 'l3t2': ['_22', '_31']}
    for name, (fam, _) in _LAP_RANK3_ROUTE.items():
        kind = 's' if name in ('l3t2', 'l4t3') else 'u'
        for tag in ('2h1p', '2p1h'):
            for suf in (combos[name] if fam == 'l3ho' else ['']):
                rows = _struct_rows(name, kind, tag, fam, suf)
                all_ok &= _check(len(rows) > 0,
                                 f"route {name}{suf} [{tag}] -> fused block "
                                 f"({fam}), rows={rows}")

    # 2) NUMERICAL: fused stitch == exact materialized stitch, machine precision,
    #    on the fast single-fusion representatives of all three module families.
    mol = gto.M(atom='H 0 0 0; H 0 0 0.80; H 0 0 1.75; H 0 0 2.60',
                basis='sto-3g', verbose=0)
    mf = scf.RHF(mol); mf.conv_tol = 1e-13; mf.run()
    eps = get_orbital_energies(mf, representation='spatial')
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
    r = BuildSuperMatrixADCnRestricted(eps, ga, gab, gb, mol.nelectron // 2)
    A = r.amps_order(max_order=4)
    print(f"\nH4/sto-3g norb={r.norb}")
    mx3 = max(float(np.abs(v).max()) for v in A['T3_2'].values())
    mx4 = max(float(np.abs(v).max()) for v in A['T4_2'].values())
    all_ok &= _check(mx3 > 1e-8 and mx4 > 1e-8,
                     f"t3_2 (|max|={mx3:.2e}) AND t4_2 (|max|={mx4:.2e}) nonzero "
                     f"-- the routing checks below are real, not zero-vs-zero")

    def matz(name, kind, amps):
        res = _resolve_struct(name, '2h1p', kind)
        p = f'{kind}{res[1]}_2h1p'
        return r.stitch_k1r(res[0], f'{p}_occ_{name}', f'{p}_vir_{name}', 'IP',
                             {**r.rargs, **amps})

    # (name, kind, l_ord, t_ord, materialized amps for that assignment)
    cases = [
        ('l2vt3', 'u', 1, 2, {**A['L2_1'], **A['T3_2']}),   # u4_laplace (t3)
        ('l3vt2', 'u', 2, 1, {**A['L3_2'], **A['T2_1']}),   # u4_laplace (l3)
        ('l4vt2', 'u', 2, 1, {**A['L4_2'], **A['T2_1']}),   # u4_laplace (l4)
        ('l3ft2', 'u', 2, 2, {**A['L3_2'], **A['T2_2']}),   # l3_higherorder u, combo 22
        ('l3t2',  's', 2, 2, {**A['L3_2'], **A['T2_2']}),   # l3_higherorder s, combo 22
    ]
    for name, kind, lo, to, amps in cases:
        mz = matz(name, kind, amps)
        fz = _lap_rank3_stitch(r, name, kind, '2h1p', 'IP', lo, to, A, eps, 6, None)
        d = float(np.abs(fz - mz).max())
        m = float(np.abs(mz).max())
        all_ok &= _check(m > 1e-8,
                         f"{name} (l^{lo},t^{to}): materialized stitch NONZERO "
                         f"(|max|={m:.2e})")
        all_ok &= _check(d < TOL,
                         f"{name} (l^{lo},t^{to}): fused == materialized "
                         f"({d:.2e} < {TOL:.0e})")

    print('\nALL OK' if all_ok else '\nFAILURES')
    return 0 if all_ok else 1


def test_main():
    assert not main(), 'main() returned a nonzero exit code'


if __name__ == '__main__':
    sys.exit(main())
