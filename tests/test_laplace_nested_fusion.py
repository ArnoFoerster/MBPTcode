def _numblk(block, rank):
    keys = T_BRA[rank][1]
    return block if block in keys else block.translate(str.maketrans('ab', 'ba'))


def _num_fn(rank, order, block):
    return t_numerator_terms_restricted(rank, order, _numblk(block, rank))


def _signed(terms, sign):
    return [[f"{float(t[0]) * sign:+.15g}"] + list(t[1:]) for t in terms]


def _fuse_outer_l3_order3(outer):
    """Fuse the outer l3 tag(s) at ORDER 3 (nested) using fuse_nested_numerator
    for l3's numerator and the to_l (lambda) canonical/sign for the l3 factor."""
    terms = outer
    while True:
        tags = {t: rk for t, rk in highrank_tags(terms).items() if t.startswith('l3_')}
        if not tags:
            break
        tag = sorted(tags)[0]
        block = tag.split('_', 1)[1]
        same = len(set(block)) == 1
        lcs = lambda_canonical_and_sign(3)
        canon, sign = lcs['same'] if same else lcs['mixed']
        inner = _signed(fuse_nested_numerator(_num_fn, 3, 3, block), sign)
        matching = [t for t in terms if term_has_factor(t, tag)]
        rest = [t for t in terms if not term_has_factor(t, tag)]
        terms = rest + fuse_amplitude_into_consumer(
            inner, 3, matching, tag, canonical=canon, dress_names=('Oe_l3', 'Ve_l3'))
    return terms


PARAMS = ['f_aa', 'f_bb', 'g_aaaa', 'g_abab', 'g_bbbb', 'd_aa', 'd_bb', 'o', 'v', 'nv', 'no',
          'eps_a', 't2_1_aaaa', 't2_1_abab', 't2_2_aaaa', 't2_2_abab', 't1_2_aa',
          't2out_aaaa', 't2out_abab']
ALIASES = {'t2_2_bbbb': 't2_2_aaaa', 't2_1_bbbb': 't2_1_aaaa',
           't1_2_bb': 't1_2_aa', 't2out_bbbb': 't2out_aaaa'}


def main():
    mol = gto.M(atom='H 0 0 0; H 0 0 0.8; H 0 0 1.75; H 0 0 2.6', basis='sto-3g', verbose=0)
    mf = scf.RHF(mol); mf.conv_tol = 1e-13; mf.run()
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
    eps = get_orbital_energies(mf, representation='spatial')
    r = BuildSuperMatrixADCnRestricted(eps, ga, gab, gb, mol.nelectron // 2)
    base = dict(r._rargs); A = r._amps_order(max_order=4)
    lp = {**base, 'eps_a': eps,
          't2_1_aaaa': A['T2_1']['t2_aaaa'], 't2_1_abab': A['T2_1']['t2_abab'],
          't2_2_aaaa': A['T2_2']['t2_aaaa'], 't2_2_abab': A['T2_2']['t2_abab'],
          't1_2_aa': A['T1_2']['t1_aa'],
          't2out_aaaa': A['T2_1']['t2_aaaa'], 't2out_abab': A['T2_1']['t2_abab']}

    sector = 'IP'
    conv = class_index_convention(1, sector)
    ket = precursor_ket_string(1, sector, occ_offset=conv['nh'], vir_offset=conv['np'])
    kh, kp = class_letters(1, sector, occ_offset=conv['nh'], vir_offset=conv['np'])
    ket_letters = kh + kp
    p_occ = OCC_LETTERS[2 * conv['nh']]

    # Two blocks, occ row, aaaa output -- enough to exercise the full nested
    # machinery (l3, t3, t4 kinds; order-tagging; T-role inner) on H4's only
    # nonzero t4 block (aabbaabb), on BOTH the superop U-side (l3ft2) and the
    # overlap S-side (l3t2). Each l3ft2 block fuses to ~2.7e4 terms, so this is
    # deliberately narrow; the full spin/row sweep was validated out-of-band.
    p_letter, row = p_occ, 'occ'
    out_idx = ket_letters + [p_letter]
    sl = dict(zip(out_idx, ('a', 'a', 'a', 'a')))
    families = [
        ('l3ft2', 'u3_2h1p', superop_element_terms(
            [f'a*({p_letter})'], ket, sector, ('f',), left_ops=[['l3']],
            ket_dressing=['t2'], spin_labels=sl)),
        ('l3t2', 's3_2h1p', overlap_element_terms(
            [f'a*({p_letter})'], ket, left_ops=[['l3']], ket_dressing=['t2'], spin_labels=sl)),
    ]
    damp = {**A['L3_3'], **A['T2_1']}
    all_ok, worst = True, 0.0
    for fam, prefix, outer in families:
        outer = [[t[0]] + [re.sub(r'^t2_', 't2out_', f.strip()) for f in t[1:]] for t in outer]
        fused = _fuse_outer_l3_order3(outer)
        name = f'{prefix}_{row}_{fam}_aaaa'
        src = assemble_laplace_fused_multikind(
            name, PARAMS, ALIASES, 'out', shape_expr(out_idx), fused, out_idx,
            eps_o_expr='eps_a[o]', eps_v_expr='eps_a[v]')
        ns = {}
        exec('import numpy as np\nfrom src.SingleReference.CC.cached_einsum import einsum\n'
             'from src.Base.utils.grids.grids import minimax_time_grid\n' + src, ns)
        lapf = ns[name]
        largs = {p: lp[p] for p in inspect.signature(lapf).parameters if p != 'ntau'}
        lapval = lapf(**largs, ntau=6)
        dfn = getattr(dm, name)
        dargs = {p: (damp[p] if p in damp else base[p]) for p in inspect.signature(dfn).parameters}
        ref = dfn(**dargs)
        err = float(np.max(np.abs(lapval - ref)))
        denom = float(np.max(np.abs(ref)))
        ok = err < 1e-11
        all_ok &= ok
        worst = max(worst, err)
        print(f"  {name:28s} |ref|={denom:.3e} err(ntau=6)={err:.2e} "
              f"{'OK' if ok else '*** FAIL ***'}")
    print(f"nested l3ft2/l3t2 (3,1) vs dense: worst err = {worst:.2e}  "
          f"{'ALL OK' if all_ok else 'FAILURE'}")
    assert all_ok, "nested Laplace fusion disagrees with dense reference"


