"""Validates the NESTED Laplace fusion (an OUTER amplitude whose OWN numerator
carries rank>=3 leaves) added to laplace_codegen.py -- fuse_nested_numerator +
tag_lowrank_leaves_by_order + assemble_laplace_fused_multikind.

Target: l3ft2 / l3t2 at the (l3^3, t2^1) order combo, i.e. the ADC(5) case where
l3^(3)'s order-3 numerator has t3^(2)/t4^(2) leaves that must themselves be
Laplace-fused (a fusion nested inside a fusion). This is the "nested-fusion" piece; it needs
TWO things together -- (1) order-tagging the materialized low-rank leaves (l3's
direct t2 is order 2, the inner t3/t4 numerators' t2 is order 1; a single
generic tag would feed one the wrong order), and (2) fusing inner leaves in the
pure T-frame (amp_out_indices), the to_l transpose belonging only to the OUTER
l3 fusion.

Compares, block by block, against the dense adc4_u3_blocks_restricted twins
evaluated at (L3_3, T2_1). H4/sto-3g is deliberate: it is the smallest system
whose only nonzero t4 block (aabbaabb) actually exercises the nested double-tau
(same-spin t4 vanishes there), and no=nv so a wrong-order/mis-canonical dressing
gives silently-wrong numbers (no shape error) rather than a crash.
"""
