"""Gate for the ORDER-GENERAL driver assembly (sigma_driver.u_dot_orb_order):
at n=3 it must reproduce the hand-written u3_dot_orb (itself bit-exact against
the lambda-oracle-validated u3_generated) to machine precision.

This is what makes the driver genuinely ADC(n): the order-3 stitch list is no
longer written out by hand, it is enumerated from adc_order_rule.u_order_terms
and resolved against whichever generated module holds each tag structure
(pruned structures are skipped, exactly as before).
"""
import os, sys
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))
import numpy as np
from pyscf import gto, scf
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.SingleReference.ADC.sigma_driver import u3_dot_orb, u_dot_orb_order
from src.SingleReference.ADC.generated_modules import lazy
s2r = lazy('adc4_c2_s2c_apply_restricted_blocks')
from src.Base.pyscf.pyscf_interface import get_orbital_energies, get_antisymmetrized_spin_block_eri
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)

def main():
    all_ok = True
    for atom, basis, label in [('Li 0 0 0; H 0 0 1.6', 'sto-3g', 'LiH/sto-3g'),
                               ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g')]:
        mol = gto.M(atom=atom, basis=basis, verbose=0); mf = scf.RHF(mol).run()
        ns = mol.nelectron // 2
        eps = get_orbital_energies(mf, representation='spatial')
        ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
        r = BuildSuperMatrixADCnRestricted(eps, ga, gab, gb, ns)
        pv = np.random.default_rng(3).standard_normal(r.norb)
        for sec in ('IP', 'EA'):
            ref = u3_dot_orb(r, sec, pv, s2r)
            gen = u_dot_orb_order(r, sec, pv, 3, s2r)
            d = np.abs(gen - ref).max()
            ok = d < 1e-12; all_ok &= ok
            print(f"[{'OK' if ok else 'FAIL'}] {label} {sec}: order-general(n=3) == u3_dot_orb: {d:.2e}")
    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
