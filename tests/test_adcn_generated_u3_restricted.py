"""Increment 4 (arbiter U^(3)) gate of the spin-free ADC(2)-(5) plan
the restricted
(spin-blocked, RHF) BuildSuperMatrixADCnRestricted.u3_generated assembles the
disputed order-3 orbital<->k=1 U^(3) coupling (the ADC(4) arbiter that hit
the exact-FCI 0.0126 H2 target where the printed SCW83 B3 gave 0.0671)
purely from SPATIAL spin-block tensors + restricted MPn amplitudes at the
same multi-order assignment as the spin-orbital driver (reused u2/s2 blocks
at higher amplitude orders + the new U^(3) tag structures, with the
-N^(2)U^(1) / -eps_p S^(3) / -1/2 U^(1) S^(2) corrections).

Oracle: the spin-orbital GENERATED U^(3) block (itself the lambda-oracle-
validated arbiter). The restricted alpha-sector U^(3) (alpha orbital
columns) must equal the spin-orbital U^(3)[:, 0::2] at the corresponding
alpha-sector configs.

LiH/sto-3g is decisive here (the plan flags H2 parity degeneracy for U^(3));
H2O/sto-3g and H2/sto-3g included too.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.SingleReference.ADC.adc_autogenerated import (
    BuildSuperMatrixADCn, BuildSuperMatrixADCnRestricted)
from src.SingleReference.ADC.precursor_classes import class_configs
from src.Base.pyscf.pyscf_interface import (
    get_orbital_energies, get_two_electron_integrals_chemist,
    get_antisymmetrized_spin_eri, get_antisymmetrized_spin_block_eri)
from tests.adc_common import alpha_to_class_index
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)


def check(label, diff, tol=1e-11):
    ok = diff < tol
    print(f"[{'OK' if ok else 'FAIL'}] {label}: {diff:.3e}")
    return ok


def main():
    all_ok = True

    for atom, basis, label in [
        ('H 0 0 0; H 0 0 0.74', 'sto-3g', 'H2/sto-3g (smoke)'),
        ('Li 0 0 0; H 0 0 1.6', 'sto-3g', 'LiH/sto-3g (decisive)'),
        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g'),
    ]:
        mol = gto.M(atom=atom, basis=basis, verbose=0)
        mf = scf.RHF(mol).run()
        nocc_sp = mol.nelectron // 2
        nocc = 2 * nocc_sp
        eps = get_orbital_energies(mf, representation='spin')
        eri = get_two_electron_integrals_chemist(mol, mf, representation='spatial')
        g = get_antisymmetrized_spin_eri(eri)
        so = BuildSuperMatrixADCn(eps, g, nocc)

        eps_sp = get_orbital_energies(mf, representation='spatial')
        g_aaaa, g_bbbb, g_abab = get_antisymmetrized_spin_block_eri(mol, mf)
        r = BuildSuperMatrixADCnRestricted(eps_sp, g_aaaa, g_abab, g_bbbb, nocc_sp)

        print(f"\n=== {label} ===")
        for sector in ('IP', 'EA'):
            U3r = r.u3_generated(sector)
            U3so = so.u3_generated(sector)[:, 0::2]   # alpha orbital columns
            cols = class_configs(nocc, len(eps), 1, sector)
            cfg = r.sector_configs(sector)
            idx = alpha_to_class_index(cfg, sector, cols, nocc)
            diff = np.abs(U3r - U3so[idx]).max()
            all_ok &= check(f"U^(3) {sector} restricted == spin-orbital generated", diff)

    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
