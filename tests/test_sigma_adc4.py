"""ADC(4)-level matrix-free operator (2p1h/EA sector): the sigma operator
completed to ADC(4) by composing the generated U^(3) correction into the
orbital<->2p1h coupling.

U^(3) is an ORBITAL x CLASS block (norb x n2p1h), NOT class x class like
C^(2) -- so it never reaches the (ncfg)^2 memory wall and is correctly kept
dense (generated BuildSuperMatrixADCn.u3_generated, the lambda-oracle arbiter
that hits 0.0126 on H2 where printed-B3 gives 0.0671). The (n2p1h, n2p1h)
excitation block (K + C^(1) + C^(2)) stays FULLY matrix-free. Since
sector_operator already takes an arbitrary U, ADC(4) = ADC(4)-base coupling +
U^(3) composes with no operator change:

    U_total = u_2p1h_adc3 (order 2) + u3_generated (order 3)

Validated: the matrix-free operator reproduces the dense assembly of the same
2p1h-sector ADC(4) blocks (operator == dense; eigsh == eigh). This is the
2p1h sub-block of full ADC(4) (no 3h2p here -- that class is a separate,
larger extension).
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf
from scipy.sparse.linalg import eigsh

from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCn
from src.SingleReference.ADC.generated_modules import lazy
c1ap = lazy('adc4_c1_self_apply_blocks')
c2ap = lazy('adc4_c2_apply_blocks')
s2ap = lazy('adc4_c2_s2c_apply_blocks')
from src.SingleReference.ADC.sigma_driver import sector_operator, diag_K
from src.SingleReference.DensityMatrix.mpn_density_driver import MPnDensityDriver
from src.SingleReference.common.mp_amplitudes import to_l
from src.Base.pyscf.pyscf_interface import (
    get_orbital_energies, get_two_electron_integrals_chemist,
    get_antisymmetrized_spin_eri)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)


def main():
    all_ok = True
    for atom, basis, label in [
        ('Li 0 0 0; H 0 0 1.6', 'sto-3g', 'LiH/sto-3g'),
        ('H 0 0 0; H 0 0 0.74; H 0 0 1.5; H 0 0 2.2', 'sto-3g', 'H4/sto-3g'),
        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g'),
    ]:
        mol = gto.M(atom=atom, basis=basis, verbose=0)
        mf = scf.RHF(mol).run()
        nocc = 2 * (mol.nelectron // 2)
        eps = get_orbital_energies(mf, representation='spin')
        eri = get_two_electron_integrals_chemist(mol, mf, representation='spatial')
        g = get_antisymmetrized_spin_eri(eri)
        norb = len(eps)
        no, nv = nocc, norb - nocc

        gen = BuildSuperMatrixADCn(eps, g, nocc)
        n2 = gen.n2_norm()
        # U through order 3 = order-2 U + generated U^(3) correction
        U = gen.u_2p1h_adc3() + gen.u3_generated('EA')          # (n2p1h, norb)

        mpn = MPnDensityDriver(eps, g, nocc)
        t2 = mpn.compute_t2_1()
        t1_2, _, _, _ = mpn.compute_order2_amplitudes(t2)
        pool = {'f': np.diag(eps), 'g': g, 'kd': np.eye(norb),
                'o': slice(0, nocc), 'v': slice(nocc, norb), 'no': no, 'nv': nv,
                't2': t2, 'l2': to_l(t2, 2), 't1': t1_2, 'l1': to_l(t1_2, 1)}

        # dense reference from the SAME blocks
        ncfg = U.shape[0]
        n = norb + ncfg
        Href = np.zeros((n, n))
        Href[:norb, :norb] = np.diag(eps)
        Href[norb:, :norb] = U
        Href[:norb, norb:] = U.T
        Href[norb:, norb:] = (np.diag(diag_K(eps, nocc, norb, 'EA'))
                              + gen.c1_block('EA') + gen.c2_block_generated('EA'))

        op = sector_operator('EA', U, pool, eps, n2, nocc, norb, c1ap, c2ap, s2ap)
        recon = np.column_stack([op.matvec(e) for e in np.eye(n)])
        opdiff = np.abs(recon - Href).max()
        k = min(6, n - 2)
        w_mf = np.sort(eigsh(op, k=k, which='SA', return_eigenvectors=False))
        w_dense = np.sort(np.linalg.eigvalsh(Href))[:k]
        eigdiff = np.abs(w_mf - w_dense).max()

        ok = opdiff < 1e-10 and eigdiff < 1e-8
        all_ok &= ok
        print(f"\n=== {label}  (dim {n}) ===")
        print(f"  [{'OK' if opdiff < 1e-10 else 'FAIL'}] ADC(4) EA matrix-free op == dense: {opdiff:.2e}")
        print(f"  [{'OK' if eigdiff < 1e-8 else 'FAIL'}] lowest-{k} eigenvalues: {eigdiff:.2e}")
        print(f"        lowest matrix-free ADC(4) EA eigenvalue = {w_mf[0]:.6f} Ha (dense {w_dense[0]:.6f})")

    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
