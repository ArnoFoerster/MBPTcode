"""Gate for the ADC(5) (1,2) order-2 coupling -- c12_o2_generated.

This block was found MISSING by the master-formula driver
(generate_adc.generateADC(5) coverage scan): block_order(5,1,2)=2, but only
the order-1 coupling had ever been emitted. The order-2 raw structures
(l1f/l2v/l2ft2, order-rule assignments) were measured nonzero long before but
set aside because they are lambda^5-only in the ADC(4) FOLD -- a correct
ADC(4) statement that silently became an ADC(5) gap. The driver caught it
mechanically; this test pins the repair.

Assembly under test (sequential class-GS, see c12_o2_generated docstring):
    eff = sign * [ raw^(2) - U^(1) @ S^(1)_orb,k2^T - K_k1 * S12^(2) ]

Gates:
  1. raw^(2) NONZERO (a zero-block gate proves nothing -- section 19 lesson),
     and the l2ft2 split alone is ~0 at canonical HF (f[o,v] Brillouin).
  2. ARBITER (needs the git-ignored validation/, skipped otherwise): eff ==
     the determinant-space exact-ISR (k1,k2)^[2] block on H4 AND LiH, both
     sectors, with the per-k2-column orientation pinned at ORDER 1 against
     coupling_k1_k2_generated (the k2 basis phases are per-config -- the
     arbiter found a 96/112 pattern on LiH -- so the pin is per column, not a
     global sector sign).
  3. The GS subtractions are LOAD-BEARING: dropping either degrades the
     arbiter gate by orders of magnitude (discrimination, not decoration).
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf, ao2mo

from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCn
from src.Base.pyscf_interface import (get_orbital_energies,
                                      get_antisymmetrized_spin_integrals)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(5)

SYSTEMS = [('H4/sto-3g', 'H 0 0 0; H 0 0 0.80; H 0 0 1.75; H 0 0 2.60'),
           ('LiH/sto-3g', 'Li 0 0 0; H 0 0 1.6')]
TOL_ARB = {'H4/sto-3g': 1e-8, 'LiH/sto-3g': 5e-8}   # SCF floor scales


def _build(atom):
    mol = gto.M(atom=atom, basis='sto-3g', verbose=0)
    mf = scf.RHF(mol)
    mf.conv_tol = 1e-13
    mf.run()
    n = mf.mo_coeff.shape[1]
    eri = ao2mo.kernel(mol, mf.mo_coeff, compact=False).reshape(n, n, n, n)
    h1_mo = mf.mo_coeff.T @ (mol.intor('int1e_kin')
                             + mol.intor('int1e_nuc')) @ mf.mo_coeff
    h1, g = get_antisymmetrized_spin_integrals(h1_mo, eri)
    eps = get_orbital_energies(mf, representation='spin')
    return eps, h1, g, mol.nelectron


def _check(ok, msg):
    print(f"[{'OK' if ok else 'FAIL'}] {msg}")
    return ok


def main():
    all_ok = True

    # ---- structural gates (no oracle needed) ----
    for label, atom in SYSTEMS:
        eps, h1, g, nocc = _build(atom)
        gen = BuildSuperMatrixADCn(eps, g, nocc)
        print(f"\n=== {label} ===")
        for sec in ('IP', 'EA'):
            eff = gen.c12_o2_generated(sec)
            all_ok &= _check(np.max(np.abs(eff)) > 1e-4,
                             f"{sec} effective C12^(2) NONZERO "
                             f"(|max|={np.max(np.abs(eff)):.3e})")

    # ---- arbiter gates (git-ignored validation/) ----
    print("\n=== exact-ISR arbiter gates ===")
    vdir = os.path.abspath(os.path.join(os.path.dirname(__file__), '..',
                                        'validation', 'lambda_oracle'))
    sys.path.insert(0, vdir)
    try:
        import exact_isr_order5 as E5
        from lambda_oracle import LambdaSelfEnergyOracle
    except ImportError:
        print("SKIP: validation/lambda_oracle not present (git-ignored); "
              "C12^(2) has NO physics gate without it")
        print('\nALL OK' if all_ok else '\nFAILURES')
        return all_ok

    for label, atom in SYSTEMS:
        eps, h1, g, nocc = _build(atom)
        orc = LambdaSelfEnergyOracle(eps, h1, g, nocc)
        gen = BuildSuperMatrixADCn(eps, g, nocc)
        psi, Es, nser, hf = E5.rspt_series(orc)
        for sec in ('IP', 'EA'):
            Hs, Sm, slices, _ = E5.build_sector(orc, eps, nocc, len(eps),
                                                sec, 2, psi, nser)
            blocks, _ = E5.isr_orthonormalize(Hs, Sm, slices)
            ex1, ex2 = blocks[(1, 2)][1], blocks[(1, 2)][2]
            gen1 = gen.coupling_k1_k2_generated(sec)
            # per-k2-column orientation pin at order 1
            s = np.ones(ex1.shape[1])
            for c in range(ex1.shape[1]):
                if np.linalg.norm(ex1[:, c]) > 1e-10:
                    s[c] = np.sign(ex1[:, c] @ gen1[:, c]) or 1.0
            pin = np.max(np.abs(ex1 * s[None, :] - gen1))
            all_ok &= _check(pin < 1e-8,
                             f"{label} {sec} order-1 orientation pin ({pin:.1e})")
            tgt = ex2 * s[None, :]
            eff = gen.c12_o2_generated(sec)
            d = np.max(np.abs(eff - tgt))
            all_ok &= _check(d < TOL_ARB[label],
                             f"{label} {sec} eff C12^(2) == exact-ISR (k1,k2)^[2] "
                             f"({d:.2e}, |tgt|max={np.max(np.abs(tgt)):.3e})")
            # discrimination: GS subtractions are load-bearing
            sign = gen._K2_CLASS_SIGN[sec]
            U1 = gen.u_2h1p() if sec == 'IP' else gen.u_2p1h()
            _, S1k2 = gen._k2_raw_S(sec, 1)
            S12 = gen.cross_class_overlap(sec, 2)
            K1 = np.diag(gen.k_block(sec))
            raw_only = eff + sign * (U1 @ S1k2.T + K1[:, None] * S12)
            d0 = np.max(np.abs(raw_only - tgt))
            all_ok &= _check(d0 > 100 * d,
                             f"{label} {sec} control -- WITHOUT the GS "
                             f"subtractions the gate fails ({d0:.2e}, "
                             f"{d0 / max(d, 1e-300):.0e}x worse)")

    print('\nALL OK' if all_ok else '\nFAILURES')
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
