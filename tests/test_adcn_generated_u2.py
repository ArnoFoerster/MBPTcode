"""Phase 3 falsification test for the automated ADC(n) generator: does the
superoperator-element + Omega-dressing machinery reproduce Dyson-ADC(3)'s
U^(2) coupling corrections?

This is exactly the territory where the earlier naive attempt failed
(generic denominator-insertion could not
produce U^(2)'s "dangerous" 4-orbital denominators that mix external and
dummy labels). The present machinery is structurally different: the only
denominators anywhere live INSIDE the separately-computed MBPT amplitudes
(t2^(1) carries exactly the eps_i+eps_k-eps_c-eps_a-type combination that
the generic rule couldn't build), and the element itself is a plain
single-v Wick contraction. Since U^(0)=0 (canonical) and S^(1)=0
identically, the Loewdin layer is inert at this order and the raw dressed
elements ARE the orthogonalized U^(2) -- so the comparison is direct:

    u_2h1p_adc3()/u_2p1h_adc3()  vs  the U blocks sliced straight out of
    adc_spinorbital.build_supermatrix (term0 + corr_cd + corr_kc1 +
    corr_kc2, validated against QuAcK + the Ne/aug-cc-pVDZ reference).

Outcome either way is decisive: exact match validates the generator's
core claim (Phase 3 gate passes); a mismatch localizes exactly which
dressing split disagrees (falsification with a pointer, not a mystery).
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.SingleReference.ADC import ADCSolverUnrestricted
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCn
from src.Base.pyscf.pyscf_interface import (
    get_orbital_energies, get_two_electron_integrals_chemist,
    get_antisymmetrized_spin_eri)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)


def check(label, diff, tol=1e-12):
    ok = diff < tol
    print(f"[{'OK' if ok else 'FAIL'}] {label}: max diff = {diff:.3e}")
    return ok


def main():
    all_ok = True

    for atom, basis, label in [
        ('H 0 0 0; H 0 0 0.74', 'sto-3g', 'H2/sto-3g (smoke)'),
        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g (decisive)'),
    ]:
        mol = gto.M(atom=atom, basis=basis, verbose=0)
        mf = scf.RHF(mol).run()
        nocc = 2 * (mol.nelectron // 2)
        eps = get_orbital_energies(mf, representation='spin')
        eri = get_two_electron_integrals_chemist(mol, mf, representation='spatial')
        g = get_antisymmetrized_spin_eri(eri)
        norb = len(eps)

        gen_solver = BuildSuperMatrixADCn(eps, g, nocc)
        adc3 = ADCSolverUnrestricted.from_arrays(eps, g)
        d = adc3.dimensions(nocc)
        H_ref = adc3.build_supermatrix(nocc)
        off1, off2 = norb, norb + d['n2h1p']

        U1_ref = H_ref[off1:off2, :norb]        # full U_2h1p (term0 + all corr)
        U2_ref = H_ref[off2:, :norb]            # full U_2p1h

        print(f"\n=== {label} ===")
        all_ok &= check("U_2h1p through order 2 == adc3 build_supermatrix block",
                        np.abs(gen_solver.u_2h1p_adc3() - U1_ref).max())
        all_ok &= check("U_2p1h through order 2 == adc3 build_supermatrix block",
                        np.abs(gen_solver.u_2p1h_adc3() - U2_ref).max())

        # --- the whole thing: full generated ADC(3) supermatrix + poles ---
        H_gen = gen_solver.build_supermatrix_adc3()
        all_ok &= check("FULL generated ADC(3) supermatrix == adc3 build_supermatrix",
                        np.abs(H_gen - H_ref).max())
        ev_gen = np.linalg.eigvalsh(H_gen)
        ev_ref = np.linalg.eigvalsh(H_ref)
        all_ok &= check("ADC(3) eigenvalues (all poles) identical",
                        np.abs(ev_gen - ev_ref).max())

    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
