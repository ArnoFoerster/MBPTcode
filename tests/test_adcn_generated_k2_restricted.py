"""ADC(5)-push increment A gate: restricted (spin-blocked) k=2 (3h2p/3p2h)
extended-space blocks. BuildSuperMatrixADCnRestricted.coupling_k1_k2_generated
(first-order 2h1p<->3h2p / 2p1h<->3p2h) and .u2_k2_generated (order-2
orbital<->k=2, Dyson class-GS) assemble the alpha-Dyson sector from SPATIAL
spin-block tensors, and must match the spin-orbital generated driver
(BuildSuperMatrixADCn.coupling_k1_k2_generated / u2_k2_generated -- validated
against adc4_base's k=2 blocks) at the corresponding alpha-sector configs.

k=2 needs >=3 occupied and >=2 virtual spatial orbitals, so LiH/sto-3g and
H2O/sto-3g are the test systems (H2 has no 3h2p/3p2h configs).
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.SingleReference.ADC.adc_autogenerated import (
    BuildSuperMatrixADCn, BuildSuperMatrixADCnRestricted)
from src.SingleReference.ADC.precursor_classes import class_configs
from src.Base.pyscf.pyscf_interface import (
    get_orbital_energies, get_two_electron_integrals_chemist,
    get_antisymmetrized_spin_eri, get_antisymmetrized_spin_block_eri)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)


def check(label, diff, tol=1e-11):
    ok = diff < tol
    print(f"[{'OK' if ok else 'FAIL'}] {label}: {diff:.3e}")
    return ok


def _kmap(r, sector, nocc_spin, norb_spin, k):
    """restricted class-k config -> spin-orbital class_configs(k) index."""
    cols = [np.asarray(c) for c in class_configs(nocc_spin, norb_spin, k, sector)]
    cfg = r.kconfigs(sector, k)
    nh, npart = cfg['nh'], cfg['npart']
    out = []
    for c in range(len(cfg['K'])):
        hs, ps, sp = cfg['hole_sp'][c], cfg['part_sp'][c], cfg['spins'][c]
        hso = sorted(2 * hs[j] + sp[j] for j in range(nh))
        pso = sorted(nocc_spin + 2 * ps[j] + sp[nh + j] for j in range(npart))
        tgt = hso + pso
        mask = np.ones(len(cols[0]), bool)
        for ax, v in enumerate(tgt):
            mask &= (cols[ax] == v)
        out.append(np.where(mask)[0][0])
    return np.array(out, dtype=int)


def main():
    all_ok = True

    for atom, basis, label in [
        ('Li 0 0 0; H 0 0 1.6', 'sto-3g', 'LiH/sto-3g'),
        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g'),
    ]:
        mol = gto.M(atom=atom, basis=basis, verbose=0)
        mf = scf.RHF(mol).run()
        nocc_sp = mol.nelectron // 2
        nocc = 2 * nocc_sp
        eps = get_orbital_energies(mf, representation='spin')
        norb = len(eps)
        eri = get_two_electron_integrals_chemist(mol, mf, representation='spatial')
        g = get_antisymmetrized_spin_eri(eri)
        so = BuildSuperMatrixADCn(eps, g, nocc)

        eps_sp = get_orbital_energies(mf, representation='spatial')
        g_aaaa, g_bbbb, g_abab = get_antisymmetrized_spin_block_eri(mol, mf)
        r = BuildSuperMatrixADCnRestricted(eps_sp, g_aaaa, g_abab, g_bbbb, nocc_sp)

        print(f"\n=== {label} ===")
        for sector in ('IP', 'EA'):
            i1 = r._class_index_map(sector)
            i2 = _kmap(r, sector, nocc, norb, 2)

            Cr = r.coupling_k1_k2_generated(sector)
            Cso = so.coupling_k1_k2_generated(sector)
            all_ok &= check(f"coupling k1<->k2 {sector} restricted == spin-orbital",
                            np.abs(Cr - Cso[np.ix_(i1, i2)]).max())

            Ur = r.u2_k2_generated(sector)
            Uso = so.u2_k2_generated(sector)[:, 0::2]
            all_ok &= check(f"U^(2) k2 {sector} restricted == spin-orbital",
                            np.abs(Ur - Uso[i2]).max())

    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
