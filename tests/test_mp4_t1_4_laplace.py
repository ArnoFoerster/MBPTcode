"""GATE for the Laplace-fused order-4 singles amplitude T1^(4)/L1^(4) -- the
NESTED-amplitude case (t1_4 -> t3_3 -> t3_2/t4_2, a fusion two deep):
MPnDensityDriverRestricted.compute_t1_4_laplace and the ADC provider
BuildSuperMatrixADCnRestricted.amps_order_lowrank_laplace (which now completes
the order-<=4 rank-<=2 amplitude set the U^(4) coupling consumes).

Builds t1_4 with NONE of the O(no^3 nv^3) t3_3 (nor t3_2/t4_2) tensors formed,
via mp4_t1_4_laplace_restricted.t1_4_aa_laplace. The DEPTH-QUALIFIED taus are
load-bearing: the outer t3_3 and inner t3_2 are BOTH rank 3, and without a
per-depth tau they share one -> a ~7% CONSTANT error (independent of ntau). So
this gate checks CONVERGENCE with ntau (a fixed offset would betray the
collision), not just smallness.

  * compute_t1_4_laplace == materialized compute_t1_4 (ntau=6 ~6e-10 -> ntau=10
    ~5e-13).
  * amps_order_lowrank_laplace(ntau)['L1_4'] == amps_order(4)['L1_4'] (exact),
    and the provider is a complete rank>=3-free {..,L2_3,L1_4} set.

NH3/sto-3g (5 occ / 3 vir): smallest system with t3 genuinely nonzero.

Run:  ~/anaconda3/envs/py310/bin/python -u tests/test_mp4_t1_4_laplace.py
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.Base.pyscf.pyscf_interface import (get_orbital_energies,
                                            get_antisymmetrized_spin_block_eri)
from src.SingleReference.DensityMatrix.mpn_density_driver_restricted import (
    MPnDensityDriverRestricted)
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)

_RANK_GE3 = ('L3', 'L4', 'T3', 'T4', 'L5', 'T5')


def _check(ok, msg):
    print(f"[{'OK' if ok else 'FAIL'}] {msg}")
    return ok


def main():
    mol = gto.M(atom='N 0 0 0; H 0 0 1.01; H 0.95 0 -0.3; H -0.48 0.82 -0.3',
                basis='sto-3g', verbose=0)
    mf = scf.RHF(mol); mf.conv_tol = 1e-13; mf.run()
    eps = get_orbital_energies(mf, representation='spatial')
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
    nocc = mol.nelectron // 2
    print(f"NH3/sto-3g norb={len(eps)} nocc={nocc} nvir={len(eps) - nocc}")
    all_ok = True

    # --- driver level: compute_t1_4_laplace vs materialized compute_t1_4 ---
    d = MPnDensityDriverRestricted(np.diag(eps), ga, gab, gb, nocc)
    t2_1a, t2_1b = d.compute_t2_1()
    o2 = d.compute_order2_amplitudes(t2_1a, t2_1b, max_rank=4)
    t1_2a, t2_2a, t2_2b = o2[0], o2[1], o2[2]
    t3_2, t4_2 = o2[3:6], o2[6:10]
    mx3 = max(float(np.abs(x).max()) for x in t3_2)
    all_ok &= _check(mx3 > 1e-8, f"t3_2 (|max|={mx3:.2e}) nonzero -- real check")
    E2 = d.compute_E(t2_1a, t2_1b)
    t1_3a, t2_3a, t2_3b, t3_3a, t3_3b, t3_3c = d.compute_order3_amplitudes(
        t1_2a, t2_2a, t2_2b, *t3_2, *t4_2, t2_1a, t2_1b, E2)
    t1_4_ex = d.compute_t1_4(t1_3a, t2_3a, t2_3b, t3_3a, t3_3b, t3_3c, t1_2a, E2)

    prev = None
    for ntau in (6, 10):
        t1_4 = d.compute_t1_4_laplace(t1_3a, t2_3a, t2_3b, t2_2a, t2_2b,
                                      t1_2a, t2_1a, t2_1b, E2, ntau)
        err = float(np.abs(t1_4 - t1_4_ex).max())
        all_ok &= _check(err < (1e-8 if ntau == 6 else 1e-11),
                         f"compute_t1_4_laplace(ntau={ntau}) == materialized t1_4 "
                         f"({err:.2e})")
        if prev is not None:
            all_ok &= _check(err < prev * 1e-2,
                             f"  CONVERGES sharply with ntau ({err:.2e} << "
                             f"{prev:.2e}) -- depth-qualified taus, not a shared-tau "
                             f"constant offset")
        prev = err

    # --- ADC provider: L1_4 correct + complete rank>=3-free set ---
    r = BuildSuperMatrixADCnRestricted(eps, ga, gab, gb, nocc)
    lap = r.amps_order_lowrank_laplace(6)
    exact = r.amps_order(max_order=4)
    bad = [k for k in lap if any(k.startswith(p) for p in _RANK_GE3)]
    all_ok &= _check(not bad,
                     f"provider carries NO rank>=3 key (keys={sorted(lap)})")
    for key in ('T1_4', 'L1_4'):
        worst = max(float(np.abs(lap[key][leaf] - exact[key][leaf]).max())
                    for leaf in lap[key])
        all_ok &= _check(worst < 1e-8,
                         f"provider {key} == amps_order(4) {key} ({worst:.2e})")

    print('\nALL OK' if all_ok else '\nFAILURES')
    return 0 if all_ok else 1


def test_main():
    assert not main(), 'main() returned a nonzero exit code'


if __name__ == '__main__':
    sys.exit(main())
