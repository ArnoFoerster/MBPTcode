"""Gate for the ORDER-GENERAL blockwise ISR assembly (Phase 1c keystone,
src/SingleReference/ADC/isr_assembly.py.

Three layers, most fundamental last:

  1. ACCESSOR PARITY (no oracle): the ONE engine reproduces every per-order
     hand assembly it subsumes, from ONE set of raw series --
       (0,1)@2 == u_adc3 increment          (0,1)@3 == u3_generated
       (1,1)@2 == c_block_generated(2)      (1,1)@3 == c_block_generated(3)
                                            (incl. _orbital_gs_cross)
       (0,2)@1 == 0 (gauge annihilation)    (0,2)@2 == u2_k2_generated
       (0,2)@3 == u3_k2_generated           (1,2)@1 == coupling_k1_k2
       (1,2)@2 == c12_o2_generated          (2,2)@1 == k2_self('v')
     (k2 comparisons carry _K2_CLASS_SIGN -- the engine stays in precursor
     orientation.)
  2. RESTRICTED (0,1)@4: the engine's U^(4) == u_dot_orb_isr columns (the
     arbiter-fixed production path), from the restricted raw series.
  3. ARBITER (validation/ present, else skipped): RAW collector series ==
     the determinant-space Hsup/Smet blocks, and engine EFFECTIVE blocks ==
     isr_orthonormalize's, per (pair, order), with per-class column-sign
     pins anchored at order 1 (k1 via H(0,1)^[1], k2 via S(0,2)^[1]).

The engine exceeding the hand assemblies (post-GS W, cross-class GS at
higher order) first BITES at ADC(6) orders -- not gated here; the arbiter
remains the instrument for those when they land.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf, ao2mo

from src.SingleReference.ADC.adc_autogenerated import (BuildSuperMatrixADCn,
                                                 BuildSuperMatrixADCnRestricted)
from src.SingleReference.ADC.isr_assembly import (isr_effective_blocks,
                                                  collect_spinorbital_raw,
                                                  norm_divide)
from src.SingleReference.ADC.sigma_driver import u_raw_series
from tests.u_isr_oracle import u_dot_orb_isr
from src.SingleReference.ADC.generated_modules import lazy
s2r = lazy('adc4_c2_s2c_apply_restricted_blocks')
from src.Base.pyscf.pyscf_interface import (get_orbital_energies,
                                            get_antisymmetrized_spin_integrals,
                                            get_antisymmetrized_spin_block_eri)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(5)

SYSTEMS = [('H4/sto-3g', 'H 0 0 0; H 0 0 0.80; H 0 0 1.75; H 0 0 2.60'),
           ('LiH/sto-3g', 'Li 0 0 0; H 0 0 1.6')]
NMAX = 5

# Arbiter tolerance = 50 * the system's measured SCF floor max|f[o,v]|: the
# determinant side uses the true converged Fock, the tensors assume CANONICAL
# f, and the floor amplifies up to ~15x through the raw elements (observed:
# LiH RAW H(1,2)@1 at 14x f_ov, annihilated to 3e-16 by the orthonormalizer
# -- pure gauge-direction floor, not content). 50x stays >=30x below the
# smallest real defect the arbiter ever caught (U^(4)'s 5.4e-6).
FLOOR_MULT = 50.0


def _build(atom):
    mol = gto.M(atom=atom, basis='sto-3g', verbose=0)
    mf = scf.RHF(mol)
    mf.conv_tol = 1e-13
    mf.run()
    n = mf.mo_coeff.shape[1]
    eri = ao2mo.kernel(mol, mf.mo_coeff, compact=False).reshape(n, n, n, n)
    h1_mo = mf.mo_coeff.T @ (mol.intor('int1e_kin')
                             + mol.intor('int1e_nuc')) @ mf.mo_coeff
    h1, g = get_antisymmetrized_spin_integrals(h1_mo, eri)
    eps = get_orbital_energies(mf, representation='spin')
    eps_sp = get_orbital_energies(mf, representation='spatial')
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf, eri_chemist=eri)
    nocc = mol.nelectron
    f = h1 + np.einsum('piqi->pq', g[:, :nocc, :, :nocc])
    fov = float(np.max(np.abs(f[:nocc, nocc:])))
    return dict(eps=eps, h1=h1, g=g, nocc=nocc, eps_sp=eps_sp,
                ga=ga, gb=gb, gab=gab, nsp=nocc // 2, fov=fov)


def _check(ok, msg):
    print(f"[{'OK' if ok else 'FAIL'}] {msg}")
    return ok


def _close(A, B, tol):
    d = float(np.max(np.abs(A - B))) if np.size(A) else 0.0
    return d, d < tol


def main():
    all_ok = True
    TOLP = 5e-11          # accessor parity: FP re-association only

    for label, atom in SYSTEMS:
        dd = _build(atom)
        gen = BuildSuperMatrixADCn(dd['eps'], dd['g'], dd['nocc'])
        print(f"\n=== {label}: accessor parity ===")
        for sec in ('IP', 'EA'):
            H, S, dims, norm = collect_spinorbital_raw(gen, sec)
            blocks, _ = isr_effective_blocks(H, S, dims, NMAX, norm=norm)
            sign = gen._K2_CLASS_SIGN[sec]
            u1 = gen.u_2h1p() if sec == 'IP' else gen.u_2p1h()
            targets = [
                ('(0,1)@2 == u_adc3 - U1', blocks[(0, 1)][2].T,
                 (gen.u_2h1p_adc3() if sec == 'IP' else gen.u_2p1h_adc3()) - u1),
                ('(0,1)@3 == u3_generated', blocks[(0, 1)][3].T,
                 gen.u3_generated(sec)),
                ('(1,1)@2 == c_block_generated(2)', blocks[(1, 1)][2],
                 gen.c_block_generated(sec, 2)),
                ('(1,1)@3 == c_block_generated(3)', blocks[(1, 1)][3],
                 gen.c_block_generated(sec, 3)),
            ]
            if 2 in dims:
                targets += [
                    ('(0,2)@1 == 0 (gauge annihilation)',
                     blocks[(0, 2)].get(1, np.zeros((1, 1))), 0.0),
                    ('(0,2)@2 == u2_k2_generated',
                     sign * blocks[(0, 2)][2].T, gen.u2_k2_generated(sec)),
                    ('(0,2)@3 == u3_k2_generated',
                     sign * blocks[(0, 2)][3].T, gen.u3_k2_generated(sec)),
                    ('(1,2)@1 == coupling_k1_k2',
                     sign * blocks[(1, 2)][1],
                     gen.coupling_k1_k2_generated(sec)),
                    ('(1,2)@2 == c12_o2_generated',
                     sign * blocks[(1, 2)][2], gen.c12_o2_generated(sec)),
                    ('(2,2)@1 == k2_self(v)', blocks[(2, 2)][1],
                     gen.k2_self_block_generated(sec, ham='v')),
                ]
            for name, A, B in targets:
                d, ok = _close(A, B, TOLP)
                all_ok &= _check(ok, f"{sec} {name}  ({d:.2e})")

        # ---- restricted (0,1)@4 vs the production u_dot_orb_isr ----
        print(f"=== {label}: restricted (0,1)@4 vs u_dot_orb_isr ===")
        r = BuildSuperMatrixADCnRestricted(dd['eps_sp'], dd['ga'], dd['gab'],
                                          dd['gb'], dd['nsp'])
        norb = len(dd['eps_sp'])
        for sec in ('IP', 'EA'):
            raws, Ss = u_raw_series(r, sec, 4)
            n1 = raws[1].shape[0]
            # norm through N^(3) only (restricted n_norm_order stops there):
            # sufficient for (0,1)@<=4, where N^(4)/N^(5) would multiply
            # raw(0,1)@0 = 0, and the (0,0) raws below need norm only to the
            # order at which an eff-component can pair with them (@2).
            normr = {0: 1.0, 2: r.n_norm_order(2), 3: r.n_norm_order(3)}
            Hr = {(0, 0): {m: v * np.diag(r.eps) for m, v in normr.items()},
                  (0, 1): {m: raws[m].T for m in raws}}
            Sr = {(0, 0): {m: v * np.eye(norb) for m, v in normr.items()},
                  (0, 1): {m: Ss[m].T for m in Ss},
                  (1, 1): {0: np.eye(n1)}}
            for m in (2, 3):
                _, S_m = r._class_raw_S(sec, m)
                if S_m is not None:
                    Sr[(1, 1)][m] = S_m
            blk, _ = isr_effective_blocks(Hr, Sr, {0: norb, 1: n1}, NMAX,
                                          norm=normr)
            U4 = np.zeros((n1, norb))
            for q in range(norb):
                e = np.zeros(norb)
                e[q] = 1.0
                U4[:, q] = u_dot_orb_isr(r, sec, e, 4, s2r)
            d, ok = _close(blk[(0, 1)][4].T, U4, TOLP)
            all_ok &= _check(ok, f"{sec} restricted (0,1)@4 == u_dot_orb_isr "
                                 f"({d:.2e})")

    # ------------------------------------------------------------------
    # arbiter gates
    # ------------------------------------------------------------------
    print("\n=== exact-ISR arbiter gates ===")
    vdir = os.path.abspath(os.path.join(os.path.dirname(__file__), '..',
                                        'validation', 'lambda_oracle'))
    sys.path.insert(0, vdir)
    try:
        import exact_isr_order5 as E5
        from lambda_oracle import LambdaSelfEnergyOracle
    except ImportError as err:
        print(f"SKIP: exact-ISR arbiter unavailable ({err}); the engine has NO "
              "determinant-space gate without it -- the layers above are "
              "accessor parity only")
        print('\nALL OK' if all_ok else '\nFAILURES')
        return all_ok

    for label, atom in SYSTEMS:
        dd = _build(atom)
        tol = FLOOR_MULT * dd['fov']
        print(f"--- {label}: SCF floor max|f[o,v]| = {dd['fov']:.2e} "
              f"-> tol {tol:.2e} ---")
        orc = LambdaSelfEnergyOracle(dd['eps'], dd['h1'], dd['g'], dd['nocc'])
        gen = BuildSuperMatrixADCn(dd['eps'], dd['g'], dd['nocc'])
        psi, Es, nser, hf = E5.rspt_series(orc)
        for sec in ('IP', 'EA'):
            H, S, dims, norm = collect_spinorbital_raw(gen, sec)
            Hn = {k: norm_divide(v, norm, NMAX) for k, v in H.items()}
            Sn = {k: norm_divide(v, norm, NMAX) for k, v in S.items()}
            blocks, _ = isr_effective_blocks(H, S, dims, NMAX, norm=norm)
            Hs, Sm_ex, slices, _ = E5.build_sector(
                orc, dd['eps'], dd['nocc'], len(dd['eps']), sec, 2, psi, nser)
            ex_blocks, _ = E5.isr_orthonormalize(Hs, Sm_ex, slices)

            # per-class sign pins, anchored at order 1
            dvec = {0: np.ones(dims[0])}
            ex01 = Hs[1][slices[0], slices[1]]
            s1, res1 = E5.column_sign_fix(ex01, Hn[(0, 1)][1])
            dvec[1] = s1
            all_ok &= _check(res1 < tol,
                             f"{label} {sec} k1 pin at H(0,1)^[1] ({res1:.1e})")
            if 2 in dims:
                ex02 = Sm_ex[1][slices[0], slices[2]]
                s2_, res2 = E5.column_sign_fix(ex02, Sn[(0, 2)][1])
                dvec[2] = s2_
                all_ok &= _check(res2 < tol,
                                 f"{label} {sec} k2 pin at S(0,2)^[1] "
                                 f"({res2:.1e})")

            gate_orders = {(0, 1): (1, 2, 3), (1, 1): (0, 1, 2, 3),
                           (0, 2): (1, 2, 3), (1, 2): (1, 2), (2, 2): (0, 1)}
            for (i, j), orders in gate_orders.items():
                if i not in dims or j not in dims:
                    continue
                pin = dvec[i][:, None] * dvec[j][None, :]
                for m in orders:
                    # RAW collector gate
                    for tagname, exS, mine in (('H', Hs, Hn), ('S', Sm_ex, Sn)):
                        ex = exS[m][slices[i], slices[j]] * pin
                        A = mine.get((i, j), {}).get(m)
                        if A is None:
                            A = np.zeros_like(ex)
                        d, ok = _close(ex, A, tol)
                        all_ok &= _check(ok, f"{label} {sec} RAW {tagname}"
                                             f"({i},{j})@{m}  ({d:.2e})")
                    # EFFECTIVE engine gate
                    ex = ex_blocks[(i, j)][m] * pin
                    A = blocks[(i, j)].get(m)
                    if A is None:
                        A = np.zeros_like(ex)
                    d, ok = _close(ex, A, tol)
                    all_ok &= _check(ok, f"{label} {sec} EFF ({i},{j})@{m}  "
                                         f"({d:.2e})")

    print('\nALL OK' if all_ok else '\nFAILURES')
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
