"""Validation of the ASSEMBLED matrix-free C^(2) matvec
(sigma_driver.assembled_c2_matvec): the full ISR-Loewdin-corrected 2h1p/2p1h
self-block, applied to a vector WITHOUT forming the (ncfg, ncfg) block, must
equal the dense adc_autogenerated.BuildSuperMatrixADCn.c2_block_generated @ v.

This is the payoff of the sigma stack: the disputed C^(2) (the lambda-oracle
arbiter that beat printed-B7 by 4 orders) as an actual matrix-free operator a
Davidson/Lanczos solve can call. It composes the raw C^(2) split applies + the
within-class S^(2) split applies (both driven through config space) with the
diagonal K and the scalar N^(2), reproducing isr_engine.assemble_kplusc's
order-2 output.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCn
from src.SingleReference.ADC.generated_modules import lazy
c2ap = lazy('adc4_c2_apply_blocks')
s2ap = lazy('adc4_c2_s2c_apply_blocks')
from src.SingleReference.ADC.sigma_driver import assembled_c2_matvec
from src.SingleReference.DensityMatrix.mpn_density_driver import MPnDensityDriver
from src.SingleReference.common.mp_amplitudes import to_l
from src.Base.pyscf.pyscf_interface import (
    get_orbital_energies, get_two_electron_integrals_chemist,
    get_antisymmetrized_spin_eri)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)


def main():
    all_ok = True
    for atom, basis, label in [
        ('Li 0 0 0; H 0 0 1.6', 'sto-3g', 'LiH/sto-3g'),
        ('H 0 0 0; H 0 0 0.74; H 0 0 1.5; H 0 0 2.2', 'sto-3g', 'H4/sto-3g'),
        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g'),
    ]:
        mol = gto.M(atom=atom, basis=basis, verbose=0)
        mf = scf.RHF(mol).run()
        nocc = 2 * (mol.nelectron // 2)
        eps = get_orbital_energies(mf, representation='spin')
        eri = get_two_electron_integrals_chemist(mol, mf, representation='spatial')
        g = get_antisymmetrized_spin_eri(eri)
        norb = len(eps)
        no, nv = nocc, norb - nocc

        so = BuildSuperMatrixADCn(eps, g, nocc)   # dense oracle + N^(2)
        n2 = so.n2_norm()

        mpn = MPnDensityDriver(eps, g, nocc)
        t2 = mpn.compute_t2_1()
        t1_2, _, _, _ = mpn.compute_order2_amplitudes(t2)
        pool = {'f': np.diag(eps), 'g': g, 'kd': np.eye(norb),
                'o': slice(0, nocc), 'v': slice(nocc, norb), 'no': no, 'nv': nv,
                't2': t2, 'l2': to_l(t2, 2), 't1': t1_2, 'l1': to_l(t1_2, 1)}
        rng = np.random.default_rng(0)

        print(f"\n=== {label}  (no={no}, nv={nv}) ===")
        for sector in ('IP', 'EA'):
            C2 = so.c2_block_generated(sector)          # dense (ncfg, ncfg)
            v = rng.standard_normal(C2.shape[1])
            ref = C2 @ v
            y = assembled_c2_matvec(v, sector, pool, eps, n2, nocc, norb, c2ap, s2ap)
            diff = np.abs(y - ref).max()
            rel = diff / (np.abs(ref).max() + 1e-300)
            ok = diff < 1e-10
            all_ok &= ok
            print(f"  [{'OK' if ok else 'FAIL'}] assembled C^(2) {sector} matvec "
                  f"(dim {C2.shape[0]}):  max|mf - dense@v| = {diff:.2e} (rel {rel:.1e})")

    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
