"""DF/RI twin of the U^(3) blocks must equal the full-g blocks exactly.

Why
---
Every emitted block is to be spin-restricted AND Laplace AND DF AND
matrix-free. U^(3) had the first, second and (since the matrix-free apply) the
fourth, but NO `_df_blocks` twin -- so it consumed the full 4-index g and DF
could not be used end-to-end anywhere in ADC(4). `generate_adc4_u3_restricted(
df=True)` now emits adc4_u3_blocks_restricted_df.py by composing
df_codegen.dress_integral_factor with the same restricted emitter.

Test method (same as test_sigma_codegen_restricted_df): feed the DF functions
an EXACT RI factor B -- one that reconstructs g to machine precision -- so any
disagreement is a codegen bug, not fitting error. The two must then agree to
~1e-13; RI incompleteness is a separate, physical question this does not probe.

Guards the composition itself: the U^(3) equations are higher-rank than the
MP2/MP3-density-scale ones df_codegen documents as its tested regime, so the
rewrite meeting them is not assumed to work -- it is checked block by block.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.Base.pyscf_interface import (get_orbital_energies,
                                      get_antisymmetrized_spin_block_eri,
                                      get_density_fitting_coefficients)
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)
from src.SingleReference.ADC.generated_modules import lazy
dense = lazy('adc4_u3_blocks_restricted')
dfm = lazy('adc4_u3_blocks_restricted_df')

TOL = 1e-12


def main():
    all_ok = True
    for atom, basis, label in [
        ('H 0 0 0; H 0 0 0.74', 'sto-3g', 'H2/sto-3g'),
        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g'),
    ]:
        mol = gto.M(atom=atom, basis=basis, verbose=0)
        mf = scf.RHF(mol).run()
        ns = mol.nelectron // 2
        eps = get_orbital_energies(mf, representation='spatial')
        g_aaaa, g_bbbb, g_abab = get_antisymmetrized_spin_block_eri(mol, mf)
        r = BuildSuperMatrixADCnRestricted(eps, g_aaaa, g_abab, g_bbbb, ns)
        B_aa = get_density_fitting_coefficients(mol, mf, representation='spatial')
        B_bb = B_aa

        print(f"\n=== {label} (naux={B_aa.shape[0]}) ===")
        rec_aaaa = (np.einsum('Qpr,Qqs->pqrs', B_aa, B_aa, optimize=True)
                    - np.einsum('Qps,Qqr->pqrs', B_aa, B_aa, optimize=True))
        rec_abab = np.einsum('Qpr,Qqs->pqrs', B_aa, B_bb, optimize=True)
        for nm, v in (('g_aaaa', np.abs(rec_aaaa - g_aaaa).max()),
                      ('g_abab', np.abs(rec_abab - g_abab).max())):
            ok = v < 1e-10
            print(f"  [{'OK' if ok else 'FAIL'}] B reconstructs {nm} ({v:.2e}) "
                  "-- RI is exact here, so any block mismatch is codegen")
            all_ok &= ok

        pool = {**r._rargs, **r._amplitude_pool()}
        pool_df = {**pool, 'B_aa': B_aa, 'B_bb': B_bb}

        names = [n for n in dir(dense) if n.startswith(('u3_', 's3_'))]
        checked, worst, missing = 0, 0.0, []
        for nm in names:
            fd, fdf = getattr(dense, nm), getattr(dfm, nm, None)
            if fdf is None:
                missing.append(nm)
                continue
            import inspect
            try:
                a_d = {k: pool[k] for k in inspect.signature(fd).parameters}
                a_f = {k: pool_df[k] for k in inspect.signature(fdf).parameters}
            except KeyError:
                continue          # leaf this system does not populate
            out_d, out_f = fd(**a_d), fdf(**a_f)
            d = np.abs(out_d - out_f).max()
            worst = max(worst, d)
            checked += 1
        ok = checked > 0 and worst < TOL and not missing
        print(f"  [{'OK' if ok else 'FAIL'}] {checked} U^(3)/S^(3) blocks: "
              f"DF == full-g, worst {worst:.2e} (< {TOL:.0e})"
              + (f"; MISSING DF twins: {missing[:3]}" if missing else ""))
        all_ok &= ok

    print('ALL OK' if all_ok else 'FAILURES')
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
