"""Screened ADC(2)-x == screened multichannel Dyson equation (Romaniello &
Berger, arXiv:2603.27329, ~/publications/2603.27329v1.pdf).

The screened MCDE replaces the bare Coulomb v by the static RPA-screened W in
the ADC(2)-x first-order 2h1p/2p1h C^(1) block, per the paper's Eq. 12
pattern: particle-particle / hole-hole ladders fully screened, electron-hole
rings screened in the exchange integral only (the direct/RPA-bubble integral
stays bare to avoid double counting the screening the MCDE already resums).
Implemented (spin-orbital) via src.SingleReference.ADC.screened_coulomb feeding
a pre-screened tensor to the unmodified generated c1_2h1p/c1_2p1h.

Covers both screened ADC(2)-x (= screened MCDE, W in the C^(1) block only) and
screened ADC(3), which additionally screens the pp/hh LADDER vertices of the
U^(2) coupling while leaving the ph-ring vertices bare (screening those would
double count the RPA polarization the resummation already builds).

Checks (per level):
  1. W=v invariant: with W==eri the screened supermatrix is byte-identical to
     bare (guarantees the substitution touches nothing it shouldn't).
  2. Consistency: the production restricted ADCSolverRestricted.from_arrays(level='adc2x')
     doublet poles all appear in the (bare) spin-orbital spectrum.
  3. Hermiticity of the screened supermatrix.
  4. Screening is active: it modifies poles (adc2x); U^(2) ladder screening
     moves H beyond C^(1)-only screening (adc3).
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.Base.pyscf_interface import (get_orbital_energies,
                                      get_two_electron_integrals_chemist,
                                      get_antisymmetrized_spin_eri)
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCn
from src.SingleReference.ADC import ADCSolverRestricted
import src.SingleReference.ADC.adc_utils as _adc_utils_mod
import src.SingleReference.ADC.adc_r_utils as _adc_r_utils_mod
import src.SingleReference.ADC.adc_r_sigma_df as _adc_r_sigma_df_mod


class _SpyTargets:
    """Forwarding patch target: the file split spread _g_slice_df bindings
    over three modules; setting an attribute here sets all of them."""
    _mods = (_adc_utils_mod, _adc_r_utils_mod, _adc_r_sigma_df_mod)

    def __getattr__(self, name):
        return getattr(self._mods[0], name)

    def __setattr__(self, name, value):
        for m in self._mods:
            setattr(m, name, value)
from src.Base.pyscf_interface import DFIntegrals
from src.SingleReference.LinearResponse.linear_response import (
    static_screened_coulomb_chemist, static_screened_coulomb_aux)
from src.SingleReference.ADC.screened_coulomb import (
    screened_c1_tensor, solve_screened_adc)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)


def main():
    all_ok = True

    for atom, basis in [('H 0 0 0; F 0 0 0.9', 'sto-3g'),
                        ('O 0 0 0; H 0 0.76 0.59; H 0 -0.76 0.59', 'sto-3g'),
                        ('N 0 0 0; N 0 0 1.1', 'sto-3g')]:
        mol = gto.M(atom=atom, basis=basis, verbose=0)
        mf = scf.RHF(mol).run()
        nocc = mol.nelectron // 2
        eps = get_orbital_energies(mf, representation='spatial')
        eri = get_two_electron_integrals_chemist(mol, mf)
        eps_spin = np.repeat(eps, 2)
        g_spin = get_antisymmetrized_spin_eri(eri)
        nsp = 2 * nocc
        tag = f"{atom.split(';')[0].strip():5s} {basis}"

        bare = BuildSuperMatrixADCn(eps_spin, g_spin, nsp)
        H_bare = bare.build_supermatrix_adc2x()
        poles_bare = np.linalg.eigvalsh(H_bare)

        # 1. W=v invariant
        g_c1_id = screened_c1_tensor(eri, eri, nocc)
        H_id = BuildSuperMatrixADCn(eps_spin, g_spin, nsp, g_c1=g_c1_id).build_supermatrix_adc2x()
        inv = np.max(np.abs(H_id - H_bare))
        ok = inv < 1e-12
        all_ok &= ok
        print(f"[{tag}] W=v invariant (max|H_scr-H_bare|={inv:.1e}): {'OK' if ok else 'FAIL'}")

        # 2. restricted-production doublet poles subset of spin-orbital spectrum
        poles_rest = np.linalg.eigvalsh(ADCSolverRestricted.from_arrays(eps, eri, level='adc2x').build_supermatrix(nocc))
        maxmis = max(np.min(np.abs(poles_bare - p)) for p in poles_rest)
        ok = maxmis < 1e-8
        all_ok &= ok
        print(f"[{tag}] restricted adc2x poles in SO spectrum (max mismatch={maxmis:.1e}): {'OK' if ok else 'FAIL'}")

        # 3. Hermiticity + 4. screening active
        W = static_screened_coulomb_chemist(eps, eri, nocc)
        H_scr = BuildSuperMatrixADCn(eps_spin, g_spin, nsp,
                                    g_c1=screened_c1_tensor(eri, W, nocc)).build_supermatrix_adc2x()
        herm = np.max(np.abs(H_scr - H_scr.T))
        ok = herm < 1e-12
        all_ok &= ok
        print(f"[{tag}] screened H Hermitian (max asym={herm:.1e}): {'OK' if ok else 'FAIL'}")

        shift = np.max(np.abs(np.linalg.eigvalsh(H_scr) - poles_bare))
        ok = shift > 1e-4          # W != v here, so poles MUST move
        all_ok &= ok
        print(f"[{tag}] screening changes poles (max shift={shift:.3f} Ha): {'OK' if ok else 'FAIL'}")

        # entry-point smoke test
        res = solve_screened_adc(mf, screening='rpa', z_threshold=0.1)
        ok = res['energies'].shape == res['Z'].shape and np.all(res['Z'] <= 1.0 + 1e-8)
        all_ok &= ok
        print(f"[{tag}] solve_screened_adc(level='adc2x') entry ({res['energies'].size} poles Z>0.1): {'OK' if ok else 'FAIL'}")

        # ---- ADC(3) with C^(1) screening (U^(2) vertex always bare) ----
        H3_bare = bare.build_supermatrix_adc3()
        gc1_id = screened_c1_tensor(eri, eri, nocc)
        H3_id = BuildSuperMatrixADCn(eps_spin, g_spin, nsp, g_c1=gc1_id).build_supermatrix_adc3()
        inv3 = np.max(np.abs(H3_id - H3_bare))
        ok = inv3 < 1e-12
        all_ok &= ok
        print(f"[{tag}] adc3 W=v invariant (max|H_scr-H_bare|={inv3:.1e}): {'OK' if ok else 'FAIL'}")

        gc1_s = screened_c1_tensor(eri, W, nocc)
        H3_full = BuildSuperMatrixADCn(eps_spin, g_spin, nsp, g_c1=gc1_s).build_supermatrix_adc3()
        herm3 = np.max(np.abs(H3_full - H3_full.T))
        ok = herm3 < 1e-11
        all_ok &= ok
        print(f"[{tag}] screened adc3 Hermitian (max asym={herm3:.1e}): {'OK' if ok else 'FAIL'}")

        res3 = solve_screened_adc(mf, level='adc3', screening='rpa', z_threshold=0.1)
        ok = res3['energies'].size > 0 and np.all(res3['Z'] <= 1.0 + 1e-8)
        all_ok &= ok
        print(f"[{tag}] solve_screened_adc(level='adc3') entry ({res3['energies'].size} poles Z>0.1): {'OK' if ok else 'FAIL'}")

        # ================= restricted / DF / matrix-free PRODUCTION path (adc2x) =================
        # The restricted C^(1) screening reproduces the spin-orbital screened
        # MCDE exactly; here we check the production build against it and its own
        # DF / matrix-free variants. (adc3 restricted's U^(2) coupling screening
        # is a separate, pending CSF derivation -- not covered here.)
        rest = ADCSolverRestricted.from_arrays(eps, eri, level='adc2x', W_chemist=W)
        Hr = rest.build_supermatrix(nocc)
        # W=v invariant (restricted)
        Hr_id = ADCSolverRestricted.from_arrays(eps, eri, level='adc2x', W_chemist=eri).build_supermatrix(nocc)
        Hr_bare = ADCSolverRestricted.from_arrays(eps, eri, level='adc2x').build_supermatrix(nocc)
        inv_r = np.max(np.abs(Hr_id - Hr_bare))
        ok = inv_r < 1e-11
        all_ok &= ok
        print(f"[{tag}] restricted adc2x W=v invariant (max|dH|={inv_r:.1e}): {'OK' if ok else 'FAIL'}")
        # restricted screened doublet poles are a subset of the spin-orbital screened spectrum
        so_scr = solve_screened_adc(mf, screening='rpa')['energies']
        pr = np.linalg.eigvalsh(Hr)
        maxmis = max(np.min(np.abs(so_scr - p)) for p in pr)
        ok = maxmis < 1e-8
        all_ok &= ok
        print(f"[{tag}] restricted adc2x screened == spin-orbital screened (max mismatch={maxmis:.1e}): {'OK' if ok else 'FAIL'}")
        # matrix-free screened == dense screened
        aop, _, _ = rest.build_matrix_free_operator(nocc)
        rng = np.random.default_rng(0); nHr = Hr.shape[0]
        dmf = max(np.max(np.abs(aop(z := rng.standard_normal(nHr)) - Hr @ z)) for _ in range(3))
        ok = dmf < 1e-8
        all_ok &= ok
        print(f"[{tag}] restricted adc2x matrix-free screened == dense (max diff={dmf:.1e}): {'OK' if ok else 'FAIL'}")
        # DF-exact screened == full-ERI screened (dense build; the matrix-free
        # W_chemist+DF combo is RETIRED -- W_aux is the DF screening, below)
        dfi = DFIntegrals.from_scf(mol, mf, exact=True)
        rest_df = ADCSolverRestricted.from_arrays(eps, eri, level='adc2x', W_chemist=W,
                                                  B_aa=dfi.B_aa, matrix_free=False)
        Hr_df = rest_df.build_supermatrix(nocc)
        ddf = np.max(np.abs(Hr_df - Hr))
        ok = ddf < 1e-8
        all_ok &= ok
        print(f"[{tag}] restricted adc2x DF screened == full-ERI screened (max diff={ddf:.1e}): {'OK' if ok else 'FAIL'}")
        try:
            rest_df.build_matrix_free_operator(nocc)
            ok = False
        except ValueError:
            ok = True
        all_ok &= ok
        print(f"[{tag}] matrix-free W_chemist+DF combo refused (use W_aux): {'OK' if ok else 'FAIL'}")
        # DF-W (memory-lean): screen from B_aa + W_aux metric, never forming the
        # dense W / V^4 g_vvvv. Must reproduce the dense-W screened supermatrix,
        # AND (since the M_aa eigendecomposition made W_aux streamable) build
        # no O^2V^2-shaped integral slice anywhere in the matvec -- checked
        # with the same _g_slice_df spy pattern as test_adc3_df_memory_fix.py.
        w_aux = static_screened_coulomb_aux(eps, dfi.B_aa, nocc)
        _restricted_mod = _SpyTargets()
        O_, norb_ = nocc, len(eps); V_ = norb_ - O_
        banned = {(V_, O_, O_, V_), (V_, O_, V_, O_), (O_, V_, O_, V_),
                  (O_, V_, V_, O_), (O_, O_, V_, V_), (V_, V_, O_, O_)}
        built_shapes = []
        _real_slice = _restricted_mod._g_slice_df
        def _spy_slice(Bx, p, q, r, s):
            out = _real_slice(Bx, p, q, r, s)
            built_shapes.append(out.shape)
            return out
        _restricted_mod._g_slice_df = _spy_slice
        try:
            rest_dfw = ADCSolverRestricted.from_arrays(eps, None, level='adc2x', B_aa=dfi.B_aa, W_aux=w_aux)
            aop_dfw, _, _ = rest_dfw.build_matrix_free_operator(nocc)
            ddfw = max(np.max(np.abs(aop_dfw(z := rng.standard_normal(nHr)) - Hr @ z)) for _ in range(3))
        finally:
            _restricted_mod._g_slice_df = _real_slice
        offenders = [s for s in built_shapes if s in banned]
        ok = ddfw < 1e-8 and not offenders
        all_ok &= ok
        print(f"[{tag}] restricted adc2x DF-W (B.W_aux.B, no V^4) == dense-W screened "
              f"(max diff={ddfw:.1e}), no O^2V^2 slice built ({len(built_shapes)} slices): "
              f"{'OK' if ok else 'FAIL'}" + (f" offenders={offenders}" if offenders else ""))

        # eigh policy: a genuinely indefinite W_aux must raise (RPA
        # instability, fail loud) ...
        w_bad = w_aux.copy()
        lam_b, Q_b = np.linalg.eigh(w_bad)
        lam_b[0] = -0.1
        w_bad = (Q_b * lam_b) @ Q_b.T
        try:
            ADCSolverRestricted.from_arrays(eps, None, level='adc2x', B_aa=dfi.B_aa,
                                W_aux=w_bad).build_matrix_free_operator(nocc)
            ok = False
        except ValueError as e:
            ok = 'RPA instability' in str(e)
        all_ok &= ok
        print(f"[{tag}] indefinite W_aux raises ValueError (RPA instability): {'OK' if ok else 'FAIL'}")

        # ... while a noise-level negative eigenvalue in [-tol, 0) is clipped
        # to zero and the solve proceeds. Reference: the SAME waux with that
        # mode set to exactly zero (PSD-singular -- the case plain Cholesky
        # would already crash on), expanded to the dense W it represents.
        lam_n, Q_n = np.linalg.eigh(w_aux)
        i0 = int(np.argmin(lam_n))
        lam_zero = lam_n.copy(); lam_zero[i0] = 0.0
        w_zero = (Q_n * lam_zero) @ Q_n.T
        Wp_zero = np.einsum('Ppr,PQ,Qqs->pqrs', dfi.B_aa, w_zero, dfi.B_aa, optimize=True)
        Hr_zero = ADCSolverRestricted.from_arrays(eps, eri, level='adc2x',
                                      W_chemist=Wp_zero.transpose(0, 2, 1, 3)).build_supermatrix(nocc)
        lam_noise = lam_n.copy(); lam_noise[i0] = -1e-12
        w_noise = (Q_n * lam_noise) @ Q_n.T
        aop_n, _, _ = ADCSolverRestricted.from_arrays(eps, None, level='adc2x', B_aa=dfi.B_aa,
                                          W_aux=w_noise).build_matrix_free_operator(nocc)
        dn = np.max(np.abs(aop_n(z := rng.standard_normal(nHr)) - Hr_zero @ z))
        ok = dn < 1e-6
        all_ok &= ok
        print(f"[{tag}] noise-negative W_aux eigenvalue clipped to zero-mode W "
              f"(max diff={dn:.1e}): {'OK' if ok else 'FAIL'}")

    print("\nALL PASSED" if all_ok else "\nFAILURES DETECTED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
