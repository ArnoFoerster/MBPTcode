"""Hand-written non-Dyson DF ADC(3) (adc_r_nondyson_df) against the generated
intermediate-state route (nondyson_restricted) and against pyscf.adc.

The DF factor is an exact factorization of the MO integrals (no fitting
error), so every route sees the same Hamiltonian. Gates on LiH and H2O in
sto-3g, H2O in 6-31g and NH3 in cc-pVDZ, both sectors:
  1. every eigenvalue of the hand-written operator is an eigenvalue of the
     generated one (which also holds the quartet 2h1p/2p1h states the CSF
     layout leaves out, so its lowest roots may include a quartet);
  2. the static orbital block M equals pyscf's M_ij (IP) / M_ab (EA);
  3. the lowest root equals pyscf's non-Dyson ADC(3) root;
  4. the operator is symmetric.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
import pytest
from pyscf import adc, ao2mo, gto, scf
from pyscf.adc import radc_ea, radc_ip

from src.Base.pyscf.pyscf_interface import get_orbital_energies
from src.SingleReference.ADC import ADCSolver, ADCSolverRestricted, build_static_correction
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.SingleReference.ADC.adc_r_nondyson_df import build_operator
from src.SingleReference.ADC.nondyson_restricted import NonDysonRestricted
from tests.generated_runtime import requires_runtime

SYSTEMS = [('LiH', 'Li 0 0 0; H 0 0 1.6', 'sto-3g'),
           ('H2O', 'O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g'),
           ('H2O', 'O 0 0 0; H 0 0 0.96; H 0.96 0 0', '6-31g'),
           ('NH3', 'N 0 0 0.1; H 0.94 0 -0.25; H -0.47 0.81 -0.25; H -0.47 -0.81 -0.25',
            'cc-pvdz')]
TOL = 1e-10          # same Hamiltonian, dense eigensolves
TOL_PYSCF = 1e-7     # pyscf's Davidson (its default convergence)


def _setup(atom, basis):
    mol = gto.M(atom=atom, basis=basis, verbose=0)
    mf = scf.RHF(mol).run(conv_tol=1e-12)
    eps = get_orbital_energies(mf, representation='spatial')
    nocc, n = mol.nelectron // 2, len(eps)
    eri = ao2mo.restore(1, ao2mo.kernel(mol, mf.mo_coeff), n).reshape(n * n, n * n)
    w, V = np.linalg.eigh(eri)
    keep = w > 1e-14 * w.max()
    B = (np.sqrt(w[keep]) * V[:, keep]).T.reshape(-1, n, n)
    s = ADCSolverRestricted.from_arrays(eps, B_aa=B, nocc=nocc, level="adc3")
    sc = build_static_correction(mf, kind='mp2_unrelaxed', B_aa=B)
    return mf, eps, nocc, B, s, sc


def _dense(apply, n):
    return np.column_stack([apply(e) for e in np.eye(n)])


@requires_runtime(3)
@pytest.mark.parametrize('label,atom,basis', SYSTEMS)
@pytest.mark.parametrize('sector', ['IP', 'EA'])
def test_handwritten_matches_generated_and_pyscf(label, atom, basis, sector):
    mf, eps, nocc, B, s, sc = _setup(atom, basis)
    aop, diag, d = build_operator(s, nocc, sector, sc)
    H = _dense(aop, diag.size)
    asym = float(np.max(np.abs(H - H.T)))
    assert asym < TOL
    w = np.linalg.eigvalsh(0.5 * (H + H.T))

    r = BuildSuperMatrixADCnRestricted(eps, None, None, None, nocc, B_aa=B)
    op, _ = NonDysonRestricted(r, sector).operator(3)
    Hg = _dense(op.matvec, op.shape[0])
    wg = np.linalg.eigvalsh(0.5 * (Hg + Hg.T))
    in_gen = float(max(np.min(np.abs(wg - x)) for x in w))

    a = adc.ADC(mf)
    a.method = 'adc(3)'
    a.kernel_gs()
    eris = a.transform_integrals()
    M_ref = (radc_ip.RADCIP(a) if sector == 'IP' else radc_ea.RADCEA(a)).get_imds(eris)
    dM = float(np.max(np.abs(d['M'] - M_ref)))
    a.method_type = sector.lower()
    e_py = a.kernel(nroots=1)[0][0]
    dpy = abs(w[0] - e_py)         # pyscf reports E(N-1) - E0 and E(N+1) - E0 as well
    print(f"{label}/{basis} {sector}: dim {H.shape[0]} (generated {Hg.shape[0]}), "
          f"hand roots in generated spectrum {in_gen:.1e}, "
          f"|M - M_pyscf| {dM:.1e}, lowest vs pyscf {dpy:.1e}, asymmetry {asym:.1e}")
    assert in_gen < TOL
    assert dM < TOL
    assert dpy < TOL_PYSCF


def test_refuses_non_df_and_dressed():
    mol = gto.M(atom='Li 0 0 0; H 0 0 1.6', basis='sto-3g', verbose=0)
    mf = scf.RHF(mol).run()
    with pytest.raises(ValueError, match='DF solver'):
        build_operator(ADCSolver(mf, level='adc3'), 2, 'IP')
    with pytest.raises(ValueError, match='sector'):
        build_operator(ADCSolver(mf, level='adc3'), 2, 'EE')
