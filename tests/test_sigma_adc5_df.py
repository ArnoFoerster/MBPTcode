"""The ADC(5) two-sector operator off the RI factor alone.

restricted_dyson_operator picks the *_df apply twins whenever the caller
supplies B_aa, so a solver constructed without the dense g never has one
asked of it. The ADC(4) blocks did this already; the five ADC(5) modules
(C^(3), U^(3)_k2, C^(1,2), S^(1,2) and the k2 self-block) took the dense
modules unconditionally, which made DF at that level a matvec-only saving.

With an EXACT RI factor (naux = norb^2, no fitting error) the two operators
are the same linear map, so the check is a matvec on random trial vectors --
the ADC(5) matvec carries the matrix-free U^(4) and C^(3), so forming the
whole matrix to compare spectra costs hundreds of them for nothing the
matvec identity does not already prove.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
import pytest
from pyscf import gto, scf

from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.SingleReference.ADC.sigma_driver import restricted_dyson_operator
from src.Base.pyscf.pyscf_interface import (get_orbital_energies,
                                            get_antisymmetrized_spin_block_eri,
                                            get_density_fitting_coefficients)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(5)

SYSTEMS = [('LiH/sto-3g', 'Li 0 0 0; H 0 0 1.6'),
           ('H2O/sto-3g', 'O 0 0 0; H 0 0 0.96; H 0.96 0 0')]
LEVELS = ['adc4', 'adc5']
NVEC = 3
TOL = 1e-10


def _solver(atom):
    mol = gto.M(atom=atom, basis='sto-3g', verbose=0)
    mf = scf.RHF(mol)
    mf.conv_tol = 1e-13
    mf.run()
    eps = get_orbital_energies(mf, representation='spatial')
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
    B = get_density_fitting_coefficients(mol, mf)
    r = BuildSuperMatrixADCnRestricted(eps, ga, gab, gb, mol.nelectron // 2)
    return r, B


@pytest.mark.parametrize('label,atom', SYSTEMS)
@pytest.mark.parametrize('level', LEVELS)
def test_df_operator_equals_dense(label, atom, level):
    r, B = _solver(atom)
    op_dense, diag_dense = restricted_dyson_operator(r, level, construction='twosector')
    op_df, diag_df = restricted_dyson_operator(r, level,
                                               extra_leaves={'B_aa': B, 'B_bb': B},
                                               construction='twosector')
    assert op_df.shape == op_dense.shape
    d_diag = float(np.max(np.abs(diag_df - diag_dense)))
    rng = np.random.default_rng(0)
    worst = scale = 0.0
    for _ in range(NVEC):
        v = rng.standard_normal(op_dense.shape[0])
        y_dense, y_df = op_dense.matvec(v), op_df.matvec(v)
        worst = max(worst, float(np.max(np.abs(y_df - y_dense))))
        scale = max(scale, float(np.max(np.abs(y_dense))))
    print(f"{label} {level}: dim {op_dense.shape[0]}, exact-DF vs dense matvec "
          f"{worst:.2e} (|y| up to {scale:.3e}), K diagonal {d_diag:.2e}")
    assert scale > 1.0
    assert worst <= TOL, worst
    assert d_diag <= TOL


def main():
    for label, atom in SYSTEMS:
        for level in LEVELS:
            test_df_operator_equals_dense(label, atom, level)
    print('\nALL OK')
    return True


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
