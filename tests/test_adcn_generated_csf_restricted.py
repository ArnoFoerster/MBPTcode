"""Increment 5 gate of the spin-free ADC(2)-(5) plan
wire the restricted
(spin-blocked, spatial) ADC blocks into spin_adapt.py's NUMERICAL
doublet-CSF isometry T (no hand CSF formulas). The restricted alpha-Dyson
sector configs ARE the kept-Sz rows T touches, so
BuildSuperMatrixADCnRestricted.build_csf_supermatrix sandwiches the spatial
blocks with T[alpha rows] to produce the CSF-basis supermatrix.

Two checks:
1. The CSF ADC(3) supermatrix (undisputed U^(2)/C^(1)/K physics) built from
   the restricted spatial blocks reproduces the PRODUCTION CSF ADC(3)
   (spin_adapt.ADCSolverCSF.build_supermatrix) pole-for-pole -- end-to-end
   validation of the wiring against the shipped code.
2. The CSF C^(2) and U^(3) arbiter blocks built from the restricted spatial
   blocks equal the spin-orbital GENERATED C^(2)/U^(3) lifted through the
   SAME T. This is the payoff: the CSF route now carries the lambda-oracle-
   validated GENERATED arbiter blocks (not the rejected SCW83 B7/B3 that
   ADCSolverCSF's wrapped spin-orbital solver still uses) -- so
   build_csf_supermatrix('adc4_base'/'adc4') deliberately DIFFERS from
   ADCSolverCSF's _M_SD_* there.

LiH/sto-3g and H2O/sto-3g.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.SingleReference.ADC import ADCSolverUnrestricted
from src.SingleReference.ADC.adc_autogenerated import (
    BuildSuperMatrixADCn, BuildSuperMatrixADCnRestricted)
from src.SingleReference.ADC.spin_adapt import build_T, ADCSolverCSF
from src.Base.pyscf.pyscf_interface import (
    get_orbital_energies, get_two_electron_integrals_chemist,
    get_antisymmetrized_spin_eri, get_antisymmetrized_spin_block_eri)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)


def check(label, diff, tol=1e-11):
    ok = diff < tol
    print(f"[{'OK' if ok else 'FAIL'}] {label}: {diff:.3e}")
    return ok


def main():
    all_ok = True

    for atom, basis, label in [
        ('Li 0 0 0; H 0 0 1.6', 'sto-3g', 'LiH/sto-3g'),
        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g'),
    ]:
        mol = gto.M(atom=atom, basis=basis, verbose=0)
        mf = scf.RHF(mol).run()
        nocc_sp = mol.nelectron // 2
        nocc = 2 * nocc_sp
        eps = get_orbital_energies(mf, representation='spin')
        eri = get_two_electron_integrals_chemist(mol, mf, representation='spatial')
        g = get_antisymmetrized_spin_eri(eri)
        so = BuildSuperMatrixADCn(eps, g, nocc)

        eps_sp = get_orbital_energies(mf, representation='spatial')
        g_aaaa, g_bbbb, g_abab = get_antisymmetrized_spin_block_eri(mol, mf)
        r = BuildSuperMatrixADCnRestricted(eps_sp, g_aaaa, g_abab, g_bbbb, nocc_sp)

        spin_solver = ADCSolverUnrestricted.from_arrays(eps, g)
        T = build_T(spin_solver, nocc)
        csf = ADCSolverCSF(spin_solver)

        print(f"\n=== {label} ===")

        # 1. CSF ADC(3) from restricted == production ADCSolverCSF
        e_r = np.linalg.eigvalsh(r.build_csf_supermatrix(T, 'adc3'))
        e_prod = np.linalg.eigvalsh(csf.build_supermatrix(nocc))
        all_ok &= check("CSF ADC(3) from restricted == ADCSolverCSF poles",
                        np.abs(np.sort(e_r) - np.sort(e_prod)).max(), tol=1e-9)

        # 2. CSF C^(2)/U^(3) arbiter blocks == spin-orbital GENERATED, lifted
        for sector, key in (('IP', '2h1p'), ('EA', '2p1h')):
            Ta = r._T_alpha(T, sector)
            Tfull = np.asarray(T[key].todense())
            c2r = Ta.T @ r.c2_block_generated(sector) @ Ta
            c2g = Tfull.T @ so.c2_block_generated(sector) @ Tfull
            all_ok &= check(f"CSF C^(2) {sector} restricted == generated-lifted",
                            np.abs(c2r - c2g).max())

        Ta = r._T_alpha(T, 'EA')
        Tfull = np.asarray(T['2p1h'].todense())
        Torb = np.asarray(T['orb'].todense())
        u3r = r.u3_generated('EA').T @ Ta
        u3g = Torb.T @ so.u3_generated('EA').T @ Tfull
        all_ok &= check("CSF U^(3) restricted == generated-lifted",
                        np.abs(u3r - u3g).max())

    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
