"""Production union-space and diagrammatic ADC(4) against the lambda oracle.

Both constructions are the two-sector ISR-ADC(4) supermatrix plus one object
built from the generated 2h1p x 2p1h cross block X^(2): the block itself
(construction='union') or its order-3 image on the k1 couplings
(construction='diagrammatic', cross_block_decoupling). Gates, on linear H4
(r = 1.0) and LiH in sto-3g with the SCF converged to the f[o,v] floor,
against the union-space oracle (tests/union_space_oracle.py):

  1. static self-energy: the production Sigma(inf) through order 4 (v times
     the second- plus third-order RSPT density, dense spin-orbital) equals the
     oracle's orbital-block series summed through order 4;
  2. every production supermatrix is symmetric;
  3. the principal IP/EA poles of the spin-orbital production supermatrix
     (sigma_driver.build_sigma_operator, dense through matvecs) equal the oracle's
     poles at lambda = 1 for the same construction (SeriesFold at rule orders,
     decouple_cross_blocks for the diagrammatic form);
  4. the restricted production operator (sigma_driver.restricted_dyson_operator
     with construction=...) gives the same principal poles;
  5. the decoupled rows of the production block equal the emitted delta-U3
     rows (delta_u3_dressing, dense twin) and the general series decoupling;
  6. on rectangular H4 the block vanishes by symmetry (to the arithmetic
     floor) and the union and diagrammatic supermatrices and poles equal the
     two-sector ones to that floor;
  7. the restricted solver class runs the union construction end to end
     (Davidson downfold) to the dense union pole.
"""
