pytestmark = requires_runtime(4)

SYSTEMS = ['H4lin_r1.0', 'LiH']
NORD = 5                     # series orders 0..4: everything ADC(4) carries
NSTATES = 3
TOL_STATIC = 1e-12
TOL_SYM = 1e-12
TOL_POLE = 1e-10
TOL_ROWS = 1e-12
TOL_SERIES = 1e-13
TOL_E2E = 1e-6               # Davidson downfold tolerance of the solver route
_CACHE = {}


def _exact_static(eps, g, nocc):
    """Sigma(inf) through fourth order: v contracted with the exact
    second- plus third-order RSPT density (dense spin-orbital)."""
    norb = len(eps)
    mpn = MPnDensityDriver(eps, g, nocc)
    oo2, ov2, vv2 = mpn.compute_delta_gamma2()
    oo3, ov3, vv3 = mpn.compute_delta_gamma3()
    o, v = slice(0, nocc), slice(nocc, norb)
    dg = np.zeros((norb, norb))
    dg[o, o] = oo2 + oo3
    dg[o, v] = ov2 + ov3
    dg[v, o] = (ov2 + ov3).T
    dg[v, v] = vv2 + vv3
    return np.einsum('prqs,rs->pq', g, dg)


def _dense(op):
    n = op.shape[0]
    return np.column_stack([op.matvec(e) for e in np.eye(n)])


def _principal(M, norb):
    """Principal IP/EA poles (strength > PRINCIPAL_STRENGTH) of a symmetric supermatrix."""
    asym = float(np.max(np.abs(M - M.T)))
    w, V = np.linalg.eigh(0.5 * (M + M.T))
    strength = np.sum(V[:norb] ** 2, axis=0)
    ip, ips = CB.principal_poles(w, strength, -1, NSTATES)
    ea, eas = CB.principal_poles(w, strength, +1, NSTATES)
    return dict(ip=ip, ea=ea, ip_strength=ips, ea_strength=eas, asym=asym)


def _pole_diff(a, b):
    """Largest |difference| over the recorded (non-nan) IP and EA poles."""
    d = 0.0
    for key in ('ip', 'ea'):
        for x, y in zip(a[key], b[key]):
            if np.isnan(x) and np.isnan(y):
                continue
            d = max(d, abs(x - y))
    return d


def _alpha_indices(nocc, norb):
    """Alpha spin orbitals of the occupied-first layout [occ_a, occ_b, vir_a, vir_b]."""
    no_sp, nv_sp = nocc // 2, (norb - nocc) // 2
    return list(range(no_sp)) + list(range(nocc, nocc + nv_sp))


def _data(name):
    if name in _CACHE:
        return _CACHE[name]
    sysd = CB.build_system(name)
    eps, g, nocc, norb = sysd['eps'], sysd['g'], sysd['nocc'], sysd['norb']
    us = CB.UnionSpace(sysd)
    psi, E, nser = us.rspt_series(NORD)
    Ssr, Msr = us.series_matrices(psi, E, nser, NORD)
    orb = us.idx[(0, 'o')]
    F = [Msr[k][np.ix_(orb, orb)] for k in range(NORD)]
    sf = {'union': CB.SeriesFold(us, Ssr, Msr, NORD, 'union', us.kmax),
          'twosector': CB.SeriesFold(us, Ssr, Msr, NORD, 'twosector', us.kmax)}
    Bp, Dp, _, resid = CB.decouple_cross_blocks(sf['union'], NORD)
    sf['diagrammatic'] = copy.copy(sf['union'])
    sf['diagrammatic'].B, sf['diagrammatic'].D = Bp, Dp
    oracle = {}
    for mode in CONSTRUCTIONS:
        B, D = sf[mode].truncated(CB.adc_rule(4), kcap=2)
        keep = sf[mode].kseg <= 2
        Bs = sum(B)[:, keep]
        Ds = sum(D)[np.ix_(keep, keep)]
        Fs = sum(F)
        oracle[mode] = _principal(np.block([[Fs, Bs], [Bs.T, Ds]]), norb)
    static = _exact_static(eps, g, nocc)
    shim = types.SimpleNamespace(eps=eps, g=g, norb=norb)
    prod = {}
    for c in CONSTRUCTIONS:
        op, _, _ = build_sigma_operator(shim, nocc, 'adc4', static_correction=static,
                                        construction=c)
        prod[c] = _dense(op)
    d = dict(sysd=sysd, eps=eps, g=g, nocc=nocc, norb=norb, F=F, oracle=oracle,
             static=static, prod=prod, decouple_resid=resid)
    _CACHE[name] = d
    return d


@pytest.mark.parametrize('name', SYSTEMS)
def test_static_self_energy_matches_oracle_series(name):
    d = _data(name)
    ref = sum(d['F'][k] for k in range(NORD)) - np.diag(d['eps'])
    diff = float(np.max(np.abs(d['static'] - ref)))
    print(f"{name}: |Sigma_inf(v.dgamma2+3) - oracle F-series| = {diff:.2e} "
          f"(|Sigma_inf| = {float(np.max(np.abs(ref))):.3e}, f_ov {d['sysd']['f_ov']:.1e})")
    assert diff <= TOL_STATIC, diff


@pytest.mark.parametrize('name', SYSTEMS)
@pytest.mark.parametrize('construction', CONSTRUCTIONS)
def test_production_poles_match_oracle(name, construction):
    d = _data(name)
    norb = d['norb']
    mine = _principal(d['prod'][construction], norb)
    ref = d['oracle'][construction]
    diff = _pole_diff(mine, ref)
    print(f"{name} {construction}: symmetry {mine['asym']:.1e}; IP {mine['ip']} "
          f"EA {mine['ea']}; |prod - oracle| = {diff:.2e} "
          f"(decoupling residual {d['decouple_resid']:.1e})")
    assert mine['asym'] <= TOL_SYM, mine['asym']
    assert diff <= TOL_POLE, diff


@pytest.mark.parametrize('name', SYSTEMS)
@pytest.mark.parametrize('construction', CONSTRUCTIONS)
def test_restricted_operator_matches_spin_orbital(name, construction):
    d = _data(name)
    nocc, norb = d['nocc'], d['norb']
    mol, mf = d['sysd']['mol'], d['sysd']['mf']
    eps_sp = get_orbital_energies(mf, representation='spatial')
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
    r = BuildSuperMatrixADCnRestricted(eps_sp, ga, gab, gb, nocc // 2)
    alpha = _alpha_indices(nocc, norb)
    f_orb = np.diag(eps_sp) + d['static'][np.ix_(alpha, alpha)]
    op, _ = restricted_dyson_operator(r, 'adc4', f_orb=f_orb, construction=construction)
    mine = _principal(_dense(op), len(eps_sp))
    ref = _principal(d['prod'][construction], norb)
    diff = _pole_diff(mine, ref)
    print(f"{name} {construction}: restricted symmetry {mine['asym']:.1e}; "
          f"|restricted - spin-orbital| = {diff:.2e}")
    assert mine['asym'] <= TOL_SYM, mine['asym']
    assert diff <= TOL_POLE, diff


@pytest.mark.parametrize('name', SYSTEMS)
def test_decoupled_rows_equal_delta_u3_and_series(name):
    d = _data(name)
    eps, g, nocc, norb = d['eps'], d['g'], d['nocc'], d['norb']
    gen = BuildSuperMatrixADCn(eps, g, nocc)
    X = gen.cross_block_generated(2)
    u1_ip, u1_ea = gen.u_2h1p(), gen.u_2p1h()
    k_ip, k_ea = diag_K(eps, nocc, norb, 'IP'), diag_K(eps, nocc, norb, 'EA')
    du_ip, du_ea = delta_u_rows_k1(u1_ip, u1_ea, k_ip, k_ea, X)
    ref_ip, ref_ea = delta_u3_rows(eps, g, nocc, mode='dense')
    d_rows = max(float(np.max(np.abs(du_ip - ref_ip))), float(np.max(np.abs(du_ea - ref_ea))))
    scale = max(float(np.max(np.abs(ref_ip))), float(np.max(np.abs(ref_ea))))
    # the general series decoupling at n = 4: B^(1) = [U1_D | U1_C], D^(0) = K, D^(2) = X
    nI, nE = len(k_ip), len(k_ea)
    n = nI + nE
    B = [np.zeros((norb, n)) for _ in range(4)]
    B[1] = np.hstack([u1_ip.T, u1_ea.T])
    D = [np.zeros((n, n)) for _ in range(4)]
    D[0] = np.diag(np.concatenate([k_ip, k_ea]))
    D[2][:nI, nI:] = X
    D[2][nI:, :nI] = X.T
    cross = np.zeros((n, n), dtype=bool)
    cross[:nI, nI:] = True
    cross[nI:, :nI] = True
    Bp, Dp, _, resid = decouple_cross_blocks(B, D, cross, 4)
    du_gen = Bp[3] - B[3]
    d_series = max(float(np.max(np.abs(du_gen[:, :nI].T - du_ip))),
                   float(np.max(np.abs(du_gen[:, nI:].T - du_ea))))
    same_sector_shift = float(np.max(np.abs(Dp[2][~cross] - D[2][~cross])))
    print(f"{name}: rows vs emitted delta-U3 {d_rows:.2e} (|rows| {scale:.3e}); closed form "
          f"vs series {d_series:.2e}; residual cross content {resid:.1e}; same-sector "
          f"order-2 shift {same_sector_shift:.1e}")
    assert scale > 1e-4
    assert d_rows <= TOL_ROWS, d_rows
    assert d_series <= TOL_SERIES, d_series
    assert resid <= TOL_SERIES and same_sector_shift <= TOL_SERIES


def test_symmetry_zero_system_union_equals_two_sector():
    sysd = CB.build_system('H4rect')
    eps, g, nocc, norb = sysd['eps'], sysd['g'], sysd['nocc'], sysd['norb']
    X = BuildSuperMatrixADCn(eps, g, nocc).cross_block_generated(2)
    shim = types.SimpleNamespace(eps=eps, g=g, norb=norb)
    static = _exact_static(eps, g, nocc)
    M = {}
    for c in ('twosector', 'union', 'diagrammatic'):
        op, _, _ = build_sigma_operator(shim, nocc, 'adc4', static_correction=static,
                                        construction=c)
        M[c] = _dense(op)
    # the block is zero to the arithmetic floor (not an exact zero), so the
    # union and diagrammatic supermatrices differ from the two-sector one by
    # that floor only; the poles must be unchanged to the same floor
    d_union = float(np.max(np.abs(M['union'] - M['twosector'])))
    d_diag = float(np.max(np.abs(M['diagrammatic'] - M['twosector'])))
    poles = {c: _principal(M[c], norb) for c in M}
    dp = max(_pole_diff(poles['union'], poles['twosector']),
             _pole_diff(poles['diagrammatic'], poles['twosector']))
    print(f"H4rect: |X2| = {float(np.max(np.abs(X))):.1e}; |union - two-sector| = {d_union:.1e}, "
          f"|diagrammatic - two-sector| = {d_diag:.1e}; poles differ by {dp:.1e}")
    assert float(np.max(np.abs(X))) <= 1e-14
    assert d_union <= 1e-14 and d_diag <= 1e-14, (d_union, d_diag)
    assert dp <= 1e-13, dp


def test_restricted_solver_union_end_to_end():
    d = _data('H4lin_r1.0')
    nocc, norb = d['nocc'], d['norb']
    mol, mf = d['sysd']['mol'], d['sysd']['mf']
    alpha = _alpha_indices(nocc, norb)
    static_sp = d['static'][np.ix_(alpha, alpha)]
    ref = _principal(d['prod']['union'], norb)
    solver = ADCSolverRestricted(mf, mol=mol, level='adc4', pdaggerq=True,
                                 construction='union')
    e, _ = solver.solve(static_correction=static_sp, homo_index=nocc // 2 - 1)
    diff = abs(float(e[0]) - ref['ip'][0])
    print(f"H4lin_r1.0: solver union IP1 {float(e[0]):.10f} vs dense {ref['ip'][0]:.10f} "
          f"({diff:.1e})")
    assert diff <= TOL_E2E, diff


