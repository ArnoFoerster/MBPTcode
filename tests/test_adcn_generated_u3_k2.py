"""Gate for the ADC(5) orbital<->k=2 order-3 coupling U^(3)_3h2p/3p2h and the
cross-class overlap S_{k1,k2}.

`adc_order_rule.block_order(n, 0, 2)` is 2 at ADC(4) and **3 at ADC(5)**, so
the orbital<->k2 coupling needs its order-3 layer there; only the order-2 twin
(u2_k2_generated) existed. Two structurally new things enter at this order,
and both are exercised here:

1. The k=2 element has a NONZERO order-1 gauge layer (raw^(1) = u1_v +
   l2f(l2^(1)) == eps_p * S^(1), annihilated by the class-GS), so the order-3
   assembly carries an N^(2) normalization against it -- unlike k=1, where
   raw^(1) = U^(1) and S^(1) = 0. The undressed u1_v element (2 terms) was
   emitted for exactly this; generate_adc4_base_k2's "U^(1)_k2 = 0 by operator
   counting" is true of the EFFECTIVE coupling only.
2. The sequential class-GS orthogonalizes k=2 against the k=1 effective
   states, so the effective U^(3)_k2 contains -S12^(2).T @ U^(1) through the
   cross-class overlap S_{k1,k2} -- the object the per-class ISR assembly
   NEVER formed (nonzero from order 2,
   |S|~9.77e-04 on H4). Dropping it would miss ~1.4e-04 on H4 -- 1400x the
   physics gate -- so the gate genuinely discriminates.

Checks
------
1. **CONTROL (hard):** the order-2 coupling re-derived through the SAME
   order-rule pipeline (_k2_raw_S) == u2_k2_generated at 0.0e+00 exactly,
   both sectors, H4 + LiH. If this fails nothing else means anything.
2. **GAUGE:** raw^(1) == eps_p S^(1) on the generated tensors (machine zero)
   -- the class-GS annihilation of the order-1 layer, and a free check on the
   newly emitted u1_v element.
3. **TASK B physics:** cross_class_overlap(sector, n) == the exact-ISR
   cross-class METRIC block Smet[n][k1,k2] for n = 2, 3, both sectors, at
   < 1e-6 (measured ~6e-10, the SCF floor).
4. **TASK A physics:** u3_k2_generated == _K2_CLASS_SIGN * (exact-ISR
   (orb,k2) order-3 block).T from the determinant-space machinery
   (exact_isr_full_fold's construction, local copy u3k2_isrlib), both
   sectors, at < 1e-6 (measured ~1.1e-10).

Checks 3/4 need validation/lambda_oracle (git-ignored); they SKIP with a
notice when it is absent, exactly as test_adcn_generated_c3 does. The
orientation caveat is handled once and pinned: the exact machinery's k=2
config phases (class_configs + apply_ops) equal the RAW precursor convention,
i.e. u2_k2_generated == _K2_CLASS_SIGN * exact.T at 1e-16 (measured in the
recon that fixed this test's signs).
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf, ao2mo

from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCn
from src.SingleReference.ADC.adc_order_rule import block_order
from src.Base.pyscf.pyscf_interface import (get_orbital_energies,
                                            get_antisymmetrized_spin_integrals)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(5)

H4_ATOM = 'H 0 0 0; H 0 0 0.80; H 0 0 1.75; H 0 0 2.60'
SYSTEMS = [('H4/sto-3g', H4_ATOM), ('LiH/sto-3g', 'Li 0 0 0; H 0 0 1.6')]


def _build(atom):
    mol = gto.M(atom=atom, basis='sto-3g', verbose=0)
    mf = scf.RHF(mol)
    mf.conv_tol = 1e-13
    mf.run()
    n = mf.mo_coeff.shape[1]
    eri = ao2mo.kernel(mol, mf.mo_coeff, compact=False).reshape(n, n, n, n)
    h1_mo = mf.mo_coeff.T @ (mol.intor('int1e_kin')
                             + mol.intor('int1e_nuc')) @ mf.mo_coeff
    h1, g = get_antisymmetrized_spin_integrals(h1_mo, eri)
    return get_orbital_energies(mf, representation='spin'), g, mol.nelectron


def _check(ok, msg):
    print(f"[{'OK' if ok else 'FAIL'}] {msg}")
    return ok


def main():
    all_ok = True

    print("=== order rule: the block this test gates ===")
    all_ok &= _check(block_order(4, 0, 2) == 2 and block_order(5, 0, 2) == 3,
                     "orb<->k2 coupling order is 2 at ADC(4) (u2_k2_generated) "
                     "and 3 at ADC(5) (u3_k2_generated)")

    # ---------------- control + gauge (no oracle needed) ----------------
    for label, atom in SYSTEMS:
        eps, g, nocc = _build(atom)
        gen = BuildSuperMatrixADCn(eps, g, nocc)
        print(f"\n=== {label} ===")
        for sec in ('IP', 'EA'):
            sign = gen._K2_CLASS_SIGN[sec]

            raw2, S2 = gen._k2_raw_S(sec, 2)
            u2_re = sign * (raw2 - gen.eps[None, :] * S2)
            d = np.max(np.abs(u2_re - gen.u2_k2_generated(sec)))
            all_ok &= _check(d == 0.0,
                             f"{sec} CONTROL: order-2 re-derived through the "
                             f"order-rule pipeline == u2_k2_generated ({d:.1e})")

            raw1, S1 = gen._k2_raw_S(sec, 1)
            dg = np.max(np.abs(raw1 - gen.eps[None, :] * S1))
            all_ok &= _check(dg < 1e-12,
                             f"{sec} GAUGE: raw^(1) == eps_p S^(1) ({dg:.1e}, "
                             f"|raw1|={np.max(np.abs(raw1)):.2e}) -- the "
                             f"class-GS-annihilated order-1 layer")

            # the deliverables at least evaluate and are nonzero
            u3 = gen.u3_k2_generated(sec)
            s12 = gen.cross_class_overlap(sec, 2)
            all_ok &= _check(np.max(np.abs(u3)) > 1e-6
                             and np.max(np.abs(s12)) > 1e-9,
                             f"{sec} U^(3)_k2 and S_k1k2 nonzero "
                             f"(|U3_k2|={np.max(np.abs(u3)):.2e}, "
                             f"|S12^(2)|={np.max(np.abs(s12)):.2e})")

    # ---------------- exact-ISR physics gates (oracle-scale, H4) ----------------
    oracle_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), '..',
                                              'validation', 'lambda_oracle'))
    sys.path.insert(0, oracle_dir)
    try:
        from derive_c2_u3 import build_system
        from lambda_oracle import LambdaSelfEnergyOracle
        from u3k2_isrlib import build_sector, isr_orthonormalize
    except ImportError:
        print("\nSKIP: validation/lambda_oracle not present (git-ignored); "
              "exact-ISR physics gates for U^(3)_k2 / S_k1k2 not run")
        print('\nALL OK' if all_ok else '\nFAILURES')
        return all_ok

    eps, h1, g, nocc = build_system(H4_ATOM, 'sto-3g', 0)
    orc = LambdaSelfEnergyOracle(eps, h1, g, nocc)
    gen = BuildSuperMatrixADCn(eps, g, nocc)
    print("\n=== H4 exact-ISR physics gates (determinant space) ===")
    for sec in ('IP', 'EA'):
        Hs, Sm, slices, _ = build_sector(orc, eps, nocc, len(eps), sec, 2)
        blocks = isr_orthonormalize(Hs, Sm, slices)
        so, s1_, s2_ = slices
        sign = gen._K2_CLASS_SIGN[sec]

        for n in (2, 3):
            dn = np.max(np.abs(gen.cross_class_overlap(sec, n)
                               - Sm[n][s1_, s2_]))
            all_ok &= _check(dn < 1e-6,
                             f"{sec} TASK B: S_k1k2 order {n} == exact metric "
                             f"block ({dn:.2e})")

        u3g = gen.u3_k2_generated(sec)
        tgt = sign * blocks[(0, 2)][3].T
        da = np.max(np.abs(u3g - tgt))
        all_ok &= _check(da < 1e-6,
                         f"{sec} TASK A: u3_k2_generated == exact-ISR (orb,k2) "
                         f"order-3 block ({da:.2e})")

        # order-2 cross-check of the SAME exact machinery (orientation pin)
        d2 = np.max(np.abs(gen.u2_k2_generated(sec) - sign * blocks[(0, 2)][2].T))
        all_ok &= _check(d2 < 1e-8,
                         f"{sec} orientation pin: u2_k2_generated == exact-ISR "
                         f"order-2 block ({d2:.2e})")

    print('\nALL OK' if all_ok else '\nFAILURES')
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
