"""Production ADC(5) against the lambda oracle's two-sector ADC(5).

The oracle builds the same theory in the determinant space: RSPT series,
class Gram-Schmidt plus Loewdin orthonormalization as series, the manifold
rule, and the two-sector convention that deletes the D x C blocks. Its
supermatrix at n = 5 is therefore what the generated ADC(5) must reproduce,
given the orbital block its order demands -- Sigma(infinity) through order 5,
i.e. the MP4 density (build_mp4_static_correction_restricted).

On linear H4 the whole spectrum is compared (the operator is small enough to
form); on LiH the production Davidson root-following gives the first
ionization potential, the quantity a run actually reports. Both systems are
free of the MAX_RANK=4 amplitude truncation by orbital count, so ADC(5) here
is exact through lambda^5 and any deviation is a defect, not an approximation.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
import pytest

from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.SingleReference.ADC.sigma_driver import restricted_dyson_operator, solve_dyson_adc
from src.SingleReference.ADC.static_correction import build_mp4_static_correction_restricted
from src.Base.pyscf.pyscf_interface import (get_orbital_energies,
                                            get_antisymmetrized_spin_block_eri)
from tests.generated_runtime import requires_runtime
from tests import union_space_oracle as CB

pytestmark = requires_runtime(5)

NORD = 6            # series orders 0..5: everything ADC(5) carries
NSTATES = 2
TOL = 1e-10


def _oracle_adc5(us):
    """(IPs, EAs) of the oracle's two-sector ADC(5) supermatrix at lambda = 1."""
    psi, E, nser = us.rspt_series(NORD)
    Ssr, Msr = us.series_matrices(psi, E, nser, NORD)
    orb = us.idx[(0, 'o')]
    Fs = sum(Msr[k][np.ix_(orb, orb)] for k in range(NORD))
    sf = CB.SeriesFold(us, Ssr, Msr, NORD, 'twosector', us.kmax)
    B, D = sf.truncated(CB.adc_rule(5), kcap=2)
    keep = sf.kseg <= 2
    M = np.block([[Fs, sum(B)[:, keep]], [sum(B)[:, keep].T, sum(D)[np.ix_(keep, keep)]]])
    w, V = np.linalg.eigh(0.5 * (M + M.T))
    strength = np.sum(V[:us.norb] ** 2, axis=0)
    ip, _ = CB.principal_poles(w, strength, -1, NSTATES)
    ea, _ = CB.principal_poles(w, strength, +1, NSTATES)
    return ip, ea


def _production(sysd):
    """(restricted solver, order-consistent F block) for the production ADC(5)."""
    eps_sp = get_orbital_energies(sysd['mf'], representation='spatial')
    ga, gb, gab = get_antisymmetrized_spin_block_eri(sysd['mol'], sysd['mf'])
    r = BuildSuperMatrixADCnRestricted(eps_sp, ga, gab, gb, sysd['nocc'] // 2)
    f_orb = np.diag(eps_sp) + build_mp4_static_correction_restricted(sysd['mf'], sysd['mol'])
    return r, f_orb


def test_full_spectrum_matches_oracle_h4():
    sysd = CB.build_system('H4lin_r1.0')
    us = CB.UnionSpace(sysd)
    ip_or, ea_or = _oracle_adc5(us)
    r, f_orb = _production(sysd)
    op, _ = restricted_dyson_operator(r, 'adc5', f_orb=f_orb, construction='twosector')
    n = op.shape[0]
    M = np.column_stack([op.matvec(e) for e in np.eye(n)])
    asym = float(np.max(np.abs(M - M.T)))
    w, V = np.linalg.eigh(0.5 * (M + M.T))
    strength = np.sum(V[:len(f_orb)] ** 2, axis=0)
    ip, _ = CB.principal_poles(w, strength, -1, NSTATES)
    ea, _ = CB.principal_poles(w, strength, +1, NSTATES)
    d_ip = max(abs(a - b) for a, b in zip(ip, ip_or))
    d_ea = max(abs(a - b) for a, b in zip(ea, ea_or))
    print(f"H4lin_r1.0 ADC(5): production IP {np.round(ip, 9)} EA {np.round(ea, 9)}; "
          f"oracle IP {np.round(ip_or, 9)} EA {np.round(ea_or, 9)}; "
          f"|dIP| {d_ip:.2e} |dEA| {d_ea:.2e}; operator symmetry {asym:.1e}")
    assert asym <= 1e-12
    assert d_ip <= TOL and d_ea <= TOL, (d_ip, d_ea)


def test_davidson_ip_matches_oracle_lih():
    sysd = CB.build_system('LiH')
    us = CB.UnionSpace(sysd)
    ip_or, _ = _oracle_adc5(us)
    r, f_orb = _production(sysd)
    homo = sysd['nocc'] // 2 - 1
    out = solve_dyson_adc(r, homo, level='adc5', f_orb=f_orb, tol=1e-10, construction='twosector')
    d = abs(out['e'] - ip_or[0])
    print(f"LiH ADC(5): production Davidson IP1 {out['e']:.10f} (Z {out['Z']:.3f}, dim {out['dim']}); "
          f"oracle {ip_or[0]:.10f}; |diff| {d:.2e}")
    assert d <= TOL, d


def main():
    test_full_spectrum_matches_oracle_h4()
    test_davidson_ip_matches_oracle_lih()
    print('\nALL OK')
    return True


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
