@pytest.mark.parametrize('name', NONZERO_SYSTEMS)
def test_x2_matches_oracle(name):
    sysd, us, Ssr, Msr = _oracle_x2(name, nord=3, kmax=1)
    eps, g, nocc, norb = sysd['eps'], sysd['g'], sysd['nocc'], sysd['norb']
    gen = BuildSuperMatrixADCn(eps, g, nocc)
    X = gen.cross_block_generated(2)
    rows, cols, sign = _config_map(us, nocc, norb)
    D1, C1 = us.idx[(1, 'D')], us.idx[(1, 'C')]
    Xor = Msr[2][np.ix_(D1, C1)]
    d = float(np.max(np.abs(X - sign * Xor[np.ix_(rows, cols)])))
    scale = float(np.max(np.abs(Xor)))
    print(f"{name}: |X2|={scale:.3e}  |production - oracle|={d:.2e}  (f_ov {sysd['f_ov']:.1e})")
    assert scale > 1e-3, name
    assert d <= TOL_ORACLE, (name, d)
    # the metric cross block of the oracle is zero (operator identity)
    assert float(np.max(np.abs(Ssr[2][np.ix_(D1, C1)]))) <= TOL_ZERO
    # the f[o,v]-carrying structure contributes nothing for canonical HF
    mpn = MPnDensityDriver(eps, g, nocc)
    amps = mpn.compute_order_amplitudes_general(2)
    l2f = x2so.x2_2h1p_2p1h_l2f(**gen.kernel_args(), l2=to_l(amps[(2, 2)], 2))
    assert float(np.max(np.abs(l2f))) <= 1e-13, float(np.max(np.abs(l2f)))


@pytest.mark.parametrize('name', ['H4lin_r1.0', 'LiH'])
def test_production_x2_closes_c4_in_the_oracle_fold(name):
    nord = 6
    sysd, us, Ssr, Msr = _oracle_x2(name, nord=nord)
    eps, g, nocc, norb = sysd['eps'], sysd['g'], sysd['nocc'], sysd['norb']
    X = BuildSuperMatrixADCn(eps, g, nocc).cross_block_generated(2)
    rows, cols, sign = _config_map(us, nocc, norb)
    sf_u = CB.SeriesFold(us, Ssr, Msr, nord, 'union', us.kmax)
    sf_2 = CB.SeriesFold(us, Ssr, Msr, nord, 'twosector', us.kmax)
    nC1, nD1 = len(us.idx[(1, 'C')]), len(us.idx[(1, 'D')])
    o1C = slice(sf_u.offs[(1, 'C')], sf_u.offs[(1, 'C')] + nC1)
    o1D = slice(sf_u.offs[(1, 'D')], sf_u.offs[(1, 'D')] + nD1)
    Xor_from_prod = np.zeros((nD1, nC1))
    Xor_from_prod[np.ix_(rows, cols)] = sign * X
    sf_p = copy.copy(sf_u)
    sf_p.D = [d.copy() for d in sf_u.D]
    sf_p.D[2][o1D, o1C] = Xor_from_prod
    sf_p.D[2][o1C, o1D] = Xor_from_prod.T
    rule = CB.adc_rule(4)
    worst = dict(union=0.0, prod=0.0, two=0.0, prod_vs_union=0.0, scale=0.0)
    for om in CB.OMEGAS_C[:2]:
        cex = us.contour_coeffs(om, [4], radius=0.3, n_points=32)[4]
        cu = sf_u.fold_coeffs(om, 4, rule=rule)[4]
        c2 = sf_2.fold_coeffs(om, 4, rule=rule)[4]
        cp = sf_p.fold_coeffs(om, 4, rule=rule)[4]
        worst['union'] = max(worst['union'], CB.maxabs(cu - cex))
        worst['two'] = max(worst['two'], CB.maxabs(c2 - cex))
        worst['prod'] = max(worst['prod'], CB.maxabs(cp - cex))
        worst['prod_vs_union'] = max(worst['prod_vs_union'], CB.maxabs(cp - cu))
        worst['scale'] = max(worst['scale'], CB.maxabs(cex))
    print(f"{name}: c4 gaps vs exact -- two-sector {worst['two']:.3e} "
          f"({100 * worst['two'] / worst['scale']:.2f}%), union (oracle block) "
          f"{worst['union']:.2e}, union (production block) {worst['prod']:.2e}; "
          f"production vs oracle fold {worst['prod_vs_union']:.2e}")
    assert worst['two'] > 1e-5, "the two-sector gap must be visible for the closure to mean anything"
    assert worst['union'] <= TOL_FOLD
    assert worst['prod'] <= TOL_FOLD, worst['prod']
    assert worst['prod_vs_union'] <= TOL_ZERO, worst['prod_vs_union']


@pytest.mark.parametrize('name', ZERO_SYSTEMS)
def test_x2_vanishes_by_symmetry(name):
    sysd = CB.build_system(name)
    X = BuildSuperMatrixADCn(sysd['eps'], sysd['g'], sysd['nocc']).cross_block_generated(2)
    mag = float(np.max(np.abs(X))) if X.size else 0.0
    print(f"{name}: |X2| = {mag:.2e}")
    assert mag <= TOL_ZERO, (name, mag)


def _restricted_inputs(atom):
    mol = gto.M(atom=atom, basis='sto-3g', verbose=0)
    mf = scf.RHF(mol)
    mf.conv_tol = 1e-13
    mf.run()
    dd = _build(atom)
    B = DFIntegrals.from_scf(mol, mf, exact=True).B_aa
    return mol, mf, dd, B


@pytest.mark.parametrize('label,atom', [
    ('H4/sto-3g', 'H 0 0 0; H 0 0 0.80; H 0 0 1.75; H 0 0 2.60'),
    ('LiH/sto-3g', 'Li 0 0 0; H 0 0 1.6'),
    ('BeH2/sto-3g', BEH2)])
def test_restricted_df_and_apply_twins(label, atom):
    mol, mf, dd, B = _restricted_inputs(atom)
    gen = BuildSuperMatrixADCn(dd['eps'], dd['g'], dd['nocc'])
    X = gen.cross_block_generated(2)
    r = BuildSuperMatrixADCnRestricted(dd['eps_sp'], dd['ga'], dd['gab'], dd['gb'], dd['nsp'])
    Xr = r.cross_block_generated(2)
    m_ip, m_ea = r._class_index_map('IP'), r._class_index_map('EA')
    d = float(np.max(np.abs(Xr - X[np.ix_(m_ip, m_ea)])))
    scale = float(np.max(np.abs(Xr)))
    print(f"{label}: restricted vs spin-orbital {d:.2e} (|X|={scale:.3e})")
    assert scale > 1e-3
    assert d <= 1e-11, d
    leaves = {'B_aa': B, 'B_bb': B}
    Xdf = r.cross_block_generated(2, module=x2r_df, extra_leaves=leaves)
    ddf = float(np.max(np.abs(Xdf - Xr)))
    print(f"{label}: exact-DF restricted vs dense {ddf:.2e}")
    assert ddf <= 1e-9, ddf
    cfg_ip, cfg_ea = r.sector_configs('IP'), r.sector_configs('EA')
    no, nv = r.nocc, r.nvir
    pool = {**r.rargs, **r.amplitude_pool()}
    rng = np.random.default_rng(7)
    v_ea = rng.standard_normal(len(cfg_ea['K']))
    v_ip = rng.standard_normal(len(cfg_ip['K']))
    y_ip = restricted_class_matvec(x2ap, 'apply_x2_2h1p_2p1h_', v_ea, cfg_ip, pool, no, nv,
                                   cfg_ket=cfg_ea)
    y_ea = restricted_class_matvec(x2ap, 'apply_x2_2p1h_2h1p_', v_ip, cfg_ea, pool, no, nv,
                                   cfg_ket=cfg_ip)
    d_fwd = float(np.max(np.abs(y_ip - Xr @ v_ea)))
    d_bwd = float(np.max(np.abs(y_ea - Xr.T @ v_ip)))
    print(f"{label}: apply forward {d_fwd:.2e}, transpose {d_bwd:.2e}")
    assert d_fwd <= 1e-11 and d_bwd <= 1e-11, (d_fwd, d_bwd)
    pool_df = {**pool, **leaves}
    y_ip = restricted_class_matvec(x2ap_df, 'apply_x2_2h1p_2p1h_', v_ea, cfg_ip, pool_df,
                                   no, nv, cfg_ket=cfg_ea)
    y_ea = restricted_class_matvec(x2ap_df, 'apply_x2_2p1h_2h1p_', v_ip, cfg_ea, pool_df,
                                   no, nv, cfg_ket=cfg_ip)
    d_fwd = float(np.max(np.abs(y_ip - Xr @ v_ea)))
    d_bwd = float(np.max(np.abs(y_ea - Xr.T @ v_ip)))
    print(f"{label}: DF apply forward {d_fwd:.2e}, transpose {d_bwd:.2e}")
    assert d_fwd <= 1e-9 and d_bwd <= 1e-9, (d_fwd, d_bwd)


