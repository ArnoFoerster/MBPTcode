TOL_ORACLE = 1e-12
TOL_ZERO = 1e-14
TOL_FOLD = 2e-12          # fold vs contour quadrature: LiH c4 1.2e-12 with MKL


def _config_map(us, nocc, norb):
    """Rows/cols of the oracle k1 blocks in the production config order, and
    the D-operator sign (production D = a+_i a+_j a_a, oracle a+_j a+_i a_a)."""
    D1, C1 = us.idx[(1, 'D')], us.idx[(1, 'C')]
    posD = {tuple(us.ops[m]['lab']): r for r, m in enumerate(D1)}
    posC = {tuple(us.ops[m]['lab']): c for c, m in enumerate(C1)}
    i_, j_, a_ = (np.asarray(c) for c in class_configs(nocc, norb, 1, 'IP'))
    k_, b_, c_ = (np.asarray(c) for c in class_configs(nocc, norb, 1, 'EA'))
    rows = np.array([posD[(int(a), int(i), int(j))] for i, j, a in zip(i_, j_, a_)])
    cols = np.array([posC[(int(k), int(b), int(c))] for k, b, c in zip(k_, b_, c_)])
    return rows, cols, -1.0


def _oracle_x2(name, nord=3, kmax=None):
    sysd = CB.build_system(name)
    us = CB.UnionSpace(sysd, kmax=kmax)
    psi, E, nser = us.rspt_series(nord)
    Ssr, Msr = us.series_matrices(psi, E, nser, nord)
    return sysd, us, Ssr, Msr


