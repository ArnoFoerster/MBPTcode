"""Gates for the emitted union-space 2h1p x 2p1h cross block X^(2)
(generatedADC/adc4/adc4_x2_k1k1_blocks*.py, runtime
BuildSuperMatrixADCn.cross_block_generated / the restricted twin), the
Hamiltonian block the two-sector ISR-ADC(n) supermatrix deletes and whose
absence is the lambda^4 gap of two-sector ADC(4).

  a. X^(0) = X^(1) = 0 and the metric cross block vanish symbolically (no
     pdaggerq terms); X^(2) equals the determinant-space union-space block
     (D_mu|H^|C_nu) of the union-space oracle (tests/union_space_oracle.py:
     series_matrices order 2) after the config-basis map
     -- D_production = a+_i a+_j a_a = -D_oracle (a+_j a+_i a_a), hole pair
     outer -- on linear H4, LiH and BeH2 (1e-12); the f[o,v]-carrying l2f
     structure is zero for the canonical reference.
  b. Fed into the oracle's series fold in place of its own block, the
     production X^(2) closes c4 of ADC(4) on H4 and LiH (union fold vs exact
     contour 2e-12, the quadrature floor across BLAS builds; production fold vs
     oracle fold 1e-14), while the two-sector fold keeps its gap.
  c. (tests/test_adc4_union_poles.py) production union-space ADC(4) poles.
  d. On H2 and rectangular H4 the block vanishes by symmetry (1e-14).
  Restricted twin == spin-orbital block at the alpha-sector configs (1e-11),
  DF twin (exact factors) == dense (1e-9), apply forms (both directions,
  dense and DF) == dense block times a trial vector.
"""
