"""The FULL ADC(4) operator must apply U^(3) matrix-free, and identically.

Why
---
`_sector_data` built the orbital<->k1 coupling as
`u_adc3(sector) + u3_generated(sector)`, and `u3_generated` materializes the
dense (n_k1, n_k1) class-GS S^(2) purely to form -1/2 (S2C @ U1) -- the
~17.5 GB / 284 s aug-cc-pVTZ blocker. That made full ADC(4) (and the new
downfolded solver, which routes through the same operator) unusable at
production basis sets, and left a block that was not matrix-free.

U^(3) factorizes as  M - 1/2 (S2C - n2) U1  with M and U1 both (n_k1, norb),
so BOTH directions follow from cheap stitches plus one S^(2) MATVEC:

    U^(3)   x_orb = M   x_orb - 1/2 (S2C - n2)(U1 x_orb)
    U^(3)^T y_k1  = M^T y_k1  - 1/2 U1^T[(S2C - n2) y_k1]

the transpose being available only because S2C is an OVERLAP matrix, hence
symmetric. Nothing (n_k1)^2 is ever formed.

The gate compares against the dense path via an EXPLICIT `u3_matrix_free` flag.
That flag exists because `restricted_dyson_operator` DEFAULTS s2cr_module to
the real module when it is None -- so "pass s2cr_module to select matrix-free"
silently selects it in both branches, and a comparison written that way comes
back 0.0 by construction while testing nothing. (Observed: it did.)
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.Base.pyscf_interface import (get_orbital_energies,
                                      get_antisymmetrized_spin_block_eri)
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.SingleReference.ADC.sigma_driver import (restricted_dyson_operator, _eigs,
                                                  u3_dot_orb, u3_dot_k1)
from src.SingleReference.ADC.generated_modules import lazy
s2cr = lazy('adc4_c2_s2c_apply_restricted_blocks')
from src.Base.constants import HARTREE_TO_EV
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)



def main():
    all_ok = True
    mol = gto.M(atom='O 0 0 0; H 0 0 0.96; H 0.93 0 -0.24', basis='sto-3g', verbose=0)
    mf = scf.RHF(mol).run()
    ns = mol.nelectron // 2
    eps = get_orbital_energies(mf, representation='spatial')
    homo = ns - 1
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
    r = BuildSuperMatrixADCnRestricted(eps, ga, gab, gb, ns)
    rng = np.random.default_rng(0)

    # ---- 1. both directions vs the dense u3_generated matrix ----
    for sec in ('IP', 'EA'):
        U3 = r.u3_generated(sec)
        x = rng.standard_normal(r.norb)
        y = rng.standard_normal(U3.shape[0])
        fwd = np.abs(u3_dot_orb(r, sec, x, s2cr) - U3 @ x).max()
        bwd = np.abs(u3_dot_k1(r, sec, y, s2cr) - U3.T @ y).max()
        ok = fwd < 1e-12 and bwd < 1e-12
        print(f"[{'OK' if ok else 'FAIL'}] {sec}: U3 fwd {fwd:.2e}, U3^T bwd {bwd:.2e} "
              "vs dense u3_generated")
        all_ok &= ok

    # ---- 2. operator matvec: matrix-free == dense ----
    op_d, dg_d = restricted_dyson_operator(r, 'adc4', u3_matrix_free=False)
    op_m, dg_m = restricted_dyson_operator(r, 'adc4', u3_matrix_free=True)
    v = rng.standard_normal(op_d.shape[0])
    mv = np.abs(op_d.matvec(v) - op_m.matvec(v)).max()
    ok = np.abs(dg_d - dg_m).max() == 0.0 and mv < 1e-12
    print(f"[{'OK' if ok else 'FAIL'}] full ADC(4) matvec: matrix-free == dense "
          f"({mv:.2e}); diagonals identical")
    all_ok &= ok

    # ---- 3. same eigenvalue ----
    v0 = np.zeros(op_d.shape[0]); v0[homo] = 1.0
    wd, _, cd = _eigs(op_d, dg_d, v0=v0, follow=True, tol=1e-10)
    wm, _, cm = _eigs(op_m, dg_m, v0=v0, follow=True, tol=1e-10)
    assert cd.all() and cm.all()
    d_ev = abs(wd[0] - wm[0]) * HARTREE_TO_EV
    ok = d_ev < 1e-9
    print(f"[{'OK' if ok else 'FAIL'}] full ADC(4) IP identical: "
          f"{-wd[0]*HARTREE_TO_EV:.9f} vs {-wm[0]*HARTREE_TO_EV:.9f} eV (diff {d_ev:.2e} eV)")
    all_ok &= ok

    # ---- 4. the dense path must really be dense (guards the flag itself) ----
    from src.SingleReference.ADC.sigma_driver import _sector_data
    dd = _sector_data(r, 'IP', 'adc4', None, s2cr_module=s2cr, u3_matrix_free=False)
    dm = _sector_data(r, 'IP', 'adc4', None, s2cr_module=s2cr, u3_matrix_free=True)
    ok = ('u3' not in dd) and ('u3' in dm)
    print(f"[{'OK' if ok else 'FAIL'}] u3_matrix_free flag actually switches paths "
          "(dense carries no 'u3' stitches; matrix-free does)")
    all_ok &= ok

    print('ALL OK' if all_ok else 'FAILURES')
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
