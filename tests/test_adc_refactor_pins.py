# ---------------------------------------------------------------- record / verify

def _run_route(name):
    fn, tol = ROUTES[name]
    out = fn()
    return {k: np.asarray(v, dtype=float) for k, v in out.items()}, tol


def record(missing_only=False):
    pins = {}
    if missing_only and os.path.exists(PIN_FILE):
        with open(PIN_FILE) as f:
            pins = json.load(f)
    for name in sorted(ROUTES):
        if missing_only and name in pins:
            continue
        t0 = time.time()
        out, _tol = _run_route(name)
        pins[name] = {k: v.tolist() for k, v in out.items()}
        print(f"{name:45s} {time.time() - t0:8.2f}s  "
              f"e[0]={out['e'][0]:.10f}", flush=True)
    with open(PIN_FILE, 'w') as f:
        json.dump(pins, f, indent=1)
    print(f"\nwrote {len(pins)} pins -> {PIN_FILE}")


