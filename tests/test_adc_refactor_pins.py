    g = _rgen(s)
    op, diag = restricted_dyson_operator(g, 'adc3',
                                         extra_leaves={'B_aa': s['B'], 'B_bb': s['B']})
    v0 = np.zeros(op.shape[0]); v0[s['nocc'] - 1] = 1.0
    w, X, _conv = follow_roots(op, diag, v0, tol=1e-8)
    return {'e': np.atleast_1d(w),
            'Z': np.atleast_1d(np.sum(X[:g.norb, :] ** 2, axis=0))}


