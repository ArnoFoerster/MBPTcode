@lru_cache(maxsize=None)
def h2o_sto3g():
    mol = gto.M(atom='O 0 0 0; H 0 -0.757 0.587; H 0 0.757 0.587',
                basis='sto-3g', verbose=0)
    mf = scf.RHF(mol).run(conv_tol=1e-12)
    nocc = mol.nelectron // 2
    eps = get_orbital_energies(mf, representation='spatial')
    eri = get_two_electron_integrals_chemist(mol, mf, representation='spatial')
    B = DFIntegrals.from_scf(mol, mf, exact=True).B_aa
    eps_spin = np.repeat(eps, 2)
    g_anti = get_antisymmetrized_spin_eri(eri)
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
    return dict(mol=mol, mf=mf, nocc=nocc, eps=eps, eri=eri, B=B,
                eps_spin=eps_spin, g_anti=g_anti, ga=ga, gb=gb, gab=gab)


@lru_cache(maxsize=None)
def h2o_631g():
    mol = gto.M(atom='O 0 0 0; H 0 -0.757 0.587; H 0 0.757 0.587',
                basis='6-31g', verbose=0)
    mf = scf.RHF(mol).run(conv_tol=1e-12)
    nocc = mol.nelectron // 2
    eps = get_orbital_energies(mf, representation='spatial')
    eri = get_two_electron_integrals_chemist(mol, mf, representation='spatial')
    return dict(mol=mol, mf=mf, nocc=nocc, eps=eps, eri=eri)


@lru_cache(maxsize=None)
def oh_uhf():
    mol = gto.M(atom='O 0 0 0; H 0 0 0.97', basis='sto-3g', spin=1, verbose=0)
    mf = scf.UHF(mol).run(conv_tol=1e-12)
    eps_spin, g_anti_spin, nocc_spin = get_uhf_spin_orbital_arrays_blockstacked(mol, mf)
    return dict(mol=mol, mf=mf, eps_spin=eps_spin, g_anti=g_anti_spin,
                nocc_spin=nocc_spin)


# ---------------------------------------------------------------- helpers

def _dense_result(H, norb):
    w, v = np.linalg.eigh(H)
    return {'e': w, 'Z': np.sum(v[:norb, :] ** 2, axis=0)}


def _rgen(s, dress=None):
    return BuildSuperMatrixADCnRestricted(s['eps'], s['ga'], s['gab'], s['gb'],
                                          s['nocc'], u2_denom_dress=dress)


def _davidson_mf(solver, nocc, homo_index, static_correction=None, t2_ijcd=None):
    if t2_ijcd is not None:
        aop, diag, dims = solver.build_matrix_free_operator(
            nocc, static_correction=static_correction, t2_ijcd=t2_ijcd)
    else:
        aop, diag, dims = solver.build_matrix_free_operator(
            nocc, static_correction=static_correction)
    e, Z, vec, conv = davidson_follow(aop, diag, dims['nH'], solver.norb, homo_index,
                                      None, 1, tol=1e-6)
    assert conv.all()
    return e, Z, vec


ROUTES = {}


def route(name, tol=TOL_DENSE):
    def deco(fn):
        ROUTES[name] = (fn, tol)
        return fn
    return deco


# --------------------------------------------- R hand-written: dense/sigma x full/df

def _r_solver(s, level='adc3', df=False, dress=None, **kw):
    return ADCSolverRestricted.from_arrays(s['eps'], s['eri'], nocc=s['nocc'],
                                           level=level,
                                           B_aa=s['B'] if df else None,
                                           en_dress=dress, **kw)


for _level in ('adc2x', 'adc3'):
    for _df in (False, True):
        tag = f"r_hw_{_level}_dense_{'df' if _df else 'full'}"

        @route(tag)
        def _(level=_level, df=_df):
            s = h2o_sto3g()
            solver = _r_solver(s, level=level, df=df)
            H = solver.build_supermatrix(s['nocc'])
            return _dense_result(H, solver.norb)

        tag = f"r_hw_{_level}_sigma_{'df' if _df else 'full'}"

        @route(tag, tol=TOL_ITER)
        def _(level=_level, df=_df):
            s = h2o_sto3g()
            solver = _r_solver(s, level=level, df=df)
            e, Z, _v = _davidson_mf(solver, s['nocc'],
                                                       homo_index=s['nocc'] - 1)
            return {'e': e, 'Z': Z}


