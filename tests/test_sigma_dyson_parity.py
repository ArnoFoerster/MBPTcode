"""Production-parity gate for the TWO-SECTOR (Dyson) restricted matrix-free
operator -- the check that was missing and let the single-sector bug through.

A physical Dyson IP/EA needs the orbital (F) block coupled to BOTH 2h1p AND
2p1h at once. restricted_dyson_operator builds that two-sector supermatrix
matrix-free; this test pins it to the production references:

  1. FULL-SPECTRUM parity (small, dense): eigvalsh(restricted_dyson_operator
     'adc3') == eigvalsh(BuildSuperMatrixADCnRestricted.build_supermatrix_adc3)
     on LiH/H2O.
  2. PHYSICAL IP parity (the bug-catcher): the Ne aug-cc-pVDZ 2p IP from the
     matrix-free two-sector Dyson-ADC(3) (Davidson, follow HOMO) == the
     production solve_adc_unrestricted('adc3') pole (~21.40 eV). A single-sector
     operator gives ~19.9 eV (ADC(2)) here -- a ~1.5 eV error this test fails on.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.SingleReference.ADC import ADCSolver
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.SingleReference.ADC.sigma_driver import restricted_dyson_operator, u3_dot_orb
from src.SingleReference.ADC.solve import follow_roots
from src.Base.pyscf.pyscf_interface import (
    get_orbital_energies, get_antisymmetrized_spin_block_eri)
from src.Base.numerics.constants import HARTREE_TO_EV
from tests.generated_runtime import requires_runtime
from src.SingleReference.ADC.generated_modules import generated

pytestmark = requires_runtime(4)



def rsolver(atom, basis='sto-3g'):
    mol = gto.M(atom=atom, basis=basis, verbose=0)
    mf = scf.RHF(mol).run()
    ns = mol.nelectron // 2
    eps = get_orbital_energies(mf, representation='spatial')
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mol, mf)
    return BuildSuperMatrixADCnRestricted(eps, ga, gab, gb, ns), mf, ns


def main():
    all_ok = True

    # ---- 1. full-spectrum parity vs build_supermatrix_adc3 (small) ----
    for atom, label in [('Li 0 0 0; H 0 0 1.6', 'LiH/sto-3g'),
                        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'H2O/sto-3g')]:
        r, mf, ns = rsolver(atom)
        op, _ = restricted_dyson_operator(r, 'adc3')
        n = op.shape[0]
        recon = np.column_stack([op.matvec(e) for e in np.eye(n)])
        w_mf = np.sort(np.linalg.eigvalsh(0.5 * (recon + recon.T)))
        w_ref = np.sort(np.linalg.eigvalsh(r.build_supermatrix_adc3()))
        diff = np.abs(w_mf - w_ref).max()
        ok = diff < 1e-9
        all_ok &= ok
        print(f"[{'OK' if ok else 'FAIL'}] {label} Dyson-ADC(3) spectrum == build_supermatrix_adc3: {diff:.2e}")

        # matrix-free u3_dot_orb == u3_generated @ p_orb (guards the downfold's
        # U^(3) term / its stitch-list replication against front-track drift)
        _s2r = generated('adc4_c2_s2c_apply_restricted_blocks')
        pv = np.random.default_rng(1).standard_normal(r.norb)
        u3d = max(np.abs(u3_dot_orb(r, sec, pv, _s2r) - r.u3_generated(sec) @ pv).max()
                  for sec in ('IP', 'EA'))
        all_ok &= u3d < 1e-11
        print(f"[{'OK' if u3d < 1e-11 else 'FAIL'}] {label} u3_dot_orb == u3_generated@p_orb: {u3d:.2e}")

        # Laplace-fused l3 path (t3/l3 never materialized) converges to the
        # exact u3_dot_orb with ntau -- guards adc4_u3_l3_laplace_restricted +
        # _u3_amps_laplace against the exact stitch list.
        u3l = max(np.abs(u3_dot_orb(r, sec, pv, _s2r, laplace_ntau=20)
                         - u3_dot_orb(r, sec, pv, _s2r)).max() for sec in ('IP', 'EA'))
        all_ok &= u3l < 1e-9
        print(f"[{'OK' if u3l < 1e-9 else 'FAIL'}] {label} u3_dot_orb Laplace(ntau=20) == exact: {u3l:.2e}")

    # ---- 2. physical Ne 2p IP == production (the bug-catcher) ----
    r, mf, ns = rsolver('Ne 0 0 0', 'aug-cc-pvdz')
    eps = r.eps; homo = ns - 1
    op, diag = restricted_dyson_operator(r, 'adc3')
    n = op.shape[0]; v0 = np.zeros(n); v0[homo] = 1.0
    w, X, conv = follow_roots(op, diag, v0, tol=1e-8)
    assert conv.all()
    ip_mf = -w[0] * HARTREE_TO_EV
    eGF, Z = ADCSolver(mf, spin='spinorbital').solve(homo_index=homo, nroots=1)
    ip_prod = -np.atleast_1d(eGF)[0] * HARTREE_TO_EV
    err = abs(ip_mf - ip_prod)
    ok = err < 1e-3
    all_ok &= ok
    print(f"[{'OK' if ok else 'FAIL'}] Ne/aVDZ 2p IP: matrix-free Dyson-ADC(3) {ip_mf:.4f} eV == production {ip_prod:.4f} eV  (|d|={err*1000:.2f} meV)")

    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
