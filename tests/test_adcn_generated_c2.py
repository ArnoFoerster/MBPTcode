"""Phase 4 checks on the generated C^(2) class-class blocks
(adc_autogenerated.c2_block_generated -- the generator's ARBITER candidate for
the disputed ADC(4) C^(2), whose printed SCW83 B7 form the
lambda-oracle rejected).

Internal (always-on) checks here:
1. Hermiticity -- NONTRIVIAL emergent property: the ket-dressed vt2 split
   survives pdaggerq pruning while its would-be transpose l2v prunes to
   zero, so symmetry only appears in the full assembled sum (raw splits
   - N^(2) normalization - within-class Loewdin correction).
2. H2/sto-3g: the generated C^(2) must be IDENTICALLY ZERO -- matching the
   lambda-oracle's headline finding that the exact lambda^4 residue on H2
   requires no C^(2)-fold contribution at all.

(There is no comparison of H2O/sto-3g against a hand-written ADC(4)'s printed
B7 blocks: such a check would be diagnostic-only, not gated by all_ok, and its
disagreement is already expected/rejected by the lambda-oracle.)
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCn
from src.Base.pyscf_interface import (
    get_orbital_energies, get_two_electron_integrals_chemist,
    get_antisymmetrized_spin_eri)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)


def check(label, diff, tol=1e-12):
    ok = diff < tol
    print(f"[{'OK' if ok else 'FAIL'}] {label}: max diff = {diff:.3e}")
    return ok


def main():
    all_ok = True

    for atom, basis, label in [
        ('H 0 0 0; H 0 0 0.74', 'sto-3g', 'H2/sto-3g'),
        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g'),
    ]:
        mol = gto.M(atom=atom, basis=basis, verbose=0)
        mf = scf.RHF(mol).run()
        nocc = 2 * (mol.nelectron // 2)
        eps = get_orbital_energies(mf, representation='spin')
        eri = get_two_electron_integrals_chemist(mol, mf, representation='spatial')
        g = get_antisymmetrized_spin_eri(eri)

        solver = BuildSuperMatrixADCn(eps, g, nocc)

        print(f"\n=== {label} ===")
        for sector, tag in (('IP', '2h1p'), ('EA', '2p1h')):
            C2 = solver.c2_block_generated(sector)
            all_ok &= check(f"C2_{tag} generated is Hermitian",
                            np.abs(C2 - C2.T).max())
            if label.startswith('H2/'):
                all_ok &= check(f"C2_{tag} generated == 0 on H2 (lambda-oracle "
                                "headline)", np.abs(C2).max())

    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
