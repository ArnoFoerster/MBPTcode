"""Gate for the ADC(5) (2,2) block: matrix-free + spin-restricted + DF/RI.

Every emitted block must be spin-restricted, Laplace-transformed, DF/RI
and matrix-free -- "a block that has only three of the four is NOT done". For
the k=2 class-class self-coupling the matrix-free property is not a performance
tier but the ONLY viable representation: the dense twin is a 10-index
(no^3 nv^2)^2 tensor, already ~2 GB at H2O/sto-3g. It exists purely as the
small-system arbiter this file validates against.

**Laplace is vacuous here, by construction.** Laplace fusion exists to avoid
materializing t3/l3 amplitudes; the (2,2) block is a bare order-1 superoperator
element with NO amplitude dressing at all (its terms are deltas times a single
<pq||rs>), so there is nothing to fuse. That is a genuine "not applicable",
not a missing fourth property.

Validation chain (each link cross-representation, not self-consistency):
  1. spin-orbital apply      == spin-orbital dense matvec
  2. restricted apply        == spin-orbital dense, at the alpha configs
  3. restricted DF/RI apply  == the same

Link 2 is the load-bearing one: it crosses the spin-blocking AND the
dense/matrix-free boundary at once, so a spin-suffix or config-ordering error
cannot hide behind agreement within one representation.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf, ao2mo

from src.SingleReference.ADC.adc_autogenerated import (BuildSuperMatrixADCn,
                                                 BuildSuperMatrixADCnRestricted)
from src.SingleReference.ADC.sigma_driver import (sigma_matvec,
                                                  restricted_class_matvec)
from src.SingleReference.ADC.precursor_classes import class_configs
from src.SingleReference.ADC.generated_modules import lazy
ap = lazy('adc5_k2k2_apply_blocks')
apr = lazy('adc5_k2k2_apply_restricted_blocks')
apr_df = lazy('adc5_k2k2_apply_restricted_df_blocks')
from src.Base.pyscf.pyscf_interface import (
    get_orbital_energies, get_antisymmetrized_spin_block_eri,
    get_antisymmetrized_spin_integrals, DFIntegrals)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(5)

SYSTEMS = [('H4/sto-3g', 'H 0 0 0; H 0 0 0.80; H 0 0 1.75; H 0 0 2.60'),
           ('LiH/sto-3g', 'Li 0 0 0; H 0 0 1.6')]


def _alpha_to_class_k2(cfg, cols, nocc_so):
    """Restricted k=2 alpha config -> spin-orbital class_configs(k=2) index.
    The k=2 generalization of test_adcn_generated_c2_restricted's k=1 helper:
    rebuild each config's spin-orbital indices (holes 2*p+spin, particles
    nocc_so + 2*p + spin), sort each family ascending (class_configs' own
    convention) and look the row up."""
    nh, npart = cfg['hole_sp'].shape[1], cfg['part_sp'].shape[1]
    idx = []
    for c in range(len(cfg['K'])):
        hs, ps, sp = cfg['hole_sp'][c], cfg['part_sp'][c], cfg['spins'][c]
        tgt = (sorted(2 * int(hs[t]) + int(sp[t]) for t in range(nh))
               + sorted(nocc_so + 2 * int(ps[t]) + int(sp[nh + t])
                        for t in range(npart)))
        m = np.where(np.all([cols[t] == tgt[t] for t in range(len(tgt))],
                            axis=0))[0]
        idx.append(m[0])
    return np.array(idx)


def _check(ok, msg):
    print(f"[{'OK' if ok else 'FAIL'}] {msg}")
    return ok


def main():
    all_ok = True
    for label, atom in SYSTEMS:
        mol = gto.M(atom=atom, basis='sto-3g', verbose=0)
        mf = scf.RHF(mol)
        mf.conv_tol = 1e-13
        mf.run()
        nocc_so = mol.nelectron
        eps_sp = get_orbital_energies(mf, representation='spatial')
        g_aaaa, g_bbbb, g_abab = get_antisymmetrized_spin_block_eri(mol, mf)
        r = BuildSuperMatrixADCnRestricted(eps_sp, g_aaaa, g_abab, g_bbbb,
                                          mol.nelectron // 2)
        n = mf.mo_coeff.shape[1]
        eri = ao2mo.kernel(mol, mf.mo_coeff, compact=False).reshape(n, n, n, n)
        h1_mo = mf.mo_coeff.T @ (mol.intor('int1e_kin')
                                 + mol.intor('int1e_nuc')) @ mf.mo_coeff
        h1, g = get_antisymmetrized_spin_integrals(h1_mo, eri)
        so = BuildSuperMatrixADCn(get_orbital_energies(mf, representation='spin'),
                                 g, nocc_so)
        dfi = DFIntegrals.from_scf(mol, mf, exact=True)
        pool = dict(r._rargs)
        pool_df = dict(pool, B_aa=dfi.B_aa, B_bb=dfi.B_aa)
        so_args = (so.f, g, so.kd, so.o, so.v, so.no, so.nv)
        rng = np.random.default_rng(11)

        print(f"\n=== {label} ===")
        for sec, tag in (('IP', '3h2p'), ('EA', '3p2h')):
            dense_so = so.k2_self_block_generated(sec, ham='v')

            # 1. spin-orbital matrix-free == dense
            worst = 0.0
            for _ in range(3):
                x = rng.standard_normal(dense_so.shape[0])
                worst = max(worst, np.max(np.abs(
                    sigma_matvec(getattr(ap, f'apply_c1_{tag}'), so_args, x,
                                 nocc_so, so.norb, 2, 2, sec) - dense_so @ x)))
            all_ok &= _check(worst < 1e-11,
                             f"{sec} spin-orbital matrix-free == dense matvec "
                             f"({worst:.1e}, n_k2={dense_so.shape[0]})")

            # 2/3. restricted (and DF) matrix-free == spin-orbital dense
            cfg = r._kconfigs(sec, 2)
            cols = class_configs(nocc_so, 2 * len(eps_sp), 2, sec)
            idx = _alpha_to_class_k2(cfg, cols, nocc_so)
            dense = dense_so[np.ix_(idx, idx)]
            w = wdf = 0.0
            for _ in range(2):
                x = rng.standard_normal(len(idx))
                ref = dense @ x
                w = max(w, np.max(np.abs(restricted_class_matvec(
                    apr, f'apply_c1_{tag}_', x, cfg, pool, r.nocc, r.nvir) - ref)))
                wdf = max(wdf, np.max(np.abs(restricted_class_matvec(
                    apr_df, f'apply_c1_{tag}_', x, cfg, pool_df,
                    r.nocc, r.nvir) - ref)))
            all_ok &= _check(w < 1e-11,
                             f"{sec} RESTRICTED matrix-free == spin-orbital "
                             f"dense at the alpha configs ({w:.1e}, n_k2={len(idx)})")
            all_ok &= _check(wdf < 1e-9,
                             f"{sec} restricted DF/RI matrix-free == the same "
                             f"({wdf:.1e})")

    print('\nALL OK' if all_ok else '\nFAILURES')
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
