"""GATE for the U^(4) DF/RI twin (adc5_u4_blocks_restricted_df) -- closing the
DF requirement for the ADC(5) orbital<->k1 layer.

Two levels, both with an EXACT RI factor (naux = norb^2,
DFIntegrals.from_scf(exact=True)) so any disagreement is codegen/plumbing,
never fitting error:

  1. BLOCK level (the test_adc4_u3_df_blocks pattern, one order up): every
     u4_*/s4_* function's DF twin == the dense function, fed the same
     amplitude pool (rank-4 l4/t4 included). The summed |max| over blocks is
     asserted NONZERO first -- a DF==dense agreement between zeros proves
     nothing (section 19's trap).

  2. ASSEMBLY level (task-spec gate): sigma_driver.u_dot_orb_order(rsolver,
     sector, p_orb, 4, s2cr_module) evaluated WITH the DF modules (B leaves ->
     _df twins via the new stitch-time registration + DF s2c module) vs
     WITHOUT: max dev < 1e-8 for random p_orb, BOTH sectors, LiH/sto-3g.
     The result vector is asserted nonzero too.

LiH/sto-3g note: LiH zeroes t3_aaaaaa/t4-pure-alpha blocks (2 occupied
spatial orbitals), but its MIXED-spin t3/t4 blocks are nonzero, so the
l2vt3/l3vt2/l4* structures contribute -- the nonzero assertions verify that
this system actually exercises the rank-3/4 DF rewrites.

Run:  ~/anaconda3/envs/py310/bin/python -u tests/test_sigma_u4_df.py
"""
import inspect
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.Base.pyscf_interface import (get_orbital_energies,
                                      get_antisymmetrized_spin_block_eri,
                                      DFIntegrals)
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.SingleReference.ADC.sigma_driver import u_dot_orb_order
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(5)
from src.SingleReference.ADC.generated_modules import lazy
s2cr = lazy('adc4_c2_s2c_apply_restricted_blocks')
s2cr_df = lazy('adc4_c2_s2c_apply_restricted_df_blocks')
dense = lazy('adc5_u4_blocks_restricted')
dfm = lazy('adc5_u4_blocks_restricted_df')

TOL_BLOCK = 1e-12    # DF == dense per block, exact B
TOL_ASM = 1e-8       # task-spec assembly gate


def _check(ok, msg):
    print(f"[{'OK' if ok else 'FAIL'}] {msg}")
    return ok


def main():
    rng = np.random.default_rng(11)
    all_ok = True
    mol = gto.M(atom='Li 0 0 0; H 0 0 1.6', basis='sto-3g', verbose=0)
    mf = scf.RHF(mol)
    mf.conv_tol = 1e-13
    mf.run()
    ns = mol.nelectron // 2
    eps = get_orbital_energies(mf, representation='spatial')
    g_aaaa, g_bbbb, g_abab = get_antisymmetrized_spin_block_eri(mol, mf)
    r = BuildSuperMatrixADCnRestricted(eps, g_aaaa, g_abab, g_bbbb, ns)
    dfi = DFIntegrals.from_scf(mol, mf, exact=True)
    B_aa, B_bb = dfi.B_aa, dfi.B_bb
    print(f"=== LiH/sto-3g (norb={r.norb}, naux={dfi.naux_aa}) ===")

    rec_aaaa, rec_bbbb, rec_abab = dfi.reconstruct_g()
    for nm, dev in (('g_aaaa', np.abs(rec_aaaa - g_aaaa).max()),
                    ('g_abab', np.abs(rec_abab - g_abab).max())):
        all_ok &= _check(dev < 1e-10,
                         f"exact-plumbing B reconstructs {nm} ({dev:.2e}) -- any "
                         f"block mismatch below is codegen, not RI error")

    # ---- level 1: every u4_/s4_ block, DF twin == dense --------------------
    amp_pool = {}
    for d in r._amps_order(max_order=4).values():
        amp_pool.update(d)
    pool = {**r._rargs, **amp_pool}
    pool_df = {**pool, 'B_aa': B_aa, 'B_bb': B_bb}
    names = [n for n in dir(dense) if n.startswith(('u4_', 's4_'))]
    checked, worst, biggest, missing = 0, 0.0, 0.0, []
    for nm in names:
        fd, fdf = getattr(dense, nm), getattr(dfm, nm, None)
        if fdf is None:
            missing.append(nm)
            continue
        a_d = {k: pool[k] for k in inspect.signature(fd).parameters}
        a_f = {k: pool_df[k] for k in inspect.signature(fdf).parameters}
        out_d, out_f = fd(**a_d), fdf(**a_f)
        worst = max(worst, float(np.abs(out_d - out_f).max()))
        biggest = max(biggest, float(np.abs(out_d).max()))
        checked += 1
    all_ok &= _check(biggest > 1e-10,
                     f"dense U^(4)/S^(4) blocks NONZERO on LiH (|max| = "
                     f"{biggest:.3e}) -- zero-vs-zero would prove nothing")
    all_ok &= _check(checked == len(names) and not missing,
                     f"every dense block has a DF twin ({checked}/{len(names)})"
                     + (f"; MISSING: {missing[:4]}" if missing else ""))
    all_ok &= _check(worst < TOL_BLOCK,
                     f"{checked} U^(4)/S^(4) blocks: DF == dense, worst "
                     f"{worst:.3e} (< {TOL_BLOCK:.0e})")

    # ---- level 2: u_dot_orb_order(n=4) assembly, DF vs full-g --------------
    for sector in ('IP', 'EA'):
        worst = 0.0
        norm = 0.0
        for _ in range(2):
            p_orb = rng.standard_normal(r.norb)
            y_g = u_dot_orb_order(r, sector, p_orb, 4, s2cr)
            y_b = u_dot_orb_order(r, sector, p_orb, 4, s2cr_df,
                                  extra_leaves={'B_aa': B_aa, 'B_bb': B_bb})
            worst = max(worst, float(np.abs(y_g - y_b).max()))
            norm = max(norm, float(np.abs(y_g).max()))
        all_ok &= _check(norm > 1e-10,
                         f"{sector}: u_dot_orb_order(n=4) NONZERO "
                         f"(|max| = {norm:.3e})")
        all_ok &= _check(worst < TOL_ASM,
                         f"{sector}: u_dot_orb_order(n=4) DF modules == full-g, "
                         f"max dev {worst:.3e} (< {TOL_ASM:.0e})")

    print('\nALL OK' if all_ok else '\nFAILURES')
    return 0 if all_ok else 1


def test_main():
    assert not main(), 'main() returned a nonzero exit code'


if __name__ == '__main__':
    sys.exit(main())
