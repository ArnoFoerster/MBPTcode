"""Non-Dyson IP/EA-ADC(n) on the restricted route (nondyson_restricted.
NonDysonRestricted: restricted apply twins, matrix-free ISR) against the dense
spin-orbital construction (nondyson_isr.NonDysonISR) and against pyscf.

The restricted operator acts on one S_z sector (-1/2 IP, +1/2 EA); the spin-
orbital matrix holds both, which are degenerate copies, so the two spectra
agree as sets of distinct values. Gates on LiH and H2O in sto-3g:
  1. ADC(2), ADC(2)-x, ADC(3) and ADC(4) equal the spin-orbital construction,
     with every block matrix-free and with the low classes held dense;
  2. every pyscf IP/EA-ADC(2)/(2)-x/(3) root has a restricted partner;
  3. the batched apply twins (batched_apply) equal the column-by-column apply.
Non-Dyson ADC(5) is pinned to the code behind the published numbers in
test_adc5_archive_pins; its Laplace-fused T4^(3) (quadruples_ntau) is gated at
the amplitude level in test_laplace_amplitudes (a dense ADC(5) spectrum with the
fused T4^(3) takes hours even on H4, in the archive code as well).
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
import pytest
from pyscf import adc

from src.Base.numerics.constants import ISR_DENSE_BLOCK_ELEMENTS
from src.Base.pyscf.pyscf_interface import get_orbital_energies, get_antisymmetrized_spin_block_eri
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.SingleReference.ADC.batched_apply import restricted_class_matmat
from src.SingleReference.ADC.nondyson_isr import NonDysonISR
from src.SingleReference.ADC.nondyson_restricted import NonDysonRestricted
from src.SingleReference.ADC.sigma_driver import restricted_class_matvec
from tests.generated_runtime import requires_mp_numerators, requires_runtime
from tests.test_nondyson_adc import _spinorb, _distinct

SYSTEMS = [('LiH', 'Li 0 0 0; H 0 0 1.6'), ('H2O', 'O 0 0 0; H 0 0 0.96; H 0.96 0 0')]
LEVELS = [(2, None), (2, {(1, 1): 1}), (3, None), (4, None)]
TOL = 1e-9
NROOTS = 6


def _restricted(mf):
    eps = get_orbital_energies(mf, representation='spatial')
    ga, gb, gab = get_antisymmetrized_spin_block_eri(mf.mol, mf)
    return BuildSuperMatrixADCnRestricted(eps, ga, gab, gb, mf.mol.nelectron // 2)


def _dense(op):
    return np.column_stack([op.matvec(e) for e in np.eye(op.shape[0])])


def _match(a, b):
    """Largest distance from a distinct value of `a` to the nearest of `b`."""
    return float(max(np.min(np.abs(b - x)) for x in a))


@requires_runtime(4)
@requires_mp_numerators(4)
@pytest.mark.parametrize('label,atom', SYSTEMS)
@pytest.mark.parametrize('sector', ['IP', 'EA'])
def test_restricted_matches_spin_orbital_and_pyscf(label, atom, sector):
    mf, eps_so, g_so, nocc_so = _spinorb(atom)
    nd_r = NonDysonRestricted(_restricted(mf), sector)
    nd_so = NonDysonISR(eps_so, g_so, nocc_so, sector)
    worst = 0.0
    spectra = {}
    for n, extra in LEVELS:
        w_so = _distinct(nd_so.eigenpairs(n, extra=extra)[0])
        for dense_max in (0, ISR_DENSE_BLOCK_ELEMENTS):
            op, diag = nd_r.operator(n, extra=extra, dense_max=dense_max)
            M = _dense(op)
            asym = float(np.max(np.abs(M - M.T)))
            w_r = _distinct(np.linalg.eigvalsh(0.5 * (M + M.T)))
            d = max(_match(w_r, w_so), _match(w_so, w_r))
            spectra[(n, bool(extra))] = w_r
            worst = max(worst, d, asym)
            print(f"{label} {sector} ADC({n}{'-x' if extra else ''}) dense_max={dense_max}: "
                  f"dim {op.shape[0]}, restricted vs spin-orbital {d:.1e}, asymmetry {asym:.1e}")
            assert diag.shape == (op.shape[0],)
    for method, key in (('adc(2)', (2, False)), ('adc(2)-x', (2, True)), ('adc(3)', (3, False))):
        a = adc.ADC(mf)
        a.method, a.method_type, a.verbose = method, sector.lower(), 0
        a.conv_tol, a.max_cycle, a.max_space = 1e-14, 300, 60
        e = np.sort(np.atleast_1d(a.kernel(nroots=NROOTS)[0]))
        d = _match(e, spectra[key])
        print(f"{label} {sector} {method}: every pyscf root within {d:.1e}")
        worst = max(worst, d)
    assert worst <= TOL, worst


@requires_runtime(4)
@pytest.mark.parametrize('sector', ['IP', 'EA'])
def test_batched_twin_equals_column_apply(sector):
    """restricted_class_matmat (the batched twin of a generated apply module,
    several columns per call, chunked) equals restricted_class_matvec column by
    column, forward and transpose, on the non-Dyson (1,2) coupling."""
    mf, _, _, _ = _spinorb(SYSTEMS[1][1])
    r = _restricted(mf)
    nd = NonDysonRestricted(r, sector)
    mod, fwd, tr = nd._resolve('u', 'v', 1, 1, 2)
    pool = {**r.rargs}
    c1, c2 = nd.configs(1), nd.configs(2)
    rng = np.random.default_rng(3)
    worst = 0.0
    for prefix, bra, ket in ((fwd, c1, c2), (tr, c2, c1)):
        V = rng.standard_normal((len(ket['K']), 5))
        ref = np.column_stack([restricted_class_matvec(mod, prefix, V[:, j], bra, pool,
                                                       r.nocc, r.nvir, cfg_ket=ket)
                               for j in range(V.shape[1])])
        for batch in (10 ** 9, 1):                 # one call; one column per chunk
            got = restricted_class_matmat(mod, prefix, V, bra, pool, r.nocc, r.nvir,
                                          cfg_ket=ket, batch_elements=batch)
            worst = max(worst, float(np.max(np.abs(got - ref))) / float(np.max(np.abs(ref))))
    print(f"H2O {sector}: batched vs column apply {worst:.1e}")
    assert worst <= 1e-13, worst


def main():
    for label, atom in SYSTEMS:
        for sector in ('IP', 'EA'):
            test_restricted_matches_spin_orbital_and_pyscf(label, atom, sector)
    for sector in ('IP', 'EA'):
        test_batched_twin_equals_column_apply(sector)
    print('\nALL OK')
    return True


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
