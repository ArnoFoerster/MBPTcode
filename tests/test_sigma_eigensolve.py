"""End-to-end matrix-free ADC eigenvalue: a single-sector ADC(4)-base
supermatrix (orbitals + 2h1p/2p1h) whose (ncfg, ncfg) excitation-space block
(K + C^(1) + C^(2)) is applied ENTIRELY matrix-free via the sigma driver, fed
to the sigma driver's block Davidson -- the first eigenvalues to come out of
the generated matrix-free path.

Two checks per sector/system:
  1. OPERATOR == DENSE: reconstruct the matrix-free LinearOperator by applying
     it to every unit vector and compare to the dense supermatrix assembled
     from the SAME generated blocks (isolates matrix-free correctness from any
     physics choice -- both use identical K/C1/C2/U/eps).
  2. EIGENVALUES: Davidson's lowest-k eigenvalues of the matrix-free operator
     == eigh's lowest-k of the dense matrix, multiplicities included. The
     spin-orbital spectrum is degenerate (LiH/sto-3g IP: a four-fold 2h1p
     level at -5.744787 Ha inside the lowest six), and single-vector Lanczos
     (eigsh) sees one direction per eigenspace from its start, so from a
     random start it returned three of the four copies about half the time and
     the sixth value was the next level, 7.0e-2 Ha higher. The block Davidson
     starts from a fixed-seed generic block of 2k+4 vectors, which has weight
     on every copy of a level of multiplicity up to the block size. Its
     default start (unit vectors on the lowest diagonal entries) is not
     enough: on a cluster's MKL it converged the sixth Ritz pair onto the true
     eigenpair -21.95368 Ha of H2O/sto-3g IP before the second copy of the
     -22.046211 pair entered, and stopped there.

The dense C^(2) is adc_autogenerated.BuildSuperMatrixADCn.c2_block_generated (the
lambda-oracle arbiter); U^(1) and C^(1) are the generated first-order blocks.
Physics level (U order etc.) is irrelevant here -- the point is that the
matrix-free operator reproduces the dense one it is built to match.
"""
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCn
from src.SingleReference.ADC.generated_modules import lazy
c1ap = lazy('adc4_c1_self_apply_blocks')
c2ap = lazy('adc4_c2_apply_blocks')
s2ap = lazy('adc4_c2_s2c_apply_blocks')
from src.SingleReference.ADC.sigma_driver import sector_operator, diag_K
from src.SingleReference.ADC.solve import follow_roots
from src.SingleReference.DensityMatrix.mpn_density_driver import MPnDensityDriver
from src.SingleReference.common.mp_amplitudes import to_l
from src.Base.pyscf.pyscf_interface import (
    get_orbital_energies, get_two_electron_integrals_chemist,
    get_antisymmetrized_spin_eri)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)


def dense_sector_matrix(so, sector, U, eps, nocc, norb):
    """[[diag(eps), U^T],[U, K + C1 + C2]] from the generated blocks."""
    ncfg = U.shape[0]
    n = norb + ncfg
    H = np.zeros((n, n))
    H[:norb, :norb] = np.diag(eps)
    H[norb:, :norb] = U
    H[:norb, norb:] = U.T
    K = np.diag(diag_K(eps, nocc, norb, sector))
    C1 = so.c1_block(sector)
    C2 = so.c2_block_generated(sector)
    H[norb:, norb:] = K + C1 + C2
    return H


def main():
    all_ok = True
    for atom, basis, label in [
        ('Li 0 0 0; H 0 0 1.6', 'sto-3g', 'LiH/sto-3g'),
        ('H 0 0 0; H 0 0 0.74; H 0 0 1.5; H 0 0 2.2', 'sto-3g', 'H4/sto-3g'),
        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g'),
    ]:
        mol = gto.M(atom=atom, basis=basis, verbose=0)
        mf = scf.RHF(mol).run()
        nocc = 2 * (mol.nelectron // 2)
        eps = get_orbital_energies(mf, representation='spin')
        eri = get_two_electron_integrals_chemist(mol, mf, representation='spatial')
        g = get_antisymmetrized_spin_eri(eri)
        norb = len(eps)
        no, nv = nocc, norb - nocc
        so = BuildSuperMatrixADCn(eps, g, nocc)
        n2 = so.n2_norm()
        mpn = MPnDensityDriver(eps, g, nocc)
        t2 = mpn.compute_t2_1()
        t1_2, _, _, _ = mpn.compute_order2_amplitudes(t2)
        pool = {'f': np.diag(eps), 'g': g, 'kd': np.eye(norb),
                'o': slice(0, nocc), 'v': slice(nocc, norb), 'no': no, 'nv': nv,
                't2': t2, 'l2': to_l(t2, 2), 't1': t1_2, 'l1': to_l(t1_2, 1)}

        print(f"\n=== {label}  (norb={norb}) ===")
        for sector, Ufn in (('IP', so.u_2h1p), ('EA', so.u_2p1h)):
            U = Ufn()                                   # (ncfg, norb)
            Href = dense_sector_matrix(so, sector, U, eps, nocc, norb)
            op = sector_operator(sector, U, pool, eps, n2, nocc, norb,
                                 c1ap, c2ap, s2ap)
            n = Href.shape[0]

            # 1. operator == dense (reconstruct by applying to identity)
            recon = np.column_stack([op.matvec(e) for e in np.eye(n)])
            opdiff = np.abs(recon - Href).max()
            ok1 = opdiff < 1e-10
            all_ok &= ok1

            # 2. eigenvalues (lowest k) matrix-free vs dense
            k = min(6, n - 2)
            dg = np.concatenate([eps, diag_K(eps, nocc, norb, sector)])
            start = np.random.default_rng(0).standard_normal((n, 2 * k + 4))
            w_mf, _, conv = follow_roots(op, dg, start, nroots=k, tol=1e-10, follow=False)
            w_mf = np.sort(w_mf)
            all_ok &= bool(conv.all())
            w_dense = np.sort(np.linalg.eigvalsh(Href))[:k]
            eigdiff = np.abs(w_mf - w_dense).max()
            ok2 = eigdiff < 1e-8
            all_ok &= ok2
            print(f"  [{'OK' if ok1 else 'FAIL'}] {sector} matrix-free op == dense "
                  f"(dim {n}): {opdiff:.2e}    "
                  f"[{'OK' if ok2 else 'FAIL'}] lowest-{k} eigenvalues: {eigdiff:.2e}")
            print(f"        lowest matrix-free eigenvalue = {w_mf[0]:.6f} Ha  "
                  f"(dense {w_dense[0]:.6f})")

    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
