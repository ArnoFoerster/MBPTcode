"""Regression test for restricted x sigma: the spin-blocked matrix-free C^(2)
apply module (generatedADC/adc4_c2_apply_restricted_blocks.py, from
sigma_codegen.generate_adc4_base_c2_apply_restricted).

Validates every generated spin-blocked apply function against its SHIPPED
dense restricted counterpart (adc4_c2_blocks_restricted.py, the parallel
committed increment 4) contracted with a trial vector:

    apply_c2_TAG_SPLIT_SPINS(..., x)  ==  einsum('bra,ket->bra', dense, x)

for every surviving Ms-conserving spin pattern. The spin-block tensor + restricted
MPn amplitude args come from BuildSuperMatrixADCnRestricted (their validated
runtime, used read-only). Equivalence is algebraic, so any consistent arrays
work; the real restricted amplitudes are used for realism. This closes the
restricted x sigma rung: the emitter consumes their restricted term-lists with
zero change to their code (the IR-contract prediction).
"""
import inspect
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.SingleReference.ADC.generated_modules import lazy
dense = lazy('adc4_c2_blocks_restricted')
appl = lazy('adc4_c2_apply_restricted_blocks')
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.Base.pyscf.pyscf_interface import (
    get_orbital_energies, get_antisymmetrized_spin_block_eri)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)


def main():
    all_ok = True
    for atom, basis, label in [
        ('H 0 0 0; H 0 0 0.74', 'sto-3g', 'H2/sto-3g'),
        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g'),
    ]:
        mol = gto.M(atom=atom, basis=basis, verbose=0)
        mf = scf.RHF(mol).run()
        nocc_sp = mol.nelectron // 2
        eps_sp = get_orbital_energies(mf, representation='spatial')
        g_aaaa, g_bbbb, g_abab = get_antisymmetrized_spin_block_eri(mol, mf)
        r = BuildSuperMatrixADCnRestricted(eps_sp, g_aaaa, g_abab, g_bbbb, nocc_sp)
        pool = {**r._rargs, **r._amplitude_pool()}
        rng = np.random.default_rng(0)

        # every apply_* function must match its dense c2_* counterpart
        apply_names = [n for n in dir(appl) if n.startswith('apply_c2_')]
        n_checked, worst = 0, 0.0
        for aname in apply_names:
            dname = aname[len('apply_'):]                 # strip 'apply_'
            dfn = getattr(dense, dname, None)
            if dfn is None:
                print(f"[FAIL] no dense counterpart for {aname}")
                all_ok = False
                continue
            afn = getattr(appl, aname)
            T = dfn(**{p: pool[p] for p in inspect.signature(dfn).parameters})
            nbra = T.ndim // 2
            x = rng.standard_normal(T.shape[nbra:])
            ref = np.tensordot(T, x, axes=(list(range(nbra, T.ndim)),
                                           list(range(x.ndim))))
            akw = {p: pool[p] for p in inspect.signature(afn).parameters if p != 'x'}
            y = afn(x=x, **akw)
            diff = np.abs(y - ref).max()
            worst = max(worst, diff)
            n_checked += 1
            if diff >= 1e-11:
                all_ok = False
                print(f"[FAIL] {aname}: {diff:.3e}")

        ok = worst < 1e-11
        all_ok &= ok
        print(f"[{'OK' if ok else 'FAIL'}] {label}: all {n_checked} spin-blocked "
              f"C^(2) applies == dense@x, worst = {worst:.3e}")

    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
