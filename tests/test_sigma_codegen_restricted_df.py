"""Regression test for restricted x sigma x DF: the spin-blocked +
density-fitted matrix-free C^(2) apply module
(generatedADC/adc4_c2_apply_restricted_df_blocks.py, from
sigma_codegen.generate_adc_class_pair_apply(2, restricted=True, df=True)).

All three emission axes composed on one path -- spin-restricted, matrix-free,
DF -- validated against the SHIPPED dense restricted blocks
(adc4_c2_blocks_restricted.py) contracted with a trial vector:

    apply_c2_TAG_SPLIT_SPINS(f_aa,f_bb,B_aa,B_bb,..., x) == einsum('bra,ket->bra', dense, x)

with EXACT spin-block RI factors B_aa/B_bb (naux = norb^2, no fitting error);
a sanity check first confirms B reconstructs g_aaaa/g_abab/g_bbbb (same-spin
with exchange, cross-spin without -- mpn_density_driver_restricted._g_df's
convention). Isolates the composition, not DF accuracy.
"""
import inspect
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import numpy as np
from pyscf import gto, scf

from src.SingleReference.ADC.generated_modules import lazy
dense = lazy('adc4_c2_blocks_restricted')
appl = lazy('adc4_c2_apply_restricted_df_blocks')
from src.SingleReference.ADC.adc_autogenerated import BuildSuperMatrixADCnRestricted
from src.Base.pyscf.pyscf_interface import (
    get_orbital_energies, get_antisymmetrized_spin_block_eri,
    get_density_fitting_coefficients)
from tests.generated_runtime import requires_runtime

pytestmark = requires_runtime(4)


def check(label, diff, tol=1e-11):
    ok = diff < tol
    print(f"  [{'OK' if ok else 'FAIL'}] {label}: {diff:.3e}")
    return ok


def main():
    all_ok = True
    for atom, basis, label in [
        ('H 0 0 0; H 0 0 0.74', 'sto-3g', 'H2/sto-3g'),
        ('O 0 0 0; H 0 0 0.96; H 0.96 0 0', 'sto-3g', 'H2O/sto-3g'),
    ]:
        mol = gto.M(atom=atom, basis=basis, verbose=0)
        mf = scf.RHF(mol).run()
        nocc_sp = mol.nelectron // 2
        eps_sp = get_orbital_energies(mf, representation='spatial')
        g_aaaa, g_bbbb, g_abab = get_antisymmetrized_spin_block_eri(mol, mf)
        r = BuildSuperMatrixADCnRestricted(eps_sp, g_aaaa, g_abab, g_bbbb, nocc_sp)

        B_aa = get_density_fitting_coefficients(mol, mf, representation='spatial')  # exact
        B_bb = B_aa                                                                # RHF twin

        print(f"\n=== {label}  (naux={B_aa.shape[0]}) ===")
        # sanity: B reconstructs the spin-block g's the dense blocks use
        g_aaaa_rec = (np.einsum('Qpr,Qqs->pqrs', B_aa, B_aa, optimize=True)
                      - np.einsum('Qps,Qqr->pqrs', B_aa, B_aa, optimize=True))
        g_abab_rec = np.einsum('Qpr,Qqs->pqrs', B_aa, B_bb, optimize=True)
        all_ok &= check("B reconstructs g_aaaa", np.abs(g_aaaa_rec - g_aaaa).max())
        all_ok &= check("B reconstructs g_abab", np.abs(g_abab_rec - g_abab).max())

        pool = {**r.rargs, **r.amplitude_pool(), 'B_aa': B_aa, 'B_bb': B_bb}
        rng = np.random.default_rng(0)
        n_checked, worst = 0, 0.0
        for aname in [n for n in dir(appl) if n.startswith('apply_c2_')]:
            dfn = getattr(dense, aname[len('apply_'):], None)
            if dfn is None:
                print(f"  [FAIL] no dense counterpart for {aname}")
                all_ok = False
                continue
            afn = getattr(appl, aname)
            T = dfn(**{p: pool[p] for p in inspect.signature(dfn).parameters})
            nbra = T.ndim // 2
            x = rng.standard_normal(T.shape[nbra:])
            ref = np.tensordot(T, x, axes=(list(range(nbra, T.ndim)), list(range(x.ndim))))
            akw = {p: pool[p] for p in inspect.signature(afn).parameters if p != 'x'}
            y = afn(x=x, **akw)
            d = np.abs(y - ref).max()
            worst = max(worst, d)
            n_checked += 1
            if d >= 1e-11:
                all_ok = False
                print(f"  [FAIL] {aname}: {d:.3e}")
        all_ok &= check(f"all {n_checked} restricted+DF C^(2) applies == dense@x", worst)

    print("\nALL OK" if all_ok else "\nSOME FAILED")
    return all_ok


def test_main():
    assert main()


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
